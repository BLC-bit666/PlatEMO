function assertFrozenSources(rootPath,Frozen)
    required = {'files','combinedSHA256'};
    if ~isstruct(Frozen) || ~isscalar(Frozen) || ...
            ~all(isfield(Frozen,required)) || numel(Frozen.files) ~= 7
        error('CBSPairGuide:BadDetailFrozenFingerprint', ...
            'Campaign source fingerprint is invalid.');
    end
    for i = 1 : numel(Frozen.files)
        source = fullfile(rootPath,char(Frozen.files(i).relativePath));
        requireFile(source,'frozen campaign source');
        if sha256File(source) ~= string(Frozen.files(i).sha256)
            error('CBSPairGuide:DetailFrozenSourceChanged', ...
                'Frozen campaign source changed: %s',source);
        end
    end
end

function writeManifestAtomic(manifestMAT,manifestCSV,Summary,Figures, ...
        DetailManifest,InputManifest)
    partialMAT = [manifestMAT,'.partial.mat'];
    partialCSV = [manifestCSV,'.partial.csv'];
    partialCleanup = onCleanup(@()deletePartials(partialMAT,partialCSV));
    save(partialMAT,'Summary','Figures','DetailManifest','InputManifest');
    writetable(DetailManifest,partialCSV);
    atomicReplace(partialMAT,manifestMAT, ...
        'CBSPairGuide:DetailManifestMATMoveFailed');
    atomicReplace(partialCSV,manifestCSV, ...
        'CBSPairGuide:DetailManifestCSVMoveFailed');
    clear partialCleanup;
end

function atomicReplace(source,destination,errorId)
    [moved,message] = movefile(source,destination,'f');
    if ~moved
        error(errorId,'%s',message);
    end
end

function valid = validPNG(file)
    valid = false;
    if exist(file,'file') ~= 2
        return;
    end
    try
        Info = imfinfo(file);
        valid = strcmpi(Info.Format,'png') && ...
            Info.Width >= 3800 && Info.Height >= 1400;
    catch
        valid = false;
    end
end

function textValue = commaNumber(value)
    textValue = regexprep(sprintf('%.0f',value), ...
        '(?<!\d)(\d{1,3})(?=(\d{3})+(?!\d))','$1,');
end

function value = empiricalQuantile(X,probability)
    X = sort(double(X(:)));
    if isempty(X) || probability < 0 || probability > 1
        error('CBSPairGuide:BadDetailQuantile', ...
            'Quantile input or probability is invalid.');
    end
    if isscalar(X)
        value = X;
        return;
    end
    position = 1+(numel(X)-1)*probability;
    lo = floor(position);
    hi = ceil(position);
    fraction = position-lo;
    value = X(lo)+fraction*(X(hi)-X(lo));
end

function value = numberList(values)
    value = strjoin(compose('%.15g',double(values(:)')),',');
end

function digest = sha256File(file)
    engine = java.security.MessageDigest.getInstance('SHA-256');
    fid = fopen(file,'rb');
    if fid < 0
        error('CBSPairGuide:DetailHashReadFailed', ...
            'Cannot read file for hashing: %s',file);
    end
    cleanup = onCleanup(@()fclose(fid));
    while true
        bytes = fread(fid,1024*1024,'*uint8');
        if isempty(bytes)
            break;
        end
        engine.update(typecast(bytes(:),'int8'));
    end
    clear cleanup;
    bytes = typecast(engine.digest(),'uint8');
    digest = string(lower(reshape(dec2hex(bytes,2).',1,[])));
end

