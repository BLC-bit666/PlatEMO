function [rates,visible,total] = visibilityStats(Snapshots,View,M)
    fields = {'population1Objs','population2Objs','rawObjs', ...
        'targetObjs','centerObjs','guidedObjs'};
    visible = zeros(1,numel(fields));
    total = zeros(1,numel(fields));
    for arm = 1 : numel(Snapshots)
        for snapshot = 1 : numel(Snapshots{arm})
            S = Snapshots{arm}(snapshot);
            for layer = 1 : numel(fields)
                Obj = double(S.(fields{layer}));
                total(layer) = total(layer)+size(Obj,1);
                visible(layer) = visible(layer)+sum(all( ...
                    Obj(:,1:M) >= View.lower & ...
                    Obj(:,1:M) <= View.upper,2));
            end
        end
    end
    rates = visible./max(1,total);
end

function simplifyBackground(Ax,M)
    if M ~= 2
        return;
    end
    Images = findobj(Ax,'Type','image');
    for i = 1 : numel(Images)
        data = Images(i).CData;
        if size(data,1) > 140 || size(data,2) > 140
            rows = unique(round(linspace(1,size(data,1),140)));
            columns = unique(round(linspace(1,size(data,2),140)));
            Images(i).CData = data(rows,columns,:);
            alpha = Images(i).AlphaData;
            if ~isscalar(alpha)
                Images(i).AlphaData = alpha(rows,columns);
            end
        end
    end
end

