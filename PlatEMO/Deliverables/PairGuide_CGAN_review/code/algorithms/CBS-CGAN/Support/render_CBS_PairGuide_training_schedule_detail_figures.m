function B = emptyBundle()
    B = struct('armName',"",'armValues',zeros(1,3), ...
        'Snapshots',{{}},'inputFiles',strings(1,3), ...
        'inputSHA256',strings(1,3),'M',0,'N',0,'D',0);
end

function F = selectSourceFigure(Figures,stage,problem)
    rows = find(string({Figures.stage}) == stage & ...
        string({Figures.problem}) == problem);
    if numel(rows) ~= 1
        error('CBSPairGuide:DetailSourceFigureIdentity', ...
            'Expected one %s %s source figure; found %d.', ...
            stage,problem,numel(rows));
    end
    F = Figures(rows);
    if F.snapshotCount ~= 30 || numel(F.targetFE) ~= 10 || ...
            ~isequal(size(F.actualFE),[3,10])
        error('CBSPairGuide:BadDetailSourceFigure', ...
            '%s %s source metadata is incomplete.',stage,problem);
    end
end

function [B,Rows] = loadBundle(campaignDir,stage,problem,F)
    stageDir = fullfile(campaignDir,char(stage));
    stageManifest = fullfile(stageDir,'campaign_manifest.mat');
    requireFile(stageManifest,'stage campaign manifest');
    M = load(stageManifest,'Protocol','Tasks');
    if ~isfield(M,'Protocol') || ~isfield(M,'Tasks')
        error('CBSPairGuide:BadDetailStageManifest', ...
            '%s must contain Protocol and Tasks.',stageManifest);
    end
    arms = double(M.Protocol.arms(:)');
    armName = string(M.Protocol.armName);
    if numel(arms) ~= 3 || ~isequal(arms,double(F.armValues)) || ...
            armName ~= string(F.armName)
        error('CBSPairGuide:DetailArmMismatch', ...
            '%s %s stage arms disagree with the source figure.', ...
            problem,stage);
    end
    taskProblems = string({M.Tasks.problem});
    taskRuns = double([M.Tasks.run]);
    taskArms = double([M.Tasks.armValue]);
    snapshots = cell(1,3);
    inputFiles = strings(1,3);
    inputSHA256 = strings(1,3);
    dimensions = zeros(3,3);
    Rows = repmat(emptyInputRecord(),3,1);
    for arm = 1 : 3
        tolerance = 64*eps(max(1,abs(arms(arm))));
        rows = find(taskProblems == problem & taskRuns == F.run & ...
            abs(taskArms-arms(arm)) <= tolerance);
        if numel(rows) ~= 1
            error('CBSPairGuide:DetailTaskIdentity', ...
                '%s needs one %s=%g run %d task; found %d.', ...
                problem,armName,arms(arm),F.run,numel(rows));
        end
        resultFile = resolveResultFile( ...
            char(M.Tasks(rows).outputFile),stageDir);
        Data = loadDetailResult(resultFile,problem,F.run, ...
            F.targetFE,F.actualFE(arm,:));
        snapshots{arm} = Data.Snapshots;
        inputFiles(arm) = string(resultFile);
        inputSHA256(arm) = sha256File(resultFile);
        dimensions(arm,:) = [double(Data.Record.M), ...
            double(Data.Record.N),double(Data.Record.D)];
        Rows(arm) = struct('stage',stage,'problem',problem, ...
            'run',F.run,'armName',armName,'armValue',arms(arm), ...
            'sourceStage',string(Data.Record.stageName), ...
            'reused',string(Data.Record.stageName) ~= stage, ...
            'snapshotCount',numel(Data.Snapshots), ...
            'targetFE',numberList([Data.Snapshots.targetFE]), ...
            'actualFE',numberList([Data.Snapshots.actualFE]), ...
            'inputFile',string(resultFile), ...
            'inputSHA256',inputSHA256(arm));
    end
    if any(any(dimensions ~= dimensions(1,:)))
        error('CBSPairGuide:DetailDimensionMismatch', ...
            '%s %s arms disagree on M/N/D.',problem,stage);
    end
    B = struct('armName',armName,'armValues',arms, ...
        'Snapshots',{snapshots},'inputFiles',inputFiles, ...
        'inputSHA256',inputSHA256,'M',dimensions(1,1), ...
        'N',dimensions(1,2),'D',dimensions(1,3));
end

function Data = loadDetailResult(file,problem,run,targetFE,actualFE)
    requireFile(file,'training-schedule result');
    variables = string({whos('-file',file).name});
    required = ["Record","Snapshots"];
    missing = required(~ismember(required,variables));
    if ~isempty(missing)
        error('CBSPairGuide:BadDetailResultVariables', ...
            '%s is missing variables: %s',file,strjoin(missing,', '));
    end
    Data = load(file,'Record','Snapshots');
    R = Data.Record;
    S = Data.Snapshots;
    recordFields = {'status','stageName','problem','run', ...
        'M','N','D','snapshotCount'};
    if ~isstruct(R) || ~isscalar(R) || ...
            ~all(isfield(R,recordFields)) || string(R.status) ~= "ok" || ...
            string(R.problem) ~= problem || double(R.run) ~= run || ...
            double(R.snapshotCount) ~= 10 || ~ismember(double(R.M),[2,3])
        error('CBSPairGuide:BadDetailResultRecord', ...
            '%s has invalid Record metadata.',file);
    end
    if ~isstruct(S) || numel(S) ~= 10 || ...
            ~isequal(double([S.targetFE]),double(targetFE(:)')) || ...
            ~isequal(double([S.actualFE]),double(actualFE(:)'))
        error('CBSPairGuide:BadDetailSnapshots', ...
            '%s does not match the source figure FE schedule.',file);
    end
    layers = {'raw','target','center','guided','population1','population2'};
    for snapshot = 1 : numel(S)
        for layer = 1 : numel(layers)
            name = layers{layer};
            objs = S(snapshot).([name,'Objs']);
            cons = S(snapshot).([name,'Cons']);
            if ~isnumeric(objs) || size(objs,2) ~= double(R.M) || ...
                    any(~isfinite(objs),'all') || ~isnumeric(cons) || ...
                    size(cons,1) ~= size(objs,1) || ...
                    any(~isfinite(cons),'all')
                error('CBSPairGuide:BadDetailSnapshotLayer', ...
                    '%s snapshot %d layer %s is invalid.', ...
                    file,snapshot,name);
            end
        end
        if size(S(snapshot).rawObjs,1) ~= 500
            error('CBSPairGuide:BadDetailRawCount', ...
                '%s snapshot %d does not contain 500 raw points.', ...
                file,snapshot);
        end
    end
end

function View = detailView(Bundles)
    M = Bundles(1).M;
    if any([Bundles.M] ~= M)
        error('CBSPairGuide:DetailViewDimensionMismatch', ...
            'Ratio and epoch bundles disagree on objective count.');
    end
    panelUpper = zeros(60,M);
    pooledForeground = zeros(0,M);
    panel = 0;
    for stage = 1 : numel(Bundles)
        for arm = 1 : numel(Bundles(stage).Snapshots)
            S = Bundles(stage).Snapshots{arm};
            for snapshot = 1 : numel(S)
                panel = panel+1;
                foreground = [double(S(snapshot).population1Objs); ...
                    double(S(snapshot).population2Objs); ...
                    double(S(snapshot).targetObjs); ...
                    double(S(snapshot).centerObjs); ...
                    double(S(snapshot).guidedObjs)];
                foreground = foreground(all(isfinite(foreground),2),:);
                if isempty(foreground)
                    error('CBSPairGuide:EmptyDetailForeground', ...
                        'Panel %d has no finite foreground points.',panel);
                end
                pooledForeground = [pooledForeground;foreground]; %#ok<AGROW>
                for objective = 1 : M
                    panelUpper(panel,objective) = empiricalQuantile( ...
                        foreground(:,objective),0.95);
                end
            end
        end
    end
    if panel ~= 60
        error('CBSPairGuide:DetailPanelCount', ...
            'Detail view used %d panels; expected 60.',panel);
    end
    coreLower = zeros(1,M);
    coreUpper = zeros(1,M);
    for objective = 1 : M
        coreLower(objective) = empiricalQuantile( ...
            pooledForeground(:,objective),0.005);
        coreUpper(objective) = empiricalQuantile( ...
            panelUpper(:,objective),0.75);
    end
    span = coreUpper-coreLower;
    if any(span <= eps(max(1,max(abs(pooledForeground),[],1))))
        error('CBSPairGuide:DegenerateDetailForeground', ...
            'Foreground detail extent is degenerate.');
    end
    lower = max(0,coreLower-0.05*span);
    upper = coreUpper+0.05*span;
    View = struct('lower',lower,'upper',upper, ...
        'coreLower',coreLower,'coreUpper',coreUpper);
end

function F = makeFigureRecord(stage,problem,Source,B,View, ...
        layerNames,problemFile,problemSHA256,outputFile,Info)
    paddedLower = nan(1,3);
    paddedUpper = nan(1,3);
    paddedCoreLower = nan(1,3);
    paddedCoreUpper = nan(1,3);
    paddedLower(1:B.M) = View.lower;
    paddedUpper(1:B.M) = View.upper;
    paddedCoreLower(1:B.M) = View.coreLower;
    paddedCoreUpper(1:B.M) = View.coreUpper;
    [layerRates,layerInView,layerTotals] = visibilityStats( ...
        B.Snapshots,View,B.M);
    F = struct('stage',stage,'problem',problem,'run',Source.run, ...
        'M',B.M,'armName',B.armName,'armValues',B.armValues, ...
        'targetFE',double(Source.targetFE), ...
        'actualFE',double(Source.actualFE), ...
        'viewLower',paddedLower,'viewUpper',paddedUpper, ...
        'focusCoreLower',paddedCoreLower, ...
        'focusCoreUpper',paddedCoreUpper, ...
        'snapshotCount',30,'layerNames',layerNames, ...
        'layerInViewRates',layerRates, ...
        'layerTotalCounts',layerTotals, ...
        'layerInViewCounts',layerInView, ...
        'layerClippedCounts',layerTotals-layerInView, ...
        'inputFiles',B.inputFiles,'inputSHA256',B.inputSHA256, ...
        'problemConstructor',problemFile, ...
        'problemConstructorSHA256',problemSHA256, ...
        'file',string(outputFile),'outputSHA256',sha256File(outputFile), ...
        'width',Info.Width,'height',Info.Height);
end

function renderSheet(Problem,problem,stage,armName,arms,run, ...
        Snapshots,View,outputFile)
    Figure = figure('Visible','off','Color','w', ...
        'Position',[20,40,4200,1650]);
    cleanup = onCleanup(@()close(Figure));
    C = figureColors();
    legendHandles = gobjects(1,0);
    legendAxes = gobjects(1,1);
    left = 0.008;
    right = 0.008;
    bottom = 0.060;
    top = 0.935;
    horizontalGap = 0.003;
    verticalGap = 0.017;
    cellWidth = (1-left-right-9*horizontalGap)/10;
    cellHeight = (top-bottom-2*verticalGap)/3;
    for arm = 1 : 3
        armLabel = sprintf('%s=%g',armName,arms(arm));
        rowTop = top-(arm-1)*(cellHeight+verticalGap);
        cellY = rowTop-cellHeight;
        for snapshot = 1 : 10
            cellX = left+(snapshot-1)*(cellWidth+horizontalGap);
            Ax = axes(Figure,'Units','normalized','Position',[ ...
                cellX+0.085*cellWidth,cellY+0.055*cellHeight, ...
                0.86*cellWidth,0.75*cellHeight]);
            hold(Ax,'on');
            [hFeasible,hInfeasible] = draw_CBS_CGAN_objective_region( ...
                Ax,Problem,problem,C,View);
            simplifyBackground(Ax,Problem.M);
            H = drawLayers(Ax,Problem.M,Snapshots{arm}(snapshot),C);
            setView(Ax,View,Problem.M);
            styleAxes(Ax,Problem.M,arm,snapshot);
            if Problem.M == 3
                camzoom(Ax,0.82);
            end
            if snapshot == 1
                timeLabel = 'first use';
            else
                timeLabel = sprintf('%gK target', ...
                    Snapshots{arm}(snapshot).targetFE/1000);
            end
            annotation(Figure,'textbox',[cellX, ...
                cellY+cellHeight-0.042,cellWidth,0.040], ...
                'String',sprintf('%s\n%s | actual FE %s', ...
                    armLabel,timeLabel, ...
                    commaNumber(Snapshots{arm}(snapshot).actualFE)), ...
                'Interpreter','none','EdgeColor','none', ...
                'HorizontalAlignment','center', ...
                'VerticalAlignment','middle','FontName','Helvetica', ...
                'FontSize',6.5,'FontWeight','normal','Margin',0);
            if arm == 1 && snapshot == 1
                legendAxes = Ax;
                legendHandles = [hFeasible,hInfeasible,H];
            end
        end
    end
    annotation(Figure,'textbox',[0.04,0.962,0.92,0.028], ...
        'String',sprintf([ ...
            '%s | %s stage | representative run %d | ', ...
            'lower-left detail | shared view across both stages'], ...
            problem,stage,run),'Interpreter','none','EdgeColor','none', ...
        'HorizontalAlignment','center','VerticalAlignment','middle', ...
        'FontName','Helvetica','FontWeight','bold','FontSize',15, ...
        'Margin',0);
    labels = {'feasible region','infeasible region','P1','P2', ...
        'raw 500','selected target','selected center','guided child'};
    Legend = legend(legendAxes,legendHandles,labels, ...
        'Orientation','horizontal','NumColumns',8,'FontSize',7, ...
        'Box','off','Interpreter','none');
    Legend.Units = 'normalized';
    drawnow;
    Legend.Position = [0.25,0.012,0.50,0.025];
    drawnow;

    partialFile = [outputFile,'.partial.png'];
    partialCleanup = onCleanup(@()deleteIfExists(partialFile));
    exportgraphics(Figure,partialFile,'Resolution',96, ...
        'BackgroundColor','white');
    if ~validPNG(partialFile)
        error('CBSPairGuide:InvalidDetailPNG', ...
            'Rendered PNG failed validation: %s',partialFile);
    end
    atomicReplace(partialFile,outputFile, ...
        'CBSPairGuide:DetailPNGMoveFailed');
    clear partialCleanup cleanup;
end

function H = drawLayers(Ax,M,S,C)
    if M == 2
        hRaw = scatter(Ax,S.rawObjs(:,1),S.rawObjs(:,2),4,C.raw, ...
            'filled','o','MarkerFaceAlpha',0.30,'MarkerEdgeColor','none');
        hP1 = scatter(Ax,S.population1Objs(:,1), ...
            S.population1Objs(:,2),10,C.p1,'filled','o', ...
            'MarkerFaceAlpha',0.76,'MarkerEdgeColor','none');
        hP2 = scatter(Ax,S.population2Objs(:,1), ...
            S.population2Objs(:,2),11,C.p2,'filled','^', ...
            'MarkerFaceAlpha',0.76,'MarkerEdgeColor','none');
        hTarget = scatter(Ax,S.targetObjs(:,1),S.targetObjs(:,2), ...
            23,C.target,'filled','v','MarkerEdgeColor',[0.1,0.1,0.1], ...
            'LineWidth',0.25);
        hCenter = plot(Ax,S.centerObjs(:,1),S.centerObjs(:,2),'x', ...
            'Color',C.center,'MarkerSize',4.2,'LineWidth',0.8);
        hGuided = scatter(Ax,S.guidedObjs(:,1),S.guidedObjs(:,2), ...
