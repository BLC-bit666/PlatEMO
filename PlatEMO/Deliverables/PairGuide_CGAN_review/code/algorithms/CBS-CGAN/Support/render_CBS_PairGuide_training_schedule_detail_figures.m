function Summary = render_CBS_PairGuide_training_schedule_detail_figures( ...
        rootPath,campaignName)
%RENDER_CBS_PAIRGUIDE_TRAINING_SCHEDULE_DETAIL_FIGURES Redraw zoomed sheets.
%   This post-processing renderer reads the completed campaign MAT files and
%   writes a separate set of lower-left detail views. It never changes the
%   campaign results, the original figures, or their manifests.

    if nargin < 1 || isempty(rootPath)
        rootPath = fileparts(which('platemo'));
    end
    if nargin < 2 || strlength(string(campaignName)) == 0
        campaignName = "CBS_PairGuide_training_schedule_v1_20260901";
    end
    rootPath = char(rootPath);
    campaignName = string(campaignName);
    campaignDir = fullfile(rootPath,'Data',char(campaignName));
    stages = ["ratio","epoch"];
    layerNames = ["P1","P2","raw 500","selected target", ...
        "selected center","guided child"];
    addCBSPaths(rootPath);

    campaignManifest = fullfile(campaignDir,'campaign_manifest.mat');
    requireFile(campaignManifest,'campaign manifest');
    Campaign = load(campaignManifest,'CampaignProtocol');
    if ~isfield(Campaign,'CampaignProtocol') || ...
            ~isfield(Campaign.CampaignProtocol,'sourceFingerprint')
        error('CBSPairGuide:BadDetailCampaignManifest', ...
            '%s is missing CampaignProtocol.sourceFingerprint.', ...
            campaignManifest);
    end
    Frozen = Campaign.CampaignProtocol.sourceFingerprint;
    assertFrozenSources(rootPath,Frozen);

    sourceFigureDir = fullfile(campaignDir,'figures','training_schedule');
    sourceManifestMAT = fullfile(sourceFigureDir,'figure_manifest.mat');
    sourceManifestCSV = fullfile(sourceFigureDir,'figure_manifest.csv');
    requireFile(sourceManifestMAT,'source figure manifest MAT');
    requireFile(sourceManifestCSV,'source figure manifest CSV');
    Original = load(sourceManifestMAT,'Figures');
    if ~isfield(Original,'Figures') || ...
            ~isstruct(Original.Figures) || numel(Original.Figures) ~= 12
        error('CBSPairGuide:BadDetailFigureManifest', ...
            '%s must contain the 12 source Figures.',sourceManifestMAT);
    end
    sourceProblems = string({Original.Figures.problem});
    problems = unique(sourceProblems,'stable');
    if numel(problems) ~= 6
        error('CBSPairGuide:BadDetailProblemCount', ...
            'Source figure manifest must contain six problems.');
    end

    rendererFile = string(mfilename('fullpath'));
    if ~endsWith(rendererFile,".m")
        rendererFile = rendererFile+".m";
    end
    drawFile = string(which('draw_CBS_CGAN_objective_region'));
    requireFile(drawFile,'objective-region renderer');
    rendererSHA256 = sha256File(rendererFile);
    drawSHA256 = sha256File(drawFile);
    sourceManifestMatSHA256 = sha256File(sourceManifestMAT);
    sourceManifestCsvSHA256 = sha256File(sourceManifestCSV);
    frozenFingerprint = string(Frozen.combinedSHA256);

    outputDir = fullfile(campaignDir,'figures', ...
        'training_schedule_detail_v1');
    ensureFolder(outputDir);
    Figures = repmat(emptyFigureRecord(),12,1);
    Inputs = repmat(emptyInputRecord(),36,1);
    figureRow = 0;
    inputRow = 0;
    for p = 1 : numel(problems)
        problem = problems(p);
        Source = repmat(Original.Figures(1),2,1);
        Bundle = repmat(emptyBundle(),2,1);
        Problem = [];
        problemFile = "";
        for s = 1 : numel(stages)
            Source(s) = selectSourceFigure( ...
                Original.Figures,stages(s),problem);
            if s == 2 && (Source(s).run ~= Source(1).run || ...
                    ~isequal(double(Source(s).targetFE), ...
                        double(Source(1).targetFE)))
                error('CBSPairGuide:DetailCrossStageMismatch', ...
                    '%s source stages disagree on run or target FE.',problem);
            end
            [Bundle(s),Rows] = loadBundle(campaignDir,stages(s), ...
                problem,Source(s));
            for r = 1 : numel(Rows)
                inputRow = inputRow+1;
                Inputs(inputRow) = Rows(r);
            end
            if isempty(Problem)
                constructor = str2func(char(problem));
                Problem = constructor('N',Bundle(s).N, ...
                    'D',Bundle(s).D,'maxFE',1e9,'maxRuntime',Inf);
                if Problem.M ~= Bundle(s).M
                    error('CBSPairGuide:DetailProblemDimension', ...
                        '%s constructor and result objective counts differ.', ...
                        problem);
                end
                problemFile = string(which(char(problem)));
                requireFile(problemFile,'problem constructor');
            elseif any([Problem.M,Problem.N,Problem.D] ~= ...
                    [Bundle(s).M,Bundle(s).N,Bundle(s).D])
                error('CBSPairGuide:DetailCrossStageDimension', ...
                    '%s ratio and epoch results disagree on M/N/D.',problem);
            end
        end
        View = detailView(Bundle);
        problemSHA256 = sha256File(problemFile);
        for s = 1 : numel(stages)
            B = Bundle(s);
            F = Source(s);
            outputFile = fullfile(outputDir,sprintf( ...
                '%s_%s_run%02d_3x10_detail_v1.png', ...
                stages(s),problem,F.run));
            renderSheet(Problem,problem,stages(s),B.armName, ...
                B.armValues,F.run,B.Snapshots,View,outputFile);
            Info = imfinfo(outputFile);
            figureRow = figureRow+1;
            Figures(figureRow) = makeFigureRecord(stages(s),problem,F, ...
                B,View,layerNames,problemFile,problemSHA256, ...
                outputFile,Info);
        end
    end
    if figureRow ~= 12 || inputRow ~= 36
        error('CBSPairGuide:DetailOutputCount', ...
            'Built %d figures and %d inputs; expected 12 and 36.', ...
            figureRow,inputRow);
    end

    finishedAt = string(datetime('now'));
    ManifestRows = repmat(emptyManifestRow(),numel(Figures),1);
    for i = 1 : numel(Figures)
        F = Figures(i);
        ManifestRows(i) = struct( ...
            'stage',F.stage,'problem',F.problem,'run',F.run, ...
            'armName',F.armName,'armValues',numberList(F.armValues), ...
            'targetFE',numberList(F.targetFE), ...
            'snapshotCount',F.snapshotCount, ...
            'viewLower',numberList(F.viewLower(1:F.M)), ...
            'viewUpper',numberList(F.viewUpper(1:F.M)), ...
            'focusCoreLower',numberList(F.focusCoreLower(1:F.M)), ...
            'focusCoreUpper',numberList(F.focusCoreUpper(1:F.M)), ...
            'layerNames',strjoin(F.layerNames,';'), ...
            'layerInViewRates',numberList(F.layerInViewRates), ...
            'layerTotalCounts',numberList(F.layerTotalCounts), ...
            'layerInViewCounts',numberList(F.layerInViewCounts), ...
            'layerClippedCounts',numberList(F.layerClippedCounts), ...
            'frozenSourceFingerprint',frozenFingerprint, ...
            'sourceFigureManifestMatSHA256', ...
                sourceManifestMatSHA256, ...
            'sourceFigureManifestCsvSHA256', ...
                sourceManifestCsvSHA256, ...
            'rendererSHA256',rendererSHA256, ...
            'objectiveRegionRendererSHA256',drawSHA256, ...
            'problemConstructorSHA256',F.problemConstructorSHA256, ...
            'inputFiles',strjoin(F.inputFiles,';'), ...
            'inputSHA256',strjoin(F.inputSHA256,';'), ...
            'file',F.file,'outputSHA256',F.outputSHA256, ...
            'width',F.width,'height',F.height, ...
            'finishedAt',finishedAt);
    end
    DetailManifest = struct2table(ManifestRows);
    InputManifest = struct2table(Inputs);
    Summary = struct( ...
        'schemaVersion',"CBS-PairGuide-training-schedule-detail-v1", ...
        'campaignName',campaignName,'figureCount',numel(Figures), ...
        'expectedFigureCount',12,'panelsPerFigure',30, ...
        'viewRule',strjoin([ ...
            "foreground={P1,P2,target,center,guided}; lower=pooled q0.5%, ", ...
            "upper=q75 across per-panel q95; add 5% span padding; ", ...
            "clamp benchmark objective lower bounds to zero"],""), ...
        'outlierPolicy',"points outside the lower-left detail view are clipped", ...
        'frozenSourceFingerprint',frozenFingerprint, ...
        'sourceFigureManifestMAT',string(sourceManifestMAT), ...
        'sourceFigureManifestMatSHA256',sourceManifestMatSHA256, ...
        'sourceFigureManifestCSV',string(sourceManifestCSV), ...
        'sourceFigureManifestCsvSHA256',sourceManifestCsvSHA256, ...
        'renderer',rendererFile,'rendererSHA256',rendererSHA256, ...
        'objectiveRegionRenderer',drawFile, ...
        'objectiveRegionRendererSHA256',drawSHA256, ...
        'finishedAt',finishedAt);
    manifestMAT = fullfile(outputDir,'detail_manifest.mat');
    manifestCSV = fullfile(outputDir,'detail_manifest.csv');
    writeManifestAtomic(manifestMAT,manifestCSV,Summary,Figures, ...
        DetailManifest,InputManifest);
end

