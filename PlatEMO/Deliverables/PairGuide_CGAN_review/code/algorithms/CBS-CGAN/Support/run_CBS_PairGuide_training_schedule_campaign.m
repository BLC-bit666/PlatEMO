function Fingerprint = sourceFingerprint(rootPath)
%SOURCEFINGERPRINT Freeze all code that defines or interprets the campaign.

    relativeFiles = [ ...
        "Algorithms/Multi-objective optimization/CBS-CGAN/Core/"+ ...
            "CBS_RegionWGAN_GP_Core.m"; ...
        "Algorithms/Multi-objective optimization/CBS-CGAN/Core/"+ ...
            "PairBoundaryWGAN_RC.m"; ...
        "Algorithms/Multi-objective optimization/CBS-CGAN/Core/"+ ...
            "PairBoundaryArchive_RC.m"; ...
        "Algorithms/Multi-objective optimization/CBS-CGAN-PairGuide/"+ ...
            "CBS_RegionWGAN_GP_PairGuide.m"; ...
        "Algorithms/Multi-objective optimization/CBS-CGAN/Support/"+ ...
            "run_CBS_PairGuide_training_schedule_campaign.m"; ...
        "Algorithms/Multi-objective optimization/CBS-CGAN/Support/"+ ...
            "analyze_CBS_PairGuide_training_schedule_stage.m"; ...
        "Algorithms/Multi-objective optimization/CBS-CGAN/Support/"+ ...
            "render_CBS_PairGuide_training_schedule_figures.m"];
    roles = ["core";"pairWGAN";"pairArchive";"pairGuideEntry"; ...
        "runner";"analyzer";"renderer"];
    Files = repmat(struct('role',"",'relativePath',"", ...
        'sha256',""),numel(relativeFiles),1);
    canonical = "";
    for i = 1 : numel(relativeFiles)
        file = fullfile(rootPath,char(relativeFiles(i)));
        if ~isfile(file)
            error('CBSPairGuide:MissingFingerprintSource', ...
                'Cannot fingerprint missing campaign source: %s',file);
        end
        digest = sha256File(file);
        Files(i) = struct('role',roles(i), ...
            'relativePath',relativeFiles(i),'sha256',digest);
        canonical = canonical+roles(i)+"|"+relativeFiles(i)+"|"+ ...
            digest+newline;
    end
    Fingerprint = struct();
    Fingerprint.algorithm = "SHA-256";
    Fingerprint.files = Files;
    Fingerprint.combinedSHA256 = sha256Bytes( ...
        unicode2native(char(canonical),'UTF-8'));
end

function valid = validSourceFingerprint(F)
    valid = isstruct(F) && isscalar(F) && ...
        all(isfield(F,{'algorithm','files','combinedSHA256'})) && ...
        string(F.algorithm) == "SHA-256" && ...
        isstruct(F.files) && numel(F.files) == 7 && ...
        all(isfield(F.files,{'role','relativePath','sha256'})) && ...
        strlength(string(F.combinedSHA256)) == 64 && ...
        all(strlength(string({F.files.sha256})) == 64);
end

function assertSourceFingerprint(rootPath,expected)
    current = sourceFingerprint(rootPath);
    if ~isequaln(current,expected)
        error('CBSPairGuide:TrainingScheduleSourceChanged', ...
            ['Campaign source changed after the manifest was frozen; ', ...
             'refusing to mix result identities.']);
    end
end

function digest = sha256File(file)
    engine = java.security.MessageDigest.getInstance('SHA-256');
    fid = fopen(file,'rb');
    if fid < 0
        error('CBSPairGuide:FingerprintReadFailed', ...
            'Cannot read campaign source for hashing: %s',file);
    end
    cleanup = onCleanup(@()fclose(fid));
    while true
        bytes = fread(fid,1024*1024,'*uint8');
        if isempty(bytes)
            break;
        end
        engine.update(typecast(bytes(:),'int8'));
    end
    clear cleanup;
    digest = digestHex(engine.digest());
end

function digest = sha256Bytes(bytes)
    engine = java.security.MessageDigest.getInstance('SHA-256');
    engine.update(typecast(uint8(bytes(:)),'int8'));
    digest = digestHex(engine.digest());
end

function digest = digestHex(bytes)
    bytes = typecast(bytes,'uint8');
    digest = string(lower(reshape(dec2hex(bytes,2).',1,[])));
end

