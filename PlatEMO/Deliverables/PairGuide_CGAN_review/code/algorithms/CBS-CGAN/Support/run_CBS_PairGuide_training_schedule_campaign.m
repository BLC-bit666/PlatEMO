function atomicMove(source,destination,errorId)
    if isfile(destination)
        error(errorId,'Atomic destination already exists: %s',destination);
    end
    [moved,message] = movefile(source,destination);
    if ~moved
        error(errorId,'%s',message);
    end
end

function atomicReplace(source,destination,errorId)
    [moved,message] = movefile(source,destination,'f');
    if ~moved
        error(errorId,'%s',message);
    end
end

