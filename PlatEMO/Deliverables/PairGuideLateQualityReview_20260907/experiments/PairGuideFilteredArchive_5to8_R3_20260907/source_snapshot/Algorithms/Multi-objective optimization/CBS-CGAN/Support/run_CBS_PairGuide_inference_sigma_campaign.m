function Summary = run_CBS_PairGuide_inference_sigma_campaign( ...
        rootPath,nWorker,trainingSigma)
%RUN_CBS_PAIRGUIDE_INFERENCE_SIGMA_CAMPAIGN Compare latent-noise scales.
%   trainingSigma=1 keeps the original two inference arms. A value of 0.5
%   trains only the new model and combines its sigmaUse=0.5 arm with the
%   existing sigmaTrain=1 campaign in three-panel figures.

    if nargin < 1 || isempty(rootPath)
        rootPath = fileparts(which('platemo'));
    end
    if nargin < 2 || isempty(nWorker)
        nWorker = 10;
    end
    if nargin < 3 || isempty(trainingSigma)
        trainingSigma = 1;
    end
    rootPath = char(rootPath);
    addCBSPaths(rootPath);
    P = protocol(rootPath,nWorker,trainingSigma);
    validateProtocol(P);
    campaignDir = fullfile(rootPath,'Data',char(P.campaignName));
    resultDir = fullfile(campaignDir,'results');
    failureDir = fullfile(campaignDir,'failures');
    ensureFolder(resultDir);
    ensureFolder(failureDir);
    Tasks = buildTasks(P,resultDir);
    manifestFile = fullfile(campaignDir,'campaign_manifest.mat');
    if exist(manifestFile,'file') == 2
        Existing = load(manifestFile,'Protocol','Tasks');
        if ~isequaln(Existing.Protocol,P) || ~isequaln(Existing.Tasks,Tasks)
            error('CBSPairGuide:SigmaManifestMismatch', ...
                'Existing inference-sigma campaign uses another protocol.');
        end
    else
        Manifest = struct('Protocol',P,'Tasks',Tasks);
        save(manifestFile,'-struct','Manifest');
    end

    pending = Tasks(~tasksComplete(Tasks,P));
    pool = [];
    ownsPool = false;
    if ~isempty(pending)
        [pool,ownsPool] = exactPool(P.nWorker);
    end
    cleanup = onCleanup(@()closeOwnedPool(pool,ownsPool));
    for attempt = 1 : P.maxAttempts
        if isempty(pending)
            break;
        end
        fprintf('PairGuide paired inference sigma: %d tasks, attempt %d/%d\n', ...
            numel(pending),attempt,P.maxAttempts);
        parfor (i = 1:numel(pending),P.nWorker)
            Task = pending(i);
            try
                runTask(rootPath,Task,P);
            catch err
                writeFailure(failureDir,Task,attempt,err);
            end
        end
        pending = Tasks(~tasksComplete(Tasks,P));
    end
    if ~isempty(pending)
        error('CBSPairGuide:SigmaCampaignTasksFailed', ...
            '%d paired sigma tasks failed.',numel(pending));
    end
    clear cleanup;
    closeOwnedPool(pool,ownsPool);

    Analysis = analyzeCampaign(rootPath,P,Tasks,campaignDir);
    ThreeWayAnalysis = struct();
    if protocolTrainingSigma(P) == 0.5
        ThreeWayAnalysis = analyzeThreeWayCampaign( ...
            rootPath,P,Tasks,campaignDir);
        Figures = renderThreeWayCampaign(rootPath,P,Tasks,campaignDir);
        displayedArmCount = 3*numel(Tasks);
    else
        Figures = renderCampaign(rootPath,P,Tasks,campaignDir);
        displayedArmCount = numel(Tasks)*numel(P.sampleSigmas);
    end
    Summary = struct('schemaVersion',P.schemaVersion, ...
        'campaignName',P.campaignName,'trainingTaskCount',numel(Tasks), ...
        'armCount',displayedArmCount, ...
        'figureCount',Figures.figureCount, ...
        'pairedInference',true, ...
        'trainingNoiseSigma',protocolTrainingSigma(P), ...
        'finishedAt',string(datetime('now')));
    save(fullfile(campaignDir,'campaign_summary.mat'), ...
        'Summary','Analysis','ThreeWayAnalysis','Figures');
    writelines("COMPLETE",fullfile(campaignDir,'COMPLETE.txt'));
end

function P = protocol(rootPath,nWorker,trainingSigma)
    P = struct( ...
        'schemaVersion',"CBS-PairGuide-inference-sigma-v1", ...
        'campaignName', ...
            "CBS_PairGuide_inference_sigma_epoch1000_v1_20260901", ...
        'rootPath',string(rootPath), ...
        'algorithm',"PairGuide", ...
        'problems',["LIRCMOP5_BC","LIRCMOP7_BC", ...
            "LIRCMOP8_BC","LIRCMOP10_BC", ...
            "LIRCMOP12_BC","LIRCMOP14_BC"], ...
        'epoch',1000,'runs',1:2,'sampleSigmas',[1 0.5], ...
        'popSize',100,'dimension',30,'maxFE',200000, ...
        'rawGuideCount',500,'zDim',6,'miniBatch',64,'nCritic',4, ...
        'minGANTrainCount',32,'productionSampleSigma',1, ...
        'expectedRequestedCount',20,'nWorker',double(nWorker), ...
        'maxAttempts',2);
    trainingSigma = double(trainingSigma);
    if trainingSigma == 0.5
        P.schemaVersion = "CBS-PairGuide-train-use-sigma-threeway-v1";
        P.campaignName = ...
            "CBS_PairGuide_train_use_sigma_threeway_epoch1000_v1_20260901";
        P.trainingSigma = trainingSigma;
        P.baselineCampaignName = ...
            "CBS_PairGuide_inference_sigma_epoch1000_v1_20260901";
    elseif trainingSigma ~= 1
        error('CBSPairGuide:BadTrainingSigmaCampaignValue', ...
            'This campaign supports trainingSigma=1 or 0.5 only.');
    end
end

function validateProtocol(P)
    expectedProblems = ["LIRCMOP5_BC","LIRCMOP7_BC", ...
        "LIRCMOP8_BC","LIRCMOP10_BC", ...
        "LIRCMOP12_BC","LIRCMOP14_BC"];
    if P.algorithm ~= "PairGuide" || ...
            ~isequal(P.problems,expectedProblems) || P.epoch ~= 1000 || ...
            ~isequal(P.runs,1:2) || ~isequal(P.sampleSigmas,[1 0.5]) || ...
            P.popSize ~= 100 || P.dimension ~= 30 || ...
            P.rawGuideCount ~= 500 || P.miniBatch ~= 64 || ...
            P.minGANTrainCount ~= 32 || P.expectedRequestedCount ~= 20 || ...
            P.nWorker ~= 10 || ...
            ~ismember(protocolTrainingSigma(P),[1 0.5])
        error('CBSPairGuide:BadSigmaCampaignProtocol', ...
            'The fixed paired inference-sigma protocol was changed.');
    end
    if protocolTrainingSigma(P) == 0.5 && ...
            (~isfield(P,'baselineCampaignName') || ...
             P.schemaVersion ~= "CBS-PairGuide-train-use-sigma-threeway-v1")
        error('CBSPairGuide:BadThreeWaySigmaProtocol', ...
            'The fixed three-way training/use sigma protocol was changed.');
    end
end

function sigma = protocolTrainingSigma(P)
    sigma = 1;
    if isfield(P,'trainingSigma')
        sigma = double(P.trainingSigma);
    end
end

function Tasks = buildTasks(P,resultDir)
    template = struct('problem',"",'run',0,'seed',0, ...
        'sampleSeed',0,'outputFile',"");
    Tasks = repmat(template,numel(P.problems)*numel(P.runs),1);
    row = 0;
    for problem = 1 : numel(P.problems)
        for run = P.runs
            row = row+1;
            Tasks(row).problem = P.problems(problem);
            Tasks(row).run = run;
            Tasks(row).seed = run;
            Tasks(row).sampleSeed = 200000+1000*problem+run;
            Tasks(row).outputFile = string(fullfile(resultDir,sprintf( ...
                '%s_epoch%04d_run%02d.mat',P.problems(problem), ...
                P.epoch,run)));
        end
    end
end

function OutputFile = runTask(rootPath,Task,P)
    cd(rootPath);
    addCBSPaths(rootPath);
    try
        maxNumCompThreads(1);
    catch
    end
    if exist(Task.outputFile,'file') == 2
        if resultComplete(Task,P)
            OutputFile = char(Task.outputFile);
            return;
        end
        error('CBSPairGuide:ExistingInvalidSigmaResult', ...
            'Invalid result exists and will not be overwritten: %s', ...
            Task.outputFile);
    end

    rng(Task.seed,'twister');
    constructor = str2func(char(Task.problem));
    Problem = constructor('N',P.popSize,'D',P.dimension, ...
        'maxFE',P.maxFE,'maxRuntime',Inf);
    parameters = {P.rawGuideCount,P.zDim,P.epoch,P.miniBatch, ...
        P.nCritic,P.minGANTrainCount,P.productionSampleSigma};
    Algorithm = PairGuide('parameter',parameters, ...
        'save',0,'run',Task.run,'outputFcn',@silentOutput);
    Algorithm.configureFirstPairGuideUseCapture(struct( ...
        'enabled',true,'stopAfterUse',true, ...
        'sampleSeed',Task.sampleSeed,'sampleSigmas',P.sampleSigmas, ...
        'trainingSigma',protocolTrainingSigma(P)));

    started = datetime('now','TimeZone','local');
    wallClock = tic;
    Algorithm.Solve(Problem);
    elapsed = toc(wallClock);
    Capture = Algorithm.firstPairGuideUseCapture();
    Audit = Algorithm.guideExperimentSnapshot();
    validateCapture(Task,P,Problem,Capture,Audit);

    EvalProblem = constructor('N',P.popSize,'D',P.dimension, ...
        'maxFE',1e9,'maxRuntime',Inf);
    Snapshots = repmat(emptyArmSnapshot(Problem),numel(P.sampleSigmas),1);
    for arm = 1 : numel(P.sampleSigmas)
        A = Capture.sigmaArms(arm);
        rawCount = size(A.rawDecs,1);
        Population = EvalProblem.Evaluation([A.rawDecs;A.childDecs]);
        Objs = double(Population.objs);
        Cons = double(Population.cons);
        rawObjs = Objs(1:rawCount,:);
        rawCons = Cons(1:rawCount,:);
        childObjs = Objs(rawCount+1:end,:);
        childCons = Cons(rawCount+1:end,:);
        childFeasible = rowFeasible(childCons);
        childDominating = all(childObjs <= A.parentObjs+1e-12,2) & ...
            any(childObjs < A.parentObjs-1e-12,2);
        Snapshots(arm) = struct('sigma',A.sigma, ...
            'poolFE',Capture.poolFE,'useFE',Capture.useFE, ...
            'rawCount',rawCount,'rawObjs',rawObjs,'rawCons',rawCons, ...
            'rawFeasible',rowFeasible(rawCons), ...
            'requestedCount',A.requestedCount, ...
            'guidedCount',A.selectedCount,'fallbackCount',A.fallbackCount, ...
            'guidedObjs',childObjs,'guidedCons',childCons, ...
            'guidedFeasible',childFeasible, ...
            'guidedDominating',childDominating, ...
            'guidedUseful',childFeasible & childDominating, ...
            'parentObjs',double(A.parentObjs), ...
            'constrainedPopulationObjs', ...
                double(Capture.constrainedPopulationObjs), ...
            'constrainedPopulationCons', ...
                double(Capture.constrainedPopulationCons), ...
            'unconstrainedPopulationObjs', ...
                double(Capture.unconstrainedPopulationObjs), ...
            'unconstrainedPopulationCons', ...
                double(Capture.unconstrainedPopulationCons));
    end
    Record = struct('schemaVersion',P.schemaVersion,'status',"ok", ...
        'algorithm',P.algorithm,'problem',Task.problem,'epoch',P.epoch, ...
        'run',Task.run,'seed',Task.seed,'sampleSeed',Task.sampleSeed, ...
        'sampleSigmas',P.sampleSigmas,'N',P.popSize,'D',P.dimension, ...
        'trainingSigma',protocolTrainingSigma(P), ...
        'M',Problem.M,'maxFE',P.maxFE,'startedAt',string(started), ...
        'finishedAt',string(datetime('now')), ...
        'wallClockSeconds',elapsed, ...
        'algorithmRuntimeSeconds',double(Algorithm.metric.runtime), ...
        'searchFE',double(Problem.FE), ...
        'offlineEvaluationFE',double(EvalProblem.FE), ...
        'trainingEvents',double(Audit.pairTrainingEvents));

    OutputFile = char(Task.outputFile);
    partialFile = [OutputFile,'.partial.mat'];
    save(partialFile,'Record','Capture','Snapshots','Audit','-v7.3');
    PartialTask = Task;
    PartialTask.outputFile = string(partialFile);
    if ~resultComplete(PartialTask,P)
        error('CBSPairGuide:InvalidSigmaPartial', ...
            'Saved partial inference-sigma result failed validation.');
    end
    [moved,message] = movefile(partialFile,OutputFile);
    if ~moved
        error('CBSPairGuide:SigmaResultMoveFailed','%s',message);
    end
end

function S = emptyArmSnapshot(Problem)
    S = struct('sigma',NaN,'poolFE',NaN,'useFE',NaN, ...
        'rawCount',0,'rawObjs',zeros(0,Problem.M), ...
        'rawCons',zeros(0,0),'rawFeasible',false(0,1), ...
        'requestedCount',0,'guidedCount',0,'fallbackCount',0, ...
        'guidedObjs',zeros(0,Problem.M),'guidedCons',zeros(0,0), ...
        'guidedFeasible',false(0,1),'guidedDominating',false(0,1), ...
        'guidedUseful',false(0,1),'parentObjs',zeros(0,Problem.M), ...
        'constrainedPopulationObjs',zeros(0,Problem.M), ...
        'constrainedPopulationCons',zeros(0,0), ...
        'unconstrainedPopulationObjs',zeros(0,Problem.M), ...
        'unconstrainedPopulationCons',zeros(0,0));
end

function validateCapture(Task,P,Problem,C,Audit)
    trainingSigma = protocolTrainingSigma(P);
    validArms = C.pairedSampling && numel(C.sigmaArms) == 2 && ...
        isequal([C.sigmaArms.sigma],P.sampleSigmas);
    for arm = 1 : numel(C.sigmaArms)
        A = C.sigmaArms(arm);
        validArms = validArms && size(A.rawDecs,1) == P.rawGuideCount && ...
            size(A.rawDecs,2) == Problem.D && ...
            A.requestedCount == P.expectedRequestedCount && ...
            A.selectedCount+A.fallbackCount == A.requestedCount && ...
            size(A.childDecs,1) == A.selectedCount && ...
            A.sampleTrace.sampleSigma == P.sampleSigmas(arm);
    end
    primaryMatches = isequaln(C.sigmaArms(1).rawDecs,C.rawDecs) && ...
        isequaln(C.sigmaArms(1).selectedCandidateDecs, ...
            C.selectedCandidateDecs) && ...
        isequaln(C.sigmaArms(1).childDecs,C.childDecs);
    if ~C.complete || ~C.trainStatus.trained || ...
            ~C.trainStatus.useModel || C.trainStatus.epochs ~= P.epoch || ...
            C.trainingSigma ~= trainingSigma || ...
            C.trainStatus.trainingSigma ~= trainingSigma || ...
            Problem.FE ~= C.useFE || C.useFE-C.poolFE ~= Problem.N || ...
            ~validArms || ~primaryMatches || ...
            size(C.constrainedPopulationObjs,1) ~= P.popSize || ...
            size(C.unconstrainedPopulationObjs,1) ~= P.popSize || ...
            Audit.rawOracleCount ~= 0 || Audit.pairTrainingEvents ~= 1
        error('CBSPairGuide:BadSigmaCapture', ...
            '%s run %d has an invalid paired capture.',Task.problem,Task.run);
    end
end

function complete = resultComplete(Task,P)
    complete = false;
    if exist(Task.outputFile,'file') ~= 2
        return;
    end
    try
        Data = load(Task.outputFile,'Record','Capture','Snapshots','Audit');
        R = Data.Record;
        C = Data.Capture;
        trainingSigma = protocolTrainingSigma(P);
        trainingMatches = legacyOrMatchingTrainingSigma( ...
            R,C,trainingSigma);
        complete = string(R.schemaVersion) == P.schemaVersion && ...
            string(R.status) == "ok" && string(R.problem) == Task.problem && ...
            R.epoch == P.epoch && R.run == Task.run && ...
            R.seed == Task.seed && R.sampleSeed == Task.sampleSeed && ...
            isequal(R.sampleSigmas,P.sampleSigmas) && ...
            trainingMatches && ...
            R.searchFE == C.useFE && R.trainingEvents == 1 && ...
            C.complete && C.pairedSampling && numel(C.sigmaArms) == 2 && ...
            isequal([C.sigmaArms.sigma],P.sampleSigmas) && ...
            all(arrayfun(@(A)size(A.rawDecs,1) == P.rawGuideCount, ...
                C.sigmaArms)) && numel(Data.Snapshots) == 2 && ...
            Data.Audit.rawOracleCount == 0 && ...
            Data.Audit.pairTrainingEvents == 1;
    catch
        complete = false;
    end
end

function matches = legacyOrMatchingTrainingSigma(R,C,expected)
    recordMatches = isfield(R,'trainingSigma') && ...
        double(R.trainingSigma) == expected;
    captureMatches = isfield(C,'trainingSigma') && ...
        double(C.trainingSigma) == expected && ...
        isfield(C,'trainStatus') && ...
        isfield(C.trainStatus,'trainingSigma') && ...
        double(C.trainStatus.trainingSigma) == expected;
    matches = recordMatches && captureMatches;
    if expected == 1 && ~isfield(R,'trainingSigma') && ...
            ~isfield(C,'trainingSigma') && ...
            (~isfield(C,'trainStatus') || ...
             ~isfield(C.trainStatus,'trainingSigma'))
        matches = true;
    end
end

function mask = tasksComplete(Tasks,P)
    mask = false(numel(Tasks),1);
    for i = 1 : numel(Tasks)
        mask(i) = resultComplete(Tasks(i),P);
    end
end

function Analysis = analyzeCampaign(~,P,Tasks,campaignDir)
%ANALYZECAMPAIGN Quantify thickness, boundary quality, and diversity loss.

    Rows = repmat(emptyMetricRow(),numel(Tasks)*numel(P.sampleSigmas),1);
    Pairs = repmat(emptyPairRow(),numel(Tasks),1);
    row = 0;
    for task = 1 : numel(Tasks)
        Data = load(Tasks(task).outputFile, ...
            'Record','Capture','Snapshots');
        C = Data.Capture;
        constructor = str2func(char(Tasks(task).problem));
        Problem = constructor('N',P.popSize,'D',P.dimension, ...
            'maxFE',1e9,'maxRuntime',Inf);
        baseConstructor = str2func(char(erase(Tasks(task).problem,"_BC")));
        BaseProblem = baseConstructor('N',P.popSize,'D',P.dimension, ...
            'maxFE',1e9,'maxRuntime',Inf);
        lower = double(Problem.lower);
        span = double(Problem.upper)-lower;
        span(span <= eps) = 1;
        W = double(C.referenceVectors);
        Scale = C.referenceScale;
        for arm = 1 : numel(P.sampleSigmas)
            row = row+1;
            A = C.sigmaArms(arm);
            S = Data.Snapshots(arm);
            Continuous = BaseProblem.Evaluation([A.rawDecs;A.childDecs]);
            continuousCons = double(Continuous.cons);
            rawContinuous = continuousCons(1:S.rawCount,:);
            childContinuous = continuousCons(S.rawCount+1:end,:);
            rawCV = constraintViolation(rawContinuous);
            childCV = constraintViolation(childContinuous);
            Xn = (double(A.rawDecs)-lower)./span;
            Yn = (double(S.rawObjs)-double(Scale.minimum))./ ...
                double(Scale.span);
            [decisionWithin,decisionTotal] = cloudRMS(Xn,A.rawRefs);
            [objectiveWithin,objectiveTotal] = cloudRMS(Yn,A.rawRefs);
            assignedRefs = AssignReferenceVectors_CBS(S.rawObjs,W,Scale);
            rawSignature = round(Xn/1e-6);
            Row = emptyMetricRow();
            Row.problem = Tasks(task).problem;
            Row.run = Tasks(task).run;
            Row.trainingSigma = protocolTrainingSigma(P);
            Row.sigma = A.sigma;
            Row.poolFE = C.poolFE;
            Row.useFE = C.useFE;
            Row.wallClockSeconds = Data.Record.wallClockSeconds;
            Row.trainingPairs = C.trainStatus.trainingPairs;
            Row.batchesPerEpoch = C.trainStatus.batchesPerEpoch;
            Row.trainingUpdates = C.trainStatus.updates;
            Row.candidateValidCount = A.poolTrace.validCount;
            Row.candidateValidRate = A.poolTrace.validCount/S.rawCount;
            Row.requestedCount = A.requestedCount;
            Row.guidedCount = A.selectedCount;
            Row.fallbackCount = A.fallbackCount;
            Row.fullQuota = A.selectedCount == A.requestedCount;
            Row.rawFeasibleRate = mean(S.rawFeasible);
            Row.rawInfeasibleRate = mean(rawCV > 0);
            Row.rawBoundaryMarginMedian = constraintMargin(rawContinuous,50);
            Row.rawBoundaryMarginP90 = constraintMargin(rawContinuous,90);
            Row.rawCVMedian = median(rawCV);
            Row.rawDecisionUniqueRate = ...
                size(unique(rawSignature,'rows'),1)/S.rawCount;
            Row.requestedRefCoverage = ...
                numel(unique(A.rawRefs))/size(W,1);
            Row.assignedRefCoverage = ...
                numel(unique(assignedRefs))/size(W,1);
            Row.referenceMatchRate = mean(assignedRefs == A.rawRefs);
            Row.assignedRefEntropy = normalizedEntropy( ...
                assignedRefs,size(W,1));
            Row.decisionWithinRefRMS = decisionWithin;
            Row.decisionTotalRMS = decisionTotal;
            Row.decisionWithinRefRatio = safeRatio( ...
                decisionWithin,decisionTotal);
            Row.objectiveWithinRefRMS = objectiveWithin;
            Row.objectiveTotalRMS = objectiveTotal;
            Row.objectiveWithinRefRatio = safeRatio( ...
                objectiveWithin,objectiveTotal);
            Row.guidedFeasibleRate = safeMean(S.guidedFeasible);
            Row.guidedDominatingRate = safeMean(S.guidedDominating);
            Row.guidedUsefulPerQuota = ...
                sum(S.guidedUseful)/S.requestedCount;
            Row.guidedBoundaryMarginMedian = ...
                constraintMargin(childContinuous,50);
            Row.guidedCVMedian = safeMedian(childCV);
            Rows(row) = Row;
        end
        one = Rows(row-1);
        half = Rows(row);
        A1 = C.sigmaArms(1);
        A2 = C.sigmaArms(2);
        S1 = Data.Snapshots(1);
        S2 = Data.Snapshots(2);
        X1 = (double(A1.rawDecs)-lower)./span;
        X2 = (double(A2.rawDecs)-lower)./span;
        Y1 = (double(S1.rawObjs)-double(Scale.minimum))./double(Scale.span);
        Y2 = (double(S2.rawObjs)-double(Scale.minimum))./double(Scale.span);
        Pairs(task) = struct('problem',Tasks(task).problem, ...
            'run',Tasks(task).run,'poolFE',C.poolFE,'useFE',C.useFE, ...
            'decisionThicknessRatio',safeRatio( ...
                half.decisionWithinRefRMS,one.decisionWithinRefRMS), ...
            'objectiveThicknessRatio',safeRatio( ...
                half.objectiveWithinRefRMS,one.objectiveWithinRefRMS), ...
            'decisionWithinRatioDelta',half.decisionWithinRefRatio- ...
                one.decisionWithinRefRatio, ...
            'objectiveWithinRatioDelta',half.objectiveWithinRefRatio- ...
                one.objectiveWithinRefRatio, ...
            'rawBoundaryMarginRatio',safeRatio( ...
                half.rawBoundaryMarginMedian,one.rawBoundaryMarginMedian), ...
            'rawInfeasibleRateDelta',half.rawInfeasibleRate- ...
                one.rawInfeasibleRate, ...
            'candidateValidRateDelta',half.candidateValidRate- ...
                one.candidateValidRate, ...
            'referenceMatchRateDelta',half.referenceMatchRate- ...
                one.referenceMatchRate, ...
            'uniqueRateDelta',half.rawDecisionUniqueRate- ...
                one.rawDecisionUniqueRate, ...
            'assignedCoverageDelta',half.assignedRefCoverage- ...
                one.assignedRefCoverage, ...
            'entropyDelta',half.assignedRefEntropy-one.assignedRefEntropy, ...
            'guidedCountDelta',half.guidedCount-one.guidedCount, ...
            'guidedFeasibleRateDelta',half.guidedFeasibleRate- ...
                one.guidedFeasibleRate, ...
            'guidedBoundaryMarginRatio',safeRatio( ...
                half.guidedBoundaryMarginMedian, ...
                one.guidedBoundaryMarginMedian), ...
            'guidedUsefulPerQuotaDelta',half.guidedUsefulPerQuota- ...
                one.guidedUsefulPerQuota, ...
            'pairedRawDecisionRMS',sqrt(mean(sum((X2-X1).^2,2))), ...
            'pairedRawObjectiveRMS',sqrt(mean(sum((Y2-Y1).^2,2))));
    end
    ArmMetrics = struct2table(Rows);
    PairedDeltas = struct2table(Pairs);
    PerProblem = aggregateArms(ArmMetrics,P,true);
    Overall = aggregateArms(ArmMetrics,P,false);
    PairSummary = summarizePairs(PairedDeltas);
    analysisDir = fullfile(campaignDir,'analysis');
    ensureFolder(analysisDir);
    writetable(ArmMetrics,fullfile(analysisDir,'arm_metrics.csv'));
    writetable(PairedDeltas,fullfile(analysisDir,'paired_deltas.csv'));
    writetable(PerProblem,fullfile(analysisDir,'per_problem_sigma.csv'));
    writetable(Overall,fullfile(analysisDir,'overall_sigma.csv'));
    writetable(PairSummary,fullfile(analysisDir,'paired_summary.csv'));
    Analysis = struct('schemaVersion',P.schemaVersion, ...
        'campaignName',P.campaignName,'trainingTaskCount',numel(Tasks), ...
        'armCount',height(ArmMetrics),'pairCount',height(PairedDeltas), ...
        'pairedSameModelQueryNoiseAndMutation',true, ...
        'finishedAt',string(datetime('now')));
    save(fullfile(analysisDir,'sigma_analysis.mat'), ...
        'Analysis','ArmMetrics','PairedDeltas','PerProblem','Overall', ...
        'PairSummary');
    lines = ["PairGuide inference sigma paired analysis"; ...
        "Epoch: "+P.epoch; ...
        "Pairs: "+height(PairedDeltas); ...
        "Median decision thickness ratio (0.5 / 1): "+ ...
            PairSummary.decisionThicknessRatioMedian; ...
        "Median objective thickness ratio (0.5 / 1): "+ ...
            PairSummary.objectiveThicknessRatioMedian; ...
        "Decision thickness improved pairs: "+ ...
            PairSummary.decisionThicknessImproved+" / "+height(PairedDeltas); ...
        "Objective thickness improved pairs: "+ ...
            PairSummary.objectiveThicknessImproved+" / "+height(PairedDeltas)];
    writelines(lines,fullfile(analysisDir,'summary.txt'));
end

function Summary = analyzeThreeWayCampaign(rootPath,P,Tasks,campaignDir)
%ANALYZETHREEWAYCAMPAIGN Isolate training sigma at fixed use sigma=0.5.

    baselineDir = fullfile(rootPath,'Data',char(P.baselineCampaignName));
    baselineFile = fullfile(baselineDir,'analysis','arm_metrics.csv');
    newFile = fullfile(campaignDir,'analysis','arm_metrics.csv');
    if exist(baselineFile,'file') ~= 2
        error('CBSPairGuide:MissingBaselineSigmaMetrics', ...
            'Missing reusable baseline metrics: %s',baselineFile);
    end
    Old = readtable(baselineFile,'TextType','string');
    New = readtable(newFile,'TextType','string');
    Old.problem = string(Old.problem);
    New.problem = string(New.problem);
    if ~ismember("trainingSigma",string(Old.Properties.VariableNames))
        Old.trainingSigma = ones(height(Old),1);
    end
    if ~isequal(sort(string(Old.Properties.VariableNames)), ...
            sort(string(New.Properties.VariableNames)))
        error('CBSPairGuide:ThreeWayMetricSchemaMismatch', ...
            'Baseline and new metric schemas are incompatible.');
    end
    Old = Old(:,New.Properties.VariableNames);
    OldOne = Old(abs(Old.sigma-1) <= eps,:);
    OldHalf = Old(abs(Old.sigma-0.5) <= eps,:);
    NewHalf = New(abs(New.sigma-0.5) <= eps,:);
    expected = numel(Tasks);
    if height(OldOne) ~= expected || height(OldHalf) ~= expected || ...
            height(NewHalf) ~= expected
        error('CBSPairGuide:ThreeWayMetricCountMismatch', ...
            'Each displayed arm must contain exactly %d rows.',expected);
    end
    OldOne = tagThreeWayArm(OldOne,1,"train1_use1",1,1);
    OldHalf = tagThreeWayArm(OldHalf,2,"train1_use0p5",1,0.5);
    NewHalf = tagThreeWayArm(NewHalf,3,"train0p5_use0p5",0.5,0.5);
    ThreeWayMetrics = [OldOne;OldHalf;NewHalf];
    ThreeWayMetrics.problemOrder = problemOrder( ...
        ThreeWayMetrics.problem,P.problems);
    ThreeWayMetrics = sortrows(ThreeWayMetrics, ...
        {'problemOrder','run','armOrder'});
    ThreeWayMetrics.problemOrder = [];

    Effects = repmat(emptyTrainingSigmaEffectRow(),expected,1);
    for task = 1 : expected
        keyProblem = Tasks(task).problem;
        keyRun = Tasks(task).run;
        baseline = OldHalf(OldHalf.problem == keyProblem & ...
            OldHalf.run == keyRun,:);
        half = NewHalf(NewHalf.problem == keyProblem & ...
            NewHalf.run == keyRun,:);
        if height(baseline) ~= 1 || height(half) ~= 1 || ...
                baseline.poolFE ~= half.poolFE || ...
                baseline.useFE ~= half.useFE || ...
                baseline.trainingPairs ~= half.trainingPairs || ...
                baseline.trainingUpdates ~= half.trainingUpdates
            error('CBSPairGuide:UnpairedTrainingSigmaMetrics', ...
                '%s run %d is not an exact training-sigma pair.', ...
                keyProblem,keyRun);
        end
        Effects(task) = trainingSigmaEffectRow( ...
            keyProblem,keyRun,baseline,half);
    end
    TrainingSigmaEffects = struct2table(Effects);
    PerProblem = aggregateThreeWay(ThreeWayMetrics,P,true);
    Overall = aggregateThreeWay(ThreeWayMetrics,P,false);
    EffectSummary = summarizeTrainingSigmaEffects(TrainingSigmaEffects);
    analysisDir = fullfile(campaignDir,'analysis');
    writetable(ThreeWayMetrics, ...
        fullfile(analysisDir,'three_way_arm_metrics.csv'));
    writetable(TrainingSigmaEffects, ...
        fullfile(analysisDir,'training_sigma_effect_deltas.csv'));
    writetable(PerProblem, ...
        fullfile(analysisDir,'three_way_per_problem.csv'));
    writetable(Overall,fullfile(analysisDir,'three_way_overall.csv'));
    writetable(EffectSummary, ...
        fullfile(analysisDir,'training_sigma_effect_summary.csv'));
    Summary = struct('schemaVersion',P.schemaVersion, ...
        'campaignName',P.campaignName,'displayedArmCount', ...
        height(ThreeWayMetrics),'trainingEffectPairCount', ...
        height(TrainingSigmaEffects), ...
        'trainingEffectComparison', ...
        "train0.5/use0.5 versus train1/use0.5", ...
        'decisionThicknessRatioMedian', ...
        EffectSummary.decisionThicknessRatioMedian, ...
        'objectiveThicknessRatioMedian', ...
        EffectSummary.objectiveThicknessRatioMedian, ...
        'finishedAt',string(datetime('now')));
    save(fullfile(analysisDir,'three_way_analysis.mat'), ...
        'Summary','ThreeWayMetrics','TrainingSigmaEffects', ...
        'PerProblem','Overall','EffectSummary');
    lines = ["PairGuide three-way train/use sigma analysis"; ...
        "Epoch: "+P.epoch; ...
        "Training-effect pairs: "+height(TrainingSigmaEffects); ...
        "Comparison: train0.5/use0.5 versus train1/use0.5"; ...
        "Median decision thickness ratio: "+ ...
            EffectSummary.decisionThicknessRatioMedian; ...
        "Median objective thickness ratio: "+ ...
            EffectSummary.objectiveThicknessRatioMedian; ...
        "Decision thickness improved pairs: "+ ...
            EffectSummary.decisionThicknessImproved+" / "+expected; ...
        "Objective thickness improved pairs: "+ ...
            EffectSummary.objectiveThicknessImproved+" / "+expected];
    writelines(lines,fullfile(analysisDir,'three_way_summary.txt'));
end

