function renderOne(Problem,Task,P,Capture,Snapshots,View,outputFile)
    Figure = figure('Visible','off','Color','w', ...
        'Position',[80,80,1800,900]);
    cleanup = onCleanup(@()close(Figure));
    Layout = tiledlayout(Figure,1,2,'Padding','compact', ...
        'TileSpacing','compact');
    for arm = 1 : numel(Snapshots)
        Ax = nexttile(Layout,arm);
        plotArm(Ax,Problem,Task,Capture.sigmaArms(arm), ...
            Snapshots(arm),View,1,true);
    end
    sgtitle(Layout,sprintf( ...
        '%s | Epoch %d | run %d | first-use FE %s | same model, QueryC, Z_0', ...
        Task.problem,P.epoch,Task.run,commaNumber(Capture.useFE)), ...
        'Interpreter','none','FontName','Helvetica', ...
        'FontWeight','bold','FontSize',15);
    partialFile = [outputFile,'.partial.png'];
    exportgraphics(Figure,partialFile,'Resolution',170, ...
        'BackgroundColor','white');
    if ~validPNG(partialFile)
        error('CBSPairGuide:InvalidSigmaPNG', ...
            'Rendered PNG failed validation: %s',partialFile);
    end
    [moved,message] = movefile(partialFile,outputFile);
    if ~moved
        error('CBSPairGuide:SigmaPNGMoveFailed','%s',message);
    end
    clear cleanup;
end

