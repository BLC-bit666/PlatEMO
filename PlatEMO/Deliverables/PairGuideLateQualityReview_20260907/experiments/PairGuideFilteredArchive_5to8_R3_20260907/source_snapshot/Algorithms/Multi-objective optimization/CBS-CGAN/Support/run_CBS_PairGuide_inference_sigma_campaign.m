function valid = validPNG(file)
    valid = false;
    if exist(file,'file') ~= 2
        return;
    end
    try
        Info = imfinfo(file);
        valid = strcmpi(Info.Format,'png') && ...
            Info.Width >= 1500 && Info.Height >= 700;
    catch
        valid = false;
    end
end

function feasible = rowFeasible(Cons)
    feasible = constraintViolation(Cons) <= 0;
end

function CV = constraintViolation(Cons)
    if isempty(Cons)
        CV = zeros(size(Cons,1),1);
    else
        CV = sum(max(0,double(Cons)),2);
    end
end

function value = constraintMargin(Cons,percentile)
    if isempty(Cons)
        value = NaN;
    else
        distance = min(abs(double(Cons)),[],2);
        value = empiricalQuantile(distance,percentile/100);
    end
end

function value = safeMean(X)
    if isempty(X)
        value = NaN;
    else
        value = mean(double(X));
    end
end

function value = safeMedian(X)
    if isempty(X)
        value = NaN;
    else
        value = median(double(X),'omitnan');
    end
end

function value = safeRatio(numerator,denominator)
    if isfinite(numerator) && isfinite(denominator) && denominator > 0
        value = numerator/denominator;
    else
        value = NaN;
    end
end

function textValue = commaNumber(value)
    textValue = regexprep(sprintf('%.0f',value), ...
        '(?<!\d)(\d{1,3})(?=(\d{3})+(?!\d))','$1,');
end

function [pool,ownsPool] = exactPool(nWorker)
    pool = gcp('nocreate');
    ownsPool = isempty(pool);
    if ownsPool
        pool = parpool("Processes",nWorker);
    elseif pool.NumWorkers ~= nWorker
        error('CBSPairGuide:SigmaWorkerCount', ...
            'Existing pool must contain exactly %d workers.',nWorker);
    end
end

function closeOwnedPool(pool,ownsPool)
    if ownsPool && ~isempty(pool) && isvalid(pool)
        delete(pool);
    end
end

