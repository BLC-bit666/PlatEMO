function [within,total] = cloudRMS(X,groups)
    X = double(X);
    groups = reshape(double(groups),[],1);
    valid = all(isfinite(X),2) & isfinite(groups);
    X = X(valid,:);
    groups = groups(valid);
    if isempty(X)
        within = NaN;
        total = NaN;
        return;
    end
    center = mean(X,1);
    total = sqrt(mean(sum((X-center).^2,2)));
    squared = zeros(size(X,1),1);
    for value = reshape(unique(groups),1,[])
        rows = groups == value;
        localCenter = mean(X(rows,:),1);
        squared(rows) = sum((X(rows,:)-localCenter).^2,2);
    end
    within = sqrt(mean(squared));
end

function value = normalizedEntropy(refs,count)
    refs = reshape(double(refs),[],1);
    refs = refs(isfinite(refs) & refs >= 1 & refs <= count);
    if isempty(refs) || count <= 1
        value = 0;
        return;
    end
    counts = accumarray(refs,1,[count,1]);
    p = counts(counts > 0)/numel(refs);
    value = -sum(p.*log(p))/log(count);
end

