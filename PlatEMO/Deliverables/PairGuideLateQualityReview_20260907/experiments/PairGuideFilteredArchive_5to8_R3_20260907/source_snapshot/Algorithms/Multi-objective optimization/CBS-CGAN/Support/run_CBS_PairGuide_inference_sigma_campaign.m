function validateThreeWayResultPair(Task,Old,New)
    OC = Old.Capture;
    NC = New.Capture;
    samePreUse = OC.poolFE == NC.poolFE && OC.useFE == NC.useFE && ...
        isequaln(OC.constrainedPopulationObjs, ...
            NC.constrainedPopulationObjs) && ...
        isequaln(OC.constrainedPopulationCons, ...
            NC.constrainedPopulationCons) && ...
        isequaln(OC.unconstrainedPopulationObjs, ...
            NC.unconstrainedPopulationObjs) && ...
        isequaln(OC.unconstrainedPopulationCons, ...
            NC.unconstrainedPopulationCons) && ...
        isequaln(OC.referenceVectors,NC.referenceVectors) && ...
        isequaln(OC.referenceScale,NC.referenceScale) && ...
        isequaln(OC.sigmaArms(2).rawRefs,NC.sigmaArms(2).rawRefs);
    if ~samePreUse || NC.trainingSigma ~= 0.5 || ...
            NC.trainStatus.trainingSigma ~= 0.5 || ...
            Old.Record.run ~= New.Record.run || ...
            string(Old.Record.problem) ~= string(New.Record.problem)
        error('CBSPairGuide:UnpairedThreeWayResult', ...
            '%s run %d is not an exact three-way pair.', ...
            Task.problem,Task.run);
    end
end

