function View = informativeView(Snapshots,M)
    Raw = zeros(0,M);
    Required = zeros(0,M);
    for arm = 1 : numel(Snapshots)
        S = Snapshots(arm);
        Raw = [Raw;double(S.rawObjs(:,1:M))]; %#ok<AGROW>
        Required = [Required;double(S.guidedObjs(:,1:M))]; %#ok<AGROW>
    end
    Required = [Required;double(Snapshots(1).constrainedPopulationObjs(:,1:M)); ...
        double(Snapshots(1).unconstrainedPopulationObjs(:,1:M))];
    lower = nan(1,3);
    upper = nan(1,3);
    for objective = 1 : M
        raw = Raw(isfinite(Raw(:,objective)),objective);
        required = Required(isfinite(Required(:,objective)),objective);
        lo = empiricalQuantile(raw,0.01);
        hi = empiricalQuantile(raw,0.99);
        if ~isempty(required)
            lo = min(lo,min(required));
            hi = max(hi,max(required));
        end
        width = hi-lo;
        if ~isfinite(width) || width <= eps(max(1,max(abs([lo hi]))))
            width = max(1,max(abs([lo hi])));
        end
        lower(objective) = max(0,lo-0.05*width);
        upper(objective) = hi+0.05*width;
    end
    outside = any(~isfinite(Raw),2);
    finite = ~outside;
    outside(finite) = any(Raw(finite,:) < lower(1:M) | ...
        Raw(finite,:) > upper(1:M),2);
    View = struct('lower',lower,'upper',upper, ...
        'rawOutside',sum(outside));
end

function value = empiricalQuantile(X,probability)
    X = sort(double(X(:)));
    if isempty(X)
        value = 0;
    elseif isscalar(X)
        value = X;
    else
        position = 1+(numel(X)-1)*probability;
        lo = floor(position);
        hi = ceil(position);
        fraction = position-lo;
        value = X(lo)+fraction*(X(hi)-X(lo));
    end
end

