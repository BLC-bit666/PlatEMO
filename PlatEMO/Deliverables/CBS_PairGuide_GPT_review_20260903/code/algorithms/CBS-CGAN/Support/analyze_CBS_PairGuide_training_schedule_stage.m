function resultFile = resolveResultFile(outputFile,stageDir,rootPath)
    outputFile = char(outputFile);
    candidates = {outputFile,fullfile(stageDir,outputFile), ...
        fullfile(rootPath,outputFile)};
    resultFile = '';
    for i = 1 : numel(candidates)
        if isfile(candidates{i})
            resultFile = candidates{i};
            break;
        end
    end
    if isempty(resultFile)
        error('CBSPairGuide:MissingScheduleResult', ...
            'Missing result file: %s',outputFile);
    end
end

function validateRecordParameters(Record,Task,resultFile)
    if ~isstruct(Record) || ~isscalar(Record)
        error('CBSPairGuide:BadScheduleRecord', ...
            'Record must be a scalar struct: %s',resultFile);
    end
    fields = {'initialEpoch','retrainEpoch','nCritic'};
    for field = fields
        name = field{1};
        if ~isfield(Record,name) || ~isnumeric(Record.(name)) || ...
                ~isscalar(Record.(name)) || ...
                double(Record.(name)) ~= double(Task.(name))
            error('CBSPairGuide:ScheduleParameterMismatch', ...
                'Record.%s does not match task: %s',name,resultFile);
        end
    end
    if isfield(Record,'stageName') && ...
            string(Record.stageName) ~= string(Task.resultStage)
        error('CBSPairGuide:ScheduleResultStageMismatch', ...
            'Record.stageName does not match task.resultStage: %s', ...
            resultFile);
    end
end

function [FE,IGD,FeasibleCount] = trajectoryVectors(T,resultFile)
    required = {'FE','IGD','FeasibleCount'};
    if istable(T)
        names = T.Properties.VariableNames;
        for field = required
            if ~ismember(field{1},names)
                error('CBSPairGuide:BadScheduleTrajectory', ...
                    'Trajectory lacks %s: %s',field{1},resultFile);
            end
        end
        FE = double(T.FE(:));
        IGD = double(T.IGD(:));
        FeasibleCount = double(T.FeasibleCount(:));
    elseif isstruct(T) && all(isfield(T,required))
        if isscalar(T)
            FE = double(T.FE(:));
            IGD = double(T.IGD(:));
            FeasibleCount = double(T.FeasibleCount(:));
        else
            FE = double(reshape([T.FE],[],1));
            IGD = double(reshape([T.IGD],[],1));
            FeasibleCount = double(reshape([T.FeasibleCount],[],1));
        end
    else
        error('CBSPairGuide:BadScheduleTrajectory', ...
            'Trajectory must expose FE, IGD, and FeasibleCount: %s', ...
            resultFile);
    end
    if numel(FE) < 2 || numel(IGD) ~= numel(FE) || ...
            numel(FeasibleCount) ~= numel(FE) || ...
            any(~isfinite(FE)) || any(IGD(isfinite(IGD)) < 0) || ...
            any(~isfinite(FeasibleCount))
        error('CBSPairGuide:InvalidScheduleTrajectory', ...
            'Trajectory values are incomplete or invalid: %s',resultFile);
    end
    [FE,order] = sort(FE);
    IGD = IGD(order);
    FeasibleCount = FeasibleCount(order);
    if any(diff(FE) <= 0)
        error('CBSPairGuide:NonIncreasingScheduleFE', ...
            'Trajectory FE values must be unique and increasing: %s', ...
            resultFile);
    end
end

function S = buildIGDPenalties(Tasks,problems,stageDir,rootPath)
    template = struct('problem',"",'finiteValueCount',0, ...
        'nonfiniteValueCount',0,'maximumFiniteIGD',NaN,'penalty',NaN);
    Rows = repmat(template,numel(problems),1);
    taskProblems = string({Tasks.problem})';
    for i = 1 : numel(problems)
        maximum = -Inf;
        finiteCount = 0;
        nonfiniteCount = 0;
        taskRows = find(taskProblems == problems(i));
        for j = taskRows'
            resultFile = resolveResultFile( ...
                Tasks(j).outputFile,stageDir,rootPath);
            Data = load(resultFile,'Trajectory');
            if ~isfield(Data,'Trajectory')
                error('CBSPairGuide:IncompleteScheduleResult', ...
                    'Result lacks Trajectory: %s',resultFile);
            end
            [~,IGD,~] = trajectoryVectors(Data.Trajectory,resultFile);
            finite = IGD(isfinite(IGD));
            finiteCount = finiteCount+numel(finite);
            nonfiniteCount = nonfiniteCount+nnz(~isfinite(IGD));
            if ~isempty(finite)
                maximum = max(maximum,max(finite));
            end
        end
        if finiteCount == 0
            error('CBSPairGuide:NoFiniteScheduleIGD', ...
                'Problem %s has no finite IGD in any arm, run, or FE.', ...
                problems(i));
        end
        penalty = 10*max(maximum,realmin);
        Rows(i) = struct('problem',problems(i), ...
            'finiteValueCount',finiteCount, ...
            'nonfiniteValueCount',nonfiniteCount, ...
            'maximumFiniteIGD',maximum,'penalty',penalty);
    end
    S = struct2table(Rows);
end

function value = valueAtFE(FE,Y,targetFE,resultFile,name)
    tolerance = 16*eps(max(targetFE,FE(end)));
    if FE(1) > targetFE+tolerance || FE(end) < targetFE-tolerance
        error('CBSPairGuide:ScheduleTrajectoryTooShort', ...
            'Trajectory does not cover FE=%g for %s: %s', ...
            targetFE,name,resultFile);
    end
    exact = find(abs(FE-targetFE) <= tolerance,1,'last');
    if isempty(exact)
        value = interp1(FE,Y,targetFE,'linear');
    else
        value = Y(exact);
    end
end

function value = recordString(Record,name)
    if isfield(Record,name)
        value = string(Record.(name));
    else
        value = "";
    end
end

function value = recordNumber(Record,name)
    if isfield(Record,name) && isnumeric(Record.(name)) && ...
            isscalar(Record.(name))
        value = double(Record.(name));
    else
        value = NaN;
    end
end

function [Rows,Summary] = expandTrainingDiagnostics( ...
        Audit,Task,Identity,resultFile)
    requiredAudit = {'pairTrainingLog','pairInitialEpoch', ...
        'pairRetrainEpoch','nCritic'};
    if ~isstruct(Audit) || ~isscalar(Audit) || ...
            ~all(isfield(Audit,requiredAudit))
        error('CBSPairGuide:BadTrainingDiagnosticsAudit', ...
            'Audit lacks the pair training schedule/log: %s',resultFile);
    end
    if double(Audit.pairInitialEpoch) ~= double(Task.initialEpoch) || ...
            double(Audit.pairRetrainEpoch) ~= double(Task.retrainEpoch) || ...
            double(Audit.nCritic) ~= double(Task.nCritic)
        error('CBSPairGuide:TrainingDiagnosticsScheduleMismatch', ...
            'Audit training schedule does not match task: %s',resultFile);
    end
    Log = Audit.pairTrainingLog(:);
    if isempty(Log) || ~isstruct(Log)
        error('CBSPairGuide:MissingTrainingDiagnostics', ...
            'Audit.pairTrainingLog is empty: %s',resultFile);
    end
    requiredEvent = {'fe','kind','nCritic','epochs','trainingPairs', ...
        'changedPairs','newRegions','updates','pairVisits', ...
        'batchesPerEpoch','preAllRelationRMSE', ...
        'preChangedRelationRMSE','preCriticGap', ...
        'preGeneratedNearestMedian','preGeneratedSpread', ...
        'postAllRelationRMSE','postChangedRelationRMSE', ...
        'postCriticGap','postGeneratedNearestMedian', ...
        'postGeneratedSpread'};
    if ~all(isfield(Log,requiredEvent))
        error('CBSPairGuide:IncompleteTrainingDiagnostics', ...
            'Training log fields are incomplete: %s',resultFile);
    end
    if isfield(Audit,'pairTrainingEvents') && ...
            double(Audit.pairTrainingEvents) ~= numel(Log)
        error('CBSPairGuide:TrainingDiagnosticsCountMismatch', ...
            'Audit training-event count does not match its log: %s', ...
            resultFile);
    end
    Rows = repmat(emptyDiagnosticRow(),numel(Log),1);
    eventFE = nan(numel(Log),1);
    for i = 1 : numel(Log)
        Event = Log(i);
        kind = string(Event.kind);
        expectedKind = "retrain";
        expectedEpochs = double(Task.retrainEpoch);
        if i == 1
            expectedKind = "initial";
            expectedEpochs = double(Task.initialEpoch);
        end
        if ~isscalar(kind) || kind ~= expectedKind || ...
                ~numericScalarEquals(Event.epochs,expectedEpochs) || ...
                ~numericScalarEquals(Event.nCritic,double(Task.nCritic))
            error('CBSPairGuide:TrainingDiagnosticsEventMismatch', ...
                'Event %d must be %s with epochs=%g and nCritic=%g: %s', ...
                i,expectedKind,expectedEpochs,Task.nCritic,resultFile);
        end
        numericFields = {'fe','nCritic','epochs','trainingPairs', ...
            'changedPairs','newRegions','updates','pairVisits', ...
            'batchesPerEpoch'};
        for field = numericFields
            value = Event.(field{1});
            if ~isnumeric(value) || ~isscalar(value) || ...
                    ~isfinite(double(value)) || double(value) < 0
                error('CBSPairGuide:InvalidTrainingDiagnosticValue', ...
                    'Event %d has invalid %s: %s', ...
                    i,field{1},resultFile);
            end
        end
        diagnosticFields = requiredEvent(11:end);
        for field = diagnosticFields
            value = Event.(field{1});
            if ~isnumeric(value) || ~isscalar(value)
                error('CBSPairGuide:InvalidTrainingDiagnosticValue', ...
                    'Event %d has invalid %s: %s', ...
                    i,field{1},resultFile);
            end
        end
        eventFE(i) = double(Event.fe);
        Row = emptyDiagnosticRow();
        Row.taskIndex = Identity.taskIndex;
        Row.stageName = Identity.stageName;
        Row.factorName = Identity.factorName;
        Row.armName = Identity.armName;
        Row.armValue = Identity.armValue;
        Row.problem = Identity.problem;
        Row.run = Identity.run;
        Row.seed = Identity.seed;
        Row.resultStage = Identity.resultStage;
        Row.reused = Identity.reused;
        Row.outputFile = Identity.outputFile;
        Row.eventIndex = i;
        Row.FE = double(Event.fe);
        Row.kind = kind;
        Row.nCritic = double(Event.nCritic);
        Row.epochs = double(Event.epochs);
        Row.trainingPairs = double(Event.trainingPairs);
        Row.changedPairs = double(Event.changedPairs);
        Row.newRegions = double(Event.newRegions);
        Row.updates = double(Event.updates);
        Row.pairVisits = double(Event.pairVisits);
        Row.batchesPerEpoch = double(Event.batchesPerEpoch);
        names = ["AllRelationRMSE","ChangedRelationRMSE", ...
            "CriticGap","GeneratedNearestMedian","GeneratedSpread"];
        for name = names
            preName = char("pre"+name);
            postName = char("post"+name);
            deltaName = char("delta"+name);
            Row.(preName) = double(Event.(preName));
            Row.(postName) = double(Event.(postName));
            Row.(deltaName) = Row.(postName)-Row.(preName);
        end
        Rows(i) = Row;
    end
    if any(diff(eventFE) <= 0)
        error('CBSPairGuide:NonIncreasingTrainingDiagnosticFE', ...
            'Training-event FE must be strictly increasing: %s',resultFile);
    end
    Summary = struct( ...
        'trainingEventCount',numel(Log), ...
        'retrainEventCount',numel(Log)-1, ...
        'medianPostAllRelationRMSE', ...
            finiteMedian([Rows.postAllRelationRMSE]), ...
        'medianPostChangedRelationRMSE', ...
            finiteMedian([Rows.postChangedRelationRMSE]), ...
        'medianPostCriticGap',finiteMedian([Rows.postCriticGap]), ...
        'medianPostGeneratedNearest', ...
            finiteMedian([Rows.postGeneratedNearestMedian]), ...
        'medianPostGeneratedSpread', ...
            finiteMedian([Rows.postGeneratedSpread]));
end

