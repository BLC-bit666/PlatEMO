function tf = numericScalarEquals(value,expected)
    tf = isnumeric(value) && isscalar(value) && ...
        isfinite(double(value)) && double(value) == expected;
end

function value = finiteMedian(X)
    X = double(X(isfinite(X)));
    if isempty(X)
        value = NaN;
    else
        value = median(X);
    end
end

function [T,blockCount] = addBlockScores(T,arms,problems,runs)
    T.blockIndex = zeros(height(T),1);
    T.blockCombinedScore = nan(height(T),1);
    block = 0;
    for problem = problems'
        for run = runs'
            block = block+1;
            rows = find(T.problem == problem & T.run == run);
            if numel(rows) ~= numel(arms)
                error('CBSPairGuide:UnpairedScheduleMetrics', ...
                    'Incomplete metric block for %s run %g.',problem,run);
            end
            minGAUC = min(T.gAUC(rows));
            minEndpoint = min(T.IGD100K(rows));
            T.blockIndex(rows) = block;
            T.blockCombinedScore(rows) = sqrt( ...
                safeRatio(T.gAUC(rows),minGAUC) .* ...
                safeRatio(T.IGD100K(rows),minEndpoint));
        end
    end
    blockCount = block;
end

function [bestArm,scores] = numericalBest(T,arms)
    scores = nan(numel(arms),1);
    for i = 1 : numel(arms)
        scores(i) = median(T.blockCombinedScore(T.armValue == arms(i)));
    end
    order = sortrows([scores,arms],[1 2]);
    bestArm = order(1,2);
end

function T = addBestRatios(T,bestArm)
    T.gAUCRatioToBest = nan(height(T),1);
    T.IGD100KRatioToBest = nan(height(T),1);
    for block = unique(T.blockIndex)'
        rows = find(T.blockIndex == block);
        reference = rows(T.armValue(rows) == bestArm);
        if numel(reference) ~= 1
            error('CBSPairGuide:MissingNumericalBestPair', ...
                'Numerical-best arm missing from block %d.',block);
        end
        T.gAUCRatioToBest(rows) = safeRatio( ...
            T.gAUC(rows),T.gAUC(reference));
        T.IGD100KRatioToBest(rows) = safeRatio( ...
            T.IGD100K(rows),T.IGD100K(reference));
    end
end

function ratio = safeRatio(value,reference)
    denominator = max(reference,realmin);
    ratio = value./denominator;
    ratio(value == 0 & reference == 0) = 1;
end

