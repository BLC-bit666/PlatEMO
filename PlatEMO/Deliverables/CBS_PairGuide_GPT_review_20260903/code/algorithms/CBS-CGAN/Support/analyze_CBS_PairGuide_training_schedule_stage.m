function Analysis = analyze_CBS_PairGuide_training_schedule_stage( ...
        rootPath,campaignName,stageName)
%ANALYZE_CBS_PAIRGUIDE_TRAINING_SCHEDULE_STAGE Analyze one paired stage.

    if nargin < 1 || isempty(rootPath)
        rootPath = fileparts(which('platemo'));
    end
    if nargin < 2 || isempty(campaignName)
        error('CBSPairGuide:MissingCampaignName', ...
            'campaignName is required.');
    end
    if nargin < 3 || isempty(stageName)
        error('CBSPairGuide:MissingStageName','stageName is required.');
    end
    rootPath = char(rootPath);
    campaignName = string(campaignName);
    stageName = string(stageName);
    stageDir = fullfile(rootPath,'Data',char(campaignName),char(stageName));
    manifestFile = fullfile(stageDir,'campaign_manifest.mat');
    if ~isfile(manifestFile)
        error('CBSPairGuide:MissingScheduleManifest', ...
            'Missing campaign manifest: %s',manifestFile);
    end
    Manifest = load(manifestFile,'Protocol','Tasks');
    if ~isfield(Manifest,'Protocol') || ~isfield(Manifest,'Tasks')
        error('CBSPairGuide:BadScheduleManifest', ...
            'Manifest must contain Protocol and Tasks.');
    end
    P = Manifest.Protocol;
    Tasks = Manifest.Tasks;
    [arms,problems,runs,factorName] = validateProtocol(P,stageName);
    validateTaskGrid(Tasks,arms,problems,runs);
    IGDPenalties = buildIGDPenalties(Tasks,problems,stageDir,rootPath);

    Rows = repmat(emptyTaskRow(),numel(Tasks),1);
    DiagnosticParts = cell(numel(Tasks),1);
    for i = 1 : numel(Tasks)
        Task = Tasks(i);
        resultFile = resolveResultFile(Task.outputFile,stageDir,rootPath);
        Data = load(resultFile,'Record','Trajectory','Snapshots','Audit');
        required = {'Record','Trajectory','Snapshots','Audit'};
        for field = required
            if ~isfield(Data,field{1})
                error('CBSPairGuide:IncompleteScheduleResult', ...
                    'Result lacks %s: %s',field{1},resultFile);
            end
        end
        validateRecordParameters(Data.Record,Task,resultFile);
        [FE,IGD,FeasibleCount] = trajectoryVectors( ...
            Data.Trajectory,resultFile);
        penaltyRow = IGDPenalties.problem == string(Task.problem);
        penalty = IGDPenalties.penalty(penaltyRow);
        rawIGD100K = valueAtFE(FE,IGD,1e5,resultFile,'IGD');
        nonfinite = ~isfinite(IGD);
        analyzedIGD = IGD;
        analyzedIGD(nonfinite) = penalty;
        gAUC = exp(trapz(FE,log(max(analyzedIGD,realmin))) / ...
            (FE(end)-FE(1)));
        IGD100K = valueAtFE(FE,analyzedIGD,1e5,resultFile,'IGD');
        feasible100K = valueAtFE(FE,FeasibleCount,1e5, ...
            resultFile,'FeasibleCount');

        Row = emptyTaskRow();
        Row.taskIndex = i;
        Row.stageName = stageName;
        Row.factorName = factorName;
        Row.armName = factorName+"="+compose('%g',Task.armValue);
        Row.armValue = double(Task.armValue);
        Row.problem = string(Task.problem);
        Row.run = double(Task.run);
        Row.seed = double(Task.seed);
        Row.initialEpoch = double(Task.initialEpoch);
        Row.retrainEpoch = double(Task.retrainEpoch);
        Row.nCritic = double(Task.nCritic);
        Row.resultStage = string(Task.resultStage);
        Row.reused = logical(Task.reused);
        Row.outputFile = string(resultFile);
        Row.sourceStageName = recordString(Data.Record,'stageName');
        Row.sourceArmName = recordString(Data.Record,'armName');
        Row.sourceArmValue = recordNumber(Data.Record,'armValue');
        Row.trajectoryPoints = numel(FE);
        Row.firstFE = FE(1);
        Row.lastFE = FE(end);
        Row.igdPenalty = penalty;
        Row.nonfiniteIGDCount = nnz(nonfinite);
        Row.gAUC = gAUC;
        Row.rawIGD100K = rawIGD100K;
        Row.IGD100K = IGD100K;
        Row.feasibleCount100K = feasible100K;
        Row.snapshotCount = numel(Data.Snapshots);
        Row.auditPresent = ~isempty(Data.Audit);
        Row.wallClockSeconds = recordNumber(Data.Record, ...
            'wallClockSeconds');
        [DiagnosticParts{i},TrainingSummary] = ...
            expandTrainingDiagnostics(Data.Audit,Task,Row,resultFile);
        Row.trainingEventCount = TrainingSummary.trainingEventCount;
        Row.retrainEventCount = TrainingSummary.retrainEventCount;
        Row.medianPostAllRelationRMSE = ...
            TrainingSummary.medianPostAllRelationRMSE;
        Row.medianPostChangedRelationRMSE = ...
            TrainingSummary.medianPostChangedRelationRMSE;
        Row.medianPostCriticGap = TrainingSummary.medianPostCriticGap;
        Row.medianPostGeneratedNearest = ...
            TrainingSummary.medianPostGeneratedNearest;
        Row.medianPostGeneratedSpread = ...
            TrainingSummary.medianPostGeneratedSpread;
        Rows(i) = Row;
    end
    TaskMetrics = struct2table(Rows);
    TrainingDiagnostics = struct2table(vertcat(DiagnosticParts{:}));
    [TaskMetrics,blockCount] = addBlockScores( ...
        TaskMetrics,arms,problems,runs);
    [numericalBestArm,numericalScores] = numericalBest( ...
        TaskMetrics,arms);
    TaskMetrics = addBestRatios(TaskMetrics,numericalBestArm);
    ProblemSummary = summarizeProblems(TaskMetrics,arms,problems);
    ArmSummary = summarizeArms(TaskMetrics,ProblemSummary,arms, ...
        numericalScores,numericalBestArm);
    DiagnosticSummary = summarizeTrainingDiagnostics( ...
        TrainingDiagnostics,arms);
    selectedArm = min(ArmSummary.armValue(ArmSummary.eligible));
    ArmSummary.selected = ArmSummary.armValue == selectedArm;

    analysisDir = fullfile(stageDir,'analysis');
    if ~isfolder(analysisDir), mkdir(analysisDir); end
    writetable(TaskMetrics,fullfile(analysisDir,'task_metrics.csv'));
    writetable(ArmSummary,fullfile(analysisDir,'arm_summary.csv'));
    writetable(ProblemSummary,fullfile(analysisDir, ...
        'problem_summary.csv'));
    writetable(TrainingDiagnostics,fullfile(analysisDir, ...
        'training_diagnostics.csv'));

    isRatioStage = strcmpi(factorName,"nCritic") || ...
        contains(lower(stageName),"ratio");
    RepresentativeRuns = table();
    representativeRule = "";
    if isRatioStage
        RepresentativeRuns = selectRepresentativeRuns( ...
            TaskMetrics,selectedArm,problems);
        writetable(RepresentativeRuns,fullfile(analysisDir, ...
            'representative_runs.csv'));
        save(fullfile(analysisDir,'representative_runs.mat'), ...
            'RepresentativeRuns');
        representativeRule = ...
            "second-lowest sqrt((gAUC/within-problem median gAUC)*"+ ...
            "(IGD100K/within-problem median IGD100K)) for selected arm";
    end

    Analysis = struct( ...
        'schemaVersion',P.schemaVersion, ...
        'campaignName',campaignName, ...
        'stageName',stageName, ...
        'factorName',factorName, ...
        'arms',arms(:)', ...
        'problems',problems(:)', ...
        'runs',runs(:)', ...
        'maxFE',double(P.maxFE), ...
        'taskCount',height(TaskMetrics), ...
        'blockCount',blockCount, ...
        'numericalBestArm',numericalBestArm, ...
        'recommendedArm',selectedArm, ...
        'selectedNCritic',NaN, ...
        'selectedRetrainEpoch',NaN, ...
        'overallMedianRatioLimit',1.05, ...
        'perProblemMedianRatioLimit',1.10, ...
        'igdPenaltyRule', ...
        "replace nonfinite IGD with 10 times that problem's maximum finite IGD", ...
        'problemIGDPenalties',IGDPenalties, ...
        'trainingEventCount',height(TrainingDiagnostics), ...
        'retrainEventCount',nnz(TrainingDiagnostics.kind == "retrain"), ...
        'trainingDiagnosticsAffectSelection',false, ...
        'trainingDiagnosticSummary',DiagnosticSummary, ...
        'trainingDiagnosticNote', ...
        "descriptive overfit/collapse evidence; arm gate remains gAUC and IGD100K only", ...
        'recommendationRule', ...
        "smallest arm passing both metric ratio gates", ...
        'representativeRule',representativeRule, ...
        'finishedAt',string(datetime('now')));
    if isRatioStage
        Analysis.selectedNCritic = selectedArm;
    elseif strcmpi(factorName,"retrainEpoch")
        Analysis.selectedRetrainEpoch = selectedArm;
    end
    save(fullfile(analysisDir,'stage_analysis.mat'), ...
        'Analysis','TaskMetrics','ArmSummary','ProblemSummary', ...
        'RepresentativeRuns','IGDPenalties','TrainingDiagnostics', ...
        'DiagnosticSummary');
    writeRecommendation(analysisDir,Analysis,ArmSummary);
end

function [arms,problems,runs,factorName] = validateProtocol(P,stageName)
    required = {'schemaVersion','stageName','armName','arms','problems', ...
        'runs','maxFE'};
    for field = required
        if ~isfield(P,field{1})
            error('CBSPairGuide:BadScheduleProtocol', ...
                'Protocol lacks %s.',field{1});
        end
    end
    if string(P.stageName) ~= stageName
        error('CBSPairGuide:ScheduleStageMismatch', ...
            'Requested stage %s, manifest contains %s.', ...
            stageName,string(P.stageName));
    end
    arms = double(P.arms(:));
    problems = string(P.problems(:));
    runs = double(P.runs(:));
    factorName = string(P.armName);
    if isempty(arms) || any(~isfinite(arms)) || numel(unique(arms)) ~= numel(arms)
        error('CBSPairGuide:BadScheduleArms', ...
            'Protocol.arms must be unique finite numeric values.');
    end
    if isempty(problems) || any(strlength(problems) == 0) || ...
            numel(unique(problems)) ~= numel(problems)
        error('CBSPairGuide:BadScheduleProblems', ...
            'Protocol.problems must be unique nonempty names.');
    end
    if isempty(runs) || any(~isfinite(runs)) || ...
            numel(unique(runs)) ~= numel(runs)
        error('CBSPairGuide:BadScheduleRuns', ...
            'Protocol.runs must be unique finite values.');
    end
    if numel(problems)*numel(runs) ~= 30
        error('CBSPairGuide:BadScheduleBlockCount', ...
            'Schedule decision requires six problems by five runs (30 blocks).');
    end
    if ~isscalar(P.maxFE) || P.maxFE < 1e5
        error('CBSPairGuide:InsufficientScheduleFE', ...
            'Protocol.maxFE must reach 100000.');
    end
end

function validateTaskGrid(Tasks,arms,problems,runs)
    required = {'problem','armValue','run','seed','initialEpoch', ...
        'retrainEpoch','nCritic','outputFile','resultStage','reused'};
    for field = required
        if ~isfield(Tasks,field{1})
            error('CBSPairGuide:BadScheduleTasks', ...
                'Tasks lack %s.',field{1});
        end
    end
    expected = numel(arms)*numel(problems)*numel(runs);
    if numel(Tasks) ~= expected
        error('CBSPairGuide:IncompleteScheduleGrid', ...
            'Expected %d paired tasks, found %d.',expected,numel(Tasks));
    end
    taskProblems = string({Tasks.problem})';
    taskArms = double([Tasks.armValue])';
    taskRuns = double([Tasks.run])';
    for problem = problems'
        for run = runs'
            for arm = arms'
                count = nnz(taskProblems == problem & taskRuns == run & ...
                    taskArms == arm);
                if count ~= 1
                    error('CBSPairGuide:UnpairedScheduleGrid', ...
                        'Expected one task for problem=%s, run=%g, arm=%g; found %d.', ...
                        problem,run,arm,count);
                end
            end
        end
    end
end

