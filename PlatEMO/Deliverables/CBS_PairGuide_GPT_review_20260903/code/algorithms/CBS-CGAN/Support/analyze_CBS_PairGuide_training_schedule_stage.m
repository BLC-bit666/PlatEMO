function S = summarizeArms(T,ProblemSummary,arms,numericalScores,bestArm)
    template = struct('stageName',"",'factorName',"",'armName',"", ...
        'armValue',NaN,'blockCount',0,'gAUCMedian',NaN, ...
        'IGD100KMedian',NaN,'numericalScore',NaN, ...
        'gAUCRatioToBestMedian',NaN,'gAUCRatioCILow',NaN, ...
        'gAUCRatioCIHigh',NaN,'IGD100KRatioToBestMedian',NaN, ...
        'IGD100KRatioCILow',NaN,'IGD100KRatioCIHigh',NaN, ...
        'overallWithinFivePercent',false, ...
        'allProblemsWithinTenPercent',false,'signrankP',NaN, ...
        'holmP',NaN,'eligible',false,'selected',false);
    Rows = repmat(template,numel(arms),1);
    for i = 1 : numel(arms)
        X = T(T.armValue == arms(i),:);
        PX = ProblemSummary(ProblemSummary.armValue == arms(i),:);
        gRatio = median(X.gAUCRatioToBest);
        endpointRatio = median(X.IGD100KRatioToBest);
        [gLow,gHigh] = bootstrapMedianCI(X.gAUCRatioToBest, ...
            20260901+2*i);
        [eLow,eHigh] = bootstrapMedianCI(X.IGD100KRatioToBest, ...
            20260902+2*i);
        overallGate = gRatio <= 1.05 && endpointRatio <= 1.05;
        problemGate = all(PX.withinTenPercent);
        Rows(i) = struct( ...
            'stageName',X.stageName(1), ...
            'factorName',X.factorName(1), ...
            'armName',X.armName(1), ...
            'armValue',arms(i), ...
            'blockCount',height(X), ...
            'gAUCMedian',median(X.gAUC), ...
            'IGD100KMedian',median(X.IGD100K), ...
            'numericalScore',numericalScores(i), ...
            'gAUCRatioToBestMedian',gRatio, ...
            'gAUCRatioCILow',gLow, ...
            'gAUCRatioCIHigh',gHigh, ...
            'IGD100KRatioToBestMedian',endpointRatio, ...
            'IGD100KRatioCILow',eLow, ...
            'IGD100KRatioCIHigh',eHigh, ...
            'overallWithinFivePercent',overallGate, ...
            'allProblemsWithinTenPercent',problemGate, ...
            'signrankP',pairedSignrank(T,arms(i),bestArm), ...
            'holmP',NaN, ...
            'eligible',overallGate && problemGate, ...
            'selected',false);
    end
    S = struct2table(Rows);
    S.holmP = holmAdjust(S.signrankP,S.armValue ~= bestArm);
end

