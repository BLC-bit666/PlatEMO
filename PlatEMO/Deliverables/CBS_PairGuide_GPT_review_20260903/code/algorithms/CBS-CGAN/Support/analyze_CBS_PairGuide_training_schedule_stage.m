function [low,high] = bootstrapMedianCI(X,seed)
    X = X(isfinite(X));
    if isempty(X)
        low = NaN;
        high = NaN;
        return;
    end
    stream = RandStream('mt19937ar','Seed',seed);
    indices = randi(stream,numel(X),numel(X),2000);
    estimates = sort(median(X(indices),1));
    low = percentile(estimates,0.025);
    high = percentile(estimates,0.975);
end

function value = percentile(sortedValues,p)
    position = 1+(numel(sortedValues)-1)*p;
    lower = floor(position);
    upper = ceil(position);
    if lower == upper
        value = sortedValues(lower);
    else
        weight = position-lower;
        value = sortedValues(lower)*(1-weight)+sortedValues(upper)*weight;
    end
end

function p = pairedSignrank(T,arm,bestArm)
    p = NaN;
    if arm == bestArm || exist('signrank','file') == 0
        return;
    end
    A = sortrows(T(T.armValue == arm,:), 'blockIndex');
    B = sortrows(T(T.armValue == bestArm,:), 'blockIndex');
    if height(A) ~= height(B) || any(A.blockIndex ~= B.blockIndex)
        return;
    end
    scoreA = 0.5*(log(max(A.gAUC,realmin))+ ...
        log(max(A.IGD100K,realmin)));
    scoreB = 0.5*(log(max(B.gAUC,realmin))+ ...
        log(max(B.IGD100K,realmin)));
    try
        p = signrank(scoreA,scoreB);
    catch
        p = NaN;
    end
end

function adjusted = holmAdjust(p,include)
    adjusted = nan(size(p));
    indices = find(include & isfinite(p));
    if isempty(indices), return; end
    [ordered,order] = sort(p(indices));
    count = numel(ordered);
    values = min(1,(count-(1:count)'+1).*ordered);
    values = cummax(values);
    adjusted(indices(order)) = values;
end

function R = selectRepresentativeRuns(T,selectedArm,problems)
    template = struct('stageName',"",'factorName',"",'armName',"", ...
        'armValue',NaN,'problem',"",'run',NaN, ...
        'rankWithinProblem',2,'representativeScore',NaN, ...
        'gAUC',NaN,'IGD100K',NaN,'seed',NaN,'outputFile',"", ...
        'snapshotCount',0);
    Rows = repmat(template,numel(problems),1);
    for i = 1 : numel(problems)
        X = T(T.armValue == selectedArm & T.problem == problems(i),:);
        if height(X) < 2
            error('CBSPairGuide:InsufficientRepresentativeRuns', ...
                'Need at least two runs for %s.',problems(i));
        end
        medianGAUC = median(X.gAUC);
        medianEndpoint = median(X.IGD100K);
        score = sqrt(safeRatio(X.gAUC,medianGAUC) .* ...
            safeRatio(X.IGD100K,medianEndpoint));
        X.representativeScore = score;
        X = sortrows(X,{'representativeScore','IGD100K','run'}, ...
            {'ascend','ascend','ascend'});
        chosen = X(2,:);
        Rows(i) = struct( ...
            'stageName',chosen.stageName, ...
            'factorName',chosen.factorName, ...
            'armName',chosen.armName, ...
            'armValue',chosen.armValue, ...
            'problem',chosen.problem, ...
            'run',chosen.run, ...
            'rankWithinProblem',2, ...
            'representativeScore',chosen.representativeScore, ...
            'gAUC',chosen.gAUC, ...
            'IGD100K',chosen.IGD100K, ...
            'seed',chosen.seed, ...
            'outputFile',chosen.outputFile, ...
            'snapshotCount',chosen.snapshotCount);
    end
    R = struct2table(Rows);
end

function writeRecommendation(analysisDir,A,S)
    selected = S(S.armValue == A.recommendedArm,:);
    numerical = S(S.armValue == A.numericalBestArm,:);
    lines = [ ...
        "PairGuide training-schedule analysis"; ...
        "Stage: "+A.stageName; ...
        "Factor: "+A.factorName; ...
        "Paired blocks: "+A.blockCount; ...
        "Numerical-best arm: "+compose('%g',A.numericalBestArm); ...
        "Recommended arm: "+compose('%g',A.recommendedArm); ...
        "Recommended gAUC median ratio: "+ ...
            compose('%.6g',selected.gAUCRatioToBestMedian); ...
        "Recommended IGD100K median ratio: "+ ...
            compose('%.6g',selected.IGD100KRatioToBestMedian); ...
        "Numerical-best paired score: "+ ...
            compose('%.6g',numerical.numericalScore); ...
        "Gate: both overall median ratios <= 1.05"; ...
        "Gate: both five-run problem median ratios <= 1.10"; ...
        "Decision: smallest arm passing both gates"; ...
        "Training diagnostics: descriptive only; selection gate unchanged"; ...
        "IGD penalty: "+A.igdPenaltyRule];
    Penalties = A.problemIGDPenalties;
    penaltyLines = "Penalty "+Penalties.problem+": "+ ...
        compose('%.9g',Penalties.penalty)+ ...
        " (nonfinite values="+Penalties.nonfiniteValueCount+")";
    lines = [lines;penaltyLines];
    if strlength(A.representativeRule) > 0
        lines(end+1) = "Representative run: "+A.representativeRule;
    end
    writelines(lines,fullfile(analysisDir,'recommendation.txt'));
end
