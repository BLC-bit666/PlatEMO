function Results = run_CCMO_GAN_BDG_localmad_ngen_experiments( ...
        workerCount,problemNames,N,D,maxFE,runIds)
%run_CCMO_GAN_BDG_localmad_ngen_experiments Run local-MAD/nGen controls.
%   Four runs isolate training-set local decision outlier weighting and
%   CGAN injection pressure under the GND_keep80 archive setup.

    rootDir = fileparts(which('platemo'));
    addpath(genpath(rootDir));
    if nargin < 1 || isempty(workerCount)
        workerCount = 8;
    end
    if nargin < 2 || isempty(problemNames)
        problemNames = defaultProblemList_localmadNGen_BDG();
    end
    if nargin < 3 || isempty(N)
        N = 100;
    end
    if nargin < 4
        D = [];
    end
    if nargin < 5 || isempty(maxFE)
        maxFE = 100000;
    end
    if nargin < 6 || isempty(runIds)
        runIds = 1:3;
    end

    workerCount = max(1,round(double(workerCount)));
    variants = ["GND_keep80_nGen50"; ...
        "GND_keep80_nGen20"; ...
        "GND_keep80_localMAD_nGen50"; ...
        "GND_keep80_localMAD_nGen20"];
    variantSets = ["gnd_keep80_ngen50"; ...
        "gnd_keep80_ngen20"; ...
        "gnd_keep80_localmad_ngen50"; ...
        "gnd_keep80_localmad_ngen20"];
    nGenValues = [50;20;50;20];
    trainFilterModes = ["condition_knn"; ...
        "condition_knn"; ...
        "local_mad_weight"; ...
        "local_mad_weight"];
    stamp = char(datetime('now','Format','yyyyMMdd_HHmmss'));
    baseDir = fullfile(rootDir,'Data','CCMO_GAN_BDG');
    if ~isfolder(baseDir)
        mkdir(baseDir);
    end

    Rows = repmat(emptyLocalMADNGenRunRow_BDG(),numel(variants),1);
    for i = 1 : numel(variants)
        outDir = fullfile(baseDir,sprintf( ...
            '%s_runs%d_n%d_fe%d_%dw_%s', ...
            char(variants(i)),numel(runIds),round(double(N)), ...
            round(double(maxFE)),workerCount,stamp));
        Rows(i).variant = variants(i);
        Rows(i).variantSet = variantSets(i);
        Rows(i).trainFilterMode = trainFilterModes(i);
        Rows(i).nGen = nGenValues(i);
        Rows(i).outDir = string(outDir);
        try
            run_CCMO_GAN_BDG_archive_pareto_filters_fullscope( ...
                outDir,workerCount,problemNames,N,D,maxFE,runIds, ...
                variantSets(i),localMADNGenAlgorithmParams_BDG(nGenValues(i)), ...
                false);
            Rows(i).status = "ok";
        catch err
            Rows(i).status = "failed";
            Rows(i).error_message = string(getReport(err,'extended', ...
                'hyperlinks','off'));
        end
    end

    Results = struct2table(Rows);
    writetable(Results,fullfile(baseDir,sprintf( ...
        'localmad_ngen_experiment_dirs_%s.csv',stamp)));
end

function Params = localMADNGenAlgorithmParams_BDG(nGen)
    Params = {1,nGen,4,5,0.20,50,0,200,0,1,1,1, ...
        "g2sl",64,0.9,1e-4,1e-4,"epoch"};
end

function Row = emptyLocalMADNGenRunRow_BDG()
    Row = struct('variant',"",'variantSet',"", ...
        'trainFilterMode',"",'nGen',NaN,'outDir',"", ...
        'status',"not_started",'error_message',"");
end

