function test_CBS_query_condition_ablation_runner_smoke()
%TEST_CBS_QUERY_CONDITION_ABLATION_RUNNER_SMOKE Check A/B/C condition runner.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    outDir = fullfile(tempdir,sprintf('cbs_query_condition_ablation_%s', ...
        char(java.util.UUID.randomUUID)));
    Options = struct( ...
        'workerCount',1, ...
        'problemNames',"DASCMOP1_BC", ...
        'N',10, ...
        'D',[], ...
        'maxFE',260, ...
        'runIds',1, ...
        'targets',220, ...
        'pairCount',3, ...
        'plotRun',0, ...
        'baseAlgorithmParams',{{1,1,4,2,1,8,1e-4,2e-4,0,1,1,4,1,1,1,0.10,1}});

    [Summary,RootDir,StageMetrics,FigureManifest,VariantManifest] = ...
        run_CBS_CGAN_query_condition_ablation(outDir,Options);

    assert(isfolder(RootDir), ...
        'Query-condition ablation runner should create the requested root dir.');
    assert(height(VariantManifest) == 3, ...
        'Runner should create one variant row per condition mode.');
    assert(isequal(string(VariantManifest.variant(:)), ...
        ["A_ref_tau";"B_ref_y_tau";"C_ref_y"]), ...
        'Variant manifest should use the planned A/B/C condition names.');
    assert(height(Summary) == 3 && all(string(Summary.status) == "ok"), ...
        'Runner should finish 3 condition variants x 1 run.');
    assert(all(Summary.figure_count == 0) && isempty(FigureManifest), ...
        'plotRun=0 must disable all figures in the condition ablation.');
    pngFiles = dir(fullfile(RootDir,'**','*.png'));
    assert(isempty(pngFiles), ...
        'Condition ablation with plotRun=0 must not write PNG files.');
    assert(height(StageMetrics) == 3, ...
        'Stage metrics should include every condition variant at the target.');
    required = ["variant","condition_mode","maxCandidatePairsPerRef"];
    for i = 1 : numel(required)
        assert(ismember(required(i),string(StageMetrics.Properties.VariableNames)), ...
            'Stage metrics missing condition-ablation column: %s',required(i));
    end
    assert(isequal(string(StageMetrics.condition_mode(:)), ...
        ["ref_tau";"ref_y_tau";"ref_y"]), ...
        'Stage metrics should preserve the condition mode used by each variant.');
    assert(all(StageMetrics.maxCandidatePairsPerRef == 3), ...
        'Condition ablation must keep K fixed at the requested pair count.');
    assert(isfile(fullfile(RootDir,'comparison_summary.csv')), ...
        'Runner should write comparison_summary.csv.');
    assert(isfile(fullfile(RootDir,'comparison_stage_metrics_all.csv')), ...
        'Runner should write comparison_stage_metrics_all.csv.');
    assert(isfile(fullfile(RootDir,'paired_variant_deltas.csv')), ...
        'Runner should write paired_variant_deltas.csv.');

    fprintf('CBS-CGAN query-condition ablation runner smoke passed: %s\n',RootDir);
end
