function test_CBS_support_eval_contract()
%TEST_CBS_SUPPORT_EVAL_CONTRACT Verify support eval scripts use CBS pair conditions.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    rng(31,'twister');
    tempRoot = fullfile(tempdir,sprintf('cbs_support_eval_%s', ...
        char(java.util.UUID.randomUUID)));
    captureDir = fullfile(tempRoot,'DASCMOP1_BC_run1');
    mkdir(captureDir);
    captureFile = fullfile(captureDir,'captured_dataset.mat');
    Data = makeCapturedData();
    save(captureFile,'Data');

    holdoutOptions = struct( ...
        'holdoutModulo',4, ...
        'holdoutRemainder',0, ...
        'queryPerCondition',1, ...
        'ganIter',1);
    Summary = run_CBS_CGAN_holdout_ref_eval(captureFile,[],holdoutOptions);
    assert(height(Summary) == 1 && string(Summary.status(1)) == "ok", ...
        'Holdout ref eval must run with [reference,tau] conditions.');

    baselineOptions = struct( ...
        'holdoutModulo',4, ...
        'holdoutRemainder',0, ...
        'samplesPerCondition',1, ...
        'mutationSigma',0.01);
    Baseline = run_CBS_CGAN_non_cgan_baseline_eval( ...
        captureFile,[],baselineOptions);
    assert(height(Baseline) == 3 && all(string(Baseline.status) == "ok"), ...
        'Non-CGAN baselines must run with [reference,tau] conditions.');

    fprintf('CBS support eval contract regressions passed.\n');
end

function Data = makeCapturedData()
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [1.00 0.00;0.67 0.33;0.33 0.67;0.00 1.00];
    n = size(W,1);
    Xf = repmat(Problem.lower,n,1) + rand(n,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,n,1);
    Xi = min(Problem.upper,Xf + 0.02);
    BMem = struct( ...
        'ref',(1:n)', ...
        'y_b',W, ...
        'gap',0.05*ones(n,1), ...
        'x_b',Xf, ...
        'x_f',Xf, ...
        'y_f',W, ...
        'x_i',Xi, ...
        'y_i',W + 0.05*[-ones(n,1),ones(n,1)], ...
        'tau',linspace(0,1,n)');
    Data = struct();
    Data.BMem = BMem;
    Data.W = W;
    Data.DatasetInfo = struct( ...
        'objMin',[0 0], ...
        'objSpan',[1 1]);
    Data.GANOptions = struct( ...
        'zDim',2, ...
        'iter',1, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',2e-4, ...
        'dPretrainIter',0, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'sigma',0.05, ...
        'reconstructionHuberDelta',0.10, ...
        'reconstructionWeight',1, ...
        'pairMargin',0.05, ...
        'pairMarginWeight',1);
end
