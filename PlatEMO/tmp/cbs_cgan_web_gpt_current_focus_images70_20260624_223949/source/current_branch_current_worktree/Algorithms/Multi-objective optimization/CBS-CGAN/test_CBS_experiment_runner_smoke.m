function test_CBS_experiment_runner_smoke()
%TEST_CBS_EXPERIMENT_RUNNER_SMOKE Minimal CBS-CGAN experiment runner check.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    outDir = fullfile(tempdir,sprintf('cbs_cgan_runner_smoke_%s', ...
        char(java.util.UUID.randomUUID)));
    Options = struct( ...
        'plotRun',0, ...
        'conditionMode',"ref_y_tau", ...
        'algorithmParams',{{1,1,4,2,1,8,1e-4,2e-4,0,1,1,4,1,1,1,0.10,1}});

    [Summary,~,Metrics,Figures] = run_CBS_CGAN_boundary_quality_experiments( ...
        outDir,1,"DASCMOP1_BC",10,[],260,3,220,Options);

    assert(height(Summary) == 1 && string(Summary.status(1)) == "ok", ...
        'Smoke runner should finish one tiny CBS-CGAN run.');
    requiredMetrics = ["finite_gap_count","inf_gap_count", ...
        "median_gap","max_gap","boundary_dist50","boundary_dist90", ...
        "segment_width90","segment_width90_ratio","side_rate", ...
        "pair_margin50","ref_cover","query_width90","feasible_rate", ...
        "query_obj_dist50","query_obj_dist90", ...
        "bmem_ref_coverage","condition_dim","train_param_ratio", ...
        "gan_sample_reuse","train_pair_dec_dist50", ...
        "train_pair_dec_dist90","train_tau_iqr", ...
        "train_tau_range","train_tau_nonzero_rate", ...
        "missing_ref_query_count","large_gap_query_count", ...
        "generated_per_train","condition_mode", ...
        "missing_ref_query_obj_dist90","large_gap_query_obj_dist90"];
    for i = 1 : numel(requiredMetrics)
        assert(ismember(requiredMetrics(i),string(Metrics.Properties.VariableNames)), ...
            'Missing metric column: %s',requiredMetrics(i));
    end
    assert(all(string(Metrics.condition_mode) == "ref_y_tau"), ...
        'Runner must propagate conditionMode into stage metrics.');
    forbiddenMetrics = ["train_dec_rmse","train_obj_dist50", ...
        "train_obj_dist90","train_feasible_rate", ...
        "generated_new_ref_hit_rate","holdout_ref_hit_rate", ...
        "novel_useful_rate"];
    for i = 1 : numel(forbiddenMetrics)
        assert(~ismember(forbiddenMetrics(i), ...
            string(Metrics.Properties.VariableNames)), ...
            'Misleading metric column should be removed: %s', ...
            forbiddenMetrics(i));
    end
    assert(isfile(Summary.history_metrics_file(1)), ...
        'Smoke runner should write per-generation history metrics.');
    History = readtable(Summary.history_metrics_file(1), ...
        'TextType','string','VariableNamingRule','preserve');
    for i = 1 : numel(requiredMetrics)
        assert(ismember(requiredMetrics(i),string(History.Properties.VariableNames)), ...
            'Missing history metric column: %s',requiredMetrics(i));
    end
    assert(all(string(History.condition_mode) == "ref_y_tau"), ...
        'Runner must propagate conditionMode into history metrics.');
    assert(height(Figures) == 0 && Summary.figure_count(1) == 0, ...
        'plotRun=0 must disable all stage and diagnostic figures.');
    pngFiles = dir(fullfile(outDir,'**','*.png'));
    assert(isempty(pngFiles), ...
        'plotRun=0 must not write PNG figures.');
    assert(isfile(fullfile(outDir,'run_summary.csv')), ...
        'Smoke runner should write run_summary.csv.');
    assert(isfile(fullfile(outDir,'stage_metrics_all.csv')), ...
        'Smoke runner should write stage_metrics_all.csv.');
    assert(isfile(fullfile(outDir,'history_metrics_all.csv')), ...
        'Smoke runner should write history_metrics_all.csv.');

    fprintf('CBS-CGAN experiment runner smoke passed: %s\n',outDir);
end
