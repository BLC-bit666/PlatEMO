function [RunSummary,VariantSummary,outRoot] = ...
        run_CCMO_GAN_BDG_compact_margin_validation( ...
        workerCount,problemNames,N,D,maxFE,runIds)
%run_CCMO_GAN_BDG_compact_margin_validation Validate margin-aware compact targets.
%   Compares the retained E6 iter30 fused branch, compact pair-cell geometry,
%   and compact pair-cell constraint-margin selection under the same setting.

    rootDir = fileparts(which('platemo'));
    addpath(genpath(rootDir));
    if nargin < 1 || isempty(workerCount)
        workerCount = 8;
    end
    if nargin < 2 || isempty(problemNames)
        problemNames = all8ProblemList_BDG();
    end
    if nargin < 3 || isempty(N)
        N = 100;
    end
    if nargin < 4
        D = [];
    end
    if nargin < 5 || isempty(maxFE)
        maxFE = 100000;
    end
    if nargin < 6 || isempty(runIds)
        runIds = 1:3;
    end

    workerCount = max(1,round(double(workerCount)));
    problemNames = cellstr(string(problemNames(:)));
    runIds = double(runIds(:)');
    assert(workerCount == 8 || maxFE < 100000, ...
        'run_CCMO_GAN_BDG_compact_margin_validation:BadWorkerCount', ...
        'Formal compact margin validation requires workerCount=8.');

    stamp = char(datetime('now','Format','yyyyMMdd_HHmmss'));
    outRoot = fullfile(rootDir,'Data','CCMO_GAN_BDG', ...
        ['compact_margin_validation_',stamp]);
    mkdir(outRoot);
    targets = min(100000,double(maxFE));

    Specs = buildValidationSpecs_BDG();
    Manifest = repmat(emptyManifestRow_BDG(),numel(Specs),1);
    RunTables = cell(numel(Specs),1);
    for i = 1 : numel(Specs)
        Spec = Specs(i);
        fprintf('=== %s (%d/%d) ===\n',Spec.label,i,numel(Specs));
        [Manifest(i),RunTables{i}] = runOneSpec_BDG(Spec,outRoot, ...
            workerCount,problemNames,N,D,maxFE,runIds,targets);
        writetable(struct2table(Manifest(1:i)),fullfile(outRoot, ...
            'compact_margin_manifest.csv'));
    end

    RunSummary = vertcat(RunTables{:});
    writetable(RunSummary,fullfile(outRoot, ...
        'compact_margin_run_summary.csv'));
    VariantSummary = summarizeValidationRuns_BDG(RunSummary);
    writetable(VariantSummary,fullfile(outRoot, ...
        'compact_margin_variant_summary.csv'));
end

function [Manifest,RunSummary] = runOneSpec_BDG(Spec,outRoot, ...
        workerCount,problemNames,N,D,maxFE,runIds,targets)
    Manifest = emptyManifestRow_BDG();
    Manifest.label = Spec.label;
    Manifest.variant = Spec.variant;
    Manifest.ganIter = Spec.ganIter;
    Manifest.ganTrainMode = Spec.ganTrainMode;
    Manifest.trainBundleMode = Spec.control.trainBundleMode;
    Manifest.pairCellMaxPerPair = Spec.control.pairCellMaxPerPair;
    Manifest.pairCellSelectionMode = Spec.control.pairCellSelectionMode;
    Manifest.status = "not_started";
    Manifest.outDir = string(fullfile(outRoot,char(Spec.label)));
    mkdir(char(Manifest.outDir));

    try
        diagOptions = struct( ...
            'variant',Spec.variant, ...
            'control',Spec.control, ...
            'algorithmParams',{algorithmParams_BDG( ...
                Spec.ganIter,Spec.ganTrainMode)}, ...
            'conditionCount',30, ...
            'zPerCondition',10, ...
            'normalN',200, ...
            'seed',20260617);
        [Summary,actualOutDir] = run_CCMO_GAN_BDG_boundary_diagnostics( ...
            char(Manifest.outDir),workerCount,problemNames,N,D,maxFE, ...
            runIds,targets,diagOptions);
        Manifest.outDir = string(actualOutDir);
        Summary.label = repmat(Spec.label,height(Summary),1);
        Summary.ganIter = repmat(Spec.ganIter,height(Summary),1);
        Summary.ganTrainMode = repmat(Spec.ganTrainMode,height(Summary),1);
        Summary.trainBundleMode = repmat(Spec.control.trainBundleMode, ...
            height(Summary),1);
        Summary.pairCellMaxPerPair = repmat( ...
            Spec.control.pairCellMaxPerPair,height(Summary),1);
        Summary.pairCellSelectionMode = repmat( ...
            Spec.control.pairCellSelectionMode,height(Summary),1);
        RunSummary = appendCoreTailMetrics_BDG(Summary);
        if all(string(RunSummary.status) == "ok")
            Manifest.status = "ok";
        else
            Manifest.status = "has_error";
        end
    catch err
        Manifest.status = "failed";
        Manifest.error_message = string(getReport(err,'extended', ...
            'hyperlinks','off'));
        RunSummary = table();
    end
end

function Summary = appendCoreTailMetrics_BDG(Summary)
    metrics = ["runtime_core_est","t_target_build","t_target_filter", ...
        "t_gan_train","target_pair_count","target_triple_count", ...
        "target_near_segment_keep_count","target_filter_pre_count", ...
        "target_filter_post_count","target_filter_retain_ratio", ...
        "target_weak_segment_candidate_count","target_skipped_pair_count", ...
        "target_compact_cell_max_per_pair", ...
        "target_pair_cell_selection_mode_code", ...
        "target_constraint_margin_count","target_constraint_margin_min", ...
        "target_constraint_margin_mean","target_constraint_margin_abs_mean", ...
        "target_constraint_margin_max","bundle_pair_count", ...
        "bundle_pair_cov","gan_g_loss_count","BoundaryHit_all", ...
        "GAN_to_Segment_Dist50","GAN_to_Segment_Dist90", ...
        "RawGANFeasibleRate"];
    for j = 1 : numel(metrics)
        Summary.(char(metrics(j))) = nan(height(Summary),1);
    end
    for i = 1 : height(Summary)
        fileName = "";
        if ismember("core_metrics_file",string(Summary.Properties.VariableNames))
            fileName = string(Summary.core_metrics_file(i));
        end
        if strlength(fileName) == 0 || ~isfile(fileName)
            continue;
        end
        Core = readtable(fileName,'TextType','string');
        if height(Core) == 0
            continue;
        end
        last = Core(end,:);
        names = string(last.Properties.VariableNames);
        for j = 1 : numel(metrics)
            name = metrics(j);
            if any(names == name)
                Summary.(char(name))(i) = double(last.(char(name)));
            end
        end
    end
end

function VariantSummary = summarizeValidationRuns_BDG(RunSummary)
    if isempty(RunSummary)
        VariantSummary = table();
        return;
    end
    groupVars = {'label','variant','ganTrainMode','ganIter', ...
        'trainBundleMode','pairCellMaxPerPair','pairCellSelectionMode'};
    metricVars = ["runtime_core_est","t_target_build","t_target_filter", ...
        "t_gan_train","target_pair_count","target_triple_count", ...
        "target_near_segment_keep_count","target_filter_pre_count", ...
        "target_filter_post_count","target_filter_retain_ratio", ...
        "target_weak_segment_candidate_count","target_skipped_pair_count", ...
        "target_compact_cell_max_per_pair", ...
        "target_pair_cell_selection_mode_code", ...
        "target_constraint_margin_count","target_constraint_margin_min", ...
        "target_constraint_margin_mean","target_constraint_margin_abs_mean", ...
        "target_constraint_margin_max","bundle_pair_count", ...
        "bundle_pair_cov","gan_g_loss_count","BoundaryHit_all", ...
        "GAN_to_Segment_Dist50","GAN_to_Segment_Dist90", ...
        "RawGANFeasibleRate"];
    metricVars = metricVars(ismember(metricVars, ...
        string(RunSummary.Properties.VariableNames)));
    VariantSummary = groupsummary(RunSummary,groupVars,'mean', ...
        cellstr(metricVars));
end

function Specs = buildValidationSpecs_BDG()
    Specs = repmat(emptySpec_BDG(),0,1);
    Specs(end+1) = spec_BDG("legacy_E6_iter30_fused", ...
        "FixMD_GNDk60_nearseg_fused_huber_z0",30,"iter", ...
        fusedControl_BDG());
    Specs(end+1) = spec_BDG("compact_paircell_iter30", ...
        "FixMD_GNDk60_nearseg_compact_huber_z0",30,"iter", ...
        compactPairCellControl_BDG("geometry"));
    Specs(end+1) = spec_BDG("compact_margin_iter30", ...
        "FixMD_GNDk60_nearseg_compact_margin_huber_z0",30,"iter", ...
        compactPairCellControl_BDG("constraint_margin"));
end

function Spec = spec_BDG(label,variant,ganIter,ganTrainMode,control)
    Spec = emptySpec_BDG();
    Spec.label = string(label);
    Spec.variant = string(variant);
    Spec.ganIter = double(ganIter);
    Spec.ganTrainMode = string(ganTrainMode);
    Spec.control = control;
end

function Spec = emptySpec_BDG()
    Spec = struct('label',"",'variant',"",'ganIter',NaN, ...
        'ganTrainMode',"",'control',struct());
end

function Control = fusedControl_BDG()
    Control = baseControl_BDG("FixMD_GNDk60_nearseg_fused_huber_z0");
    Control.trainFilterMode = "condition_knn_fused";
    Control.trainBundleMode = "none";
    Control.pairCellSelectionMode = "geometry";
end

function Control = compactPairCellControl_BDG(selectionMode)
    if nargin < 1 || isempty(selectionMode)
        selectionMode = "geometry";
    end
    if string(selectionMode) == "constraint_margin"
        variant = "FixMD_GNDk60_nearseg_compact_margin_huber_z0";
    else
        variant = "FixMD_GNDk60_nearseg_compact_huber_z0";
    end
    Control = baseControl_BDG(variant);
    Control.trainFilterMode = "condition_knn_fused";
    Control.trainBundleMode = "pair_cell";
    Control.pairCellMaxPerPair = 2;
    Control.pairCellSelectionMode = string(selectionMode);
end

