        'nearSegmentMaxPerPair',5);

    [XBase,CBase,BaseDiag] = BuildBoundaryTargetTriples_BDG( ...
        AF,AI,Problem,W,BaseOptions);
    AITrain = AI.decs(BaseDiag.target_keep_index,:);
    FilterOptions = struct( ...
        'trainFilterMode',"condition_knn", ...
        'conditionKNNK',2, ...
        'conditionKNNRetainRatio',0.50, ...
        'conditionKNNMinCount',2, ...
        'lower',Problem.lower, ...
        'upper',Problem.upper);
    [XFiltered,CFiltered,~,~,FilterDiag] = FilterBoundaryTargetTriples_BDG( ...
        XBase,CBase,AITrain,AF,AI,W,BaseDiag,FilterOptions);

    FusedOptions = BaseOptions;
    FusedOptions.targetFusionMode = "condition_knn";
    FusedOptions.conditionKNNK = 2;
    FusedOptions.conditionKNNRetainRatio = 0.50;
    FusedOptions.conditionKNNMinCount = 2;
