function assertFusedNearSegmentBuilderMatchesConditionKNNFilter()
    Problem = struct('D',2,'M',2,'lower',[0 0],'upper',[1 1]);
    W = [1.00 0.00;0.50 0.50;0.00 1.00];
    AF = struct( ...
        'decs',[0.20 0.30;0.40 0.50], ...
        'objs',[2 4;4 2], ...
        'ref',[1;3], ...
        'score',[0;0]);
    AI = struct( ...
        'decs',[0.10 0.20;0.30 0.40], ...
        'objs',[1 3;3 1], ...
        'ref',[1;3], ...
        'score',[0;0]);
    Source = struct( ...
        'decs',[0.20 0.30;0.15 0.25;0.10 0.20; ...
                0.40 0.50;0.35 0.45;0.30 0.40], ...
        'objs',[2.0 4.0;1.5 3.5;1.0 3.0; ...
