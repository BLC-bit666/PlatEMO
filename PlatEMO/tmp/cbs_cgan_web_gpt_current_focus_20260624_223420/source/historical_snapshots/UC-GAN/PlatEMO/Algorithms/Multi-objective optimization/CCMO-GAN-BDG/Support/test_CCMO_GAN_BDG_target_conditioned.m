            FusedDiag.target_filter_post_count == FilterDiag.target_filter_post_count && ...
            abs(FusedDiag.target_filter_retain_ratio - ...
            FilterDiag.target_filter_retain_ratio) < 1e-12 && ...
            FusedDiag.target_triple_count == size(XFused,1), ...
        'test_CCMO_GAN_BDG_target_conditioned:FusedNearsegBadDiag', ...
        'Fused nearseg builder must report pre/post retain diagnostics.');
