function assertLocalMADWeightDownweightsDecisionOutlier()
    Problem = struct('D',2,'M',2,'lower',[0 0],'upper',[1 1]);
    W = [1 0;0 1;0.5 0.5];
    X = [0.10 0.10;0.11 0.10;0.10 0.11;0.12 0.11; ...
         0.09 0.12;0.90 0.90];
    C = single([0.50 0.50;0.51 0.50;0.50 0.51;0.49 0.50; ...
                0.50 0.49;0.505 0.505]);
    AITrain = X + 0.01;
    AF = struct('decs',X,'objs',C,'ref',[1;1;1;1;1;1], ...
        'score',zeros(6,1));
    AI = struct('decs',AITrain,'objs',C + 0.05,'ref',AF.ref, ...
        'score',zeros(6,1));
    TripleDiag = struct('target_keep_index',(1:6)');
    Options = struct( ...
        'trainFilterMode',"local_mad_weight", ...
        'conditionKNNK',5, ...
        'conditionKNNMinCount',2, ...
        'lower',Problem.lower, ...
        'upper',Problem.upper);

    [XOut,COut,AIOut,weights,Diag] = FilterBoundaryTargetTriples_BDG( ...
        X,C,AITrain,AF,AI,W,TripleDiag,Options);

    assert(size(XOut,1) == 6 && size(COut,1) == 6 && size(AIOut,1) == 6, ...
        'test_CCMO_GAN_BDG_target_conditioned:LocalMADShouldNotHardDelete', ...
        'local_mad_weight must keep all triples and downweight local decision outliers.');
    assert(numel(weights) == 6 && weights(6) < 0.25*median(weights(1:5)), ...
        'test_CCMO_GAN_BDG_target_conditioned:LocalMADBadOutlierWeight', ...
        'local_mad_weight must assign a much smaller weight to a same-condition decision outlier.');
    assert(Diag.target_filter_post_count == 6 && ...
            Diag.train_weight_count == 6 && ...
            Diag.train_weight_min == weights(6), ...
        'test_CCMO_GAN_BDG_target_conditioned:LocalMADBadDiagnostics', ...
        'local_mad_weight must report unchanged count and emitted training weights.');
end

