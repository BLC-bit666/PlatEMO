function Variants = validateRetainedVariants(Variants)
    required = ["variant","archiveParetoFilterMode", ...
        "archivePairDirectionMode","generatorMode"];
    missing = setdiff(required,string(Variants.Properties.VariableNames));
    assert(isempty(missing), ...
        'run_CCMO_GAN_BDG_archive_pareto_filters_fullscope:BadVariantTable', ...
        'Variant table missing required columns: %s',strjoin(missing,", "));

    if ~ismember("ganCriticMode",string(Variants.Properties.VariableNames))
        Variants.ganCriticMode = repmat("af_like",height(Variants),1);
    end
    if ~ismember("generatorLossMode",string(Variants.Properties.VariableNames))
        Variants.generatorLossMode = repmat("adversarial",height(Variants),1);
    end
    if ~ismember("archiveSourceCapMode",string(Variants.Properties.VariableNames))
        Variants.archiveSourceCapMode = repmat("limited",height(Variants),1);
    end
    if ~ismember("archivePairRefMode",string(Variants.Properties.VariableNames))
        Variants.archivePairRefMode = repmat("none",height(Variants),1);
    end
    if ~ismember("trainFilterMode",string(Variants.Properties.VariableNames))
        Variants.trainFilterMode = repmat("none",height(Variants),1);
    end
    if ~ismember("conditionKNNRetainRatio", ...
            string(Variants.Properties.VariableNames))
        Variants.conditionKNNRetainRatio = repmat(0.70,height(Variants),1);
    end
    if ~ismember("cganTrainMinRefCov", ...
            string(Variants.Properties.VariableNames))
        Variants.cganTrainMinRefCov = repmat(0.00,height(Variants),1);
    end
    if ~ismember("cganTrainMinTargetTriples", ...
            string(Variants.Properties.VariableNames))
        Variants.cganTrainMinTargetTriples = repmat(0,height(Variants),1);
    end
    if ~ismember("conditionMode",string(Variants.Properties.VariableNames))
        Variants.conditionMode = repmat("yt_dt",height(Variants),1);
    end
    if ~ismember("targetRealLabelMode",string(Variants.Properties.VariableNames))
        Variants.targetRealLabelMode = repmat("binary",height(Variants),1);
    end
    Variants = Variants(:,cellstr([required,"archiveSourceCapMode", ...
        "archivePairRefMode","trainFilterMode","conditionKNNRetainRatio", ...
        "cganTrainMinRefCov","cganTrainMinTargetTriples", ...
        "conditionMode","targetRealLabelMode","ganCriticMode", ...
        "generatorLossMode"]));
    Variants.variant = string(Variants.variant);
    Variants.archiveParetoFilterMode = lower(strtrim( ...
        string(Variants.archiveParetoFilterMode)));
    Variants.archivePairDirectionMode = lower(strtrim( ...
        string(Variants.archivePairDirectionMode)));
    Variants.archiveSourceCapMode = lower(strtrim( ...
        string(Variants.archiveSourceCapMode)));
    Variants.archivePairRefMode = lower(strtrim( ...
        string(Variants.archivePairRefMode)));
    Variants.trainFilterMode = lower(strtrim( ...
        string(Variants.trainFilterMode)));
    Variants.conditionKNNRetainRatio = min(max( ...
        double(Variants.conditionKNNRetainRatio),0),1);
    Variants.cganTrainMinRefCov = min(max( ...
        double(Variants.cganTrainMinRefCov),0),1);
    Variants.cganTrainMinTargetTriples = max(0,round( ...
        double(Variants.cganTrainMinTargetTriples)));
    Variants.conditionMode = lower(strtrim(string(Variants.conditionMode)));
    Variants.targetRealLabelMode = lower(strtrim( ...
        string(Variants.targetRealLabelMode)));
    Variants.generatorMode = lower(strtrim(string(Variants.generatorMode)));
    Variants.ganCriticMode = lower(strtrim(string(Variants.ganCriticMode)));
    Variants.generatorLossMode = lower(strtrim( ...
        string(Variants.generatorLossMode)));

    Retained = retainedVariantSpecs();
    ok = false(height(Variants),1);
    for i = 1 : height(Variants)
        idx = find(Retained.variant == Variants.variant(i),1,'first');
        ok(i) = ~isempty(idx) && ...
            Variants.archiveParetoFilterMode(i) == Retained.archiveParetoFilterMode(idx) && ...
            Variants.archivePairDirectionMode(i) == Retained.archivePairDirectionMode(idx) && ...
            Variants.archiveSourceCapMode(i) == Retained.archiveSourceCapMode(idx) && ...
            Variants.archivePairRefMode(i) == Retained.archivePairRefMode(idx) && ...
            Variants.trainFilterMode(i) == Retained.trainFilterMode(idx) && ...
            abs(Variants.conditionKNNRetainRatio(i) - ...
                Retained.conditionKNNRetainRatio(idx)) < 1e-12 && ...
            abs(Variants.cganTrainMinRefCov(i) - ...
                Retained.cganTrainMinRefCov(idx)) < 1e-12 && ...
            Variants.cganTrainMinTargetTriples(i) == ...
                Retained.cganTrainMinTargetTriples(idx) && ...
            Variants.conditionMode(i) == Retained.conditionMode(idx) && ...
            Variants.targetRealLabelMode(i) == Retained.targetRealLabelMode(idx) && ...
            Variants.generatorMode(i) == Retained.generatorMode(idx) && ...
            Variants.ganCriticMode(i) == Retained.ganCriticMode(idx) && ...
            Variants.generatorLossMode(i) == Retained.generatorLossMode(idx);
    end
    assert(all(ok), ...
        'run_CCMO_GAN_BDG_archive_pareto_filters_fullscope:UnsupportedVariant', ...
        'Only retained variants are supported: %s.', ...
        strjoin(Retained.variant,", "));
end

