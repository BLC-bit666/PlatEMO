function [popCount,feasibleCount,feasibleRate,bestCount] = finalPopulationCounts(Population)
    popCount = numel(Population);
    feasibleCount = 0;
    feasibleRate = NaN;
    bestCount = 0;
    if popCount <= 0
        return;
    end
    feasible = all(Population.cons <= 0,2);
    feasibleCount = sum(feasible);
    feasibleRate = feasibleCount ./ popCount;
    bestCount = numel(Population.best);
end

