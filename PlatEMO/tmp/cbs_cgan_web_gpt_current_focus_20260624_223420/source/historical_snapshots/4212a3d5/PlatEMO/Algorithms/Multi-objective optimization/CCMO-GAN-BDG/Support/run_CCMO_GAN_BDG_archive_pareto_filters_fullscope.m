function Plot = normalizePlotOptions(Options,outDir)
    Plot = struct( ...
        'enable',false, ...
        'targets',zeros(0,1), ...
        'outDir',"", ...
        'snapshotRoot',"", ...
        'figureRoot',"", ...
        'ganN',100, ...
        'plotRuns',zeros(0,1), ...
        'plotVariants',strings(0,1));
    if isempty(Options)
        return;
    end
    if islogical(Options) || isnumeric(Options)
        Plot.enable = logical(Options);
    elseif isstruct(Options)
        Plot.enable = optionValue(Options, ...
            {'enable','enabled','plotSnapshots'},false);
        Plot.targets = optionValue(Options, ...
            {'targets','snapshotTargets'},zeros(0,1));
        Plot.outDir = string(optionValue(Options, ...
            {'outDir','snapshotOutDir'}, ...
            fullfile(outDir,'archive_objective_snapshots')));
        Plot.figureRoot = string(optionValue(Options, ...
            {'figureRoot','figureOutDir'}, ""));
        Plot.ganN = optionValue(Options,{'ganN','snapshotGanN'},100);
        Plot.plotRuns = optionValue(Options, ...
            {'plotRuns','snapshotRuns'},zeros(0,1));
        Plot.plotVariants = optionValue(Options, ...
            {'plotVariants','snapshotVariants'},strings(0,1));
    else
        error('run_CCMO_GAN_BDG_archive_pareto_filters_fullscope:BadPlotOptions', ...
            'plotOptions must be empty, logical, numeric, or a struct.');
    end
    Plot.targets = unique(round(double(Plot.targets(:)')),'stable');
    Plot.targets = Plot.targets(isfinite(Plot.targets) & Plot.targets > 0);
    if ~isempty(Plot.targets)
        Plot.enable = true;
    elseif Plot.enable
        Plot.targets = [10000 30000 50000 70000 100000];
    end
    Plot.ganN = max(0,round(double(Plot.ganN)));
    Plot.plotRuns = unique(round(double(Plot.plotRuns(:)')),'stable');
    Plot.plotRuns = Plot.plotRuns(isfinite(Plot.plotRuns) & Plot.plotRuns > 0);
    Plot.plotVariants = string(Plot.plotVariants(:));
    Plot.plotVariants = Plot.plotVariants(strlength(Plot.plotVariants) > 0);
    if Plot.enable
        if strlength(Plot.outDir) == 0
            Plot.outDir = string(fullfile(outDir,'archive_objective_snapshots'));
        end
        Plot.snapshotRoot = string(fullfile(char(Plot.outDir),'snapshots'));
        if strlength(Plot.figureRoot) == 0
            Plot.figureRoot = string(fullfile(char(Plot.outDir),'figures'));
        end
        if ~isfolder(char(Plot.snapshotRoot))
            mkdir(char(Plot.snapshotRoot));
        end
        if ~isfolder(char(Plot.figureRoot))
            mkdir(char(Plot.figureRoot));
        end
    end
end

function flag = shouldPlotTask(Row,Plot)
    flag = logical(Plot.enable);
    if ~flag
        return;
    end
    if ~isempty(Plot.plotRuns) && ~ismember(double(Row.run),Plot.plotRuns)
        flag = false;
        return;
    end
    if ~isempty(Plot.plotVariants) && ...
            ~ismember(string(Row.variant),Plot.plotVariants)
        flag = false;
    end
end

function value = optionValue(Options,names,defaultValue)
    value = defaultValue;
    for i = 1 : numel(names)
        name = char(names{i});
        if isfield(Options,name) && ~isempty(Options.(name))
            value = Options.(name);
            return;
        end
    end
end

