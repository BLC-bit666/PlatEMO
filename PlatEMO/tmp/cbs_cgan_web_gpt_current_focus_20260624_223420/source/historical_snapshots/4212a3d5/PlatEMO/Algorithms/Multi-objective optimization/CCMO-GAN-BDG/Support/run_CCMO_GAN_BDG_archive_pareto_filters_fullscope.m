function [Summary,outDir,ImageManifest] = run_CCMO_GAN_BDG_archive_pareto_filters_fullscope( ...
        outDir,workerCount,problemNames,N,D,maxFE,runIds,variantSet, ...
        algorithmParams,plotOptions)
% Run the A1 mainline and the single A2 branch. Plotting is opt-in.

    rootDir = fileparts(which('platemo'));
    if nargin < 1 || isempty(outDir)
        outDir = fullfile(rootDir,'Data','CCMO_GAN_BDG', ...
            ['archive_pareto_filters_fullscope_', ...
            char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
    end
    if nargin < 2 || isempty(workerCount)
        workerCount = 6;
    end
    if nargin < 3 || isempty(problemNames)
        problemNames = defaultProblemList();
    end
    if nargin < 4 || isempty(N)
        N = 100;
    end
    if nargin < 5
        D = [];
    end
    if nargin < 6 || isempty(maxFE)
        maxFE = 100000;
    end
    if nargin < 7 || isempty(runIds)
        runIds = 1 : 3;
    end
    if nargin < 8 || isempty(variantSet)
        variantSet = "default";
    end
    if nargin < 9
        algorithmParams = [];
    end
    if nargin < 10
        plotOptions = [];
    end

    addpath(genpath(rootDir));
    problemNames = cellstr(string(problemNames(:)));
    runIds = double(runIds(:)');
    workerCount = max(1,round(double(workerCount)));
    algorithmParams = normalizeAlgorithmParams(algorithmParams,N);
    plotOptions = normalizePlotOptions(plotOptions,outDir);
    Variants = archiveParetoVariants(variantSet);
    Tasks = buildTasks(problemNames,runIds,Variants);

    if ~isfolder(outDir)
        mkdir(outDir);
    end

    fprintf('archive_pareto_filters_fullscope outDir=%s\n',outDir);
    fprintf('tasks=%d problems x %d runs x %d variants, N=%d, D=%s, maxFE=%d, workers=%d\n', ...
        numel(problemNames),numel(runIds),height(Variants),N, ...
        defaultDText(D),maxFE,workerCount);

    Rows = repmat(emptyRunRow(),height(Tasks),1);
    if workerCount > 1
        ensureParallelPool(workerCount);
        parfor task = 1 : height(Tasks)
            Rows(task) = completeRunRow(runOneTask(Tasks(task,:),N,D, ...
                maxFE,algorithmParams,plotOptions));
        end
    else
        for task = 1 : height(Tasks)
            Rows(task) = completeRunRow(runOneTask(Tasks(task,:),N,D, ...
                maxFE,algorithmParams,plotOptions));
            fprintf('[%d/%d] %s %s run=%g status=%s\n', ...
                task,height(Tasks),Tasks.variant(task), ...
                Tasks.problem(task),Tasks.run(task),Rows(task).status);
        end
    end

    Summary = struct2table(Rows);
    writetable(Summary,fullfile(outDir,'archive_pareto_filter_run_summary.csv'));
    writeSummaries(Summary,outDir);
    writeStageSummaries(Summary,outDir);
    ImageManifest = table();
    if plotOptions.enable
        writetable(Summary,fullfile(plotOptions.outDir, ...
            'archive_snapshot_run_summary.csv'));
        ImageManifest = plotSnapshotImages(Summary,N,D,maxFE, ...
            plotOptions.figureRoot);
        writetable(ImageManifest,fullfile(plotOptions.outDir, ...
            'archive_snapshot_image_manifest.csv'));
    end
end

function Row = completeRunRow(Source)
    Row = emptyRunRow();
    names = intersect(fieldnames(Source),fieldnames(Row),'stable');
    for i = 1 : numel(names)
        Row.(names{i}) = Source.(names{i});
    end
end

