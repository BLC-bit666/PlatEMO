function [xLimits,yLimits] = objectiveAxisLimits(Problem,Boundaries)
    XParts = cell(numel(Boundaries)+1,1);
    YParts = cell(numel(Boundaries)+1,1);
    part = 0;
    PF = Problem.PF;
    if iscell(PF) && numel(PF) >= 2
        part = part + 1;
        XParts{part} = PF{1}(:);
        YParts{part} = PF{2}(:);
    elseif isnumeric(PF) && size(PF,2) >= 2
        part = part + 1;
        XParts{part} = PF(:,1);
        YParts{part} = PF(:,2);
    end
    if part > 0
        xLimits = paddedLimits(vertcat(XParts{1:part}));
        yLimits = paddedLimits(vertcat(YParts{1:part}));
        return;
    end
    for i = 1 : numel(Boundaries)
        if ~isempty(Boundaries{i}) && ...
                all(ismember({'obj1','obj2'},Boundaries{i}.Properties.VariableNames))
            part = part + 1;
            B = visibleBoundaryRows(Boundaries{i});
            XParts{part} = numericColumn(B,'obj1');
            YParts{part} = numericColumn(B,'obj2');
        end
    end
    if part == 0
        xLimits = [0 1];
        yLimits = [0 1];
        return;
    end
    xLimits = paddedLimits(vertcat(XParts{1:part}));
    yLimits = paddedLimits(vertcat(YParts{1:part}));
end

function B = visibleBoundaryRows(B)
    if ismember('archive_role',B.Properties.VariableNames)
        role = string(B.archive_role);
        B = B(role ~= "AI_train",:);
    end
end

function Limits = paddedLimits(Values)
    Values = double(Values(:));
    Values = Values(isfinite(Values));
    if isempty(Values)
        Limits = [0 1];
        return;
    end
    Limits = [min(Values),max(Values)];
    pad = 0.03*max(diff(Limits),eps);
    Limits = Limits + [-pad,pad];
end

