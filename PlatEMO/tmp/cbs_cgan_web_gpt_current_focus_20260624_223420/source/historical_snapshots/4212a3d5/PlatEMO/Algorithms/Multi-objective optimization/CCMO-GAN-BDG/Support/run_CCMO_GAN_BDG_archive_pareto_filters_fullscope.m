function Tasks = buildTasks(problemNames,runIds,Variants)
    count = numel(problemNames) * numel(runIds) * height(Variants);
    Rows = repmat(emptyTaskRow(),count,1);
    k = 0;
    for v = 1 : height(Variants)
        VariantRow = table2struct(Variants(v,:));
        fields = fieldnames(VariantRow);
        for p = 1 : numel(problemNames)
            for r = 1 : numel(runIds)
                k = k + 1;
                for f = 1 : numel(fields)
                    Rows(k).(fields{f}) = VariantRow.(fields{f});
                end
                Rows(k).variant_index = v;
                Rows(k).problem = string(problemNames{p});
                Rows(k).run = runIds(r);
            end
        end
    end
    Tasks = struct2table(Rows);
end

function Row = runOneTask(Task,N,D,maxFE,algorithmParams,plotOptions)
    Row = emptyRunRow();
    Row.variant = string(Task.variant);
    Row.archiveParetoFilterMode = string(Task.archiveParetoFilterMode);
    Row.archivePairDirectionMode = string(Task.archivePairDirectionMode);
    Row.archiveSourceCapMode = string(Task.archiveSourceCapMode);
    Row.archivePairRefMode = string(Task.archivePairRefMode);
    Row.trainFilterMode = string(Task.trainFilterMode);
    Row.conditionKNNRetainRatio = double(Task.conditionKNNRetainRatio);
    Row.cganTrainMinRefCov = double(Task.cganTrainMinRefCov);
    Row.cganTrainMinTargetTriples = double(Task.cganTrainMinTargetTriples);
    Row.conditionMode = string(Task.conditionMode);
    Row.targetRealLabelMode = string(Task.targetRealLabelMode);
    Row.generatorMode = string(Task.generatorMode);
    Row.ganCriticMode = string(Task.ganCriticMode);
    Row.generatorLossMode = string(Task.generatorLossMode);
    Row.problem = string(Task.problem);
    Row.family = problemFamily(Row.problem);
    Row.run = double(Task.run);
    Row.seed = double(Task.run);
    Row.trainFilterRandomSeed = Row.seed;
    Row.N = double(N);
    Row.maxFE = double(maxFE);
    Row = attachAlgorithmParams(Row,algorithmParams);
    Row.target_text = strjoin(string(plotOptions.targets),';');

    try
        rootDir = fileparts(which('platemo'));
        addpath(genpath(rootDir));
        rng(Row.seed,'twister');
        ProblemConstructor = str2func(char(Row.problem));
        if isempty(D)
            Problem = ProblemConstructor('N',N,'maxFE',maxFE);
        else
            Problem = ProblemConstructor('N',N,'D',D,'maxFE',maxFE);
        end
        Row.D = double(Problem.D);

        Control = experimentControl(Row,plotOptions);
        plotThisTask = shouldPlotTask(Row,plotOptions);
        if plotThisTask
            Row.snapshot_folder = string(fullfile(plotOptions.snapshotRoot, ...
                safeName(Row.variant),sprintf('%s_run%d', ...
                char(Row.problem),round(Row.run))));
            Row.snapshot_manifest_file = string(fullfile( ...
                char(Row.snapshot_folder),'archive_snapshot_manifest.csv'));
            Control.archiveSnapshotFolder = Row.snapshot_folder;
            Control.archiveSnapshotTag = Row.variant;
            if ~isfolder(char(Row.snapshot_folder))
                mkdir(char(Row.snapshot_folder));
            end
        end
        setappdata(0,'CCMO_GAN_BDG_ExperimentControl',Control);
        cleanup = onCleanup(@()rmappdataIfPresent()); %#ok<NASGU>

        Algorithm = CCMO_GAN_BDG( ...
            'save',0, ...
            'run',Row.run, ...
            'metName',{'IGD','HV','Feasible_rate'}, ...
            'outputFcn',@(varargin)[], ...
            'parameter',algorithmParams);
        Algorithm.Solve(Problem);

        Row.runtime = double(Algorithm.metric.runtime);
        Row.core_metrics_file = string(Algorithm.metric.analysis_core_csv);
        Row.stage_metrics_file = string(Algorithm.metric.analysis_stage_csv);
        Row.IGD = lastValue(Algorithm.CalMetric('IGD'));
        Row.HV = lastValue(Algorithm.CalMetric('HV'));
        Row.Feasible_rate = lastValue(Algorithm.CalMetric('Feasible_rate'));
        Row.finalFE = double(Algorithm.result{end,1});
        FinalPop = Algorithm.result{end,2};
        [Row.finalPopCount,Row.finalFeasibleCount, ...
            Row.finalFeasibleRateManual,Row.finalBestCount] = ...
            finalPopulationCounts(FinalPop);
        Row = attachArchiveFilterFinalMetrics(Row, ...
            Algorithm.metric.analysis_core_csv);
        if plotThisTask && isfile(Row.snapshot_manifest_file)
            Manifest = readtable(Row.snapshot_manifest_file, ...
