function Params = normalizeAlgorithmParams(Params,N)
    Defaults = defaultAlgorithmParams(N);
    if isempty(Params)
        Params = Defaults;
        return;
    end
    if isstruct(Params)
        names = algorithmParamNames();
        Out = Defaults;
        for i = 1 : numel(names)
            if isfield(Params,names{i}) && ~isempty(Params.(names{i}))
                Out{i} = Params.(names{i});
            end
        end
        Params = Out;
        return;
    end
    assert(iscell(Params) && numel(Params) <= numel(Defaults), ...
        'run_CCMO_GAN_BDG_archive_pareto_filters_fullscope:BadParams', ...
        'algorithmParams must be a cell array with at most %d elements.', ...
        numel(Defaults));
    if numel(Params) < numel(Defaults)
        Params(end+1:numel(Defaults)) = Defaults(end-numel(Defaults)+numel(Params)+1:end);
    end
end

