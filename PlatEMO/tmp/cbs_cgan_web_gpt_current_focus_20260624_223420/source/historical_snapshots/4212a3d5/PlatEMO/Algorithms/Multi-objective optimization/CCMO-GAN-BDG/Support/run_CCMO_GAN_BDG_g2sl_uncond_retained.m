function [RunManifest,outRoot] = run_CCMO_GAN_BDG_g2sl_uncond_retained( ...
        outRoot,workerCount,problemNames,N,D,maxFE,runIds)
% Run the two retained unconditional G2SL-style BDG baselines.

    rootDir = fileparts(which('platemo'));
    if nargin < 1 || isempty(outRoot)
        outRoot = fullfile(rootDir,'Data','CCMO_GAN_BDG', ...
            ['g2sl_uncond_retained_', ...
            char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
    end
    if nargin < 2 || isempty(workerCount)
        workerCount = 6;
    end
    if nargin < 3
        problemNames = [];
    end
    if nargin < 4 || isempty(N)
        N = 100;
    end
    if nargin < 5
        D = [];
    end
    if nargin < 6 || isempty(maxFE)
        maxFE = 100000;
    end
    if nargin < 7 || isempty(runIds)
        runIds = 1 : 3;
    end

    addpath(genpath(rootDir));
    if ~isfolder(outRoot)
        mkdir(outRoot);
    end

    specs = retainedUnconditionalSpecs();
    Rows = repmat(emptyManifestRow(),numel(specs),1);
    plotOptions = struct('enable',false,'targets',[], ...
        'plotRuns',[],'plotVariants',[],'ganN',0);

    for i = 1 : numel(specs)
        spec = specs(i);
        variantSet = table( ...
            string(spec.variant), ...
            "global_af_nd", ...
            "ai_dominates_af", ...
            "objective_target_unconditioned", ...
            "af_like", ...
            "adversarial", ...
            'VariableNames',{'variant','archiveParetoFilterMode', ...
            'archivePairDirectionMode','generatorMode','ganCriticMode', ...
            'generatorLossMode'});
        outDir = fullfile(outRoot,char(spec.variant));
        fprintf('Running %s -> %s\n',spec.variant,outDir);
        [Summary,actualOutDir] = ...
            run_CCMO_GAN_BDG_archive_pareto_filters_fullscope( ...
            outDir,workerCount,problemNames,N,D,maxFE,runIds, ...
            variantSet,spec.params,plotOptions);

        Rows(i).variant = string(spec.variant);
        Rows(i).purpose = string(spec.purpose);
        Rows(i).out_dir = string(actualOutDir);
        Rows(i).summary_file = string(fullfile(actualOutDir, ...
            'archive_pareto_filter_run_summary.csv'));
        Rows(i).ok_count = sum(Summary.status == "ok");
        Rows(i).failed_count = sum(Summary.status ~= "ok");
        Rows(i).trainGap = double(spec.params.trainGap);
        Rows(i).nGen = double(spec.params.nGen);
        Rows(i).zDim = double(spec.params.zDim);
        Rows(i).ganIter = double(spec.params.ganIter);
        Rows(i).ganDPretrainIter = double(spec.params.ganDPretrainIter);
        Rows(i).ganArchMode = string(spec.params.ganArchMode);
        Rows(i).ganRealLabel = double(spec.params.ganRealLabel);
        Rows(i).ganTrainMode = string(spec.params.ganTrainMode);
    end

    RunManifest = struct2table(Rows);
    writetable(RunManifest,fullfile(outRoot, ...
        'g2sl_uncond_retained_manifest.csv'));
end

function specs = retainedUnconditionalSpecs()
    base = struct( ...
        'trainGap',1, ...
        'nGen',50, ...
        'zDim',8, ...
        'perRef',5, ...
        'nearTau',0.20, ...
        'ganIter',5, ...
        'probeRawN',0, ...
        'stageProbeN',200, ...
        'ganDPretrainIter',0, ...
        'ganDSteps',1, ...
        'ganGSteps',1, ...
        'archiveGap',1, ...
        'ganArchMode',"g2sl", ...
        'ganMiniBatch',64, ...
        'ganRealLabel',0.9, ...
        'ganLrD',1e-4, ...
        'ganLrG',1e-4, ...
        'ganTrainMode',"epoch");

    specs = repmat(struct('variant',"",'purpose',"",'params',base),2,1);

    specs(1).variant = "U0_NoGAN";
    specs(1).purpose = "No-GAN baseline with the same archive construction.";
    specs(1).params = base;
    specs(1).params.trainGap = 1e9;
    specs(1).params.nGen = 0;
    specs(1).params.ganIter = 0;

    specs(2).variant = "U4_Epoch10";
    specs(2).purpose = "Retained unconditional GAN baseline with 10 epochs.";
    specs(2).params = base;
    specs(2).params.ganIter = 10;
end

function Row = emptyManifestRow()
    Row = struct( ...
        'variant',"", ...
        'purpose',"", ...
        'out_dir',"", ...
        'summary_file',"", ...
        'ok_count',NaN, ...
        'failed_count',NaN, ...
        'trainGap',NaN, ...
        'nGen',NaN, ...
        'zDim',NaN, ...
        'ganIter',NaN, ...
        'ganDPretrainIter',NaN, ...
        'ganArchMode',"", ...
        'ganRealLabel',NaN, ...
        'ganTrainMode',"");
end
