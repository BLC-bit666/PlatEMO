function test_CBS_endpoint_yb_norm_runner_smoke()
%TEST_CBS_ENDPOINT_YB_NORM_RUNNER_SMOKE Verify endpoint y_b condition runner.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    runnerFile = fullfile(repoRoot,'Algorithms', ...
        'Multi-objective optimization','CBS-CGAN','Support', ...
        'run_CBS_CGAN_endpoint_yb_norm_epoch50_compare_sheets.m');
    assert(isfile(runnerFile), ...
        'Endpoint y_b_norm compare runner file must exist.');

    txt = fileread(runnerFile);
    compact = regexprep(txt,'\s+','');
    compact = erase(compact,'...');
    assert(contains(compact,'"conditionMode","ref_y"') || ...
            contains(compact,'''conditionMode'',"ref_y"'), ...
        'Endpoint y_b_norm runner must use conditionMode=ref_y.');
    assert(contains(compact,'"boundaryTargetMode","feasible_endpoint"') || ...
            contains(compact,'''boundaryTargetMode'',"feasible_endpoint"'), ...
        'Endpoint y_b_norm runner must use feasible endpoint targets.');
    assert(contains(compact,'"figureKinds","train_reconstruction"') || ...
            contains(compact,'''figureKinds'',"train_reconstruction"'), ...
        'Endpoint y_b_norm runner must render only train reconstruction figures.');
    assert(contains(compact,'contact_sheets_endpoint_yb_norm_compare'), ...
        'Endpoint y_b_norm runner must write a dedicated comparison sheet folder.');

    fprintf('CBS-CGAN endpoint y_b_norm runner smoke passed.\n');
end
