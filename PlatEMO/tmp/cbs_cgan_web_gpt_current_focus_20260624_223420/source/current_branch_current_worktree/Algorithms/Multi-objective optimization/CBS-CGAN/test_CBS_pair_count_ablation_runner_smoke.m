function test_CBS_pair_count_ablation_runner_smoke()
%TEST_CBS_PAIR_COUNT_ABLATION_RUNNER_SMOKE Check pair-count ablation runner.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    outDir = fullfile(tempdir,sprintf('cbs_pair_count_ablation_%s', ...
        char(java.util.UUID.randomUUID)));
    Options = struct( ...
        'workerCount',1, ...
        'problemNames',"DASCMOP1_BC", ...
        'N',10, ...
        'D',[], ...
        'maxFE',260, ...
        'runIds',1:3, ...
        'targets',220, ...
        'pairCounts',[1 3], ...
        'plotRun',3, ...
        'baseAlgorithmParams',{{1,1,4,2,1,8,1e-4,2e-4,0,1,1,4,1,1,1,0.10,1}});

    [Summary,RootDir,StageMetrics,FigureManifest,VariantManifest] = ...
        run_CBS_CGAN_pair_count_ablation(outDir,Options);

    assert(isfolder(RootDir), ...
        'Pair-count ablation runner should create the requested root dir.');
    assert(height(VariantManifest) == 2, ...
        'Runner should create one variant row per pair count.');
    assert(all(ismember(["pair1","pair3"],string(VariantManifest.variant))), ...
        'Variant names should encode maxCandidatePairsPerRef.');
    assert(height(Summary) == 6, ...
        'Runner should run 2 pair-count variants x 3 runs.');
    assert(all(string(Summary.status) == "ok"), ...
        'All smoke ablation runs should finish.');
    assert(all(ismember(["variant","maxCandidatePairsPerRef"], ...
        string(Summary.Properties.VariableNames))), ...
        'Summary should include variant metadata.');
    assert(all(Summary.figure_count(Summary.run ~= 3) == 0), ...
        'Runs other than plotRun should not produce figures.');
    assert(all(Summary.figure_count(Summary.run == 3) >= 2), ...
        'plotRun should produce stage and diagnostic figures for each variant.');
    assert(~isempty(FigureManifest) && all(FigureManifest.run == 3), ...
        'Aggregated figure manifest should contain only plotRun figures.');
    assert(all(isfile(FigureManifest.figure_file)), ...
        'All aggregated figure paths should exist.');
    assert(height(StageMetrics) == 6, ...
        'Stage metrics should include every variant-run task at the single target.');
    assert(all(ismember(["variant","maxCandidatePairsPerRef"], ...
        string(StageMetrics.Properties.VariableNames))), ...
        'Stage metrics should include variant metadata.');
    assert(isfile(fullfile(RootDir,'comparison_summary.csv')), ...
        'Runner should write comparison_summary.csv.');
    assert(isfile(fullfile(RootDir,'comparison_stage_metrics_all.csv')), ...
        'Runner should write comparison_stage_metrics_all.csv.');
    assert(isfile(fullfile(RootDir,'comparison_figure_manifest.csv')), ...
        'Runner should write comparison_figure_manifest.csv.');

    fprintf('CBS-CGAN pair-count ablation runner smoke passed: %s\n',RootDir);
end
