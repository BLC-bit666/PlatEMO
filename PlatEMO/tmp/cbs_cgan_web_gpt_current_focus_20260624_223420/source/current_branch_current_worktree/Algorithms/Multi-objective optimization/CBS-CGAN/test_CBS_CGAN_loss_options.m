function test_CBS_CGAN_loss_options()
%TEST_CBS_CGAN_LOSS_OPTIONS Verify CBS-CGAN loss ablation switches.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    rng(41,'twister');
    testDefaultTrainZModeIsZero();
    testDefaultSampleZModeIsZero();
    testNoAdversarialZeroLatentTrainingIgnoresSigma();
    testDeletedPairAndMismatchOptionsAreIgnored();
    testInvalidTrainZModeFailsFast();
    fprintf('CBS-CGAN loss option regression passed.\n');
end

function testDefaultTrainZModeIsZero()
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,5,1) + rand(5,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,5,1);
    TrainC = [0.10 0.90;0.30 0.70;0.50 0.50;0.70 0.30;0.90 0.10];
    BaseOptions = struct( ...
        'zDim',2, ...
        'iter',1, ...
        'miniBatch',5, ...
        'lrD',1e-4, ...
        'lrG',2e-4, ...
        'dPretrainIter',0, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'sigma',0.05, ...
        'advWeight',0, ...
        'reconstructionHuberDelta',0.10, ...
        'reconstructionWeight',1);
    ZeroOptions = BaseOptions;
    ZeroOptions.trainZMode = "zero";

    rng(83,'twister');
    DefaultGAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem, ...
        BaseOptions);
    rng(83,'twister');
    ZeroGAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem, ...
        ZeroOptions);

    SampleOptions = BaseOptions;
    SampleOptions.sampleZ = zeros(size(TrainC,1),BaseOptions.zDim);
    DefaultDec = BoundaryCGAN_CBS('samplebycondition',DefaultGAN, ...
        TrainC,1,SampleOptions);
    ZeroDec = BoundaryCGAN_CBS('samplebycondition',ZeroGAN,TrainC,1, ...
        SampleOptions);

    assert(max(abs(DefaultDec - ZeroDec),[],'all') <= 1e-10, ...
        'Omitted trainZMode must default to zero latent training.');
end

