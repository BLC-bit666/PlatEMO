function testNoAdversarialZeroLatentTrainingIgnoresSigma()
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,5,1) + rand(5,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,5,1);
    TrainC = [0.10 0.90 0.00;0.30 0.70 0.25; ...
        0.50 0.50 0.50;0.70 0.30 0.75;0.90 0.10 1.00];
    Options = struct( ...
        'zDim',2, ...
        'iter',1, ...
        'miniBatch',5, ...
        'lrD',1e-4, ...
        'lrG',2e-4, ...
        'dPretrainIter',0, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'sigma',NaN, ...
        'advWeight',0, ...
        'reconstructionHuberDelta',0.10, ...
        'reconstructionWeight',1, ...
        'pairMargin',0.05, ...
        'pairMarginWeight',1, ...
        'useMismatchD',false, ...
        'trainZMode',"zero", ...
        'trainXf',TrainX, ...
        'trainXi',min(Problem.upper,TrainX + 0.05));

    GAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem,Options);
    SampleOptions = Options;
    SampleOptions.sampleZ = zeros(size(TrainC,1),Options.zDim);
    [Dec,Info] = BoundaryCGAN_CBS('samplebycondition',GAN,TrainC,1, ...
        SampleOptions);

    assert(~isempty(GAN) && isfield(GAN,'netG'), ...
        'No-adversarial zero-latent training must initialize the generator.');
    assert(all(isfinite(Dec(:))), ...
        'No-adversarial zero-latent training must not depend on finite sigma.');
    assert(isequal(size(Info.z),[size(TrainC,1),Options.zDim]) && ...
            max(abs(Info.z(:))) <= 1e-12, ...
        'samplebycondition must keep explicit zero latent rows.');
end

function testDeletedPairAndMismatchOptionsAreIgnored()
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,6,1) + rand(6,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,6,1);
    TrainC = [0.10 0.90;0.25 0.75;0.40 0.60; ...
        0.60 0.40;0.75 0.25;0.90 0.10];
    BaseOptions = struct( ...
        'zDim',2, ...
        'iter',2, ...
        'miniBatch',6, ...
        'lrD',1e-4, ...
        'lrG',2e-4, ...
        'dPretrainIter',0, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'sigma',0.05, ...
        'advWeight',1, ...
        'reconstructionHuberDelta',0.10, ...
        'reconstructionWeight',1, ...
        'trainZMode',"zero");
    LegacyOptions = BaseOptions;
    LegacyOptions.pairMargin = 100;
    LegacyOptions.pairMarginWeight = 100;
    LegacyOptions.useMismatchD = true;
    LegacyOptions.trainXf = TrainX;
    LegacyOptions.trainXi = min(Problem.upper,TrainX + 0.20);
    DeletedOptions = BaseOptions;
    DeletedOptions.pairMarginWeight = 0;
    DeletedOptions.useMismatchD = false;

    rng(73,'twister');
    LegacyGAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem, ...
        LegacyOptions);
    rng(73,'twister');
    DeletedGAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem, ...
        DeletedOptions);

    SampleOptions = BaseOptions;
    SampleOptions.sampleZ = zeros(size(TrainC,1),BaseOptions.zDim);
    LegacyDec = BoundaryCGAN_CBS('samplebycondition',LegacyGAN,TrainC,1, ...
        SampleOptions);
    DeletedDec = BoundaryCGAN_CBS('samplebycondition',DeletedGAN,TrainC,1, ...
        SampleOptions);

    assert(max(abs(LegacyDec - DeletedDec),[],'all') <= 1e-10, ...
        'pair-margin and mismatch-D options must be ignored after deletion.');
end

function testInvalidTrainZModeFailsFast()
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,4,1) + rand(4,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,4,1);
    TrainC = [0.10 0.90;0.30 0.70;0.70 0.30;0.90 0.10];
    Options = struct( ...
        'zDim',2, ...
        'iter',1, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',2e-4, ...
        'dPretrainIter',0, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'sigma',0.05, ...
        'trainZMode',"unsupported");

    didThrow = false;
    try
        BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem,Options);
    catch err
        didThrow = strcmp(err.identifier,'CBSCGAN:BadTrainZMode');
    end
    assert(didThrow, ...
        'Unsupported trainZMode must fail with CBSCGAN:BadTrainZMode.');
end
