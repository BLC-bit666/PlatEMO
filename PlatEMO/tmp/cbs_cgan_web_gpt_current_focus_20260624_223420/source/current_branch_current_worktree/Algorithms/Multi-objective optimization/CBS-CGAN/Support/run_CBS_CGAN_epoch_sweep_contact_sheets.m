function [outDir,sheetDir,Manifest] = run_CBS_CGAN_epoch_sweep_contact_sheets(outDir)
%RUN_CBS_CGAN_EPOCH_SWEEP_CONTACT_SHEETS Run D tau/huber epoch sweep.
%   The run writes only per-problem contact sheets as the delivered figures.

    rootDir = fileparts(which('platemo'));
    if isempty(rootDir)
        rootDir = pwd;
    end
    addpath(genpath(rootDir));
    if nargin < 1 || isempty(outDir)
        outDir = fullfile(rootDir,'Data','CBS_CGAN', ...
            ['train_quality_epoch_sweep_D_default_', ...
            char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
    end

    Settings = [makeEpochSetting(20); makeEpochSetting(50); ...
        makeEpochSetting(100)];
    Options = struct( ...
        'workerCount',10, ...
        'problemNames',["LIRCMOP5_BC";"LIRCMOP6_BC";"LIRCMOP7_BC"; ...
            "LIRCMOP8_BC";"LIRCMOP9_BC";"LIRCMOP10_BC"], ...
        'runIds',1, ...
        'N',100, ...
        'maxFE',100000, ...
        'targets',[10000 30000 50000 70000 100000], ...
        'plotRun',1, ...
        'visualDiagnostics',true, ...
        'plotDiagnosticTrends',false, ...
        'figureKinds',"train_reconstruction", ...
        'settings',Settings);

    [Manifest,~,~,~,FigureManifest] = ...
        run_CBS_CGAN_train_quality_sweep_lir_online(outDir,Options);
    sheetDir = make_CBS_CGAN_epoch_contact_sheets_from_manifest(outDir,true);
end

function S = makeEpochSetting(epochCount)
    name = sprintf('D_tau_huber_default_epoch%d',epochCount);
    S = struct( ...
        'setting',string(name), ...
        'variant',string(name), ...
        'conditionMode',"ref_tau", ...
        'advWeight',1, ...
        'reconstructionWeight',1, ...
        'nGen',30, ...
        'zDim',2, ...
        'ganIter',epochCount, ...
        'ganMiniBatch',32, ...
        'trainMode',"epoch", ...
        'trainZMode',"zero", ...
        'sampleZMode',"zero", ...
        'maxCandidatePairsPerRef',3, ...
        'networkPreset',"default", ...
        'generatorHidden',[64 64 64], ...
        'discriminatorHidden',[64 64 32]);
end
