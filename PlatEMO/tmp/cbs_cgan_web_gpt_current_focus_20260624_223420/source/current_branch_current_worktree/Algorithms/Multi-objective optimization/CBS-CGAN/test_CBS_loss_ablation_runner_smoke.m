function test_CBS_loss_ablation_runner_smoke()
%TEST_CBS_LOSS_ABLATION_RUNNER_SMOKE Verify offline loss ablation outputs.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    rng(53,'twister');
    outDir = fullfile(tempdir,sprintf('cbs_loss_ablation_%s', ...
        char(java.util.UUID.randomUUID)));
    snapshotFile = makeTinySnapshot(outDir);
    Options = struct( ...
        'workerCount',1, ...
        'problemNames',"LIRCMOP5_BC", ...
        'snapshotFiles',snapshotFile, ...
        'ganSeeds',1, ...
        'ganIter',1, ...
        'ganMiniBatch',4, ...
        'plotEnabled',false);

    [Summary,~,ByProblem,ByVariant,Raw,Manifest] = ...
        run_CBS_CGAN_loss_ablation_lir_offline(outDir,Options);

    assert(height(Raw) == 6, ...
        'Smoke run must evaluate the six requested loss variants.');
    assert(all(ismember(["V0_Pure_CGAN","V5_Huber_Pair_no_adv"], ...
            string(Raw.variant))), ...
        'Smoke run must include the pure-CGAN and no-adversarial variants.');
    assert(all(string(Raw.problem) == "LIRCMOP5_BC"), ...
        'Smoke run must preserve the snapshot problem name.');
    requiredMetrics = ["train_x_rec50","train_x_rec90", ...
        "train_y_rec50","train_y_rec90","query_y_err50", ...
        "query_y_err90","pair_violation_rate","z_sensitivity"];
    for i = 1 : numel(requiredMetrics)
        assert(ismember(requiredMetrics(i),string(Raw.Properties.VariableNames)), ...
            'Missing offline metric column: %s',requiredMetrics(i));
    end
    assert(height(Summary) >= 1 && height(ByProblem) >= 1 && ...
            height(ByVariant) >= 1 && height(Manifest) >= 6, ...
        'Runner must return nonempty summary and manifest tables.');
    expectedFiles = ["offline_loss_ablation_summary.csv", ...
        "offline_loss_ablation_by_problem.csv", ...
        "offline_loss_ablation_by_variant.csv", ...
        "offline_loss_ablation_raw.csv", ...
        "offline_loss_ablation_manifest.csv"];
    for i = 1 : numel(expectedFiles)
        assert(isfile(fullfile(outDir,expectedFiles(i))), ...
            'Missing output file: %s',expectedFiles(i));
    end

    fprintf('CBS-CGAN offline loss ablation smoke passed: %s\n',outDir);
end

function snapshotFile = makeTinySnapshot(outDir)
    if ~isfolder(outDir)
        mkdir(outDir);
    end
    Problem = LIRCMOP5_BC('N',8,'D',6,'maxFE',200);
    W = UniformPoint(8,Problem.M);
    n = 6;
    TrainX = repmat(Problem.lower,n,1) + rand(n,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,n,1);
    TrainObjs = Problem.CalObj(TrainX);
    refs = (1:n)';
    Xf = TrainX;
    Xi = min(Problem.upper,TrainX + 0.03);
    Yf = TrainObjs;
    Yi = Yf + 0.02;
    BMem = struct( ...
        'ref',refs, ...
        'y_b',TrainObjs, ...
        'gap',sqrt(sum((Yf - Yi).^2,2)), ...
        'x_b',TrainX, ...
        'x_f',Xf, ...
        'y_f',Yf, ...
        'x_i',Xi, ...
        'y_i',Yi, ...
        'tau',zeros(n,1));
    Snapshot = struct();
    Snapshot.problem = "LIRCMOP5_BC";
    Snapshot.run = 1;
    Snapshot.seed = 1;
    Snapshot.N = 8;
    Snapshot.D = Problem.D;
    Snapshot.maxFE = 200;
    Snapshot.conditionMode = "ref_y";
    Snapshot.W = W;
    Snapshot.BMem = BMem;
    Snapshot.TrainX = TrainX;
    Snapshot.TrainC = [W(refs,:),normalizeWithScale(TrainObjs,TrainObjs)];
    Snapshot.QueryC = Snapshot.TrainC(1:3,:);
    Snapshot.trainObjs = TrainObjs;
    Snapshot.queryObjs = TrainObjs(1:3,:);
    Snapshot.trainXf = Xf;
    Snapshot.trainXi = Xi;
    Snapshot.trainYf = Yf;
    Snapshot.trainYi = Yi;
    Snapshot.queryMeta = struct( ...
        'ref',refs(1:3), ...
        'tau',zeros(3,1), ...
        'source_interval',[refs(1:3),refs(1:3)], ...
        'source_type',repmat("smoke",3,1), ...
        'x_f',Xf(1:3,:), ...
        'x_i',Xi(1:3,:), ...
        'y_f',Yf(1:3,:), ...
        'y_i',Yi(1:3,:));
    Snapshot.objMin = min(TrainObjs,[],1);
    Snapshot.objSpan = max(TrainObjs,[],1) - Snapshot.objMin;
    Snapshot.objSpan(Snapshot.objSpan <= eps) = 1;
    Snapshot.GANOptions = struct( ...
        'zDim',2, ...
        'iter',1, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',2e-4, ...
        'dPretrainIter',0, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'sigma',0.05, ...
        'reconstructionHuberDelta',0.10, ...
        'reconstructionWeight',1, ...
        'pairMargin',0.05, ...
        'pairMarginWeight',1, ...
        'trainZMode',"zero");
    snapshotFile = fullfile(outDir,'tiny_snapshot.mat');
    save(snapshotFile,'Snapshot');
end

function YN = normalizeWithScale(Y,AllY)
    mn = min(AllY,[],1);
    sp = max(AllY,[],1) - mn;
    sp(sp <= eps) = 1;
    YN = (Y - mn)./sp;
end
