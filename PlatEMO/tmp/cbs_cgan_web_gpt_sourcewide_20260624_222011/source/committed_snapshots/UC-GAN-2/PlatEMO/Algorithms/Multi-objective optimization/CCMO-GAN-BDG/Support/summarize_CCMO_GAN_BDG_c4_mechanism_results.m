function Out = summarizeBy_BDG(T,groupVars,metricVars)
    groupVars = cellstr(groupVars);
    metricVars = cellstr(metricVars);
    [G,Out] = findgroups(T(:,groupVars));
    Out.GroupCount = splitapply(@numel,T.run,G);
    for i = 1 : numel(metricVars)
        name = metricVars{i};
        Out.(name) = splitapply(@nanMean_BDG,T.(name),G);
    end
    if ismember('variantOrder',Out.Properties.VariableNames)
        Out = sortrows(Out,intersect({'variantOrder','problemOrder'}, ...
            Out.Properties.VariableNames,'stable'));
    end
end

function Deltas = pairwiseDeltas_BDG(Overall,metricVars)
    pairs = { ...
        "C4_keep80_minus_C4_keep70","C4_keep80","C4_keep70"; ...
        "C4_keep90_minus_C4_keep80","C4_keep90","C4_keep80"; ...
        "C4_keep60_minus_C4_keep70","C4_keep60","C4_keep70"; ...
        "C4_keep70_minus_Rand_keep70","C4_keep70","Rand_keep70"; ...
        "C4_keep80_minus_Rand_keep80","C4_keep80","Rand_keep80"};
    metricVars = cellstr(metricVars);
    Rows = repmat(emptyDeltaRow_BDG(metricVars),size(pairs,1),1);
    for i = 1 : size(pairs,1)
        Rows(i).comparison = pairs{i,1};
        Rows(i).leftVariant = pairs{i,2};
        Rows(i).rightVariant = pairs{i,3};
        left = find(Overall.variant == string(pairs{i,2}),1,'first');
        right = find(Overall.variant == string(pairs{i,3}),1,'first');
        for m = 1 : numel(metricVars)
            name = metricVars{m};
            if ~isempty(left) && ~isempty(right)
                Rows(i).(name) = Overall.(name)(left) - ...
                    Overall.(name)(right);
            end
        end
    end
    Deltas = struct2table(Rows);
end

function Row = emptyDeltaRow_BDG(metricVars)
    Row = struct('comparison',"",'leftVariant',"",'rightVariant',"");
    for i = 1 : numel(metricVars)
        Row.(metricVars{i}) = NaN;
    end
end

function value = tableNumber_BDG(T,name,row)
    value = NaN;
    if ~ismember(name,T.Properties.VariableNames)
        return;
    end
    x = T.(name);
    if iscell(x) || isstring(x)
        x = str2double(string(x));
    else
        x = double(x);
    end
    if nargin >= 3
        value = x(row);
    else
        value = x;
    end
end

function value = tableString_BDG(T,name,row,defaultValue)
    value = string(defaultValue);
    if ~ismember(name,T.Properties.VariableNames)
        return;
    end
    x = string(T.(name));
    value = x(row);
end

function value = nanMean_BDG(x)
    x = double(x(:));
    x = x(isfinite(x));
    if isempty(x)
        value = NaN;
    else
        value = mean(x);
    end
end

function order = problemOrder_BDG(problem)
    names = ["DASCMOP1_BC","DASCMOP2_BC","DASCMOP4_BC", ...
        "DASCMOP5_BC","LIRCMOP5_BC","LIRCMOP6_BC", ...
        "LIRCMOP7_BC","LIRCMOP8_BC","LIRCMOP9_BC", ...
        "LIRCMOP10_BC"];
    idx = find(names == string(problem),1,'first');
    if isempty(idx)
        order = inf;
    else
        order = idx;
    end
end
