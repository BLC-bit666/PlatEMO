function SummaryDir = summarize_CCMO_GAN_BDG_c4_mechanism_results(SummaryDir)
%summarize_CCMO_GAN_BDG_c4_mechanism_results Aggregate C4 controls.

    rootDir = fileparts(which('platemo'));
    addpath(genpath(rootDir));
    baseDir = fullfile(rootDir,'Data','CCMO_GAN_BDG');
    if nargin < 1 || isempty(SummaryDir)
        SummaryDir = fullfile(baseDir, ...
            ['c4_mechanism_summary_', ...
            char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
    end
    if ~isfolder(SummaryDir)
        mkdir(SummaryDir);
    end

    Sources = c4MechanismSources_BDG(baseDir);
    writetable(Sources,fullfile(SummaryDir,'c4_mechanism_sources.csv'));

    Rows = repmat(emptyC4MechanismRunRow_BDG(),0,1);
    k = 0;
    for e = 1 : height(Sources)
        runFile = fullfile(char(Sources.outDir(e)), ...
            'archive_pareto_filter_run_summary.csv');
        assert(isfile(runFile), ...
            'summarize_CCMO_GAN_BDG_c4_mechanism_results:MissingRunSummary', ...
            'Missing run summary: %s',runFile);
        T = readtable(runFile,'TextType','string');
        for i = 1 : height(T)
            k = k + 1;
            Rows(k) = readC4MechanismRunRow_BDG( ...
                T,i,Sources(e,:),e); %#ok<AGROW>
        end
    end
    RunRows = struct2table(Rows);
    writetable(RunRows,fullfile(SummaryDir, ...
        'c4_mechanism_all_run_selected.csv'));

    Ok = RunRows(RunRows.status == "ok",:);
    overallMetrics = ["BoundaryHit_all", ...
        "ObjInterfaceScore", ...
        "GAN_to_Segment_Dist50", ...
        "GAN_to_Segment_Dist90", ...
        "GAN_to_Decision_Segment_Dist50", ...
        "RawGANFeasibleRate", ...
        "D_real_prob", ...
        "D_fake_prob", ...
        "D_mismatch_prob", ...
        "D_real_acc", ...
        "D_fake_acc", ...
        "D_mismatch_acc", ...
        "D_bal_acc", ...
        "train_ref_cov", ...
        "AF_ref_cov", ...
        "target_triple_count", ...
        "runtime"];
    diagnosticMetrics = ["target_filter_pre_count", ...
        "target_filter_post_count", ...
        "target_filter_retain_ratio", ...
        "target_filter_pre_ref_cov", ...
        "target_filter_post_ref_cov", ...
        "condition_knn_decision_spread_mean", ...
        "condition_knn_decision_spread_median", ...
        "condition_knn_decision_spread_p90", ...
        "train_ref_count", ...
        "train_ref_cov", ...
        "AF_ref_cov", ...
        "target_triple_count"];

    Overall = summarizeBy_BDG(Ok, ...
        ["variantOrder","variant","sourceVariant","filterClass", ...
        "conditionKNNRetainRatio"],overallMetrics);
    Diagnostic = summarizeBy_BDG(Ok, ...
        ["variantOrder","variant","sourceVariant","filterClass", ...
        "conditionKNNRetainRatio"],diagnosticMetrics);
    ByProblem = summarizeBy_BDG(Ok, ...
        ["variantOrder","variant","filterClass", ...
        "conditionKNNRetainRatio","problemOrder","problem"], ...
        overallMetrics);
    Focus = ByProblem(ismember(ByProblem.problem, ...
        ["DASCMOP4_BC","DASCMOP5_BC","LIRCMOP9_BC","LIRCMOP10_BC"]),:);
    Deltas = pairwiseDeltas_BDG(Overall, ...
        ["BoundaryHit_all", ...
        "ObjInterfaceScore", ...
        "GAN_to_Segment_Dist50", ...
        "GAN_to_Segment_Dist90", ...
        "GAN_to_Decision_Segment_Dist50", ...
        "RawGANFeasibleRate", ...
        "train_ref_cov", ...
        "AF_ref_cov", ...
        "target_triple_count", ...
        "runtime"]);

    writetable(Overall,fullfile(SummaryDir, ...
        'c4_mechanism_overall_selected.csv'));
    writetable(Diagnostic,fullfile(SummaryDir, ...
        'c4_mechanism_diagnostic.csv'));
    writetable(ByProblem,fullfile(SummaryDir, ...
        'c4_mechanism_by_problem_selected.csv'));
    writetable(Focus,fullfile(SummaryDir, ...
        'c4_mechanism_focus_problems.csv'));
    writetable(Deltas,fullfile(SummaryDir, ...
        'c4_mechanism_pairwise_delta.csv'));
end

