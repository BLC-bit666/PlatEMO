function [Core,Snapshot,Stage,Meta] = runArchiveFilterSmoke( ...
        mode,runId,criticMode,generatorMode,generatorLossMode)
    if nargin < 3 || isempty(criticMode)
        criticMode = "af_like";
    end
    if nargin < 4 || isempty(generatorMode)
        generatorMode = "objective_target_unconditioned";
    end
    if nargin < 5 || isempty(generatorLossMode)
        generatorLossMode = "adversarial";
    end
    controlName = 'CCMO_GAN_BDG_ExperimentControl';
    oldControl = [];
    hadOldControl = isappdata(0,controlName);
    if hadOldControl
        oldControl = getappdata(0,controlName);
    end
    rootDir = fileparts(which('platemo'));
    snapshotFolder = tempname(fullfile(rootDir,'Data','CCMO_GAN_BDG'));
    cleaner = onCleanup(@()restoreExperimentControl(controlName, ...
        hadOldControl,oldControl)); %#ok<NASGU>
    if generatorMode == "objective_target_conditioned"
        variant = "C0_z4_iter50_g1_full";
        mode = "ref_af_nd";
        pairDirectionMode = "af_not_dominates_ai";
        sourceCapMode = "none";
        pairRefMode = "neighbor4";
    elseif mode == "ref_af_nd"
        variant = "U4_noCap_dir_neighbor4";
        pairDirectionMode = "af_not_dominates_ai";
        sourceCapMode = "none";
        pairRefMode = "neighbor4";
    else
        variant = "U4_Epoch10";
        pairDirectionMode = "ai_dominates_af";
        sourceCapMode = "limited";
        pairRefMode = "none";
    end
    setappdata(0,controlName,struct( ...
        'variant',variant, ...
        'archiveParetoFilterMode',mode, ...
        'archivePairDirectionMode',pairDirectionMode, ...
        'archiveSourceCapMode',sourceCapMode, ...
        'archivePairRefMode',pairRefMode, ...
        'ganCriticMode',criticMode, ...
        'generatorMode',generatorMode, ...
        'generatorLossMode',generatorLossMode, ...
        'archiveSnapshotTargets',700, ...
        'archiveSnapshotFolder',string(snapshotFolder), ...
        'archiveSnapshotTag',mode));

    rng(runId,'twister');
    Algorithm = CCMO_GAN_BDG( ...
        'save',0, ...
        'run',runId, ...
        'outputFcn',@(varargin)[], ...
        'parameter',{1,4,2,5,1,1,0,4,1,1,1,1});
    Problem = DASCMOP1_BC('N',20,'D',30,'maxFE',760);
    Algorithm.Solve(Problem);
    Core = readtable(Algorithm.metric.analysis_core_csv,'TextType','string');
    Stage = readtable(Algorithm.metric.analysis_stage_csv,'TextType','string');
    Meta = readtable(Algorithm.metric.analysis_meta_csv,'TextType','string');

    Manifest = readtable(fullfile(snapshotFolder, ...
        'archive_snapshot_manifest.csv'),'TextType','string');
    Snapshot = readtable(Manifest.snapshot_file(end), ...
        'TextType','string');
end

