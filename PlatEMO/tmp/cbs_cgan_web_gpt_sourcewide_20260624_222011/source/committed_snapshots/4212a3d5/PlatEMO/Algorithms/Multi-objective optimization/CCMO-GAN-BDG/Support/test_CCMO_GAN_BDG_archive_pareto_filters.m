function assertUniqueGeneratedBoundaryMetricDefinitions(rootDir)
    mainFile = fullfile(rootDir,'Algorithms', ...
        'Multi-objective optimization','CCMO-GAN-BDG','CCMO_GAN_BDG.m');
    txt = string(fileread(mainFile));
    tokens = regexp(txt, ...
        "function Columns = GeneratedBoundaryMetricColumns_BDG\(\)([\s\S]*?)end", ...
        'tokens','once');
    assert(~isempty(tokens), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:MissingGeneratedBoundaryMetricDefinitions', ...
        'GeneratedBoundaryMetricColumns_BDG must be present.');
    raw = regexp(tokens{1},"'([^']+)'",'tokens');
    names = strings(numel(raw),1);
    for i = 1 : numel(raw)
        names(i) = string(raw{i}{1});
    end
    [uniqueNames,~,idx] = unique(names,'stable');
    counts = accumarray(idx,1);
    duplicates = uniqueNames(counts > 1);
    assert(isempty(duplicates), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:DuplicateGeneratedBoundaryMetricDefinitions', ...
        'GeneratedBoundaryMetricColumns_BDG has duplicate columns: %s', ...
        strjoin(duplicates,", "));
end

