        'test_CCMO_GAN_BDG_archive_pareto_filters:WrongNeighborMode', ...
        'The unified pairing test must exercise retained neighbor4 mode.');
end

function assertNoSourceCapCollectsAllFlipPairs()
    Problem = struct('N',20,'D',2,'M',2);
    W = [1 0;0.5 0.5;0 1];
    perRef = 20;
    nearTau = 10;
    EmptyArchive = emptyArchiveForProblem(Problem);
    nFlip = 15;
    x = (1:nFlip)';
    PopDec = [x x] ./ nFlip;
    OffDec = PopDec + 0.01;
    PopObj = [x nFlip + 1 - x];
    OffObj = [x + 0.1 nFlip + 0.9 - x];
    Population1 = SOLUTION(PopDec,PopObj,zeros(nFlip,1));
    Offspring1 = SOLUTION(OffDec,OffObj,ones(nFlip,1));
    Options = struct( ...
        'paretoFilterMode',"ref_af_nd", ...
        'pairDirectionMode',"af_not_dominates_ai", ...
        'sourceCapMode',"limited", ...
        'pairRefMode',"none");

    [~,~,DiagLimited] = UpdateBoundaryArchive_BDG(Problem,EmptyArchive, ...
        EmptyArchive,Population1,Offspring1,[],[],W,perRef,nearTau,Options);
    Options.sourceCapMode = "none";
    [~,~,DiagNoCap] = UpdateBoundaryArchive_BDG(Problem,EmptyArchive, ...
        EmptyArchive,Population1,Offspring1,[],[],W,perRef,nearTau,Options);

    assert(DiagLimited.pair_count_flip == 10, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:LimitedSourceCapChanged', ...
        'The limited source-cap control must keep the historical baseMaxPair=10 for N=20.');
    assert(DiagNoCap.pair_count_flip == nFlip, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:NoSourceCapTruncatedFlipPairs', ...
        'sourceCapMode=none must collect all feasibility-flip pairs before archive filtering.');
end

