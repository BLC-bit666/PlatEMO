function assertDirectionEmptyRetainsPreviousArchive()
    Problem = struct('N',20,'D',2,'M',2);
    W = [1 0;0 1;0.5 0.5];
    perRef = 5;
    nearTau = 10;
    Options = struct( ...
        'paretoFilterMode',"global_af_nd", ...
        'pairDirectionMode',"ai_dominates_af");

    AF = struct( ...
        'decs',[0.1 0.1], ...
        'objs',[3 3], ...
        'ref',1, ...
        'score',0);
    AI = struct( ...
        'decs',[0.2 0.2], ...
        'objs',[2 2], ...
        'ref',1, ...
        'score',0);

    Population1 = SOLUTION([0 0],[1 1],0);
    Offspring1 = SOLUTION([1 1],[2 2],1);
    assert(all(AI.objs <= AF.objs) && any(AI.objs < AF.objs), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:BadSyntheticPreviousPair', ...
        'The previous synthetic archive pair must satisfy AI dominates AF.');
    assert(~(all(Offspring1.objs <= Population1.objs) && ...
            any(Offspring1.objs < Population1.objs)), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:BadSyntheticNewPair', ...
        'The new synthetic pair must fail AI dominates AF.');

    [NewAF,NewAI,Diag] = UpdateBoundaryArchive_BDG(Problem,AF,AI, ...
        Population1,Offspring1,[],[],W,perRef,nearTau,Options);

    assert(Diag.archive_pareto_filter_keep_count > 0, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:MissingParetoKeep', ...
        'Synthetic archive update must keep candidates after Pareto filtering.');
    assert(Diag.archive_pair_direction_mode == "ai_dominates_af", ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:WrongDirectionMode', ...
        'Synthetic archive update must exercise ai_dominates_af.');
    assert(Diag.archive_pair_direction_candidate_count > 0, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:MissingDirectionCandidate', ...
        'Synthetic archive update must exercise a non-empty pair-direction candidate set.');
    assert(Diag.archive_pair_direction_keep_count == 0, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:UnexpectedDirectionKeep', ...
        'Synthetic archive update must exercise the empty ai_dominates_af direction gate.');
    assertArchiveEqual(NewAF,AF,"AF");
    assertArchiveEqual(NewAI,AI,"AI");

    EmptyArchive = struct( ...
        'decs',zeros(0,Problem.D), ...
        'objs',zeros(0,Problem.M), ...
        'ref',zeros(0,1), ...
        'score',zeros(0,1));
    [EmptyAF,EmptyAI,EmptyDiag] = UpdateBoundaryArchive_BDG( ...
        Problem,EmptyArchive,EmptyArchive, ...
        Population1,Offspring1,[],[],W,perRef,nearTau,Options);
    assert(EmptyDiag.archive_pair_direction_keep_count == 0, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:UnexpectedEmptyArchiveDirectionKeep', ...
        'The no-previous-archive control must exercise the empty direction gate.');
    assert(isempty(EmptyAF.decs) && isempty(EmptyAI.decs), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:DirectionEmptyCreatedArchive', ...
        'An empty current direction gate must not create an archive without previous pairs.');
end

