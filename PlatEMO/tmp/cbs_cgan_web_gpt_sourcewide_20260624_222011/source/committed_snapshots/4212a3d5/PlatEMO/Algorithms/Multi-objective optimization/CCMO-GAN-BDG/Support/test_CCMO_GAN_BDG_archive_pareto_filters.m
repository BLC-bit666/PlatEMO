function assertUnifiedNeighborPairingUsesAllSourcesAndPreviousArchive()
    Problem = struct('N',20,'D',2,'M',2);
    W = [1 0;0.75 0.25;0.5 0.5;0.25 0.75;0 1];
    perRef = 10;
    nearTau = 10;
    AF = struct( ...
        'decs',[0.3 0.3], ...
        'objs',[1 0], ...
        'ref',1, ...
        'score',0);
    AI = struct( ...
        'decs',[0.4 0.4], ...
        'objs',[0 1], ...
        'ref',5, ...
        'score',0);
    Options = struct( ...
        'paretoFilterMode',"ref_af_nd", ...
        'pairDirectionMode',"af_not_dominates_ai", ...
        'sourceCapMode',"none", ...
        'pairRefMode',"neighbor4");

    Population1 = SOLUTION([0 0],[0 1],0);
    Offspring1 = SOLUTION([1 1],[1 0],1);
    [NewAF,NewAI,Diag] = UpdateBoundaryArchive_BDG(Problem,AF,AI, ...
        Population1,Offspring1,[],[],W,perRef,nearTau,Options);

    assert(size(NewAF.decs,1) >= 2 && size(NewAI.decs,1) >= 2, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:UnifiedNeighborPairingDidNotRepairPairs', ...
