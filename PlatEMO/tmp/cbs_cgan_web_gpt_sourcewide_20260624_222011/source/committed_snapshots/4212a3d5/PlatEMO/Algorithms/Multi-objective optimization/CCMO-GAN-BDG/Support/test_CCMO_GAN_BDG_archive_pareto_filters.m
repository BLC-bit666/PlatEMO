function assertAFNotDominatesAIDirectionMode()
    Problem = struct('N',20,'D',2,'M',2);
    W = [1 0;0.5 0.5;0 1];
    perRef = 10;
    nearTau = 0;
    EmptyArchive = emptyArchiveForProblem(Problem);
    Options = struct( ...
        'paretoFilterMode',"ref_af_nd", ...
        'pairDirectionMode',"af_not_dominates_ai", ...
        'sourceCapMode',"none", ...
        'pairRefMode',"none");

    Population1 = SOLUTION([0 0],[0 1],0);
    Offspring1 = SOLUTION([1 1],[1 0],1);
    [AF,AI,Diag] = UpdateBoundaryArchive_BDG(Problem,EmptyArchive, ...
        EmptyArchive,Population1,Offspring1,[],[],W,perRef,nearTau,Options);
    assert(Diag.archive_pair_direction_keep_count == 1, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:MutualPairRejected', ...
        'af_not_dominates_ai must keep mutually nondominated AF-AI pairs.');
    assert(size(AF.decs,1) == 1 && size(AI.decs,1) == 1, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:MutualPairMissingArchive', ...
        'A mutually nondominated pair must enter the archive under af_not_dominates_ai.');

    Population1 = SOLUTION([0 0],[0 0],0);
    Offspring1 = SOLUTION([1 1],[1 1],1);
    [AF,AI,Diag] = UpdateBoundaryArchive_BDG(Problem,EmptyArchive, ...
        EmptyArchive,Population1,Offspring1,[],[],W,perRef,nearTau,Options);
    assert(Diag.archive_pair_direction_keep_count == 0, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:AFDominatesAIKept', ...
        'af_not_dominates_ai must reject pairs where AF dominates AI.');
    assert(isempty(AF.decs) && isempty(AI.decs), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:AFDominatesAICreatedArchive', ...
        'Pairs where AF dominates AI must not enter the archive.');
end

