            'test_CCMO_GAN_BDG_archive_pareto_filters:EmptyDirectionSnapshot', ...
        'Pair-direction smoke must produce AF and AI training rows.');
    afObj = [numericColumn(AF,'obj1'),numericColumn(AF,'obj2')];
    aiObj = [numericColumn(AI,'obj1'),numericColumn(AI,'obj2')];
    afPair = numericColumn(AF,'pair_index');
    aiPair = numericColumn(AI,'pair_index');
    for i = 1 : numel(afPair)
        j = find(aiPair == afPair(i),1);
        assert(~isempty(j), ...
            'test_CCMO_GAN_BDG_archive_pareto_filters:MissingAIPair', ...
            'Each AF row must retain its paired AI row.');
        aiDominatesAF = all(aiObj(j,:) <= afObj(i,:)) && ...
            any(aiObj(j,:) < afObj(i,:));
        assert(aiDominatesAF, ...
            'test_CCMO_GAN_BDG_archive_pareto_filters:AIDoesNotDominateAF', ...
            'AI endpoint must dominate the paired AF endpoint in objective space.');
    end
end

function keep = nondominatedMask(Obj)
    Obj = double(Obj);
    n = size(Obj,1);
    keep = true(n,1);
    for i = 1 : n
        for j = 1 : n
            if i == j
                continue;
            end
            if all(Obj(j,:) <= Obj(i,:)) && any(Obj(j,:) < Obj(i,:))
                keep(i) = false;
                break;
            end
        end
    end
end

function Values = numericColumn(T,Name)
    Values = T.(Name);
    if iscell(Values) || isstring(Values)
        Values = str2double(string(Values));
    elseif islogical(Values)
        Values = double(Values);
    else
        Values = double(Values);
    end
end

