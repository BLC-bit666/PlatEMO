    oldFE = Problem.FE;
    XAF = repmat(0.2,3,Problem.D);
    XAI = repmat(0.8,3,Problem.D);
    PAF = Problem.Evaluation(XAF);
    PAI = Problem.Evaluation(XAI);
    AF = struct('decs',XAF,'objs',PAF.objs);
    AI = struct('decs',XAI,'objs',PAI.objs);
    QualityData = BoundaryQualityTarget_BDG('buildData', ...
        AF,AI,Problem,0.20);

    XScaled = dlarray(zeros(Problem.D,5,'single'),'CB');
    pairIdx = ones(5,1);
    [Labels,~,Obj,Cons,Diag] = BoundaryQualityTarget_BDG( ...
        'generatedLabels',XScaled,pairIdx,QualityData);

    assert(size(Obj,2) == Problem.M, ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:GeneratedLabelsUseDefaultCalObj', ...
        'LIRCMOP_BC generated boundary-quality labels must use Evaluation when CalObj is inherited from PROBLEM.');
    assert(size(Cons,1) == size(Obj,1), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:GeneratedLabelsBadConstraintRows', ...
        'Generated boundary-quality constraints must align with generated objective rows.');
    assert(numel(extractdata(Labels)) == size(Obj,1), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:GeneratedLabelsBadLabelCount', ...
        'Generated boundary-quality labels must align with generated objective rows.');
    componentValues = [ ...
        Diag.boundary_quality_segment_score_mean, ...
        Diag.boundary_quality_feasible_score_mean, ...
        Diag.boundary_quality_outside_score_mean, ...
        Diag.boundary_quality_positive_cv_mean];
    assert(all(isfinite(componentValues)), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:GeneratedLabelsMissingComponents', ...
        'LIRCMOP_BC generated boundary-quality diagnostics must include finite component means.');
    assert(Problem.FE == oldFE + numel(PAF) + numel(PAI), ...
        'test_CCMO_GAN_BDG_archive_pareto_filters:GeneratedLabelsChangedFE', ...
        'Generated boundary-quality label diagnostics must not consume additional FE.');
end

