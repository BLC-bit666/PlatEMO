function Row = addEmptyDiagnosticSummaryFields(Row)
    Fields = diagnosticCoreFields();
    for i = 1 : numel(Fields)
        Row.(['final_',Fields{i}]) = NaN;
        Row.(['mean_',Fields{i}]) = NaN;
    end
end

function Row = addDiagnosticSummaries(Row,LastRaw,RefreshCore)
    Fields = diagnosticCoreFields();
    for i = 1 : numel(Fields)
        name = Fields{i};
        Row.(['final_',name]) = fieldValue(LastRaw,name);
        Row.(['mean_',name]) = meanFinite(fieldVector(RefreshCore,name));
    end
end

