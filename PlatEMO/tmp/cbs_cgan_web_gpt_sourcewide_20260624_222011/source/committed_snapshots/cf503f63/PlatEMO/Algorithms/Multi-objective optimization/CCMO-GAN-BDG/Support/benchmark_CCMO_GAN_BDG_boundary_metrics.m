function Results = benchmark_CCMO_GAN_BDG_boundary_metrics(problemNames,runIds,outCsv,N,maxFE,workerCount,algorithmParams)
% Run CCMO_GAN_BDG boundary/GAN diagnostics and persist per-run summaries.
%
% Default setting:
%   10 selected DASCMOP_BC/LIRCMOP_BC problems, runs 1:8, N=100,
%   maxFE=200000, and 8 local parallel workers.

    if nargin < 1 || isempty(problemNames)
        problemNames = defaultProblemList();
    end
    if nargin < 2 || isempty(runIds)
        runIds = 1 : 8;
    end
    if nargin < 3 || isempty(outCsv)
        rootDir = fileparts(which('platemo'));
        outDir = fullfile(rootDir,'Data','CCMO_GAN_BDG', ...
            ['boundary_metric_runs_',char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
        outCsv = fullfile(outDir,'benchmark_runs.csv');
    end
    if nargin < 4 || isempty(N)
        N = 100;
    end
    if nargin < 5 || isempty(maxFE)
        maxFE = 200000;
    end
    if nargin < 6 || isempty(workerCount)
        workerCount = 8;
    end
    if nargin < 7
        algorithmParams = [];
    end

    problemNames = cellstr(string(problemNames(:)));
    runIds = double(runIds(:)');
    outDir = fileparts(outCsv);
    if ~isempty(outDir) && ~isfolder(outDir)
        mkdir(outDir);
    end

    [TaskProblem,TaskRun] = ndgrid(1:numel(problemNames),runIds);
    TaskProblem = TaskProblem(:);
    TaskRun = TaskRun(:);
    TaskProblemNames = problemNames(TaskProblem);
    Rows = repmat(emptyBenchmarkRow(),numel(TaskProblem),1);

    workerCount = max(1,round(double(workerCount)));
    if workerCount > 1
        ensureParallelPool(workerCount);
        parfor task = 1 : numel(TaskProblem)
            Rows(task) = runOneBenchmark(TaskProblemNames{task},TaskRun(task),N,maxFE,algorithmParams);
        end
    else
        for task = 1 : numel(TaskProblem)
            Rows(task) = runOneBenchmark(TaskProblemNames{task},TaskRun(task),N,maxFE,algorithmParams);
        end
    end

    Results = struct2table(Rows);
    writetable(Results,outCsv);
end

function Row = runOneBenchmark(problemName,runId,N,maxFE,algorithmParams)
    Row = emptyBenchmarkRow();
    Row.problem = string(problemName);
    Row.family = problemFamily(problemName);
    Row.run = double(runId);
    try
        rootDir = fileparts(which('platemo'));
        addpath(genpath(rootDir));
        rng(double(runId),'twister');
        algorithmArgs = { ...
            'save',0, ...
            'run',double(runId), ...
            'outputFcn',@(varargin)[]};
        if ~isempty(algorithmParams)
            algorithmArgs = [algorithmArgs,{'parameter',algorithmParams}];
        end
        Algorithm = CCMO_GAN_BDG(algorithmArgs{:});
        ProblemConstructor = str2func(problemName);
        Problem = ProblemConstructor('N',N,'maxFE',maxFE);
        Algorithm.Solve(Problem);
        Row = composeBenchmarkRow(Row,Algorithm);
        Row.status = "ok";
    catch err
        Row.status = "failed";
        Row.error_message = string(err.message);
    end
end

function Row = composeBenchmarkRow(Row,Algorithm)
    Row.runtime = double(Algorithm.metric.runtime);
    Row.analysis_folder = string(Algorithm.metric.analysis_folder);
    Row.analysis_core_csv = string(Algorithm.metric.analysis_core_csv);
    if ~isfile(Algorithm.metric.analysis_core_csv)
        Row.error_message = "core_metrics.csv missing";
        return;
    end

    Core = readtable(Algorithm.metric.analysis_core_csv,'TextType','string');
    Row.log_row_count = height(Core);
    if ismember('refresh_flag',Core.Properties.VariableNames)
        RefreshCore = Core(Core.refresh_flag == 1,:);
        Row.refresh_count = height(RefreshCore);
        Row.skip_count = height(Core) - Row.refresh_count;
    else
        RefreshCore = Core;
        Row.refresh_count = height(Core);
        Row.skip_count = 0;
    end
    if isempty(Core)
        return;
    end
    Last = Core(end,:);
    LastRaw = Last;
    if ~isempty(RefreshCore)
        LastRaw = RefreshCore(end,:);
    end
    Row.final_gen = double(Last.gen);
    Row.final_FE = double(Last.FE);
    Row.final_AF_size = double(Last.AF_size);
    Row.final_AI_size = fieldValue(Last,'AI_size');
    Row.mean_AF_size = meanFinite(Core.AF_size);
    Row.mean_AI_size = meanFinite(fieldVector(Core,'AI_size'));
    Row.final_Gap_obj_med = double(Last.Gap_obj_med);
    Row.mean_Gap_obj_med = meanFinite(Core.Gap_obj_med);
    Row.final_Gap_dec_med = double(Last.Gap_dec_med);
    Row.mean_Gap_dec_med = meanFinite(Core.Gap_dec_med);
    Row.final_Ref_cov = double(Last.Ref_cov);
    Row.mean_Ref_cov = meanFinite(Core.Ref_cov);
    Row.final_AF_candidate_count = fieldValue(Last,'AF_candidate_count');
    Row.mean_AF_candidate_count = meanFinite(fieldVector(Core,'AF_candidate_count'));
    Row.final_AF_retention_ratio = fieldValue(Last,'AF_retention_ratio');
    Row.mean_AF_retention_ratio = meanFinite(fieldVector(Core,'AF_retention_ratio'));
    Row.final_AF_front1_count = fieldValue(Last,'AF_front1_count');
    Row.mean_AF_front1_count = meanFinite(fieldVector(Core,'AF_front1_count'));
    Row.final_AF_front1_ratio = fieldValue(Last,'AF_front1_ratio');
    Row.mean_AF_front1_ratio = meanFinite(fieldVector(Core,'AF_front1_ratio'));
    Row.final_AF_kept_front1_ratio = fieldValue(Last,'AF_kept_front1_ratio');
    Row.mean_AF_kept_front1_ratio = meanFinite(fieldVector(Core,'AF_kept_front1_ratio'));
    Row.final_score_gap_obj_med = fieldValue(Last,'score_gap_obj_med');
    Row.mean_score_gap_obj_med = meanFinite(fieldVector(Core,'score_gap_obj_med'));
    Row.final_score_gap_dec_med = fieldValue(Last,'score_gap_dec_med');
    Row.mean_score_gap_dec_med = meanFinite(fieldVector(Core,'score_gap_dec_med'));
    Row.final_score_conv_med = fieldValue(Last,'score_conv_med');
    Row.mean_score_conv_med = meanFinite(fieldVector(Core,'score_conv_med'));
    Row.final_score_rank_med = fieldValue(Last,'score_rank_med');
    Row.mean_score_rank_med = meanFinite(fieldVector(Core,'score_rank_med'));
    Row.final_pair_count_flip = fieldValue(Last,'pair_count_flip');
    Row.mean_pair_count_flip = meanFinite(fieldVector(Core,'pair_count_flip'));
    Row.final_pair_count_cross = fieldValue(Last,'pair_count_cross');
    Row.mean_pair_count_cross = meanFinite(fieldVector(Core,'pair_count_cross'));
    Row.final_pair_count_self = fieldValue(Last,'pair_count_self');
    Row.mean_pair_count_self = meanFinite(fieldVector(Core,'pair_count_self'));
    Row.final_pair_eval_FE = fieldValue(Last,'pair_eval_FE');
    Row.mean_pair_eval_FE = meanFinite(fieldVector(Core,'pair_eval_FE'));
    Row.final_Raw_count = fieldValue(LastRaw,'Raw_count');
    Row.mean_Raw_count = meanFinite(fieldVector(RefreshCore,'Raw_count'));
    Row.final_Raw_feasible_count = fieldValue(LastRaw,'Raw_feasible_count');
    Row.mean_Raw_feasible_count = meanFinite(fieldVector(RefreshCore,'Raw_feasible_count'));
    Row.final_Raw_hit_count = fieldValue(LastRaw,'Raw_hit_count');
    Row.mean_Raw_hit_count = meanFinite(fieldVector(RefreshCore,'Raw_hit_count'));
    Row.final_Raw_minAI_dist_med = fieldValue(LastRaw,'Raw_minAI_dist_med');
    Row.mean_Raw_minAI_dist_med = meanFinite(fieldVector(RefreshCore,'Raw_minAI_dist_med'));
    Row.final_Raw_minAI_dist_p10 = fieldValue(LastRaw,'Raw_minAI_dist_p10');
    Row.mean_Raw_minAI_dist_p10 = meanFinite(fieldVector(RefreshCore,'Raw_minAI_dist_p10'));
    Row.final_Raw_minAF_dist_med = fieldValue(LastRaw,'Raw_minAF_dist_med');
    Row.mean_Raw_minAF_dist_med = meanFinite(fieldVector(RefreshCore,'Raw_minAF_dist_med'));
    Row.final_Raw_FR = double(LastRaw.Raw_FR);
    Row.mean_Raw_FR = meanFinite(RefreshCore.Raw_FR);
    Row.final_Raw_BHR = double(LastRaw.Raw_BHR);
    Row.mean_Raw_BHR = meanFinite(RefreshCore.Raw_BHR);
    Row.final_Raw_BHR_cond = fieldValue(LastRaw,'Raw_BHR_cond');
    Row.mean_Raw_BHR_cond = meanFinite(fieldVector(RefreshCore,'Raw_BHR_cond'));
    Row.final_Repair_rate = double(LastRaw.Repair_rate);
    Row.mean_Repair_rate = meanFinite(RefreshCore.Repair_rate);
    Row = addDiagnosticSummaries(Row,LastRaw,RefreshCore);
end

function ensureParallelPool(workerCount)
    pool = gcp('nocreate');
    if ~isempty(pool) && pool.NumWorkers ~= workerCount
        delete(pool);
        pool = [];
    end
    if isempty(pool)
        parpool('local',workerCount);
    end
end

