function family = problemFamily(problemName)
    if startsWith(string(problemName),"DASCMOP")
        family = "DASCMOP_BC";
    elseif startsWith(string(problemName),"LIRCMOP")
        family = "LIRCMOP_BC";
    else
        family = "Other";
    end
end

function value = meanFinite(values)
    values = double(values(:));
    values = values(isfinite(values));
    if isempty(values)
        value = NaN;
    else
        value = mean(values);
    end
end

function value = fieldValue(T,name)
    if ismember(name,T.Properties.VariableNames)
        value = double(T.(name)(1));
    else
        value = NaN;
    end
end

function values = fieldVector(T,name)
    if isempty(T) || ~ismember(name,T.Properties.VariableNames)
        values = NaN(0,1);
    else
        values = T.(name);
    end
end
