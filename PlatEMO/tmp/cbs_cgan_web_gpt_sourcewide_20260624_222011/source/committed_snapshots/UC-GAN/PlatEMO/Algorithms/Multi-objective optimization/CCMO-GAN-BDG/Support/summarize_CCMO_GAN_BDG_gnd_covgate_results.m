function Out = summarizeBy_BDG(T,groupVars,metricVars)
    groupVars = cellstr(groupVars);
    metricVars = cellstr(metricVars);
    if isempty(T)
        Out = table();
        return;
    end
    metricVars = intersect(metricVars,T.Properties.VariableNames,'stable');
    Out = groupsummary(T,groupVars,'mean',metricVars);
end

function Delta = pairwiseDelta_BDG(Overall,metricVars)
    Delta = table();
    if isempty(Overall)
        return;
    end
    baseIdx = find(Overall.variant == "C4_keep80",1,'first');
    if isempty(baseIdx)
        return;
    end
    metricVars = cellstr(metricVars);
    rows = repmat(struct('variant',"",'baseline',"C4_keep80", ...
        'metric',"",'delta',NaN,'relative_delta',NaN),0,1);
    k = 0;
    for i = 1 : height(Overall)
        if Overall.variant(i) == "C4_keep80"
            continue;
        end
        for m = 1 : numel(metricVars)
            name = ['mean_',metricVars{m}];
            if ~ismember(name,Overall.Properties.VariableNames)
                continue;
            end
            base = double(Overall.(name)(baseIdx));
            value = double(Overall.(name)(i));
            k = k + 1;
            rows(k).variant = string(Overall.variant(i)); %#ok<AGROW>
            rows(k).baseline = "C4_keep80";
            rows(k).metric = string(metricVars{m});
            rows(k).delta = value - base;
            rows(k).relative_delta = safeRatio_BDG(value - base,abs(base));
        end
    end
    if k > 0
        Delta = struct2table(rows);
    end
end

function value = tableNumber_BDG(T,name,row)
    value = NaN;
    if ~ismember(name,T.Properties.VariableNames)
        return;
    end
    raw = T.(name);
    raw = raw(row);
    if iscell(raw) || isstring(raw)
        raw = str2double(string(raw));
    else
        raw = double(raw);
    end
    if ~isempty(raw)
        value = raw(1);
    end
end

function value = tableString_BDG(T,name,row,defaultValue)
    value = string(defaultValue);
    if ~ismember(name,T.Properties.VariableNames)
        return;
    end
    raw = T.(name);
    raw = raw(row);
    if iscell(raw)
        raw = raw{1};
    end
    value = string(raw);
end

function value = safeRatio_BDG(num,den)
    if ~isfinite(num) || ~isfinite(den) || den <= 0
        value = NaN;
    else
        value = double(num) ./ double(den);
    end
end

function outDir = latestDir_BDG(baseDir,pattern)
    info = dir(fullfile(baseDir,pattern));
    info = info([info.isdir]);
    assert(~isempty(info), ...
        'summarize_CCMO_GAN_BDG_gnd_covgate_results:MissingSourceDir', ...
        'No directory matched %s',fullfile(baseDir,pattern));
    [~,idx] = max([info.datenum]);
    outDir = fullfile(info(idx).folder,info(idx).name);
end

function order = problemOrder_BDG(problem)
    names = ["DASCMOP1_BC","DASCMOP2_BC","DASCMOP4_BC", ...
        "DASCMOP5_BC","LIRCMOP5_BC","LIRCMOP6_BC", ...
        "LIRCMOP7_BC","LIRCMOP8_BC","LIRCMOP9_BC", ...
        "LIRCMOP10_BC"];
    idx = find(names == string(problem),1,'first');
    if isempty(idx)
        order = inf;
    else
        order = idx;
    end
end
