function SummaryDir = summarize_CCMO_GAN_BDG_gnd_covgate_results( ...
        SummaryDir,c4Dir,gndDir,gateDir)
%summarize_CCMO_GAN_BDG_gnd_covgate_results Aggregate global-ND controls.

    rootDir = fileparts(which('platemo'));
    addpath(genpath(rootDir));
    baseDir = fullfile(rootDir,'Data','CCMO_GAN_BDG');
    if nargin < 1 || isempty(SummaryDir)
        SummaryDir = fullfile(baseDir, ...
            ['gnd_covgate_summary_', ...
            char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
    end
    if nargin < 2 || isempty(c4Dir)
        c4Dir = latestDir_BDG(baseDir,'C4_keep80_runs3_n100_fe100000_7w_*');
    end
    if nargin < 3 || isempty(gndDir)
        gndDir = latestDir_BDG(baseDir,'GND_keep80_runs3_n100_fe100000_7w_*');
    end
    if nargin < 4 || isempty(gateDir)
        gateDir = latestDir_BDG(baseDir, ...
            'GND_keep80_covGate_runs3_n100_fe100000_7w_*');
    end
    if ~isfolder(SummaryDir)
        mkdir(SummaryDir);
    end

    Sources = table( ...
        (1:3)', ...
        ["C4_keep80";"GND_keep80";"GND_keep80_covGate"], ...
        ["local_ref_nd";"global_nd";"global_nd_gate"], ...
        [string(c4Dir);string(gndDir);string(gateDir)], ...
        'VariableNames',{'variantOrder','variant','experimentClass', ...
        'outDir'});
    writetable(Sources,fullfile(SummaryDir,'gnd_covgate_sources.csv'));

    Rows = repmat(emptyRunRow_BDG(),0,1);
    k = 0;
    for s = 1 : height(Sources)
        runFile = fullfile(char(Sources.outDir(s)), ...
            'archive_pareto_filter_run_summary.csv');
        assert(isfile(runFile), ...
            'summarize_CCMO_GAN_BDG_gnd_covgate_results:MissingRunSummary', ...
            'Missing run summary: %s',runFile);
        T = readtable(runFile,'TextType','string');
        for i = 1 : height(T)
            k = k + 1;
            Rows(k) = readRunRow_BDG(T,i,Sources(s,:)); %#ok<AGROW>
        end
    end
    RunRows = struct2table(Rows);
    writetable(RunRows,fullfile(SummaryDir, ...
        'gnd_covgate_all_run_selected.csv'));

    Ok = RunRows(RunRows.status == "ok",:);
    metricVars = ["BoundaryHit_all", ...
        "ObjInterfaceScore", ...
        "GAN_to_Segment_Dist50", ...
        "GAN_to_Segment_Dist90", ...
        "GAN_to_Decision_Segment_Dist50", ...
        "GAN_to_Decision_Segment_Dist90", ...
        "GAN_to_AF_ObjNN_median", ...
        "GAN_to_AF_DecNN_median", ...
        "RawGANFeasibleRate", ...
        "RawGANOutsideStandardRangeCount", ...
        "RefCov", ...
        "DuplicateRate", ...
        "train_ref_cov", ...
        "target_filter_post_ref_cov", ...
        "target_triple_count", ...
        "AF_ref_cov", ...
        "archive_filter_keep_ratio", ...
        "trained_count", ...
        "coverage_gate_count", ...
        "coverage_gate_rate", ...
        "target_insufficient_count", ...
        "AF_empty_count", ...
        "IGD", ...
        "HV", ...
        "runtime"];
    Overall = summarizeBy_BDG(Ok, ...
        ["variantOrder","variant","experimentClass"],metricVars);
    ByProblem = summarizeBy_BDG(Ok, ...
        ["variantOrder","variant","experimentClass","problemOrder", ...
        "problem"],metricVars);
    Delta = pairwiseDelta_BDG(Overall, ...
        ["BoundaryHit_all","ObjInterfaceScore", ...
        "GAN_to_Segment_Dist50","GAN_to_Segment_Dist90", ...
        "GAN_to_Decision_Segment_Dist50", ...
        "RawGANFeasibleRate","RefCov","train_ref_cov", ...
        "target_filter_post_ref_cov","target_triple_count", ...
        "coverage_gate_rate","IGD","HV","runtime"]);

    writetable(Overall,fullfile(SummaryDir, ...
        'gnd_covgate_overall_selected.csv'));
    writetable(ByProblem,fullfile(SummaryDir, ...
        'gnd_covgate_by_problem_selected.csv'));
    writetable(Delta,fullfile(SummaryDir, ...
        'gnd_covgate_pairwise_delta.csv'));
end

function Row = readRunRow_BDG(T,i,Source)
    Row = emptyRunRow_BDG();
    Row.variantOrder = double(Source.variantOrder);
    Row.variant = string(Source.variant);
    Row.experimentClass = string(Source.experimentClass);
    Row.outDir = string(Source.outDir);
    Row.problem = tableString_BDG(T,'problem',i,"");
    Row.problemOrder = problemOrder_BDG(Row.problem);
    Row.run = tableNumber_BDG(T,'run',i);
    Row.status = tableString_BDG(T,'status',i,"");
    Row.runtime = tableNumber_BDG(T,'runtime',i);
    Row.IGD = tableNumber_BDG(T,'IGD',i);
    Row.HV = tableNumber_BDG(T,'HV',i);
    Row.BoundaryHit_all = tableNumber_BDG(T,'final_BoundaryHit_all',i);
    Row.ObjInterfaceScore = tableNumber_BDG(T,'final_ObjInterfaceScore',i);
    Row.GAN_to_Segment_Dist50 = ...
        tableNumber_BDG(T,'final_GAN_to_Segment_Dist50',i);
    Row.GAN_to_Segment_Dist90 = ...
        tableNumber_BDG(T,'final_GAN_to_Segment_Dist90',i);
    Row.GAN_to_Decision_Segment_Dist50 = ...
        tableNumber_BDG(T,'final_GAN_to_Decision_Segment_Dist50',i);
    Row.GAN_to_Decision_Segment_Dist90 = ...
        tableNumber_BDG(T,'final_GAN_to_Decision_Segment_Dist90',i);
    Row.GAN_to_AF_ObjNN_median = ...
        tableNumber_BDG(T,'final_GAN_to_AF_ObjNN_median',i);
    Row.GAN_to_AF_DecNN_median = ...
        tableNumber_BDG(T,'final_GAN_to_AF_DecNN_median',i);
    Row.RawGANFeasibleRate = ...
        tableNumber_BDG(T,'final_RawGANFeasibleRate',i);
    Row.RawGANOutsideStandardRangeCount = ...
        tableNumber_BDG(T,'final_RawGANOutsideStandardRangeCount',i);
    Row.RefCov = tableNumber_BDG(T,'final_RefCov',i);
    Row.DuplicateRate = tableNumber_BDG(T,'final_DuplicateRate',i);
    Row.train_ref_cov = tableNumber_BDG(T,'final_train_ref_cov',i);
    Row.target_filter_post_ref_cov = ...
        tableNumber_BDG(T,'final_target_filter_post_ref_cov',i);
    Row.target_triple_count = ...
        tableNumber_BDG(T,'final_target_triple_count',i);
    Row.AF_ref_cov = tableNumber_BDG(T,'final_AF_ref_cov',i);
    Row.archive_filter_keep_ratio = ...
        tableNumber_BDG(T,'final_archive_filter_keep_ratio',i);
    coreFile = tableString_BDG(T,'core_metrics_file',i,"");
    Row = attachSkipStats_BDG(Row,coreFile);
end

function Row = attachSkipStats_BDG(Row,coreFile)
    if strlength(coreFile) == 0 || ~isfile(coreFile)
        return;
    end
    Core = readtable(coreFile,'TextType','string');
    if isempty(Core) || ~ismember('skip_reason',Core.Properties.VariableNames)
        return;
    end
    reason = string(Core.skip_reason);
    Row.train_event_count = height(Core);
    Row.trained_count = sum(reason == "trained");
    Row.coverage_gate_count = sum(reason == "target_coverage_gate");
    Row.target_insufficient_count = sum(reason == "target_triples_insufficient");
    Row.AF_empty_count = sum(reason == "AF_empty");
    Row.coverage_gate_rate = safeRatio_BDG( ...
        Row.coverage_gate_count,Row.train_event_count);
end

