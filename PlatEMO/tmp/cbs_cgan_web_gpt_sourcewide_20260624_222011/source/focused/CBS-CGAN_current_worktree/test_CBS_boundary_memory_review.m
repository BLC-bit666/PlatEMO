function test_CBS_boundary_memory_review()
%TEST_CBS_BOUNDARY_MEMORY_REVIEW Regression tests for paired thin-boundary memory.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    testUnpairedFeasibleFallbackIsRejected();
    testBoundaryMemoryStoresFinitePairedRows();
    testBoundaryDiagnosticsExposePipelineCounts();
    testPreviousUnpairedMemoryDoesNotCompleteCurrentBoundary();
    testPreviousPairedMemoryCanParticipateAsPairCandidate();
    testBestGapPerReferenceIsRetained();
    testCanonicalCanRetainTopKPerReference();
    testThinBoundaryTargetCanUseInteriorFeasibleSupport();
    fprintf('CBS paired boundary memory regressions passed.\n');
end

function testUnpairedFeasibleFallbackIsRejected()
    W = [0.51 0.49;0.49 0.51];
    Options = defaultOptions();

    Pop = makePopulation( ...
        [0.30 0.40;0.50 0.60], ...
        [5.08 4.92;4.92 5.08], ...
        [0;0]);
    Empty = Pop([]);

    [BMem,Diag] = UpdateBoundaryMemory_CBS([],Pop,Empty,Empty,Empty,W,Options);

    assert(isempty(BMem.y_b), ...
        'Unpaired feasible supports must not enter paired thin-boundary memory.');
    assert(Diag.bmem_count == 0 && Diag.finite_gap_count == 0 && ...
            Diag.inf_gap_count == 0, ...
        'Paired memory diagnostics must not report Inf-gap fallback rows.');
end

function testBoundaryMemoryStoresFinitePairedRows()
    W = [0.51 0.49;0.49 0.51];
    Options = defaultOptions();

    feasibleDec = [0.30 0.40;0.50 0.60];
    feasibleObj = [5.08 4.92;4.92 5.08];
    infeasibleDec = [0.31 0.41;0.51 0.61];
    infeasibleObj = [5.10 4.90;4.90 5.10];
    Pop = makePopulation( ...
        [feasibleDec(1,:);infeasibleDec(1,:); ...
         feasibleDec(2,:);infeasibleDec(2,:)], ...
        [feasibleObj(1,:);infeasibleObj(1,:); ...
         feasibleObj(2,:);infeasibleObj(2,:)], ...
        [0;1;0;1]);
    Empty = Pop([]);

    [BMem,Diag] = UpdateBoundaryMemory_CBS([],Pop,Empty,Empty,Empty,W,Options);

    assert(Diag.bmem_count == 2 && Diag.finite_gap_count == 2 && ...
            Diag.inf_gap_count == 0, ...
        'Boundary memory must retain only finite-gap paired rows.');
    assert(isequal(sort(fieldnames(BMem)),sort({ ...
            'ref';'y_b';'gap';'x_b';'x_f';'y_f';'x_i';'y_i';'tau'})), ...
        'Boundary memory must expose paired feasible/infeasible support fields and tau.');
    [~,ord] = sort(BMem.ref);
    assert(max(abs(BMem.x_f(ord,:) - feasibleDec),[],'all') <= 1e-12 && ...
            max(abs(BMem.y_f(ord,:) - feasibleObj),[],'all') <= 1e-12, ...
        'BMem must preserve feasible pair endpoints.');
    assert(max(abs(BMem.x_i(ord,:) - infeasibleDec),[],'all') <= 1e-12 && ...
            max(abs(BMem.y_i(ord,:) - infeasibleObj),[],'all') <= 1e-12, ...
        'BMem must preserve paired infeasible endpoints.');
    assert(all(isfinite(BMem.gap)) && all(isfinite(BMem.tau)) && ...
            all(BMem.tau >= 0 & BMem.tau <= 1), ...
        'Paired rows must carry finite gap and normalized tau support.');
end

function testBoundaryDiagnosticsExposePipelineCounts()
    W = [0.51 0.49;0.49 0.51];
    Options = defaultOptions();

    Pop = makePopulation( ...
        [0.30 0.40;0.31 0.41;0.50 0.60;0.51 0.61], ...
        [5.08 4.92;5.10 4.90;4.92 5.08;4.90 5.10], ...
        [0;1;0;1]);
    Empty = Pop([]);

    [~,Diag] = UpdateBoundaryMemory_CBS([],Pop,Empty,Empty,Empty,W,Options);

    required = {'boundary_sample_current_count', ...
        'boundary_sample_prev_pair_count', ...
        'boundary_sample_merged_count', ...
        'boundary_sample_finite_count', ...
        'boundary_feasible_count', ...
        'boundary_infeasible_count', ...
        'boundary_main_feasible_count', ...
        'boundary_ref_pairable_count', ...
        'boundary_pair_distance_count', ...
        'boundary_pair_dominated_skip_count', ...
        'boundary_pair_appended_count', ...
        'boundary_candidate_raw_count', ...
        'boundary_candidate_pareto_count', ...
        'boundary_candidate_gap_count', ...
        'boundary_candidate_dedup_count', ...
        'boundary_candidate_final_count'};
    assert(all(isfield(Diag,required)), ...
        'Boundary diagnostics must expose pipeline count fields.');
    assert(Diag.boundary_sample_current_count == 4 && ...
            Diag.boundary_sample_prev_pair_count == 0 && ...
            Diag.boundary_sample_merged_count == 4 && ...
            Diag.boundary_sample_finite_count == 4, ...
        'Boundary diagnostics should count raw and finite sample inputs.');
    assert(Diag.boundary_feasible_count == 2 && ...
            Diag.boundary_infeasible_count == 2 && ...
            Diag.boundary_main_feasible_count == 2, ...
        'Boundary diagnostics should count feasible, infeasible, and main feasible samples.');
    assert(Diag.boundary_ref_pairable_count == 2 && ...
            Diag.boundary_pair_distance_count == 4 && ...
            Diag.boundary_pair_dominated_skip_count == 0 && ...
            Diag.boundary_pair_appended_count == 2, ...
        'Boundary diagnostics should count pair-search candidates and accepted pairs.');
    assert(Diag.boundary_candidate_raw_count == 2 && ...
            Diag.boundary_candidate_pareto_count == 2 && ...
            Diag.boundary_candidate_gap_count == 2 && ...
            Diag.boundary_candidate_dedup_count == 2 && ...
            Diag.boundary_candidate_final_count == Diag.bmem_count, ...
        'Boundary diagnostics should count filtering stages through final BMem.');
end

function testPreviousUnpairedMemoryDoesNotCompleteCurrentBoundary()
    W = [0.51 0.49;0.49 0.51];
    Options = defaultOptions();

    Pop = makePopulation([0.30 0.40],[5.08 4.92],0);
    Empty = Pop([]);
    PrevBMem = struct( ...
        'ref',2, ...
        'y_b',[4.92 5.08], ...
        'gap',Inf, ...
        'x_b',[0.50 0.60]);

    [BMem,Diag] = UpdateBoundaryMemory_CBS(PrevBMem, ...
        Pop,Empty,Empty,Empty,W,Options);

    assert(isempty(BMem.y_b) && Diag.bmem_count == 0, ...
        ['Historical feasible-only memory must not be replayed directly ', ...
        'into the current training boundary.']);
end

function testPreviousPairedMemoryCanParticipateAsPairCandidate()
    W = [0.51 0.49;0.49 0.51];
    Options = defaultOptions();

    PrevBMem = struct( ...
        'ref',2, ...
        'y_b',[4.92 5.08], ...
        'gap',0.01, ...
        'x_b',[0.50 0.60], ...
        'x_f',[0.50 0.60], ...
        'y_f',[4.92 5.08], ...
        'x_i',[0.51 0.61], ...
        'y_i',[4.90 5.10], ...
        'tau',0);
    Pop = makePopulation( ...
        [0.30 0.40;0.31 0.41], ...
        [5.08 4.92;5.10 4.90], ...
        [0;1]);
    Empty = Pop([]);

    [BMem,Diag] = UpdateBoundaryMemory_CBS(PrevBMem, ...
        Pop,Empty,Empty,Empty,W,Options);

    assert(Diag.bmem_count == 2 && Diag.finite_gap_count == 2, ...
        'Paired previous memory may participate as finite pair candidate support.');
    assert(isequal(sort(BMem.ref(:)),[1;2]), ...
        'Current and paired historical candidates should jointly cover references.');
end

function testBestGapPerReferenceIsRetained()
    W = [0.50 0.50];
    Options = struct( ...
        'pairNeighborRefRadius',0, ...
        'maxCandidatePairsPerRef',2, ...
        'maxCanonicalPairsPerRef',1, ...
        'minBoundaryLength',1);

    smallGapDec = [0.10 0.20];
    smallGapObj = [1.00 2.00];
    largeGapDec = [0.30 0.40];
    largeGapObj = [2.00 1.00];
    Pop = makePopulation( ...
        [smallGapDec;0.11 0.21;largeGapDec;0.31 0.41], ...
        [smallGapObj;1.10 1.90;largeGapObj;2.80 0.40], ...
        [0;1;0;1]);
    Empty = Pop([]);

    [BMem,Diag] = UpdateBoundaryMemory_CBS([],Pop,Empty,Empty,Empty,W,Options);

    assert(Diag.bmem_count == 1 && Diag.boundary_count == 1, ...
        'One canonical paired support should remain for a single reference.');
    assert(max(abs(BMem.x_f - smallGapDec),[],'all') <= 1e-12 && ...
            max(abs(BMem.y_f - smallGapObj),[],'all') <= 1e-12, ...
        'The retained support per reference should prefer the smaller F/I gap.');
end

function testCanonicalCanRetainTopKPerReference()
    W = [0.50 0.50];
    Options = struct( ...
        'pairNeighborRefRadius',0, ...
        'maxCandidatePairsPerRef',3, ...
        'maxCanonicalPairsPerRef',2, ...
        'minBoundaryLength',1);

    feasibleDec = [0.10 0.20;0.30 0.40;0.50 0.60];
    feasibleObj = [1.00 3.00;2.00 2.00;3.00 1.00];
    infeasibleDec = [0.11 0.21;0.31 0.41;0.51 0.61];
    infeasibleObj = [1.05 2.95;2.05 1.95;3.05 0.95];
    Pop = makePopulation( ...
        reshape([feasibleDec';infeasibleDec'],2,[])', ...
        reshape([feasibleObj';infeasibleObj'],2,[])', ...
        repmat([0;1],3,1));
    Empty = Pop([]);

    [BMem,Diag] = UpdateBoundaryMemory_CBS([],Pop,Empty,Empty,Empty,W,Options);

    assert(Diag.boundary_pair_appended_count == 3 && ...
            Diag.boundary_candidate_gap_count == 3, ...
        'The test fixture should produce three accepted same-ref candidates.');
    assert(Diag.boundary_candidate_dedup_count == 2 && ...
            Diag.bmem_count == 2 && size(BMem.y_b,1) == 2, ...
        'Canonical BMem should retain the top-K gap candidates per reference.');
end

function testThinBoundaryTargetCanUseInteriorFeasibleSupport()
    W = [0.50 0.50];
    Options = struct( ...
        'pairNeighborRefRadius',0, ...
        'maxCandidatePairsPerRef',1, ...
        'maxCanonicalPairsPerRef',1, ...
        'minBoundaryLength',1);

    endpointDec = [0.10 0.10];
    interiorDec = [0.20 0.20];
    infeasibleDec = [0.30 0.30];
    Pop = makePopulation( ...
        [endpointDec;interiorDec;infeasibleDec], ...
        [1.50 2.00;2.00 2.10;3.00 1.00], ...
        [0;0;1]);
    Empty = Pop([]);

    [BMem,Diag] = UpdateBoundaryMemory_CBS([],Pop,Empty,Empty,Empty,W,Options);

    assert(Diag.bmem_count == 1, ...
        'The fixture should produce one paired boundary memory row.');
    assert(max(abs(BMem.x_b - interiorDec),[],'all') <= 1e-12, ...
        'Thin-boundary target should use the interior feasible support, not the paired endpoint.');
    assert(BMem.tau > 0 && BMem.tau < 1, ...
        'Interior feasible support should produce non-degenerate tau.');
end

