function test_CBS_feasible_support_branch_review()
%TEST_CBS_FEASIBLE_SUPPORT_BRANCH_REVIEW Paired thin-boundary mainline checks.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    testMainlineUsesPairedThinBoundarySchema();
    testDefaultPairingWindowUsesNeighbor4();
    testBoundaryMemoryRejectsFeasibleOnlySupport();
    testDatasetUsesPairTargetAndTauCondition();
    fprintf('CBS paired thin-boundary branch regressions passed.\n');
end

function testDefaultPairingWindowUsesNeighbor4()
    key = 'CBS_CGAN_DefaultRadiusProbe';
    if isappdata(0,key)
        rmappdata(0,key);
    end
    Algorithm = TestableCBS_CGAN('save',0,'outputFcn',@silentOutput);
    Problem = DASCMOP1_BC('N',4,'D',6,'maxFE',20);
    Algorithm.Solve(Problem);
    assert(isappdata(0,key), ...
        'Default-radius probe must capture boundary update options.');
    radius = getappdata(0,key);
    rmappdata(0,key);
    assert(radius == 4, ...
        'CBS_CGAN default pairNeighborRefRadius must implement neighbor4.');
end

function testMainlineUsesPairedThinBoundarySchema()
    Algorithm = CBS_CGAN();
    BoundaryOptions = struct( ...
        'pairNeighborRefRadius',1, ...
        'maxCandidatePairsPerRef',1, ...
        'minBoundaryLength',2);
    DatasetOptions = struct( ...
        'pairNeighborRefRadius',1, ...
        'queryConditionBudget',1);

    [BoundaryOptions,DatasetOptions] = Algorithm.configureBoundaryBranch( ...
        BoundaryOptions,DatasetOptions);

    assert(~isfield(BoundaryOptions,'minChainLength'), ...
        'CBS_CGAN mainline must not configure multi-chain boundary memory.');
    assert(~isfield(BoundaryOptions,'supportPointMode') && ...
            ~isfield(DatasetOptions,'supportPointMode'), ...
        'CBS_CGAN mainline must stay on one paired thin-boundary mechanism.');

    W = [0.51 0.49;0.49 0.51];
    Pop = makePairedPopulation();
    Empty = Pop([]);

    BMem = Algorithm.updateBoundaryMemory([],Pop,Empty,Empty,Empty, ...
        W,BoundaryOptions);

    assert(~isfield(BMem,'chain'), ...
        'CBS_CGAN mainline boundary memory must use one current boundary.');
    assert(isequal(sort(fieldnames(BMem)),sort({ ...
            'ref';'y_b';'gap';'x_b';'x_f';'y_f';'x_i';'y_i';'tau'})), ...
        'CBS_CGAN mainline BMem must expose paired support fields.');
end

function testBoundaryMemoryRejectsFeasibleOnlySupport()
    W = [0.51 0.49;0.49 0.51];
    Options = struct( ...
        'pairNeighborRefRadius',1, ...
        'maxCandidatePairsPerRef',1, ...
        'minBoundaryLength',2);

    Pop = makePopulation( ...
        [0.30 0.40;0.50 0.60], ...
        [5.08 4.92;4.92 5.08], ...
        [0;0]);
    Empty = Pop([]);

    [BMem,Diag] = UpdateBoundaryMemory_CBS([],Pop,Empty,Empty,Empty,W,Options);

    assert(isempty(BMem.y_b) && Diag.bmem_count == 0, ...
        'Feasible-only support points must not form paired thin-boundary memory.');
end

function testDatasetUsesPairTargetAndTauCondition()
    rng(17,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [0.51 0.49;0.49 0.51];
    supportX = makeDecisionRows(Problem,2);
    supportY = [5.08 4.92;4.92 5.08];
    BMem = struct( ...
        'ref',[1;2], ...
        'y_b',supportY, ...
        'gap',[0.01;0.01], ...
        'x_b',supportX, ...
        'x_f',supportX, ...
        'y_f',supportY, ...
        'x_i',makeDecisionRows(Problem,2), ...
        'y_i',[5.10 4.90;4.90 5.10], ...
        'tau',[0;0]);
    Samples = SOLUTION(makeDecisionRows(Problem,2),supportY,zeros(2,1));
    Options = struct( ...
        'pairNeighborRefRadius',1, ...
        'queryConditionBudget',1);

    [TrainX,TrainC,~,BMemOut,Info] = BuildBoundaryDataset_CBS( ...
        BMem,Samples,W,Problem,Options);

    assert(max(abs(TrainX - supportX),[],'all') <= 1e-12, ...
        'Dataset construction must train on the one thin target per pair row.');
    assert(max(abs(TrainC - [W(BMemOut.ref,:),BMemOut.tau]),[],'all') <= 1e-12, ...
        'Dataset conditions must be [reference direction, recomputed pair-local tau].');
    assert(max(abs(Info.trainYf - supportY),[],'all') <= 1e-12 && ...
            max(abs(Info.trainYi - BMem.y_i),[],'all') <= 1e-12, ...
        'Dataset diagnostics must expose paired objective endpoints.');
    assert(isequal(sort(fieldnames(BMemOut)),sort({ ...
            'ref';'y_b';'gap';'x_b';'x_f';'y_f';'x_i';'y_i';'tau'})), ...
        'Dataset construction must preserve the paired BMem schema.');
end

function Pop = makePairedPopulation()
    Pop = makePopulation( ...
        [0.30 0.40;0.31 0.41;0.50 0.60;0.51 0.61], ...
        [5.08 4.92;5.10 4.90;4.92 5.08;4.90 5.10], ...
        [0;1;0;1]);
end

function X = makeDecisionRows(Problem,n)
    X = repmat(Problem.lower,n,1) + rand(n,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,n,1);
end

function Pop = makePopulation(Dec,Obj,Con)
    Pop = SOLUTION(Dec,Obj,Con);
end

