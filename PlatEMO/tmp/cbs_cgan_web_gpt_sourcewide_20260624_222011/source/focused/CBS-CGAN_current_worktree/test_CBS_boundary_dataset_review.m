function test_CBS_boundary_dataset_review()
%TEST_CBS_BOUNDARY_DATASET_REVIEW Regression tests for paired CBS-CGAN datasets.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    testTrainingConditionsAppendTau();
    testConditionModesUseQueryObjectives();
    testRefOnlyConditionUsesReferenceDirectionsOnly();
    testDatasetExportsPairSupportForGANLosses();
    testQueriesUsePairedAdjacentSegments();
    testQueryTauUsesPairLocalProjection();
    testSingleNodeDoesNotReplayFallback();
    fprintf('CBS paired boundary dataset regressions passed.\n');
end

function testTrainingConditionsAppendTau()
    rng(19,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [0.80 0.20;0.20 0.80];
    BMem = makeBMem(Problem,W,[1;2],[0.25;0.75]);
    Samples = SOLUTION(BMem.x_b,[100 900;900 100],zeros(2,1));
    Options = struct( ...
        'pairNeighborRefRadius',1, ...
        'queryConditionBudget',1, ...
        'conditionScale',struct('objMin',[0 0],'objSpan',[10 10]));

    [~,TrainC,QueryC,BMemOut,Info] = BuildBoundaryDataset_CBS( ...
        BMem,Samples,W,Problem,Options);

    assert(max(abs(TrainC - [W(BMemOut.ref,:),BMemOut.tau]),[],'all') <= 1e-12, ...
        'TrainC must use reference direction plus recomputed pair-local tau.');
    assert(size(QueryC,2) == Problem.M + 1, ...
        'QueryC must have condition dimension M+1 for [u_ref,tau].');
    assert(max(abs(Info.objMin - [0 0]),[],'all') <= 1e-12 && ...
            max(abs(Info.objSpan - [10 10]),[],'all') <= 1e-12, ...
        'Dataset diagnostics must still report the fixed objective scale.');
end

function testConditionModesUseQueryObjectives()
    rng(31,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [1.00 0.00;0.50 0.50;0.00 1.00];
    BMem = makeBMem(Problem,W,[1;3],[0.20;0.80]);
    BMem.y_b = [0.00 0.00;2.00 2.00];
    BMem.y_f = BMem.y_b;
    BMem.y_i = [0.05 -0.05;2.05 1.95];
    Samples = SOLUTION(BMem.x_b,BMem.y_b,zeros(2,1));
    BaseOptions = struct( ...
        'pairNeighborRefRadius',1, ...
        'queryConditionBudget',2, ...
        'conditionScale',struct('objMin',[0 0],'objSpan',[2 2]));

    Options = BaseOptions;
    Options.conditionMode = "ref_y_tau";
    [~,TrainC,QueryC,~,Info] = BuildBoundaryDataset_CBS( ...
        BMem,Samples,W,Problem,Options);

    expectedTrain = [W(BMem.ref,:),[0 0;1 1],Info.trainTau];
    assert(max(abs(TrainC - expectedTrain),[],'all') <= 1e-12, ...
        'ref_y_tau TrainC must be [reference direction, normalized y_b, tau].');
    assert(size(QueryC,2) == size(W,2) + Problem.M + 1, ...
        'ref_y_tau QueryC must append normalized QueryY before tau.');
    assert(max(abs(QueryC(1,:) - [W(2,:),[0.5 0.5],0]), ...
            [],'all') <= 1e-12, ...
        'ref_y_tau missing-ref QueryC must include normalized QueryY and pair-local tau.');
    assert(strcmp(string(Info.condition_mode),"ref_y_tau"), ...
        'Dataset diagnostics must report the selected condition mode.');

    Options.conditionMode = "ref_y";
    [~,TrainC,QueryC] = BuildBoundaryDataset_CBS( ...
        BMem,Samples,W,Problem,Options);

    expectedTrain = [W(BMem.ref,:),[0 0;1 1]];
    assert(max(abs(TrainC - expectedTrain),[],'all') <= 1e-12, ...
        'ref_y TrainC must be [reference direction, normalized y_b].');
    assert(size(QueryC,2) == size(W,2) + Problem.M, ...
        'ref_y QueryC must drop tau.');
    assert(max(abs(QueryC(1,:) - [W(2,:),[0.5 0.5]]), ...
            [],'all') <= 1e-12, ...
        'ref_y missing-ref QueryC must include normalized QueryY and no tau.');
end

function testRefOnlyConditionUsesReferenceDirectionsOnly()
    rng(37,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [1.00 0.00;0.50 0.50;0.00 1.00];
    BMem = makeBMem(Problem,W,[1;3],[0.20;0.80]);
    BMem.y_b = [0.00 0.00;2.00 2.00];
    BMem.y_f = BMem.y_b;
    BMem.y_i = [0.05 -0.05;2.05 1.95];
    Samples = SOLUTION(BMem.x_b,BMem.y_b,zeros(2,1));
    Options = struct( ...
        'pairNeighborRefRadius',1, ...
        'queryConditionBudget',2, ...
        'conditionMode',"ref_only", ...
        'conditionScale',struct('objMin',[0 0],'objSpan',[2 2]));

    [~,TrainC,QueryC,~,Info] = BuildBoundaryDataset_CBS( ...
        BMem,Samples,W,Problem,Options);

    assert(max(abs(TrainC - W(BMem.ref,:)),[],'all') <= 1e-12, ...
        'ref_only TrainC must contain reference directions only.');
    assert(size(QueryC,2) == size(W,2), ...
        'ref_only QueryC must drop objective coordinates and tau.');
    assert(max(abs(QueryC(1,:) - W(2,:)),[],'all') <= 1e-12, ...
        'ref_only missing-ref QueryC must use only the query reference direction.');
    assert(strcmp(string(Info.condition_mode),"ref_only"), ...
        'Dataset diagnostics must report ref_only condition mode.');
end

function testDatasetExportsPairSupportForGANLosses()
    rng(17,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [0.51 0.49;0.49 0.51];
    BMem = makeBMem(Problem,W,[1;2],[0;0]);
    Samples = SOLUTION(makeDecisionRows(Problem,2),BMem.y_b,zeros(2,1));
    Options = struct( ...
        'pairNeighborRefRadius',1, ...
        'queryConditionBudget',1);

    [TrainX,TrainC,QueryC,BMemOut,Info] = BuildBoundaryDataset_CBS( ...
        BMem,Samples,W,Problem,Options);

    assert(max(abs(TrainX - BMem.x_b),[],'all') <= 1e-12, ...
        'Dataset training targets must be the one thin target per pair row.');
    required = {'trainObjs','trainXf','trainXi','trainYf','trainYi','trainTau'};
    for i = 1 : numel(required)
        assert(isfield(Info,required{i}), ...
            'Dataset Info missing paired support field: %s',required{i});
    end
    assert(max(abs(Info.trainXf - BMem.x_f),[],'all') <= 1e-12 && ...
            max(abs(Info.trainXi - BMem.x_i),[],'all') <= 1e-12, ...
        'Dataset Info must pass paired decision endpoints to the GAN trainer.');
    assert(isfield(Info,'trainConditions') && ...
            isequal(size(Info.trainConditions),size(TrainC)), ...
        'Dataset Info must expose TrainC for visual CGAN diagnostics.');
    assert(isfield(Info,'queryConditions') && ...
            isequal(size(Info.queryConditions),size(QueryC)), ...
        'Dataset Info must expose QueryC for visual CGAN diagnostics.');
    assert(isequal(sort(fieldnames(BMemOut)),sort({ ...
            'ref';'y_b';'gap';'x_b';'x_f';'y_f';'x_i';'y_i';'tau'})), ...
        'Dataset construction must preserve the paired BMem schema.');
end

function testQueriesUsePairedAdjacentSegments()
    rng(23,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [1.00 0.00;0.50 0.50;0.00 1.00];
    BMem = makeBMem(Problem,W,[1;3],[0;0]);
    BMem.y_b = [1.00 0.00;0.00 1.00];
    BMem.y_f = BMem.y_b;
    BMem.y_i = [1.05 -0.05;-0.05 1.05];
    Samples = SOLUTION(BMem.x_b,BMem.y_b,zeros(2,1));
    Options = struct( ...
        'pairNeighborRefRadius',1, ...
        'queryConditionBudget',2, ...
        'conditionScale',struct('objMin',[0 0],'objSpan',[1 1]));

    [~,~,QueryC,~,Info] = BuildBoundaryDataset_CBS( ...
        BMem,Samples,W,Problem,Options);

    assert(size(QueryC,1) == 2, ...
        'The test setup should schedule one missing-ref and one large-gap query.');
    assert(isfield(Info,'queryMeta') && isfield(Info.queryMeta,'tau') && ...
            isfield(Info.queryMeta,'source_interval') && ...
            isfield(Info.queryMeta,'source_type'), ...
        'Dataset diagnostics must expose tau and query provenance metadata.');
    assert(~any(string(Info.queryMeta.source_type(:)) == "replay_fallback"), ...
        'Dataset queries must not use isolated replay_fallback sources.');
    assert(isequal(string(Info.queryMeta.source_type(:)), ...
        ["missing_ref";"large_gap"]), ...
        'Queries should use only missing_ref and adjacent large_gap sources.');
    assert(max(abs(QueryC - [W(Info.queryMeta.ref,:),Info.queryMeta.tau]), ...
            [],'all') <= 1e-12, ...
        'QueryC must use query reference directions plus query tau.');
    assert(max(abs(Info.queryObjs(1,:) - [0.50 0.50]),[],'all') <= 1e-12, ...
        'Missing-ref query diagnostics should store unnormalized objective-space queries.');
end

function testQueryTauUsesPairLocalProjection()
    rng(41,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [1.00 0.00;0.50 0.50;0.00 1.00];
    n = 2;
    Xf = makeDecisionRows(Problem,n);
    Xi = makeDecisionRows(Problem,n);
    BMem = struct( ...
        'ref',[1;3], ...
        'y_b',[0.00 0.00;2.00 0.00], ...
        'gap',[1;1], ...
        'x_b',Xf, ...
        'x_f',Xf, ...
        'y_f',[0.00 0.00;2.00 0.00], ...
        'x_i',Xi, ...
        'y_i',[0.00 1.00;2.00 1.00], ...
        'tau',[0.50;0.50]);
    Samples = SOLUTION(BMem.x_b,BMem.y_b,zeros(n,1));
    Options = struct( ...
        'pairNeighborRefRadius',1, ...
        'queryConditionBudget',1, ...
        'conditionScale',struct('objMin',[0 0],'objSpan',[2 1]));

    [~,~,QueryC,BMemOut,Info] = BuildBoundaryDataset_CBS( ...
        BMem,Samples,W,Problem,Options);

    assert(size(QueryC,1) == 1 && ...
            string(Info.queryMeta.source_type(1)) == "missing_ref", ...
        'The fixture should schedule one missing-reference query.');
    assert(abs(Info.queryMeta.interp_t(1) - 0.5) <= 1e-12, ...
        'Query provenance should preserve boundary-node interpolation t.');
    assert(abs(Info.queryMeta.tau(1)) <= 1e-12, ...
        'Query tau must be pair-local F/I projection, not interpolation t.');
    assert(abs(QueryC(1,end) - Info.queryMeta.tau(1)) <= 1e-12, ...
        'QueryC must use pair-local query tau.');
    assert(max(abs(BMemOut.tau),[],'all') <= 1e-12, ...
        'Training tau must also be recomputed from pair-local F/I support.');
end

function testSingleNodeDoesNotReplayFallback()
    rng(29,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [1.00 0.00];
    BMem = makeBMem(Problem,W,1,0);
    Samples = SOLUTION(BMem.x_b,BMem.y_b,zeros(1,1));
    Options = struct( ...
        'pairNeighborRefRadius',1, ...
        'queryConditionBudget',1, ...
        'conditionScale',struct('objMin',[0 0],'objSpan',[1 1]));

    [~,~,QueryC,~,Info] = BuildBoundaryDataset_CBS( ...
        BMem,Samples,W,Problem,Options);

    assert(isempty(QueryC) && isempty(Info.queryMeta.ref), ...
        'Single-node memory must not schedule unsupported replay fallback queries.');
end

function BMem = makeBMem(Problem,W,refs,tau)
    n = numel(refs);
    Xf = makeDecisionRows(Problem,n);
    Xi = makeDecisionRows(Problem,n);
    refs = refs(:);
    tau = tau(:);
    Yf = W(refs,:);
    Yi = Yf + 0.05*[-ones(n,1),ones(n,1)];
    BMem = struct( ...
        'ref',refs, ...
        'y_b',Yf, ...
        'gap',sqrt(sum((Yf - Yi).^2,2)), ...
        'x_b',Xf, ...
        'x_f',Xf, ...
        'y_f',Yf, ...
        'x_i',Xi, ...
        'y_i',Yi, ...
        'tau',tau);
end

function X = makeDecisionRows(Problem,n)
    X = repmat(Problem.lower,n,1) + rand(n,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,n,1);
end
