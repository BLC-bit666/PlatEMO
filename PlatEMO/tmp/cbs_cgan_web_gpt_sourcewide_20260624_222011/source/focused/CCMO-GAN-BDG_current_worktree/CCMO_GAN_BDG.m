function Source = BuildEvaluatedFeasibleSource_BDG(Problem,varargin)
    Source = struct('decs',zeros(0,Problem.D), ...
        'objs',zeros(0,Problem.M),'cons',zeros(0,0));
    decParts = cell(numel(varargin),1);
    objParts = cell(numel(varargin),1);
    conParts = cell(numel(varargin),1);
    rowCounts = zeros(numel(varargin),1);
    conCols = 0;
    partCount = 0;
    for i = 1 : numel(varargin)
        [DPart,OPart,CPart] = SolutionMatrices_BDG(varargin{i}, ...
            Problem.D,Problem.M);
        if isempty(DPart)
            continue;
        end
        partCount = partCount + 1;
        decParts{partCount} = DPart;
        objParts{partCount} = OPart;
        conParts{partCount} = CPart;
        rowCounts(partCount) = size(DPart,1);
        conCols = max(conCols,size(CPart,2));
    end
    if partCount <= 0
        return;
    end
    decs = vertcat(decParts{1:partCount});
    objs = vertcat(objParts{1:partCount});
    conWidths = cellfun(@(x)size(x,2),conParts(1:partCount));
    if all(conWidths == conCols)
        cons = vertcat(conParts{1:partCount});
    else
        totalRows = sum(rowCounts(1:partCount));
        cons = zeros(totalRows,conCols);
        rowStart = 1;
        for i = 1 : partCount
            rowEnd = rowStart + rowCounts(i) - 1;
            if ~isempty(conParts{i})
                cons(rowStart:rowEnd,1:size(conParts{i},2)) = conParts{i};
            end
            rowStart = rowEnd + 1;
        end
    end
    Source.decs = decs;
    Source.objs = objs;
    Source.cons = cons;
end

function [decs,objs,cons] = SolutionMatrices_BDG(S,D,M)
    decs = zeros(0,D);
    objs = zeros(0,M);
    cons = zeros(0,0);
    if isempty(S)
        return;
    end
    try
        decs = double(S.decs);
        objs = double(S.objs);
    catch
        return;
    end
    try
        cons = double(S.cons);
    catch
        cons = zeros(size(decs,1),0);
    end
    if size(decs,2) ~= D || isempty(objs)
        decs = zeros(0,D);
        objs = zeros(0,M);
        cons = zeros(0,0);
        return;
    end
    if size(objs,2) > M
        objs = objs(:,1:M);
    elseif size(objs,2) < M
        objs = [objs,nan(size(objs,1),M-size(objs,2))];
    end
    n = min(size(decs,1),size(objs,1));
    decs = decs(1:n,:);
    objs = objs(1:n,:);
    if ~isempty(cons)
        cons = cons(1:min(n,size(cons,1)),:);
    end
end

