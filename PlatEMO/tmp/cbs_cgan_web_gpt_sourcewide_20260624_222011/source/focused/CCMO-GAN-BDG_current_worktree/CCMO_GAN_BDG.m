function Metrics = ObjectiveInterfaceMetrics_BDG(objs,feasible,cons,zmin,zmax,gapObj)
    Metrics = struct( ...
        'crossSideObjMed',NaN, ...
        'objSideBalance',0, ...
        'objInterfaceScore',0);
    if isempty(objs)
        return;
    end
    n = size(objs,1);
    feasible = logical(feasible(:));
    if numel(feasible) ~= n
        feasible = false(n,1);
    end
    nF = sum(feasible);
    nI = n - nF;
    if n <= 0
        return;
    end
    Metrics.objSideBalance = 2 * min(nF,nI) / n;
    if nF == 0 || nI == 0
        Metrics.objInterfaceScore = 0;
        return;
    end

    objN = NormalizeObjMatMetrics_BDG(objs,zmin,zmax);
    distObj = pdist2(objN(feasible,:),objN(~feasible,:));
    nearest = [min(distObj,[],2);min(distObj,[],1)'];
    Metrics.crossSideObjMed = MedianFinite_BDG(nearest);
    if ~isfinite(Metrics.crossSideObjMed)
        Metrics.objInterfaceScore = 0;
        return;
    end

    tauObj = ObjectiveInterfaceTau_BDG(gapObj,Metrics.crossSideObjMed);
    marginFactor = ObjectiveInterfaceMarginFactor_BDG(cons,n);
    Metrics.objInterfaceScore = Metrics.objSideBalance .* ...
        exp(-Metrics.crossSideObjMed ./ tauObj) .* marginFactor;
    Metrics.objInterfaceScore = min(max(Metrics.objInterfaceScore,0),1);
end

function tauObj = ObjectiveInterfaceTau_BDG(gapObj,crossSideObjMed)
    if isfinite(gapObj) && gapObj > 0
        tauObj = 3 * gapObj;
    elseif isfinite(crossSideObjMed) && crossSideObjMed > 0
        tauObj = crossSideObjMed;
    else
        tauObj = 1;
    end
    tauObj = max(tauObj,1e-12);
end

function marginFactor = ObjectiveInterfaceMarginFactor_BDG(cons,n)
    marginFactor = 1;
    if isempty(cons)
        return;
    end
    margin = ConstraintMarginVector_BDG(cons);
    if numel(margin) ~= n
        return;
    end
    marginMed = MedianFinite_BDG(margin);
    if isfinite(marginMed)
        marginFactor = exp(-marginMed);
    end
end

