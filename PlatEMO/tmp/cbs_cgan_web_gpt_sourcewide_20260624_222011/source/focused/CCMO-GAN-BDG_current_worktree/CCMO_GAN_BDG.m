function rate = DecisionBoundaryClipRate_BDG(Problem,decs)
    if isempty(decs)
        rate = NaN;
        return;
    end
    X = (double(decs) - Problem.lower) ./ ...
        (Problem.upper - Problem.lower + 1e-12);
    tol = 1e-12;
    clipped = X <= tol | X >= 1 - tol;
    rate = mean(double(clipped(:)));
end

