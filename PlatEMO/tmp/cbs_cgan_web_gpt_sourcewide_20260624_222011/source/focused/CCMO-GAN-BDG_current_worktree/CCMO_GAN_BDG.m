        Control.archiveParetoFilterMode == Retained.archiveParetoFilterMode(idx) && ...
        Control.archivePairDirectionMode == Retained.archivePairDirectionMode(idx) && ...
        Control.archiveSourceCapMode == Retained.archiveSourceCapMode(idx) && ...
        Control.archivePairRefMode == Retained.archivePairRefMode(idx) && ...
        Control.trainFilterMode == Retained.trainFilterMode(idx) && ...
        abs(Control.conditionKNNRetainRatio - ...
            Retained.conditionKNNRetainRatio(idx)) < 1e-12 && ...
        abs(Control.cganTrainMinRefCov - ...
            Retained.cganTrainMinRefCov(idx)) < 1e-12 && ...
        Control.cganTrainMinTargetTriples == ...
            Retained.cganTrainMinTargetTriples(idx) && ...
        Control.conditionMode == Retained.conditionMode(idx) && ...
        Control.targetMode == Retained.targetMode(idx) && ...
        abs(Control.nearSegmentTau - Retained.nearSegmentTau(idx)) < 1e-12 && ...
        Control.nearSegmentMaxPerPair == ...
            Retained.nearSegmentMaxPerPair(idx) && ...
        Control.decisionInterpCount == Retained.decisionInterpCount(idx) && ...
        Control.targetRealLabelMode == Retained.targetRealLabelMode(idx) && ...
        Control.generatorMode == Retained.generatorMode(idx) && ...
        Control.ganCriticMode == Retained.ganCriticMode(idx) && ...
        Control.generatorLossMode == Retained.generatorLossMode(idx) && ...
        abs(Control.reconstructionWeight - ...
            Retained.reconstructionWeight(idx)) < 1e-12 && ...
        abs(Control.reconstructionHuberDelta - ...
            Retained.reconstructionHuberDelta(idx)) < 1e-12;
    assert(ok, ...
        'CCMO_GAN_BDG:UnsupportedExperimentCombo', ...
        'Only retained CCMO-GAN-BDG variants are supported: %s.', ...
        strjoin(Retained.variant,", "));
end

