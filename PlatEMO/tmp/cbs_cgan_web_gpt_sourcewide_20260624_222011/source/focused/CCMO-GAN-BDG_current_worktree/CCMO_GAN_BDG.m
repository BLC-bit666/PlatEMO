function G = SnapshotGANGenerated_BDG(Problem,GAN,n)
    G.decs = zeros(0,Problem.D);
    G.objs = zeros(0,Problem.M);
    G.ref = zeros(0,1);
    G.score = zeros(0,1);
    G.feasible = false(0,1);
    n = max(0,round(double(n)));
    if n <= 0 || isempty(GAN) || ~isfield(GAN,'netG') || ...
            ~isfield(GAN,'zDim') || ~isfield(GAN,'D')
        return;
    end
    oldFE = Problem.FE;
    rngState = rng;
    try
        S = BoundaryGAN_BDG('sample',Problem,GAN,n);
        if ~isempty(S)
            G.decs = S.decs;
            G.objs = S.objs;
            G.ref = zeros(numel(S),1);
            G.score = NaN(numel(S),1);
            if isempty(S.cons)
                G.feasible = true(numel(S),1);
            else
                G.feasible = all(S.cons <= 0,2);
            end
        end
    catch
        G.decs = zeros(0,Problem.D);
        G.objs = zeros(0,Problem.M);
        G.ref = zeros(0,1);
        G.score = zeros(0,1);
        G.feasible = false(0,1);
    end
    Problem.FE = oldFE;
    rng(rngState);
end

