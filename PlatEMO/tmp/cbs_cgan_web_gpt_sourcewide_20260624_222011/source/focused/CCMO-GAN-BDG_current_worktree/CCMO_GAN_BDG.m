function Stats = GANDiagnosticModeStats_BDG(Data)
    Stats = EmptyGANDiagnosticStats_BDG();
    n = numel(Data.conditionIndex);
    Stats.count = n;
    if n <= 0
        return;
    end
    validCondition = isfinite(Data.conditionIndex) & Data.conditionIndex > 0;
    uniqueCondition = unique(Data.conditionIndex(validCondition));
    Stats.unique_condition_count = numel(uniqueCondition);
    Stats.condition_entropy = ConditionEntropy_BDG( ...
        Data.conditionIndex(validCondition));
    Stats.condition_top10_mass = ConditionTopKMass_BDG( ...
        Data.conditionIndex(validCondition),10);
    Stats.feasible_rate = mean(double(Data.feasible));
    Stats.obj_seg_dist50 = PercentileFinite_BDG(Data.ownObjSegDist,50);
    Stats.obj_seg_dist90 = PercentileFinite_BDG(Data.ownObjSegDist,90);
    Stats.dec_seg_dist50 = PercentileFinite_BDG(Data.ownDecSegDist,50);
    Stats.dec_seg_dist90 = PercentileFinite_BDG(Data.ownDecSegDist,90);
    validOwn = Data.ownPairValid(:);
    if any(validOwn)
        Stats.projection_inside_rate = mean(double( ...
            Data.ownObjProjInside(validOwn)));
        Stats.own_pair_nearest_rate = mean(double( ...
            Data.ownPairIsNearest(validOwn)));
        Stats.pair_cover_rate = mean(double( ...
            Data.ownObjSegDist(validOwn) <= 0.05));
    end
    [Stats.within_obj_width90_median, ...
        Stats.within_obj_width90_mean] = GroupedWidth90_BDG( ...
        Data.objNorm,Data.conditionIndex);
    [Stats.within_dec_width90_median, ...
        Stats.within_dec_width90_mean] = GroupedWidth90_BDG( ...
        Data.decNorm,Data.conditionIndex);
    [Stats.within_scatter_share,Stats.between_scatter_share] = ...
        ScatterShareByCondition_BDG(Data.objNorm,Data.conditionIndex);
end

