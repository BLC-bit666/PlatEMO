        AppendCsvRow_BDG(snapshotFile,ArchiveSnapshotRow_BDG( ...
            Writer,Problem,ConstrainedPop,i,targetFE,actualFE,gen, ...
            "constrained_population","constrained_population", ...
            ConstrainedPop.feasible(i)));
