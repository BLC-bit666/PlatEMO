end

function Metrics = AddGANToAFDistanceMetrics_BDG(Metrics,Problem, ...
        decs,objs,AF,zmin,zmax)
    if isempty(decs) || isempty(AF.decs)
        return;
    end

    epsilon = 0.05;
    Metrics.AF_CoverEpsilon = epsilon;

    if ~isempty(objs) && ~isempty(AF.objs)
        GObj = NormalizeObjMatDistance_BDG(objs,zmin,zmax);
        AFObj = NormalizeObjMatDistance_BDG(AF.objs,zmin,zmax);
        distObj = min(pdist2(GObj,AFObj),[],2);
        Metrics.GAN_to_AF_ObjNN_mean = MeanFiniteMetrics_BDG(distObj);
        Metrics.GAN_to_AF_ObjNN_median = MedianFinite_BDG(distObj);
        Metrics.GAN_to_AF_ObjNN_p90 = PercentileFinite_BDG(distObj,90);
        Metrics.GAN_to_AF_Dist90 = Metrics.GAN_to_AF_ObjNN_p90;

        afCoverDist = min(pdist2(AFObj,GObj),[],2);
        valid = afCoverDist(isfinite(afCoverDist));
        if ~isempty(valid)
            Metrics.AF_Cover_epsilon = mean(double(valid <= epsilon));
        end
    end

    GDec = NormalizeDecMatMetrics_BDG(decs,Problem.lower,Problem.upper);
    AFDec = NormalizeDecMatMetrics_BDG(AF.decs,Problem.lower,Problem.upper);
    if ~isempty(GDec) && ~isempty(AFDec)
        distDec = min(pdist2(GDec,AFDec),[],2);
        distDec = distDec ./ sqrt(max(1,size(GDec,2)));
        Metrics.GAN_to_AF_DecNN_mean = MeanFiniteMetrics_BDG(distDec);
        Metrics.GAN_to_AF_DecNN_median = MedianFinite_BDG(distDec);
        Metrics.GAN_to_AF_DecNN_p90 = PercentileFinite_BDG(distDec,90);
    end
end

function Metrics = AddGANToSegmentMetrics_BDG(Metrics,objs,AF,AI,zmin,zmax)
    epsilon = 0.05;
    Metrics.PairCoverEpsilon = epsilon;
    if isempty(objs) || isempty(AF.objs) || isempty(AI.objs)
        return;
    end
    nPair = min(size(AF.objs,1),size(AI.objs,1));
    if nPair <= 0
        return;
    end
    GObj = NormalizeObjMatDistance_BDG(objs,zmin,zmax);
    AFObj = NormalizeObjMatDistance_BDG(AF.objs(1:nPair,:),zmin,zmax);
    AIObj = NormalizeObjMatDistance_BDG(AI.objs(1:nPair,:),zmin,zmax);

    dist = DistanceToBoundarySegments_BDG(GObj,AFObj,AIObj);
    Metrics.GAN_to_Segment_Dist50 = PercentileFinite_BDG(dist,50);
    Metrics.GAN_to_Segment_Dist90 = PercentileFinite_BDG(dist,90);

    pairDist = DistanceFromSegmentsToPoints_BDG(GObj,AFObj,AIObj);
    pairDist = pairDist(isfinite(pairDist));
    if ~isempty(pairDist)
        Metrics.PairCover_epsilon = mean(double(pairDist <= epsilon));
    end
end

function Metrics = AddGANToDecisionSegmentMetrics_BDG( ...
        Metrics,Problem,decs,AF,AI)
    if isempty(decs) || isempty(AF.decs) || isempty(AI.decs)
        return;
    end
    nPair = min(size(AF.decs,1),size(AI.decs,1));
    if nPair <= 0
        return;
    end
    GDec = NormalizeDecMatMetrics_BDG(decs,Problem.lower,Problem.upper);
    AFDec = NormalizeDecMatMetrics_BDG(AF.decs(1:nPair,:), ...
        Problem.lower,Problem.upper);
    AIDec = NormalizeDecMatMetrics_BDG(AI.decs(1:nPair,:), ...
        Problem.lower,Problem.upper);
    dist = DistanceToBoundarySegments_BDG(GDec,AFDec,AIDec);
    dist = dist ./ sqrt(max(1,size(GDec,2)));
    Metrics.GAN_to_Decision_Segment_Dist50 = ...
        PercentileFinite_BDG(dist,50);
    Metrics.GAN_to_Decision_Segment_Dist90 = ...
        PercentileFinite_BDG(dist,90);
end

function Metrics = AddGANClusterMetrics_BDG(Metrics,objs,zmin,zmax)
    epsilon = 0.05;
    Metrics.ClusterEpsilon = epsilon;
    if isempty(objs)
        return;
    end
    GObj = NormalizeObjMatDistance_BDG(objs,zmin,zmax);
    finite = all(isfinite(GObj),2);
    GObj = GObj(finite,:);
    n = size(GObj,1);
    if n <= 0
        return;
    end
    if n == 1
        Metrics.LargestClusterRate_epsilon = 1;
        Metrics.EffectiveClusterCount_epsilon = 1;
        return;
    end

    D = pdist2(GObj,GObj);
    linked = D <= epsilon;
    sizes = ConnectedComponentSizes_BDG(linked);
    if isempty(sizes)
        return;
    end
    p = sizes ./ n;
    Metrics.LargestClusterRate_epsilon = max(p);
    Metrics.EffectiveClusterCount_epsilon = 1 ./ sum(p.^2);
end

function sizes = ConnectedComponentSizes_BDG(linked)
    n = size(linked,1);
    seen = false(n,1);
    sizes = zeros(0,1);
    for start = 1 : n
        if seen(start)
            continue;
        end
        queue = start;
        seen(start) = true;
        count = 0;
        while ~isempty(queue)
            node = queue(1);
            queue(1) = [];
            count = count + 1;
            next = find(linked(node,:) & ~seen');
            if ~isempty(next)
                seen(next) = true;
                queue = [queue,next]; %#ok<AGROW>
            end
        end
        sizes(end+1,1) = count; %#ok<AGROW>
    end
end

function count = RawGANOutsideStandardRangeCount_BDG(Problem,objs)
    count = NaN;
    if isempty(objs)
        return;
    end
    [lower,upper,ok] = ObjectiveStandardBounds_BDG(Problem,size(objs,2));
    if ~ok
        return;
    end
    outside = ~all(isfinite(objs),2) | ...
        any(objs < lower | objs > upper,2);
    count = sum(outside);
end

function [lower,upper,ok] = ObjectiveStandardBounds_BDG(Problem,M)
    lower = nan(1,M);
    upper = nan(1,M);
    ok = false;
    try
        PF = Problem.PF;
    catch
        return;
    end
    if isnumeric(PF) && size(PF,2) >= M
        for j = 1 : M
            values = PF(:,j);
            values = values(isfinite(values));
            if isempty(values)
                return;
            end
            lower(j) = min(values);
            upper(j) = max(values);
        end
    elseif iscell(PF) && numel(PF) >= M
        for j = 1 : M
            values = PF{j}(:);
            values = values(isfinite(values));
            if isempty(values)
                return;
            end
            lower(j) = min(values);
            upper(j) = max(values);
        end
    else
        return;
    end
    ok = all(isfinite(lower)) && all(isfinite(upper));
end

