function [Writer,elapsed] = MaybeWriteArchiveSnapshots_BDG( ...
        Writer,Problem,AF,AI,GAN,gen,Population1,Population2)
    tStart = tic;
    elapsed = 0;
    if ~Writer.enabled
        return;
    end
    while Writer.next <= numel(Writer.targets) && ...
            Problem.FE >= Writer.targets(Writer.next)
        targetFE = Writer.targets(Writer.next);
        actualFE = Problem.FE;
        [AFTrain,AITrain,~] = SelectGANTrainingArchive_BDG(AF,AI);
        ConstrainedPop = PopulationSnapshotLayer_BDG(Population1,Problem);
        UnconstrainedPop = PopulationSnapshotLayer_BDG(Population2,Problem);
        GSnapshot = SnapshotGANGenerated_BDG(Problem,GAN,Writer.ganN);
        snapshotFile = WriteArchiveSnapshotFile_BDG( ...
            Writer,Problem,AFTrain,AITrain,GSnapshot, ...
            ConstrainedPop,UnconstrainedPop,targetFE,actualFE,gen);
        AppendCsvRow_BDG(Writer.manifest_file,{ ...
            Writer.problem,Writer.run,targetFE,actualFE,gen, ...
            size(AF.decs,1),size(AI.decs,1), ...
            size(AFTrain.decs,1),size(AITrain.decs,1), ...
            size(ConstrainedPop.decs,1),size(UnconstrainedPop.decs,1), ...
            size(GSnapshot.decs,1),Writer.tag,snapshotFile});
        if Writer.diagnosticEnabled
            [diagSampleFile,diagMetricFile,diagStatus] = ...
                WriteGANDiagnosticSnapshot_BDG(Writer,Problem, ...
                AFTrain,AITrain,GAN,targetFE,actualFE,gen);
            AppendCsvRow_BDG(Writer.diagnosticManifestFile,{ ...
                Writer.problem,Writer.run,targetFE,actualFE,gen, ...
                diagStatus,diagSampleFile,diagMetricFile,Writer.tag});
        end
        Writer.next = Writer.next + 1;
    end
    elapsed = toc(tStart);
end

function snapshotFile = WriteArchiveSnapshotFile_BDG( ...
        Writer,Problem,AFTrain,AITrain,GSnapshot, ...
