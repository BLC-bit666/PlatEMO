function Observer = InitMetricsObserver_BDG(Algorithm,Problem,Params,Control)
    rootDir = fileparts(which('platemo'));
    baseDir = fullfile(rootDir,'Data','CCMO_GAN_BDG');
    if nargin >= 4 && isstruct(Control) && ...
            isfield(Control,'analysisRootFolder') && ...
            strlength(string(Control.analysisRootFolder)) > 0
        baseDir = char(string(Control.analysisRootFolder));
    end
    [~,~] = mkdir(baseDir);
    [~,token] = fileparts(tempname(baseDir));
    runId = ResolveRunId_BDG(Algorithm);
    runFolder = fullfile(baseDir,sprintf('%s_%s_run%d_%s', ...
        class(Algorithm),class(Problem),runId,token));
    [~,~] = mkdir(runFolder);

    Observer = struct( ...
        'folder',runFolder, ...
        'meta_file',fullfile(runFolder,'run_meta.csv'), ...
        'core_file',fullfile(runFolder,'core_metrics.csv'), ...
        'stage_file',fullfile(runFolder,'stage_metrics.csv'));

	    WriteCsvHeader_BDG(Observer.meta_file,{ ...
	        'algorithm','problem','family','run','M','D','N','maxFE', ...
	        'trainGap','archiveGap','nGen','zDim','perRef', ...
		        'nearTau','ganIter','probeRawN', ...
		        'stageProbeN', ...
		        'ganDPretrainIter','ganDSteps','ganGSteps', ...
		        'ganArchMode','ganMiniBatch','ganRealLabel', ...
				        'ganLrD','ganLrG','ganTrainMode', ...
				        'generatorMode','generatorLossMode', ...
                        'reconstructionWeight', ...
                        'reconstructionHuberDelta', ...
			        'ganCriticMode', ...
		        'variant', ...
        'archiveParetoFilterMode','archivePairDirectionMode', ...
            'archiveSourceCapMode','archivePairRefMode', ...
            'trainFilterMode','conditionKNNRetainRatio', ...
	            'cganTrainMinRefCov','cganTrainMinTargetTriples', ...
	            'trainFilterRandomSeed','conditionMode','targetMode', ...
        'nearSegmentTau','nearSegmentMaxPerPair', ...
