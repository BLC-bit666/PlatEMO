function Data = BuildGANDiagnosticModeData_BDG(Problem,AFTrain,AITrain, ...
        Samples,Diag,mode,zId)
    Data = EmptyGANDiagnosticModeData_BDG(Problem);
    if isempty(Samples)
        return;
    end
    Data.decs = Samples.decs;
    Data.objs = Samples.objs;
    n = size(Data.decs,1);
    Data.mode = string(mode(:));
    if numel(Data.mode) ~= n
        Data.mode = repmat(Data.mode(1),n,1);
    end
    Data.zId = double(zId(:));
    if numel(Data.zId) ~= n
        Data.zId = (1:n)';
    end
    if isempty(Samples.cons)
        Data.feasible = true(n,1);
    else
        Data.feasible = all(Samples.cons <= 0,2);
    end
    if isfield(Diag,'rawgen_condition_index') && ...
            numel(Diag.rawgen_condition_index) >= n
        Data.conditionIndex = double(Diag.rawgen_condition_index(1:n));
    elseif isfield(Diag,'injected_condition_index') && ...
            numel(Diag.injected_condition_index) >= n
        Data.conditionIndex = double(Diag.injected_condition_index(1:n));
    else
        Data.conditionIndex = NaN(n,1);
    end
    if isfield(Diag,'rawgen_pair_index') && ...
            numel(Diag.rawgen_pair_index) >= n
        Data.pairIndex = double(Diag.rawgen_pair_index(1:n));
    elseif isfield(Diag,'injected_pair_index') && ...
            numel(Diag.injected_pair_index) >= n
        Data.pairIndex = double(Diag.injected_pair_index(1:n));
    else
        Data.pairIndex = Data.conditionIndex;
    end

    [Data.ownPairValid,Data.ownObjSegDist,Data.ownDecSegDist, ...
        Data.ownObjProjT,Data.ownDecProjT,Data.ownObjProjInside, ...
        Data.ownDecProjInside,Data.nearestObjPairIndex, ...
        Data.ownPairIsNearest,Data.nearestObjSegDist, ...
        Data.objNorm,Data.decNorm] = GANDiagnosticPointDistances_BDG( ...
        Problem,AFTrain,AITrain,Data.decs,Data.objs, ...
        Data.pairIndex);
end

function [ownValid,ownObjDist,ownDecDist,ownObjT,ownDecT, ...
        ownObjInside,ownDecInside,nearestIdx,ownNearest, ...
        nearestDist,objNorm,decNorm] = GANDiagnosticPointDistances_BDG( ...
        Problem,AFTrain,AITrain,decs,objs,pairIndex)
    n = size(decs,1);
    ownValid = false(n,1);
    ownObjDist = NaN(n,1);
    ownDecDist = NaN(n,1);
    ownObjT = NaN(n,1);
    ownDecT = NaN(n,1);
    ownObjInside = false(n,1);
    ownDecInside = false(n,1);
    nearestIdx = NaN(n,1);
    ownNearest = false(n,1);
    nearestDist = NaN(n,1);
    objNorm = zeros(n,Problem.M);
    decNorm = NormalizeDecMatMetrics_BDG(decs,Problem.lower,Problem.upper);
    nPair = min([size(AFTrain.decs,1),size(AITrain.decs,1), ...
        size(AFTrain.objs,1),size(AITrain.objs,1)]);
    if n == 0 || nPair <= 0 || isempty(objs)
        return;
    end
    pairObjs = [AFTrain.objs(1:nPair,:);AITrain.objs(1:nPair,:)];
    zmin = min(pairObjs,[],1);
    zmax = max(pairObjs,[],1);
    objNorm = NormalizeObjMatDistance_BDG(objs,zmin,zmax);
    AFObj = NormalizeObjMatDistance_BDG(AFTrain.objs(1:nPair,:),zmin,zmax);
    AIObj = NormalizeObjMatDistance_BDG(AITrain.objs(1:nPair,:),zmin,zmax);
    AFDec = NormalizeDecMatMetrics_BDG(AFTrain.decs(1:nPair,:), ...
        Problem.lower,Problem.upper);
    AIDec = NormalizeDecMatMetrics_BDG(AITrain.decs(1:nPair,:), ...
        Problem.lower,Problem.upper);

    for i = 1 : n
        [nearestDist(i),nearestIdx(i)] = NearestSegmentDistance_BDG( ...
            objNorm(i,:),AFObj,AIObj);
        idx = round(pairIndex(i));
        if isfinite(idx) && idx >= 1 && idx <= nPair
            ownValid(i) = true;
            [ownObjDist(i),ownObjT(i)] = PointSegmentDistance_BDG( ...
                objNorm(i,:),AFObj(idx,:),AIObj(idx,:));
            [ownDecDist(i),ownDecT(i)] = PointSegmentDistance_BDG( ...
                decNorm(i,:),AFDec(idx,:),AIDec(idx,:));
            ownDecDist(i) = ownDecDist(i) ./ sqrt(max(1,Problem.D));
            ownObjInside(i) = ownObjT(i) >= 0 && ownObjT(i) <= 1;
            ownDecInside(i) = ownDecT(i) >= 0 && ownDecT(i) <= 1;
            ownNearest(i) = nearestIdx(i) == idx;
        end
    end
end

function [dist,idx] = NearestSegmentDistance_BDG(point,A,B)
    nPair = min(size(A,1),size(B,1));
    dist = NaN;
    idx = NaN;
    for i = 1 : nPair
        d = PointSegmentDistance_BDG(point,A(i,:),B(i,:));
        if ~isfinite(dist) || d < dist
            dist = d;
            idx = i;
        end
    end
end

function [dist,t] = PointSegmentDistance_BDG(point,a,b)
    v = b - a;
    len2 = sum(v.^2);
    if len2 <= 1e-24
        t = 0;
        proj = a;
    else
        t = sum((point - a).*v) ./ len2;
        proj = a + min(max(t,0),1).*v;
    end
    dist = sqrt(sum((point - proj).^2));
end

