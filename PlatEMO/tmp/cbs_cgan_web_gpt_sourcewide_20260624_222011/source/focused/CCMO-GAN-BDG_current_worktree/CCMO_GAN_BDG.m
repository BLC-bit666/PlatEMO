function entropy = ConditionEntropy_BDG(conditionIndex)
    entropy = NaN;
    conditionIndex = conditionIndex(isfinite(conditionIndex));
    if isempty(conditionIndex)
        return;
    end
    [~,~,g] = unique(conditionIndex(:));
    counts = accumarray(g,1);
    p = counts ./ sum(counts);
    if numel(p) <= 1
        entropy = 0;
    else
        entropy = -sum(p .* log(p + 1e-12)) ./ log(numel(p));
    end
end

function mass = ConditionTopKMass_BDG(conditionIndex,k)
    mass = NaN;
    conditionIndex = conditionIndex(isfinite(conditionIndex));
    if isempty(conditionIndex)
        return;
    end
    [~,~,g] = unique(conditionIndex(:));
    counts = sort(accumarray(g,1),'descend');
    k = min(max(1,round(double(k))),numel(counts));
    mass = sum(counts(1:k)) ./ sum(counts);
end

function [medianWidth,meanWidth] = GroupedWidth90_BDG(X,conditionIndex)
    medianWidth = NaN;
    meanWidth = NaN;
    if isempty(X) || isempty(conditionIndex)
        return;
    end
    valid = isfinite(conditionIndex) & conditionIndex > 0 & ...
        all(isfinite(X),2);
    X = X(valid,:);
    conditionIndex = conditionIndex(valid);
    groups = unique(conditionIndex(:));
    widths = NaN(numel(groups),1);
    for i = 1 : numel(groups)
        rows = conditionIndex == groups(i);
        if ~any(rows)
            continue;
        end
        center = mean(X(rows,:),1);
        dist = sqrt(sum((X(rows,:) - center).^2,2));
        widths(i) = PercentileFinite_BDG(dist,90);
    end
    widths = widths(isfinite(widths));
    if ~isempty(widths)
        medianWidth = median(widths);
        meanWidth = mean(widths);
    end
end

function [withinShare,betweenShare] = ScatterShareByCondition_BDG( ...
        X,conditionIndex)
    withinShare = NaN;
    betweenShare = NaN;
    if isempty(X) || isempty(conditionIndex)
        return;
    end
    valid = isfinite(conditionIndex) & conditionIndex > 0 & ...
        all(isfinite(X),2);
    X = X(valid,:);
    conditionIndex = conditionIndex(valid);
    if size(X,1) <= 1
        return;
    end
    globalCenter = mean(X,1);
    total = sum(sum((X - globalCenter).^2,2));
    if total <= 1e-24
        withinShare = 0;
        betweenShare = 1;
        return;
    end
    groups = unique(conditionIndex(:));
    within = 0;
    for i = 1 : numel(groups)
        rows = conditionIndex == groups(i);
        center = mean(X(rows,:),1);
        within = within + sum(sum((X(rows,:) - center).^2,2));
    end
    withinShare = within ./ total;
    betweenShare = max(0,1 - withinShare);
end

function selected = SelectGANDiagnosticConditionIndices_BDG(GAN,maxCount)
    selected = zeros(0,1);
    if isempty(GAN) || ~isfield(GAN,'conditionData') || ...
            isempty(GAN.conditionData)
        return;
    end
    n = size(GAN.conditionData,1);
    maxCount = min(max(0,round(double(maxCount))),n);
    if maxCount <= 0
        return;
    end
    spanIdx = unique(round(linspace(1,n,maxCount)),'stable');
    weightIdx = zeros(0,1);
    if isfield(GAN,'conditionSamplingWeights') && ...
            numel(GAN.conditionSamplingWeights) == n
        w = double(GAN.conditionSamplingWeights(:));
        positive = find(isfinite(w) & w > 0);
        k = max(1,ceil(maxCount / 3));
        if ~isempty(positive)
            [~,hiOrder] = sort(w(positive),'descend');
            high = positive(hiOrder(1:min(k,numel(hiOrder))));
            [~,loOrder] = sort(w(positive),'ascend');
            low = positive(loOrder(1:min(k,numel(loOrder))));
            weightIdx = [high(:);low(:)];
        end
    end
    selected = unique([weightIdx(:);spanIdx(:)],'stable');
    if numel(selected) > maxCount
        selected = selected(1:maxCount);
    end
    selected = selected(:);
end

