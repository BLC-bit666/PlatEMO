    for i = 1 : numel(fields)
        name = char(fields(i));
        if ~isfield(Timing,name)
            Timing.(name) = 0;
        end
        value = double(Timing.(name));
        if isempty(value) || ~isscalar(value) || ~isfinite(value) || value < 0
            value = 0;
