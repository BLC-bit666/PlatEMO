function [gap,zmin,zmax] = PairObjectiveGap_BDG(AF,AI)
    gap = NaN;
    zmin = zeros(1,size(AF.objs,2));
    zmax = ones(1,size(AF.objs,2));
    if isempty(AF.decs) || isempty(AI.decs)
        return;
