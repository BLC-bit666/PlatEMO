    tagText = char(Writer.tag);
    if strlength(Writer.tag) > 0
        tagText = ['_',regexprep(tagText,'[^A-Za-z0-9_]+','_')];
    end
    snapshotFile = string(fullfile(char(Writer.folder), ...
        sprintf('%s_run%d_targetFE%06d%s_archive_training.csv', ...
        safeProblem,round(Writer.run),round(targetFE),tagText)));
