function Metrics = GeneratedBoundaryMetrics_BDG(Problem,decs,objs,cons, ...
        feasible,AF,AI,W,gapObj,zmin,zmax)
    Metrics = EmptyGeneratedBoundaryMetrics_BDG();
    if isempty(decs)
        return;
    end
    if isempty(feasible) || numel(feasible) ~= size(decs,1)
        feasible = FeasibleMaskFromCons_BDG(cons,size(decs,1));
    else
        feasible = logical(feasible(:));
    end
    Metrics.BoundaryHit_all = BoundaryHitAll_BDG( ...
        objs,AF,AI,gapObj,zmin,zmax);
    Interface = ObjectiveInterfaceMetrics_BDG( ...
        objs,feasible,cons,zmin,zmax,gapObj);
    Metrics.ObjInterfaceScore = Interface.objInterfaceScore;
    Metrics.RefCov = GeneratedRefCoverage_BDG(objs,W);
    Metrics.DuplicateRate = DuplicateRate_BDG(Problem,decs);
    Metrics.RawGANFeasibleRate = mean(double(feasible));
    Metrics.RawGANVarClipRate = DecisionBoundaryClipRate_BDG( ...
        Problem,decs);
    Metrics.RawGANOutsideStandardRangeCount = ...
        RawGANOutsideStandardRangeCount_BDG(Problem,objs);
    Metrics = AddGANToSegmentMetrics_BDG(Metrics,objs,AF,AI,zmin,zmax);
    Metrics = AddGANToDecisionSegmentMetrics_BDG(Metrics,Problem,decs,AF,AI);
    Metrics = AddGANClusterMetrics_BDG(Metrics,objs,zmin,zmax);
    Metrics = AddGANToAFDistanceMetrics_BDG(Metrics,Problem, ...
        decs,objs,AF,zmin,zmax);
end

function feasible = FeasibleMaskFromCons_BDG(cons,n)
    if isempty(cons)
        feasible = true(n,1);
    else
        feasible = all(cons <= 0,2);
        if numel(feasible) ~= n
            feasible = false(n,1);
        end
    end
end

function rate = BoundaryHitAll_BDG(objs,AF,AI,gapObj,zmin,zmax)
    rate = NaN;
    if isempty(objs) || isempty(AF.objs) || isempty(AI.objs) || ...
            ~isfinite(gapObj)
        return;
    end
    sampleObj = NormalizeObjMatMetrics_BDG(objs,zmin,zmax);
    fObj = NormalizeObjMatMetrics_BDG(AF.objs,zmin,zmax);
    iObj = NormalizeObjMatMetrics_BDG(AI.objs,zmin,zmax);
    dist = DistanceToBoundarySegments_BDG(sampleObj,fObj,iObj);
    tau = max(3 .* double(gapObj),1e-12);
    rate = mean(double(dist <= tau));
end

function dist = DistanceToBoundarySegments_BDG(X,A,B)
    dist = inf(size(X,1),1);
    nPair = min(size(A,1),size(B,1));
    for i = 1 : nPair
        a = A(i,:);
        v = B(i,:) - a;
        len2 = sum(v.^2);
        if len2 <= 1e-24
            d = sqrt(sum((X - a).^2,2));
        else
            t = sum((X - a).*v,2) ./ len2;
            t = min(max(t,0),1);
            proj = a + t.*v;
            d = sqrt(sum((X - proj).^2,2));
        end
        dist = min(dist,d);
    end
end

function dist = DistanceFromSegmentsToPoints_BDG(X,A,B)
    nPair = min(size(A,1),size(B,1));
    dist = inf(nPair,1);
    if isempty(X)
        return;
    end
    for i = 1 : nPair
        a = A(i,:);
        v = B(i,:) - a;
        len2 = sum(v.^2);
        if len2 <= 1e-24
            d = sqrt(sum((X - a).^2,2));
        else
            t = sum((X - a).*v,2) ./ len2;
            t = min(max(t,0),1);
            proj = a + t.*v;
            d = sqrt(sum((X - proj).^2,2));
        end
        dist(i) = min(d);
    end
end

function cov = GeneratedRefCoverage_BDG(objs,W)
    cov = NaN;
    if isempty(objs) || isempty(W)
        return;
    end
    ref = AssignRefFromObjMetrics_BDG(objs,W);
    ref = ref(ref > 0);
    cov = numel(unique(ref)) / size(W,1);
end

