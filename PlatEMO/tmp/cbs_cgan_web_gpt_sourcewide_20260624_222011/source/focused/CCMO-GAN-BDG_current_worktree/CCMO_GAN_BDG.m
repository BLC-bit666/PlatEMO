classdef CCMO_GAN_BDG < ALGORITHM
% <multi> <real> <constrained>
% CCMO + strict direct boundary GAN for binary/unknown constraints
%
% trainGap --- 1 --- GAN retraining interval in generations
% nGen     --- 50 --- Number of raw GAN offspring injected each refresh
% zDim     --- 4  --- Latent dimension of GAN
% perRef   --- 5  --- Max AF samples kept per reference vector
% nearTau  --- 0.20 --- Max normalized objective distance for cross-pop matching
% ganIter  --- 50 --- GAN training iterations/epochs per refresh
% probeRawN --- 0 --- Extra raw GAN diagnostic samples per refresh
% stageProbeN --- 200 --- Raw GAN diagnostic samples at fixed FE stages
% ganDPretrainIter --- 0 --- D-only pretraining iterations before adversarial updates
% ganDSteps --- 1 --- D update steps per GAN iteration
% ganGSteps --- 1 --- G update steps per GAN iteration
% archiveGap --- 1 --- Boundary archive update interval in generations
% ganArchMode --- g2sl --- GAN architecture mode: small, large, or g2sl
% ganMiniBatch --- 64 --- GAN mini-batch size
% ganRealLabel --- 0.9 --- Real label smoothing value in D loss
% ganLrD --- 0.0001 --- Discriminator learning rate
% ganLrG --- 0.0001 --- Generator learning rate
% ganTrainMode --- epoch --- GAN training loop mode: iter or epoch
%
% Mainline:
% 1) keep the CCMO-DE two-population skeleton,
% 2) build AF/AI boundary archives,
% 3) train one direct GAN with AF positives and G(z[,c]) negatives,
% 4) sample complete decisions by raw G(z)->x,
% 5) evaluate raw samples and inject them unchanged into Population1.

    methods
        function main(Algorithm,Problem)
            nGenDefault = 50;
            [trainGap,nGen,zDim,perRef,nearTau, ...
                ganIter,probeRawN,stageProbeN, ...
                ganDPretrainIter,ganDSteps,ganGSteps,archiveGap, ...
                ganArchMode,ganMiniBatch,ganRealLabel,ganLrD,ganLrG, ...
                ganTrainMode] = ...
                Algorithm.ParameterSet( ...
                1,nGenDefault,4,5,0.20,50,0,200, ...
                0,1,1,1,"g2sl",64,0.9,1e-4,1e-4,"epoch");
            trainGap = max(1,round(double(trainGap)));
            archiveGap = max(1,round(double(archiveGap)));
            zDim = max(0,round(double(zDim)));
            stageProbeN = max(0,round(double(stageProbeN)));
            GANTrainOptions = struct( ...
                'dPretrainIter',max(0,round(double(ganDPretrainIter))), ...
                'dSteps',max(1,round(double(ganDSteps))), ...
                'gSteps',max(1,round(double(ganGSteps))), ...
                'sampleWeights',[], ...
                'realLabels',[], ...
                'generatorMode',"objective_target_conditioned", ...
                'conditionData',[], ...
                'generatorLossMode',"adversarial", ...
                'reconstructionWeight',0, ...
                'reconstructionHuberDelta',0.10, ...
                'criticMode',"af_like", ...
                'archMode',ganArchMode, ...
                'miniBatch',ganMiniBatch, ...
                'realLabel',ganRealLabel, ...
                'lrD',ganLrD, ...
                'lrG',ganLrG, ...
                'trainMode',ganTrainMode);
            ExperimentControl = ResolveExperimentControl_BDG(archiveGap);
            archiveGap = ExperimentControl.archiveGap;
            GANTrainOptions.generatorMode = ExperimentControl.generatorMode;
            GANTrainOptions.generatorLossMode = ...
                ExperimentControl.generatorLossMode;
            GANTrainOptions.reconstructionWeight = ...
                ExperimentControl.reconstructionWeight;
            GANTrainOptions.reconstructionHuberDelta = ...
                ExperimentControl.reconstructionHuberDelta;
            GANTrainOptions.criticMode = ExperimentControl.ganCriticMode;

            Params = struct( ...
                'trainGap',trainGap, ...
                'nGen',nGen, ...
                'zDim',zDim, ...
                'perRef',perRef, ...
                'nearTau',nearTau, ...
                'ganIter',ganIter, ...
                'archiveGap',archiveGap, ...
                'probeRawN',probeRawN, ...
                'stageProbeN',stageProbeN, ...
                'ganDPretrainIter',GANTrainOptions.dPretrainIter, ...
                'ganDSteps',GANTrainOptions.dSteps, ...
                'ganGSteps',GANTrainOptions.gSteps, ...
                'ganArchMode',string(GANTrainOptions.archMode), ...
                'ganMiniBatch',double(GANTrainOptions.miniBatch), ...
                'ganRealLabel',double(GANTrainOptions.realLabel), ...
                'ganLrD',double(GANTrainOptions.lrD), ...
                'ganLrG',double(GANTrainOptions.lrG), ...
                'ganTrainMode',string(GANTrainOptions.trainMode), ...
                'generatorMode',GANTrainOptions.generatorMode, ...
                'generatorLossMode',GANTrainOptions.generatorLossMode, ...
                'reconstructionWeight', ...
                double(GANTrainOptions.reconstructionWeight), ...
                'reconstructionHuberDelta', ...
                double(GANTrainOptions.reconstructionHuberDelta), ...
                'ganCriticMode',GANTrainOptions.criticMode, ...
                'variant',ExperimentControl.variant, ...
                'archiveParetoFilterMode',ExperimentControl.archiveParetoFilterMode, ...
                'archivePairDirectionMode',ExperimentControl.archivePairDirectionMode, ...
                'archiveSourceCapMode',ExperimentControl.archiveSourceCapMode, ...
                'archivePairRefMode',ExperimentControl.archivePairRefMode, ...
                'trainFilterMode',ExperimentControl.trainFilterMode, ...
                'conditionKNNRetainRatio', ...
                ExperimentControl.conditionKNNRetainRatio, ...
                'cganTrainMinRefCov', ...
                ExperimentControl.cganTrainMinRefCov, ...
                'cganTrainMinTargetTriples', ...
                ExperimentControl.cganTrainMinTargetTriples, ...
                'trainFilterRandomSeed', ...
                ExperimentControl.trainFilterRandomSeed, ...
                'conditionMode',ExperimentControl.conditionMode, ...
                'targetMode',ExperimentControl.targetMode, ...
                'nearSegmentTau',ExperimentControl.nearSegmentTau, ...
                'nearSegmentMaxPerPair', ...
                ExperimentControl.nearSegmentMaxPerPair, ...
                'decisionInterpCount', ...
                ExperimentControl.decisionInterpCount, ...
                'targetRealLabelMode',ExperimentControl.targetRealLabelMode, ...
                'trainBundleMode',ExperimentControl.trainBundleMode);
            ArchiveOptions = struct( ...
                'scoreGapWeight',1.00, ...
                'scoreRankWeight',0.00, ...
                'sourceCapMode',ExperimentControl.archiveSourceCapMode, ...
                'paretoFilterMode',ExperimentControl.archiveParetoFilterMode, ...
                'pairDirectionMode',ExperimentControl.archivePairDirectionMode, ...
                'pairRefMode',ExperimentControl.archivePairRefMode);

            [W,~] = UniformPoint(Problem.N,Problem.M);
            Observer = InitMetricsObserver_BDG(Algorithm,Problem,Params, ...
                ExperimentControl);
            Algorithm.metric.analysis_folder   = Observer.folder;
            Algorithm.metric.analysis_meta_csv = Observer.meta_file;
            Algorithm.metric.analysis_core_csv = Observer.core_file;
            Algorithm.metric.analysis_stage_csv = Observer.stage_file;

            Population1 = Problem.Initialization();
            Population2 = Problem.Initialization();
            Fitness1    = CalFitness_BDG(Population1.objs,Population1.cons);
            Fitness2    = CalFitness_BDG(Population2.objs);

            AF = InitArchive_BDG(Problem.D,Problem.M);
            AI = InitArchive_BDG(Problem.D,Problem.M);
            GAN = [];
            gen = 0;
            stageTargets = StageTargets_BDG(Problem.maxFE);
            nextStage = 1;
            SnapshotWriter = InitArchiveSnapshotWriter_BDG( ...
                ExperimentControl,Problem,ResolveRunId_BDG(Algorithm));
            Timing = InitProfileTimer_BDG();

            while Algorithm.NotTerminated(Population1)
                gen = gen + 1;

                MatingPool1 = TournamentSelection(2,2*Problem.N,Fitness1);
                MatingPool2 = TournamentSelection(2,2*Problem.N,Fitness2);
                Offspring1  = OperatorDE(Problem,Population1, ...
                    Population1(MatingPool1(1:end/2)), ...
                    Population1(MatingPool1(end/2+1:end)));
                Offspring2  = OperatorDE(Problem,Population2, ...
                    Population2(MatingPool2(1:end/2)), ...
                    Population2(MatingPool2(end/2+1:end)));

                ArchiveDiag = EmptyMainArchiveDiag_BDG(ArchiveOptions);
                if ShouldUpdateBoundaryArchive_BDG(gen,archiveGap)
                    tStart = tic;
                    [AF,AI,ArchiveDiag] = UpdateBoundaryArchive_BDG(Problem,AF,AI, ...
                        Population1,Offspring1,Population2,Offspring2, ...
                        W,perRef,nearTau,ArchiveOptions);
                    Timing = ProfileTimerAdd_BDG(Timing, ...
                        't_archive_update',toc(tStart));
                end

                OffspringG = Offspring1([]);
                writeMetricsRow = false;
                if mod(gen,trainGap) == 0
                    GanDiag = EmptyGanDiag_BDG(Problem.M,Problem.D);
                    [AFTrain,AITrain,~] = SelectGANTrainingArchive_BDG( ...
                        AF,AI);
                    GanDiag.train_af_count = size(AFTrain.decs,1);
                    [GanDiag.train_ref_count,GanDiag.train_ref_cov] = ...
                        TrainingArchiveRefCoverage_BDG(AFTrain,W);
                    trainRefCount = GanDiag.train_ref_count;
                    trainRefCov = GanDiag.train_ref_cov;

                    refreshFlag = false;
                    skipReason = "AF_empty";
                    if ~isempty(AFTrain.decs)
                        previousGAN = GAN;
                        ThisGANTrainOptions = GANTrainOptions;
                        tStart = tic;
                        EvaluatedSource = BuildEvaluatedFeasibleSource_BDG( ...
                            Problem,Population1,Offspring1, ...
                            Population2,Offspring2,AFTrain);
                        Timing = ProfileTimerAdd_BDG(Timing, ...
                            't_source_build',toc(tStart));
                        if ExperimentControl.trainBundleMode == "refresh_local"
                            [TrainBundle,TargetTrainDiag] = ...
                                BuildBoundaryTrainBundle_BDG(AFTrain, ...
                                AITrain,W,Problem, ...
                                GANTrainOptions.generatorMode, ...
                                ExperimentControl,EvaluatedSource);
                            GANTrainDecs = TrainBundle.decs;
                            GANTrainAI = TrainBundle.aiDecs;
                            GANConditionData = TrainBundle.conditionData;
                            GANTrainWeights = TrainBundle.sampleWeights;
                            GANRealLabels = TrainBundle.realLabels;
                        else
                            [GANTrainDecs,GANTrainAI,GANConditionData, ...
                                GANTrainWeights,GANRealLabels,TargetTrainDiag] = ...
                                BuildGANTrainingSet_BDG(AFTrain,AITrain,W, ...
                                Problem,GANTrainOptions.generatorMode, ...
                                ExperimentControl,EvaluatedSource);
                        end
                        Timing = ProfileTimerAdd_BDG(Timing, ...
                            't_target_build', ...
                            DiagScalar_BDG(TargetTrainDiag,'t_target_build',0));
                        Timing = ProfileTimerAdd_BDG(Timing, ...
                            't_target_filter', ...
                            DiagScalar_BDG(TargetTrainDiag,'t_target_filter',0));
                        TargetReady = IsTrainingDataReady_BDG( ...
                            GANTrainDecs,GANConditionData, ...
                            ThisGANTrainOptions.generatorMode);
                        GanDiag = MergeDiagFields_BDG(GanDiag, ...
                            TargetTrainDiag);
                        [GanDiag.train_ref_count,GanDiag.train_ref_cov] = ...
                            TargetTrainingRefCoverage_BDG( ...
                            TargetTrainDiag,AFTrain,W, ...
                            trainRefCount,trainRefCov);
                        [GateReady,~,~] = IsCGANTrainCoverageReady_BDG( ...
                            TargetTrainDiag,GanDiag.train_ref_cov, ...
                            ExperimentControl);
                        if TargetReady && GateReady
                            ThisGANTrainOptions.sampleWeights = GANTrainWeights;
                            ThisGANTrainOptions.realLabels = GANRealLabels;
                            ThisGANTrainOptions.conditionData = GANConditionData;
                            if isfield(TargetTrainDiag,'target_keep_index')
                                ThisGANTrainOptions.conditionPairIndex = ...
                                    TargetTrainDiag.target_keep_index;
                            else
                                ThisGANTrainOptions.conditionPairIndex = [];
                            end
                            tStart = tic;
                            GAN = BoundaryGAN_BDG('traindirectboundary', ...
                                GANTrainDecs,GANTrainAI, ...
                                Problem.lower,Problem.upper, ...
                                zDim,ganIter,previousGAN, ...
                                ThisGANTrainOptions);
                            Timing = ProfileTimerAdd_BDG(Timing, ...
                                't_gan_train',toc(tStart));
                            candidateN = nGen;
                            [OffspringG,GanDiag] = BoundaryGAN_BDG( ...
                                'sample',Problem,GAN,candidateN);
                            [OffspringG,GanDiag] = SelectInjectedCandidates_BDG( ...
                                OffspringG,GanDiag,nGen);
                            GanDiag = EnsureGanDiag_BDG(GanDiag,Problem.M, ...
                                Problem.D);
                            GanDiag = MergeDiagFields_BDG(GanDiag, ...
                                TargetTrainDiag);
                            GanDiag.train_af_count = size(AFTrain.decs,1);
                            [GanDiag.train_ref_count,GanDiag.train_ref_cov] = ...
                                TargetTrainingRefCoverage_BDG( ...
                                TargetTrainDiag,AFTrain,W, ...
                                trainRefCount,trainRefCov);
                            if isfield(GAN,'targetConditionedDiag')
                                GanDiag = MergeDiagFields_BDG(GanDiag, ...
                                    GAN.targetConditionedDiag);
                            end
                            if isfield(GAN,'pretrainDiag')
                                GanDiag = MergeDiagFields_BDG(GanDiag, ...
                                    GAN.pretrainDiag);
                            end
                            trainDiagN = 100;
                            tStart = tic;
                            GanDiag = MergeDiagFields_BDG(GanDiag, ...
                                BoundaryGAN_BDG('traindiagnose',GAN, ...
                                GANTrainDecs,GANTrainAI, ...
                                Problem.lower,Problem.upper,trainDiagN));
                            if probeRawN > 0
                                GanDiag = MergeDiagFields_BDG(GanDiag, ...
                                    ProbeBoundaryGANNoBudget_BDG(Problem,GAN, ...
                                    probeRawN));
                            end
                            Timing = ProfileTimerAdd_BDG(Timing, ...
                                't_gan_diagnose',toc(tStart));
                            refreshFlag = true;
                            skipReason = "trained";
                        elseif TargetReady
                            skipReason = "target_coverage_gate";
                        else
                            skipReason = "target_triples_insufficient";
                        end
                    end
	                    writeMetricsRow = true;
                end

                [Population1,Fitness1] = EnvironmentalSelection_BDG( ...
                    [Population1,Offspring1,Offspring2,OffspringG],Problem.N,true);
                [Population2,Fitness2] = EnvironmentalSelection_BDG( ...
                    [Population2,Offspring1,Offspring2],Problem.N,false);

                [SnapshotWriter,snapshotElapsed] = MaybeWriteArchiveSnapshots_BDG( ...
                    SnapshotWriter,Problem,AF,AI,GAN,gen, ...
                    Population1,Population2);
                Timing = ProfileTimerAdd_BDG(Timing, ...
                    't_snapshot_export',snapshotElapsed);

                while nextStage <= numel(stageTargets) && ...
                        Problem.FE >= stageTargets(nextStage)
                    stageActualFE = Problem.FE;
                    tStart = tic;
                    AppendCsvRow_BDG(Observer.stage_file, ...
                        BuildStageMetricsRow_BDG(stageTargets(nextStage), ...
                        stageActualFE,gen,Problem,AF,AI,W,GAN,stageProbeN));
                    Timing = ProfileTimerAdd_BDG(Timing, ...
                        't_stage_probe',toc(tStart));
                    nextStage = nextStage + 1;
                end

                if writeMetricsRow
                    AppendMetricsRow_BDG(Observer.core_file, ...
                        BuildMetricsRow_BDG(gen,Problem,AF,AI, ...
                        W,GanDiag,ArchiveDiag,refreshFlag, ...
                        skipReason,Timing));
                end
            end
        end
    end
end

function A = InitArchive_BDG(D,M)
    A.decs  = zeros(0,D);
    A.objs  = zeros(0,M);
    A.ref   = zeros(0,1);
    A.score = zeros(0,1);
end

function flag = ShouldUpdateBoundaryArchive_BDG(gen,archiveGap)
    archiveGap = max(1,round(double(archiveGap)));
    flag = gen == 1 || mod(gen,archiveGap) == 0;
end

