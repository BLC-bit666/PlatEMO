function [sampleFile,metricFile,status] = WriteGANDiagnosticSnapshot_BDG( ...
        Writer,Problem,AFTrain,AITrain,GAN,targetFE,actualFE,gen)
    safeProblem = regexprep(char(Writer.problem),'[^A-Za-z0-9_]+','_');
    tagText = char(Writer.tag);
    if strlength(Writer.tag) > 0
        tagText = ['_',regexprep(tagText,'[^A-Za-z0-9_]+','_')];
    end
    prefix = sprintf('%s_run%d_targetFE%06d%s_gan_diagnostic', ...
        safeProblem,round(Writer.run),round(targetFE),tagText);
    sampleFile = string(fullfile(char(Writer.diagnosticFolder), ...
        [prefix,'_samples.csv']));
    metricFile = string(fullfile(char(Writer.diagnosticFolder), ...
        [prefix,'_metrics.csv']));
    WriteCsvHeader_BDG(sampleFile,GANDiagnosticSampleColumns_BDG(Problem));
    WriteCsvHeader_BDG(metricFile,GANDiagnosticMetricColumns_BDG());

    selected = SelectGANDiagnosticConditionIndices_BDG( ...
        GAN,Writer.diagnosticConditionCount);
    status = "ok";
    Normal = EmptyGANDiagnosticModeData_BDG(Problem);
    FixedZ = EmptyGANDiagnosticModeData_BDG(Problem);
    ZSweep = EmptyGANDiagnosticModeData_BDG(Problem);
    if isempty(GAN) || ~isfield(GAN,'netG') || ...
            ~isfield(GAN,'conditionData') || isempty(GAN.conditionData)
        status = "empty_gan";
        AppendCsvRow_BDG(metricFile,GANDiagnosticMetricRow_BDG( ...
            Writer,Problem,targetFE,actualFE,gen,status,selected, ...
            AFTrain,AITrain,Normal,FixedZ,ZSweep));
        return;
    end

    oldFE = Problem.FE;
    rngState = rng;
    cleanup = onCleanup(@()RestoreProblemState_BDG( ...
        Problem,oldFE,rngState)); %#ok<NASGU>
    seed = mod(round(Writer.diagnosticSeed) + ...
        1000003*round(Writer.run) + round(targetFE) + 997*round(gen), ...
        2147483646) + 1;
    rng(seed,'twister');

    try
        normalN = max(0,round(double(Writer.diagnosticNormalN)));
        if normalN > 0
            [S,Diag] = BoundaryGAN_BDG('sample',Problem,GAN,normalN);
            Normal = BuildGANDiagnosticModeData_BDG( ...
                Problem,AFTrain,AITrain,S,Diag, ...
                repmat("normal",normalN,1),(1:normalN)');
            WriteGANDiagnosticSampleRows_BDG(sampleFile,Writer, ...
                Problem,targetFE,actualFE,gen,Normal);
        end

        if ~isempty(selected)
            fixedZ = zeros(numel(selected),max(0,round(double(GAN.zDim))));
            [S,Diag] = BoundaryGAN_BDG('diagnosesample', ...
                Problem,GAN,selected(:),fixedZ);
            FixedZ = BuildGANDiagnosticModeData_BDG( ...
                Problem,AFTrain,AITrain,S,Diag, ...
                repmat("fixed_z",numel(selected),1), ...
                ones(numel(selected),1));
            WriteGANDiagnosticSampleRows_BDG(sampleFile,Writer, ...
                Problem,targetFE,actualFE,gen,FixedZ);

            zPerCondition = max(0,round(double( ...
                Writer.diagnosticZPerCondition)));
            if zPerCondition > 0
                sweepCondition = repelem(selected(:),zPerCondition);
                sweepZ = randn(numel(sweepCondition), ...
                    max(0,round(double(GAN.zDim))));
                zId = repmat((1:zPerCondition)',numel(selected),1);
                [S,Diag] = BoundaryGAN_BDG('diagnosesample', ...
                    Problem,GAN,sweepCondition,sweepZ);
                ZSweep = BuildGANDiagnosticModeData_BDG( ...
                    Problem,AFTrain,AITrain,S,Diag, ...
                    repmat("z_sweep",numel(sweepCondition),1),zId);
                WriteGANDiagnosticSampleRows_BDG(sampleFile,Writer, ...
                    Problem,targetFE,actualFE,gen,ZSweep);
            end
        end
    catch err
        status = "failed:" + string(err.identifier);
    end

    AppendCsvRow_BDG(metricFile,GANDiagnosticMetricRow_BDG( ...
        Writer,Problem,targetFE,actualFE,gen,status,selected, ...
        AFTrain,AITrain,Normal,FixedZ,ZSweep));
end

