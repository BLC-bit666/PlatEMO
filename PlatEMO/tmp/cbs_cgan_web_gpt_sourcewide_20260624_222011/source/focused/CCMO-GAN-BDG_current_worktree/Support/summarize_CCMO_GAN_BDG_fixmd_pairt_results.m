function [DiagSummary,CoreSummary] = summarize_CCMO_GAN_BDG_fixmd_pairt_results(outRoot)
% Summarize fix.md pair+t diagnostic suite outputs.

    if nargin < 1 || isempty(outRoot)
        error('summarize_CCMO_GAN_BDG_fixmd_pairt_results:MissingOutRoot', ...
            'outRoot is required.');
    end
    manifestFile = fullfile(outRoot,'suite_manifest.csv');
    if ~isfile(manifestFile)
        error('summarize_CCMO_GAN_BDG_fixmd_pairt_results:MissingManifest', ...
            'Missing suite_manifest.csv in %s.',outRoot);
    end
    Manifest = readManifestRows_BDG(manifestFile);

    MetricsAll = table();
    CoreRows = repmat(emptyCoreRow_BDG(),0,1);
    coreCount = 0;
    for i = 1 : numel(Manifest)
        outDir = char(string(Manifest(i).outDir));
        metricsFile = fullfile(outDir,'gan_diagnostic_metrics_all.csv');
        if isfile(metricsFile)
            Metrics = readtable(metricsFile,'TextType','string');
            if ~isempty(Metrics)
                Metrics.suite = repmat(string(Manifest(i).suite), ...
                    height(Metrics),1);
                MetricsAll = [MetricsAll; Metrics]; %#ok<AGROW>
            end
        end

        summaryFile = fullfile(outDir,'boundary_diagnostic_run_summary.csv');
        if ~isfile(summaryFile)
            continue;
        end
        SummaryRows = readRunSummaryRows_BDG(summaryFile);
        for r = 1 : numel(SummaryRows)
            coreFile = filePathString_BDG(SummaryRows(r).core_metrics_file);
            if strlength(coreFile) == 0 || ~isfile(coreFile)
                continue;
            end
            Core = readtable(char(coreFile),'TextType','string');
            if isempty(Core)
                continue;
            end
            coreCount = coreCount + 1;
            CoreRows(coreCount,1) = buildCoreRow_BDG( ...
                Manifest(i).suite,Manifest(i).variant,SummaryRows(r), ...
                Core(end,:)); %#ok<AGROW>
        end
    end

    CoreAll = struct2table(CoreRows);
    writetable(MetricsAll,fullfile(outRoot,'fixmd_pairt_diagnostic_all.csv'));
    writetable(CoreAll,fullfile(outRoot,'fixmd_pairt_core_final_all.csv'));

    DiagSummary = writeGroupedSummary_BDG(MetricsAll, ...
        ["suite","variant","target_FE"],diagnosticMetricVars_BDG(), ...
        fullfile(outRoot,'fixmd_pairt_diagnostic_by_variant.csv'));
    writeGroupedSummary_BDG(MetricsAll, ...
        ["suite","variant","problem_name","target_FE"], ...
        diagnosticMetricVars_BDG(), ...
        fullfile(outRoot,'fixmd_pairt_diagnostic_by_problem.csv'));

    CoreSummary = writeGroupedSummary_BDG(CoreAll, ...
        ["suite","variant"],coreMetricVars_BDG(), ...
        fullfile(outRoot,'fixmd_pairt_core_by_variant.csv'));
    writeGroupedSummary_BDG(CoreAll, ...
        ["suite","variant","problem"],coreMetricVars_BDG(), ...
        fullfile(outRoot,'fixmd_pairt_core_by_problem.csv'));

    writeRegression10Summaries_BDG(MetricsAll,CoreAll,outRoot);
end

function Row = buildCoreRow_BDG(suite,variant,Summary,Core)
    Row = emptyCoreRow_BDG();
    Row.suite = string(suite);
    Row.variant = string(variant);
    Row.problem = string(Summary.problem);
    Row.family = string(Summary.family);
    Row.run = double(Summary.run);
    Row.seed = double(Summary.seed);
    Row.N = double(Summary.N);
    Row.D = double(Summary.D);
    Row.maxFE = double(Summary.maxFE);
    Row.finalFE = double(Summary.finalFE);
    Row.runtime = double(Summary.runtime);
    Row.IGD = double(Summary.IGD);
    Row.HV = double(Summary.HV);
    Row.final_feasible_rate = double(Summary.Feasible_rate);

    vars = coreMetricVars_BDG();
    names = string(Core.Properties.VariableNames);
    for i = 1 : numel(vars)
        v = vars(i);
        if ismember(v,names)
            Row.(char(v)) = double(Core.(char(v)));
        end
    end
end

function Rows = readManifestRows_BDG(manifestFile)
    C = readcell(manifestFile,'Delimiter',',');
    if size(C,1) < 2
        Rows = repmat(emptyManifestRow_BDG(),0,1);
        return;
    end
    Header = string(C(1,:));
    Data = C(2:end,:);
    Rows = repmat(emptyManifestRow_BDG(),size(Data,1),1);
    for i = 1 : size(Data,1)
        Rows(i).suite = cellString_BDG(Data{i,col_BDG(Header,"suite")});
        Rows(i).variant = cellString_BDG(Data{i,col_BDG(Header,"variant")});
        Rows(i).outDir = cellString_BDG(Data{i,col_BDG(Header,"outDir")});
    end
end

function Rows = readRunSummaryRows_BDG(summaryFile)
    C = readcell(summaryFile,'Delimiter',',');
    if size(C,1) < 2
        Rows = repmat(emptySummaryRow_BDG(),0,1);
        return;
    end
    Header = string(C(1,:));
    Data = C(2:end,:);
    Rows = repmat(emptySummaryRow_BDG(),size(Data,1),1);
    for i = 1 : size(Data,1)
        Rows(i).problem = cellString_BDG(Data{i,col_BDG(Header,"problem")});
        Rows(i).family = cellString_BDG(Data{i,col_BDG(Header,"family")});
        Rows(i).run = cellDouble_BDG(Data{i,col_BDG(Header,"run")});
        Rows(i).seed = cellDouble_BDG(Data{i,col_BDG(Header,"seed")});
        Rows(i).N = cellDouble_BDG(Data{i,col_BDG(Header,"N")});
        Rows(i).D = cellDouble_BDG(Data{i,col_BDG(Header,"D")});
        Rows(i).maxFE = cellDouble_BDG(Data{i,col_BDG(Header,"maxFE")});
        Rows(i).finalFE = cellDouble_BDG(Data{i,col_BDG(Header,"finalFE")});
        Rows(i).runtime = cellDouble_BDG(Data{i,col_BDG(Header,"runtime")});
        Rows(i).IGD = cellDouble_BDG(Data{i,col_BDG(Header,"IGD")});
        Rows(i).HV = cellDouble_BDG(Data{i,col_BDG(Header,"HV")});
        Rows(i).Feasible_rate = cellDouble_BDG( ...
            Data{i,col_BDG(Header,"Feasible_rate")});
        Rows(i).core_metrics_file = cellString_BDG( ...
            Data{i,col_BDG(Header,"core_metrics_file")});
    end
end

function idx = col_BDG(Header,name)
    idx = find(Header == string(name),1);
    if isempty(idx)
        error('summarize_CCMO_GAN_BDG_fixmd_pairt_results:MissingColumn', ...
            'Missing column %s.',name);
    end
end

function value = cellString_BDG(x)
    if isempty(x)
        value = "";
    elseif isstring(x) && ismissing(x)
        value = "";
    elseif ischar(x) && isempty(x)
        value = "";
    else
        value = string(x);
        if ismissing(value)
            value = "";
        end
    end
end

function path = filePathString_BDG(value)
    if isempty(value)
        path = "";
        return;
    end
    path = string(value);
    if ismissing(path) || strlength(path) == 0
        path = "";
    end
end

function value = cellDouble_BDG(x)
    if isnumeric(x)
        value = double(x);
    else
        value = str2double(string(x));
    end
end

function Summary = writeGroupedSummary_BDG(T,groupVars,metricVars,outFile)
    groupVars = string(groupVars);
    metricVars = intersect(string(metricVars), ...
        string(T.Properties.VariableNames),'stable');
    if isempty(T) || isempty(metricVars)
        Summary = table();
    else
        Summary = groupsummary(T,cellstr(groupVars),'mean',cellstr(metricVars));
    end
    writetable(Summary,outFile);
end

function writeRegression10Summaries_BDG(MetricsAll,CoreAll,outRoot)
    rec = "FixMD_GNDk60_nearseg_huber_z0";
    if ~isempty(MetricsAll) && ismember("variant", ...
            string(MetricsAll.Properties.VariableNames))
        Diag = MetricsAll(string(MetricsAll.variant) == rec,:);
        if ~isempty(Diag)
            Diag.suite(:) = "regression10_recommended";
            writeGroupedSummary_BDG(Diag,["suite","variant","target_FE"], ...
                diagnosticMetricVars_BDG(), ...
                fullfile(outRoot, ...
                'fixmd_pairt_regression10_diagnostic_overview.csv'));
            writeGroupedSummary_BDG(Diag, ...
                ["suite","variant","problem_name","target_FE"], ...
                diagnosticMetricVars_BDG(), ...
                fullfile(outRoot, ...
                'fixmd_pairt_regression10_diagnostic_by_problem.csv'));
        end
    end
    if ~isempty(CoreAll) && ismember("variant", ...
            string(CoreAll.Properties.VariableNames))
        Core = CoreAll(string(CoreAll.variant) == rec,:);
        if ~isempty(Core)
            Core.suite(:) = "regression10_recommended";
            writeGroupedSummary_BDG(Core,["suite","variant"], ...
                coreMetricVars_BDG(), ...
                fullfile(outRoot, ...
                'fixmd_pairt_regression10_core_overview.csv'));
            writeGroupedSummary_BDG(Core,["suite","variant","problem"], ...
                coreMetricVars_BDG(), ...
                fullfile(outRoot, ...
                'fixmd_pairt_regression10_core_by_problem.csv'));
        end
    end
end

