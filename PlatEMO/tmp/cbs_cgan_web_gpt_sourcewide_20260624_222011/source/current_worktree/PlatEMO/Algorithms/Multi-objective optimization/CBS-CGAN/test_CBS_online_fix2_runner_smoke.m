function test_CBS_online_fix2_runner_smoke()
%TEST_CBS_ONLINE_FIX2_RUNNER_SMOKE Verify the minimal fix2 online runner.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));
    testDefaultOnlineFix2ConfigurationMatchesRequest(repoRoot);

    rng(97,'twister');
    outDir = fullfile(tempdir,sprintf('cbs_online_fix2_%s', ...
        char(java.util.UUID.randomUUID)));
    Options = struct( ...
        'workerCount',1, ...
        'problemNames',"LIRCMOP5_BC", ...
        'runIds',1, ...
        'N',20, ...
        'maxFE',800, ...
        'targets',800, ...
        'plotRun',0, ...
        'visualDiagnostics',false, ...
        'plotDiagnosticTrends',false, ...
        'algorithmParams',{{1,1,20,2,1,8,1e-4,2e-4,0,1,1,4,1,2,1,0.10,1}});

    [Summary,~,ByProblem,Raw,~,VariantManifest] = ...
        run_CBS_CGAN_loss_ablation_lir_online(outDir,Options);

    expectedVariants = ["A_ref_only_adv"; ...
        "B_ref_only_adv_huber";"C_ref_tau_adv"];
    assert(isequal(sort(string(VariantManifest.variant)), ...
            sort(expectedVariants)), ...
        'Online fix2 runner must expose only the requested A/B/C variants.');
    assert(all(ismember(expectedVariants,string(Summary.variant))), ...
        'Run summary must include all A/B/C variants.');
    assert(all(string(Raw.condition_mode(string(Raw.variant) == ...
            "A_ref_only_adv")) == "ref_only"), ...
        'Variant A must use ref_only.');
    assert(all(string(Raw.condition_mode(string(Raw.variant) == ...
            "B_ref_only_adv_huber")) == "ref_only"), ...
        'Variant B must use ref_only.');
    assert(all(string(Raw.condition_mode(string(Raw.variant) == ...
            "C_ref_tau_adv")) == "ref_tau"), ...
        'Variant C must use ref_tau.');

    expectedMetrics = ["train_x_rec90","train_y_rec90", ...
        "boundary_dist90","segment_width90","feasible_rate","side_rate", ...
        "ref_cover"];
    for i = 1 : numel(expectedMetrics)
        assert(ismember(expectedMetrics(i),string(Raw.Properties.VariableNames)), ...
            'Raw output missing fix2 metric: %s',expectedMetrics(i));
        assert(ismember("median_" + expectedMetrics(i), ...
                string(ByProblem.Properties.VariableNames)), ...
            'By-problem output missing median fix2 metric: %s',expectedMetrics(i));
    end
    forbiddenMetrics = ["query_obj_dist90","pair_violation_rate", ...
        "pair_margin50"];
    assert(~any(ismember(forbiddenMetrics,string(Raw.Properties.VariableNames))), ...
        'Raw output must not keep non-fix2 metric columns.');
    assert(~any(ismember("median_" + forbiddenMetrics, ...
            string(ByProblem.Properties.VariableNames))), ...
        'By-problem output must not aggregate non-fix2 metric columns.');

    rmdir(outDir,'s');
    fprintf('CBS-CGAN fix2 online runner smoke passed.\n');
end

function testDefaultOnlineFix2ConfigurationMatchesRequest(repoRoot)
    runnerFile = fullfile(repoRoot,'Algorithms', ...
        'Multi-objective optimization','CBS-CGAN','Support', ...
        'run_CBS_CGAN_loss_ablation_lir_online.m');
    txt = fileread(runnerFile);
    compact = regexprep(txt,'\s+','');
    compact = erase(compact,'...');
    assert(contains(compact, ...
        "ensureOnlineField(Options,'workerCount',8)"), ...
        'Default fix2 online workerCount must be 8.');
    assert(contains(compact, ...
        '["LIRCMOP5_BC";"LIRCMOP7_BC";"LIRCMOP8_BC";"LIRCMOP10_BC"]'), ...
        'Default fix2 online problem list must be LIRCMOP5/7/8/10.');
    assert(contains(compact, ...
        "ensureOnlineField(Options,'runIds',1:3)"), ...
        'Default fix2 online runIds must remain 1:3.');
    assert(contains(compact, ...
        "ensureOnlineField(Options,'targets',[10000300005000070000100000])"), ...
        'Default fix2 online targets must keep the five FE checkpoints.');
end
