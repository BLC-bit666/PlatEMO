function test_CBS_visual_diagnostics_runner_smoke()
%TEST_CBS_VISUAL_DIAGNOSTICS_RUNNER_SMOKE Verify visual CGAN diagnostic plots.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));
    testVisualDiagnosticsUseOnlyZeroLatent(repoRoot);
    testFigureKindsCanLimitTrainReconstruction();

    outDir = fullfile(tempdir,sprintf('cbs_cgan_visual_smoke_%s', ...
        char(java.util.UUID.randomUUID)));
    Options = struct( ...
        'plotRun',1, ...
        'conditionMode',"ref_y", ...
        'visualDiagnostics',true, ...
        'algorithmParams',{{1,1,10,2,1,8,1e-4,2e-4,0,1,1,4,3,1,1,0.10,1}});

    [Summary,~,~,Figures] = run_CBS_CGAN_boundary_quality_experiments( ...
        outDir,1,"DASCMOP1_BC",30,[],1500,1,1000,Options);

    assert(height(Summary) == 1 && string(Summary.status(1)) == "ok", ...
        'Visual smoke runner should finish one tiny CBS-CGAN run.');
    figureFiles = string(Figures.figure_file);
    assert(any(contains(figureFiles,"visual_z_diagnostic")), ...
        'visualDiagnostics=true must write a visual z diagnostic PNG.');
    assert(any(contains(figureFiles,"train_reconstruction")), ...
        'visualDiagnostics=true must write a TrainC reconstruction PNG.');
    assert(any(contains(figureFiles,"condition_space_coverage")), ...
        'visualDiagnostics=true must write a condition-space coverage PNG.');
    visualFiles = figureFiles(contains(figureFiles,"visual_z_diagnostic"));
    assert(all(arrayfun(@(f)isfile(f),visualFiles)), ...
        'Visual diagnostic files listed in the manifest must exist.');

    fprintf('CBS-CGAN visual diagnostics runner smoke passed: %s\n',outDir);
end

function testFigureKindsCanLimitTrainReconstruction()
    outDir = fullfile(tempdir,sprintf('cbs_cgan_train_fig_only_%s', ...
        char(java.util.UUID.randomUUID)));
    Options = struct( ...
        'plotRun',1, ...
        'conditionMode',"ref_y", ...
        'visualDiagnostics',true, ...
        'figureKinds',"train_reconstruction", ...
        'algorithmParams',{{1,1,10,2,1,8,1e-4,2e-4,0,1,1,4,3,1,1,0.10,1}});

    [Summary,~,~,Figures] = run_CBS_CGAN_boundary_quality_experiments( ...
        outDir,1,"DASCMOP1_BC",30,[],1500,1,1000,Options);

    assert(height(Summary) == 1 && string(Summary.status(1)) == "ok", ...
        'Train-only figure smoke runner should finish one tiny CBS-CGAN run.');
    figureFiles = string(Figures.figure_file);
    assert(~isempty(figureFiles), ...
        'figureKinds=train_reconstruction must still write TrainC figures.');
    assert(all(contains(figureFiles,"train_reconstruction")), ...
        'figureKinds=train_reconstruction must suppress non-training figures.');
    assert(all(arrayfun(@(f)isfile(f),figureFiles)), ...
        'Train reconstruction files listed in the manifest must exist.');
end

function testVisualDiagnosticsUseOnlyZeroLatent(repoRoot)
    cbsFile = fullfile(repoRoot,'Algorithms', ...
        'Multi-objective optimization','CBS-CGAN','CBS_CGAN.m');
    plotFile = fullfile(repoRoot,'Algorithms', ...
        'Multi-objective optimization','CBS-CGAN','Support', ...
        'run_CBS_CGAN_boundary_quality_experiments.m');
    cbsText = fileread(cbsFile);
    plotText = fileread(plotFile);
    forbidden = ["visual_query_fixed_objs","visual_train_fixed_objs", ...
        "fixedCBSLatentRows","QueryC fixed z","TrainC fixed z"];
    joined = string(cbsText) + newline + string(plotText);
    for i = 1 : numel(forbidden)
        assert(~contains(joined,forbidden(i)), ...
            'Visual diagnostics must ignore fixed z; found %s.', ...
            forbidden(i));
    end
end
