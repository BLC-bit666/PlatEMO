function Core = addSyntheticProbabilityHistograms(Core)
    Prefixes = probabilityHistogramPrefixes();
    Base = [0 0 0 0 30 35 20 10 3 2];
    for p = 1 : numel(Prefixes)
        Columns = probabilityHistogramColumns(Prefixes{p});
        Scale = p;
        Values = [
            zeros(1,10);
            Scale*Base;
            zeros(1,10);
            Scale*[0 0 2 8 30 35 15 7 2 1]];
        for c = 1 : numel(Columns)
            Core.(Columns{c}) = Values(:,c);
        end
    end
end

