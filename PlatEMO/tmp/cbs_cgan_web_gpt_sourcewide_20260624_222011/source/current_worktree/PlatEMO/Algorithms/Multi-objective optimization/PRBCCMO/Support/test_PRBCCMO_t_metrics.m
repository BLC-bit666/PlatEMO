function test_PRBCCMO_t_metrics()
% Contract test for PRBCCMO_t metrics under the current fix.md contract.

    supportDir = fileparts(mfilename('fullpath'));
    algorithmDir = fileparts(supportDir);
    repoDir = fileparts(fileparts(fileparts(algorithmDir)));
    addpath(genpath(repoDir));

    traceText = normalizeCode(fileread(fullfile(algorithmDir,'PRBCCMO_t.m')));
    coreText = normalizeCode(fileread(fullfile(algorithmDir,'PRBCCMO_objective_core.m')));
    benchText = normalizeCode(fileread(fullfile(supportDir,'benchmark_PRBCCMO_t_suite.m')));
    boundaryPlotText = normalizeCode(fileread(fullfile(supportDir,'plot_PRBCCMO_B_boundary_relation.m')));
    refinementText = normalizeCode(fileread(fullfile(supportDir,'run_PRBCCMO_t_igd_refinement.m')));

    requireContains(traceText,'Algorithm.metric.analysis_core_csv=Observer.core_file;', ...
        'test_PRBCCMO_t_metrics:CoreCsvExposed', ...
        'PRBCCMO_t must expose analysis_core_csv.');
    requireContains(traceText,'Algorithm.ParameterSet(64,200,1e-3,3,0.1,10,0,0,1)', ...
        'test_PRBCCMO_t_metrics:DefaultTunedParameters', ...
        'PRBCCMO_t must default to the fix.md recoverability-first Adam/MLP settings.');
    requireContains(benchText,'summarize_PRBCCMO_mlp_delta', ...
        'test_PRBCCMO_t_metrics:PairedDeltaSummaryHook', ...
        'Benchmark scripts must expose paired delta_igd_mlp summary support.');
    requireContains(boundaryPlotText,'''parameter'',{64,200,1e-3,3,0.1,10,0,1,1}', ...
        'test_PRBCCMO_t_metrics:BoundaryRelationParameters', ...
        'Boundary relation figures must use saveB=1 and useMLP=1.');
    requireContains(refinementText,'1,"current_baseline",64,200,0.001,3.0,0.10,10,0', ...
        'test_PRBCCMO_t_metrics:RefinementCurrentBaseline', ...
        'Refinement entry must use the fix.md baseline configuration.');

    Fields = coreMetricColumns();
    for i = 1 : numel(Fields)
        requireContains(coreText,['''',Fields{i},''''], ...
            ['test_PRBCCMO_t_metrics:CoreField_',Fields{i}], ...
            ['core_metrics.csv must expose ',Fields{i},'.']);
    end
    requireNoForbiddenCoreFields(coreText);
    requireNoPairwiseRankLoss(coreText);

    runFolder = createSyntheticRun();
    Core = readtable(fullfile(runFolder,'core_metrics.csv'),'TextType','string');
    PRBCCMOUtils.requireColumns(Core,Fields);

    RunSummary = summarize_PRBCCMO_t_run(runFolder);
    requireStructFields(RunSummary,{ ...
        'problem','family','run','analysis_folder','analysis_core_csv', ...
        'final_b_mean_pair_gap','mean_b_mean_pair_gap','p90_b_mean_pair_gap','final_b_p90_pair_gap', ...
        'final_b_mean_mid_scalar','mean_b_mean_mid_scalar', ...
        'final_b_mean_infeasible_boundary_dist','mean_b_mean_infeasible_boundary_dist', ...
        'final_b_far_infeasible_boundary_ratio','mean_b_far_infeasible_boundary_ratio', ...
        'final_b_inf_unconstrained_src_ratio','mean_b_inf_unconstrained_src_ratio', ...
        'final_b_overlap_popc_ratio','mean_b_overlap_popc_ratio', ...
        'final_b_overlap_popu_ratio','mean_b_overlap_popu_ratio', ...
        'final_b_active_sector_ratio','mean_b_active_sector_ratio', ...
        'mean_b_changed_pair_count','mean_b_changed_pair_ratio', ...
        'mean_b_replaced_pair_count','mean_b_contracted_pair_count', ...
        'mean_b_global_change_pair_ratio','mean_b_contraction_pair_ratio', ...
        'mlp_due_events','mlp_can_train_events','mlp_trained_events', ...
        'final_train_size','mean_train_size', ...
        'final_train_pos','final_train_neg', ...
        'final_train_b_core_count','final_train_refinement_count','final_train_current_pop_count', ...
        'final_train_refinement_pos_count','final_train_refinement_neg_count','mean_train_refinement_ratio', ...
        'mean_mlp_prob_bcore_feasible','mean_mlp_prob_bcore_infeasible', ...
        'mean_mlp_prob_curr_feasible','mean_mlp_prob_curr_infeasible', ...
        'mean_prob_accepted_refinement','mean_prob_rejected_refinement', ...
        'mean_mlp_prob_bcore_gap','mean_mlp_prob_current_gap','mean_prob_refinement_gap', ...
        'mlp_two_inf_tournament_total','mean_mlp_two_inf_tournament_total', ...
        'mlp_effective_win_total','mean_mlp_effective_win_total', ...
        'mlp_primary_resolution_total','mean_mlp_primary_resolution_total', ...
        'b_fallback_total','mean_b_fallback_total', ...
        'mean_mlp_two_inf_tournament_rate','mean_mlp_effective_win_rate', ...
        'mean_mlp_primary_resolution_rate','mean_b_fallback_rate', ...
        'mlp_inf_selection_generations','mlp_inf_selection_rate', ...
        'inf_feasible_deficit_total','mean_inf_feasible_deficit', ...
        'mean_inf_feasible_deficit_when_mlp_active','mean_inf_selected_when_mlp_active', ...
        'mean_inf_pool_mean_utility','mean_inf_selected_mean_utility', ...
        'mean_inf_pool_mean_prob','mean_inf_selected_mean_prob', ...
        'inf_selection_generations','inf_selected_total', ...
        'mean_inf_utility_gain','pos_rate_inf_utility_gain','mean_inf_selected_prob_gain'});
    assert(RunSummary.mlp_trained_events == 2, ...
        'test_PRBCCMO_t_metrics:TrainedEventCount', ...
        'Synthetic core trace must report two trained MLP events.');
    assert(RunSummary.final_train_size == 40 && RunSummary.final_train_pos == 20 && ...
            RunSummary.final_train_neg == 20, ...
        'test_PRBCCMO_t_metrics:FinalTrainingBufferCounts', ...
        'Summary must expose final balanced training size.');
    assert(RunSummary.final_train_b_core_count == 10 && ...
            RunSummary.final_train_refinement_count == 24 && ...
            RunSummary.final_train_current_pop_count == 6 && ...
            RunSummary.final_train_refinement_pos_count == 12 && ...
            RunSummary.final_train_refinement_neg_count == 12 && ...
            abs(RunSummary.mean_train_refinement_ratio - mean([0.00 14/30 20/36 24/40])) < 1e-12, ...
        'test_PRBCCMO_t_metrics:FinalTrainingSources', ...
        'Summary must expose B-core, refinement, current-pop, and refinement outcome class composition.');
    assert(abs(RunSummary.mean_mlp_prob_curr_feasible - mean([0.62 0.64])) < 1e-12 && ...
            abs(RunSummary.mean_prob_accepted_refinement - mean([0.56 0.58])) < 1e-12 && ...
            abs(RunSummary.mean_prob_refinement_gap - mean([0.12 0.16])) < 1e-12 && ...
            abs(RunSummary.mean_mlp_prob_current_gap - mean([0.21 0.21])) < 1e-12, ...
        'test_PRBCCMO_t_metrics:BoundaryDrivenDiagnostics', ...
        'Summary must expose current-pop and refinement recoverability diagnostics and gaps.');
    assert(RunSummary.mlp_two_inf_tournament_total == 50 && ...
            RunSummary.mlp_effective_win_total == 9 && ...
            RunSummary.mlp_primary_resolution_total == 19 && ...
            RunSummary.b_fallback_total == 31 && ...
            abs(RunSummary.mean_mlp_two_inf_tournament_total - 12.5) < 1e-12 && ...
            abs(RunSummary.mean_mlp_effective_win_total - 2.25) < 1e-12 && ...
            abs(RunSummary.mean_mlp_primary_resolution_total - 4.75) < 1e-12 && ...
            abs(RunSummary.mean_b_fallback_total - 7.75) < 1e-12, ...
        'test_PRBCCMO_t_metrics:MLPParticipationCounts', ...
        'Summary must expose raw MLP participation, primary-resolution, fallback, and effective intervention counts.');
    assert(~isfield(RunSummary,'final_train_easy_feasible') && ...
            ~isfield(RunSummary,'final_train_src_boundary_band') && ...
            ~isfield(RunSummary,'mean_mlp_gap_feasible'), ...
        'test_PRBCCMO_t_metrics:NoLegacySummaryFields', ...
        'Summary must not expose easy/boundary-band legacy fields.');

    outDir = fullfile(tempdir,'prbccmo_t_core_metrics_test');
    if ~isfolder(outDir)
        mkdir(outDir);
    end
    [RunTable,ProblemTable,FamilyTable] = summarize_PRBCCMO_t_data(runFolder,outDir);
    assert(height(RunTable) == 1 && height(ProblemTable) == 1 && height(FamilyTable) == 1, ...
        'test_PRBCCMO_t_metrics:SummaryTableShape', ...
        'Core summary helpers must produce run/problem/family tables.');
    HistTable = summarize_PRBCCMO_t_probability_histograms(runFolder,outDir);
    PRBCCMOUtils.requireColumns(HistTable,{'sample_scope','bin','count','fraction'});
    TrainHist = HistTable(string(HistTable.sample_scope) == "train",:);
    assert(height(TrainHist) == 10 && sum(TrainHist.count) == 200 && ...
            TrainHist.count(5) == 60 && TrainHist.count(6) == 70, ...
        'test_PRBCCMO_t_metrics:ProbabilityHistogramSummary', ...
        'Probability histogram summary must aggregate per-sample MLP decile counts.');
    ScopeNames = unique(string(HistTable.sample_scope),'stable');
    assert(isequal(ScopeNames,["train";"bcore_feasible";"bcore_infeasible";"curr_feasible";"curr_infeasible"]), ...
        'test_PRBCCMO_t_metrics:ProbabilityHistogramScopes', ...
        'Probability histogram scopes must match the B-driven dataset.');
    PRBCCMOUtils.requireColumns(ProblemTable,{ ...
        'mean_final_b_mean_pair_gap','mean_mean_b_active_sector_ratio','mean_mlp_trained_events', ...
        'mean_final_b_mean_mid_scalar','mean_mean_b_mean_mid_scalar', ...
        'mean_final_b_mean_infeasible_boundary_dist','mean_final_b_inf_unconstrained_src_ratio', ...
        'mean_final_train_size','mean_final_train_refinement_count', ...
        'mean_final_train_refinement_pos_count','mean_final_train_refinement_neg_count', ...
        'mean_mean_train_refinement_ratio', ...
        'mean_final_train_current_pop_count','mean_mean_mlp_prob_curr_feasible', ...
        'mean_mean_prob_accepted_refinement','mean_mean_prob_refinement_gap', ...
        'mean_mean_mlp_prob_current_gap','mean_mlp_two_inf_tournament_total', ...
        'mean_mlp_effective_win_total','mean_mean_mlp_effective_win_rate', ...
        'mean_mlp_primary_resolution_total','mean_b_fallback_total', ...
        'mean_mean_mlp_primary_resolution_rate','mean_mean_b_fallback_rate', ...
        'mean_mlp_inf_selection_generations','mean_mlp_inf_selection_rate', ...
        'mean_inf_feasible_deficit_total','mean_mean_inf_feasible_deficit_when_mlp_active', ...
        'mean_mean_inf_selected_when_mlp_active', ...
        'mean_mean_inf_selected_mean_utility','mean_mean_inf_utility_gain', ...
        'mean_pos_rate_inf_utility_gain','mean_mean_inf_selected_prob_gain'});

    Delta = summarize_PRBCCMO_mlp_delta(createSyntheticPairedIgdTable());
    PRBCCMOUtils.requireColumns(Delta,{'problem','run','igd_no_mlp_cmp','igd_mlp_cmp','delta_igd_mlp', ...
        'mlp_igd_result','mlp_igd_win','mlp_igd_loss','mlp_igd_tie','mlp_igd_missing'});
    assert(abs(Delta.delta_igd_mlp(1) - 0.03) < 1e-12, ...
        'test_PRBCCMO_t_metrics:DeltaIGDMLP', ...
        'delta_igd_mlp must be IGD(PRBCCMO-noMLPcmp) - IGD(PRBCCMO-MLPcmp).');

    metricOutDir = fullfile(tempdir,['prbccmo_t_metric_analysis_',char(java.util.UUID.randomUUID)]);
    MetricOutputs = analyze_PRBCCMO_t_benchmark_metrics(createSyntheticBenchmarkTable(),metricOutDir);
    PairedHelp = readtable(MetricOutputs.metric_paired_mlp_help_csv,'TextType','string');
    PRBCCMOUtils.requireColumns(PairedHelp,{'problem','family','run','mlp_cmp_igd','no_mlp_cmp_igd','delta_igd_mlp', ...
        'mlp_igd_result','mlp_igd_win','mlp_igd_loss','mlp_igd_tie','mlp_igd_missing'});
    assert(~ismember('delta_igd_mlp_cmp_minus_no_mlp_cmp',PairedHelp.Properties.VariableNames), ...
        'test_PRBCCMO_t_metrics:NoReverseBenchmarkDeltaIGDName', ...
        'Benchmark metric analysis must not expose the reverse IGD delta name.');

    assertCurrentPopulationFallbackWhenNoNearB();
end

