function Columns = probabilityHistogramColumns(Prefix)
    Suffixes = {'00_10','10_20','20_30','30_40','40_50', ...
        '50_60','60_70','70_80','80_90','90_100'};
    Columns = strcat(Prefix,'_',Suffixes);
end

function requireNoForbiddenCoreFields(coreText)
    Forbidden = { ...
        'b_size','b_sector_coverage','b_mean_age', ...
        'b_mean_front_gap','b_p90_front_gap', ...
        'mlp_acc_before','mlp_train_acc','mlp_degraded', ...
        'inf_applicable_count','inf_prob_gain', ...
        'inf_carry_pool_size','inf_carry_applicable_count','inf_carry_selected', ...
        'inf_carry_pool_mean_prob','inf_carry_selected_mean_prob','inf_carry_prob_gain', ...
        'train_brier_after','train_logloss_after', ...
        'inf_supportdistobj_gain','inf_frontgap_gain','inf_selected_sector_coverage'};
    for i = 1 : numel(Forbidden)
        requireNotContains(coreText,Forbidden{i}, ...
            ['test_PRBCCMO_semantics:NoCore_',Forbidden{i}], ...
            ['core_metrics.csv must not expose old or non-core field ',Forbidden{i},'.']);
    end
end

function requireNoPairwiseRankLoss(coreText)
    Forbidden = {'pairwise','rank_lambda','rankloss','rank_loss','rankingloss','ranking_loss'};
    for i = 1 : numel(Forbidden)
        requireNotContains(coreText,Forbidden{i}, ...
            ['test_PRBCCMO_semantics:No_',Forbidden{i}], ...
            ['MLP code must not depend on pairwise/rank-loss text: ',Forbidden{i}]);
    end
end

function requireNoDeprecatedEntrypoints(rootDir)
    Deprecated = {'PRBCCMO1.m','PRBCCMO2.m','PRBCCMO3.m','PRBCCMO.txt'};
    for i = 1 : numel(Deprecated)
        assert(~isfile(fullfile(rootDir,Deprecated{i})), ...
            ['test_PRBCCMO_semantics:NoDeprecated_',erase(Deprecated{i},'.')], ...
            ['Deprecated duplicate entrypoint must be removed: ',Deprecated{i}]);
    end
end

function requireNoDeprecatedDataDirs(rootDir)
    Deprecated = {'PRBCCMO1','PRBCCMO2','PRBCCMO3'};
    for i = 1 : numel(Deprecated)
        assert(~isfolder(fullfile(rootDir,'Data',Deprecated{i})), ...
            ['test_PRBCCMO_semantics:NoDeprecatedData_',Deprecated{i}], ...
            ['Deprecated duplicate result folder must be removed: Data/',Deprecated{i}]);
    end
end

function requireContains(text,pattern,id,message)
    assert(contains(text,normalizeCode(pattern)),id,message);
end

function requireNotContains(text,pattern,id,message)
    assert(~contains(text,normalizeCode(pattern)),id,message);
end

function text = normalizeCode(text)
    text = lower(regexprep(text,'\s+',''));
end
