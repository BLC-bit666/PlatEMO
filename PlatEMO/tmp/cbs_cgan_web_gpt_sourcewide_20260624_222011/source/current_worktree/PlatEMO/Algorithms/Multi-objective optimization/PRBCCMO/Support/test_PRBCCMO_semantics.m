function test_PRBCCMO_semantics()
% Static guard for the PRBCCMO objective-boundary contract in fix.md.

    supportDir = fileparts(mfilename('fullpath'));
    algorithmDir = fileparts(supportDir);
    mainText = normalizeCode(fileread(fullfile(algorithmDir,'PRBCCMO.m')));
    traceText = normalizeCode(fileread(fullfile(algorithmDir,'PRBCCMO_t.m')));
    coreText = normalizeCode(fileread(fullfile(algorithmDir,'PRBCCMO_objective_core.m')));
    boundaryPlotText = normalizeCode(fileread(fullfile(supportDir,'plot_PRBCCMO_B_boundary_relation.m')));

    requireContains(mainText, ...
        '[Params{:}]=Algorithm.ParameterSet(64,200,1e-3,3,0.1,10,0);', ...
        'test_PRBCCMO_semantics:MainParameters', ...
        'PRBCCMO must default to the fix.md recoverability-first Adam/MLP settings.');
    requireContains(traceText, ...
        '[Params{:}]=Algorithm.ParameterSet(64,200,1e-3,3,0.1,10,0,0,1);', ...
        'test_PRBCCMO_semantics:TraceParameters', ...
        'PRBCCMO_t must default to the fix.md recoverability-first Adam/MLP settings.');
    requireContains(traceText,'Algorithm.metric.analysis_core_csv=Observer.core_file;', ...
        'test_PRBCCMO_semantics:AnalysisCoreCsv', ...
        'PRBCCMO_t must expose core_metrics.csv.');
    requireContains(boundaryPlotText,'''parameter'',{64,200,1e-3,3,0.1,10,0,1,1}', ...
        'test_PRBCCMO_semantics:BoundaryRelationParameters', ...
        'Boundary relation scripts must run PRBCCMO_t with saveB=1 and useMLP=1.');

    Fields = coreMetricColumns();
    for i = 1 : numel(Fields)
        requireContains(coreText,['''',Fields{i},''''], ...
            ['test_PRBCCMO_semantics:CoreField_',Fields{i}], ...
            ['core_metrics.csv is missing required field ',Fields{i},'.']);
    end

    requireContains(coreText,'MaxRefinementBufPerClass=round(0.5*Problem.N);', ...
        'test_PRBCCMO_semantics:PerClassRefinementBuffer', ...
        'Accepted and rejected refinements must use the per-class 0.5*N buffer from fix.md.');
    requireContains(coreText,'UpdateTrainingBufferT(TrainBuffer,ContractionDiag.accepted_refined,ContractionDiag.rejected_refined,Generation,MaxRefinementBufPerClass)', ...
        'test_PRBCCMO_semantics:RecoverabilityOutcomeBuffer', ...
        'The MLP buffer must label accepted refinements as recoverable and rejected refinements as unrecoverable.');
    requireContains(coreText,'BuildBoundaryDrivenDataset(B,BInfo,TrainBuffer,PopulationC,PopulationU,OffspringU,W,Problem)', ...
        'test_PRBCCMO_semantics:BoundaryDrivenDataset', ...
        'MLP training data must be rebuilt as the B-driven D_B union D_P dataset.');
    requireContains(coreText,'SelectBoundaryPairsForTraining(B,BInfo,Problem)', ...
        'test_PRBCCMO_semantics:ObjectiveOnlyPairSelection', ...
        'Training pairs must be selected by B objective-space quality.');
    requireContains(coreText,'CollectRefinementOutcomeSamples(', ...
        'test_PRBCCMO_semantics:RefinementOutcomeSamples', ...
        'Training data must be centered on accepted/rejected refinement outcomes.');
    requireContains(coreText,'CollectBoundaryEndpointAnchors(', ...
        'test_PRBCCMO_semantics:BoundaryEndpointAnchors', ...
        'B endpoints must be retained only as recovery-training anchors.');
    requireContains(coreText,'CollectCurrentPopulationAnchors(', ...
        'test_PRBCCMO_semantics:CurrentPopulationAnchors', ...
        'Current population samples must be retained only as late supplements.');
    requireContains(coreText,'TrainingDataNeedsSupplement(Dataset,Problem)', ...
        'test_PRBCCMO_semantics:SupplementOnlyWhenInsufficient', ...
        'B/current anchors must be added only when refinement outcomes are insufficient or one class is missing.');
    requireContains(coreText,'FinalizeBoundaryDrivenDataset(Dataset,Problem)', ...
        'test_PRBCCMO_semantics:BoundaryDrivenFinalize', ...
        'Training data must be deduplicated, class-balanced, and priority-truncated.');
    requireContains(coreText,'MaxTotal=max(96,min(192,round(1.6*Problem.N)));', ...
        'test_PRBCCMO_semantics:TrainingSizeCap', ...
        'Training dataset size must follow the fix.md 1.6*N capped window.');

    requireContains(coreText,'BRank=NormalizeLexRankAsc([SupportDist,ScalarObj]);', ...
        'test_PRBCCMO_semantics:BRankUtility', ...
        'B-side value must be a lexicographic rank of support distance then scalar objective.');
    requireContains(coreText,'tauProb=0.02;', ...
        'test_PRBCCMO_semantics:ProbabilityTieThreshold', ...
        'MLP-first I-I comparison must use the fix.md probability tie threshold.');
    requireContains(coreText,'ProbRank=NormalizeTieAwareRankDesc(Prob,tauProb);', ...
        'test_PRBCCMO_semantics:TieAwareProbRank', ...
        'MLP recoverability must use tau-aware descending ranks.');
    requireContains(coreText,'Utility=ProbRank;', ...
        'test_PRBCCMO_semantics:MLPFirstRankUtility', ...
        'I-I utility must be MLP-first; B may only break tied probability ranks.');
    requireContains(coreText,'NormalizeLexRankAsc(', ...
        'test_PRBCCMO_semantics:LexRankHelper', ...
        'The additive utility must provide a lexicographic rank helper.');
    requireContains(coreText,'NormalizeTieAwareRankDesc(', ...
        'test_PRBCCMO_semantics:TieAwareRankHelper', ...
        'The additive utility must provide a tie-aware probability rank helper.');
    requireContains(coreText,'RankInfeasibleByUtilityMeta(', ...
        'test_PRBCCMO_semantics:InfeasibleUtilityRank', ...
        'Infeasible survivor truncation must use the unified utility rank.');
    requireContains(coreText,'CompareInfeasibleByUtility(', ...
        'test_PRBCCMO_semantics:InfeasibleUtilityComparator', ...
        'Mating I-I tournament must share the same utility comparator.');

    requireContains(coreText,'prob_accepted_refinement', ...
        'test_PRBCCMO_semantics:AcceptedRefinementProbabilityMetric', ...
        'Diagnostics must expose accepted-refinement recoverability probability.');
    requireContains(coreText,'prob_rejected_refinement', ...
        'test_PRBCCMO_semantics:RejectedRefinementProbabilityMetric', ...
        'Diagnostics must expose rejected-refinement recoverability probability.');
    requireContains(coreText,'EvaluateBoundaryMLPProbabilityGroups(', ...
        'test_PRBCCMO_semantics:ProbabilityGroupDiagnostics', ...
        'MLP diagnostics must include B-core/current-pop probability group means.');
    requireContains(coreText,'InitMatingDiag()', ...
        'test_PRBCCMO_semantics:MatingDiag', ...
        'Mating selection must record two-infeasible MLP tournament diagnostics.');
    requireContains(coreText,'mlp_primary_resolution_rate', ...
        'test_PRBCCMO_semantics:MLPPrimaryResolutionMetric', ...
        'Diagnostics must expose how often MLP probability ranks resolve I-I comparisons.');
    requireContains(coreText,'b_fallback_rate', ...
        'test_PRBCCMO_semantics:BFallbackMetric', ...
        'Diagnostics must expose how often tied MLP ranks fall back to B.');

    requireContains(coreText,'TrainBoundaryMLPWithDeepLearningToolbox(', ...
        'test_PRBCCMO_semantics:DeepLearningToolboxTrainer', ...
        'MLP training must use MATLAB Deep Learning Toolbox, not a hand-coded optimizer.');
    requireContains(coreText,'trainingOptions("adam"', ...
        'test_PRBCCMO_semantics:AdamTrainingOptions', ...
        'MLP training must use trainingOptions("adam").');
    requireContains(coreText,'"binary-crossentropy"', ...
        'test_PRBCCMO_semantics:BinaryCrossEntropy', ...
        'MLP training must use binary cross-entropy.');
    requireContains(coreText,'trainnet(', ...
        'test_PRBCCMO_semantics:Trainnet', ...
        'MLP training must use trainnet.');
    requireContains(coreText,'minibatchpredict(Model.Net,Xn,MiniBatchSize=1024,', ...
        'test_PRBCCMO_semantics:MinibatchPredict', ...
        'MLP inference must use Deep Learning Toolbox minibatchpredict.');

    requireNotContains(coreText,'SelectBoundaryBandTrainingPoints', ...
        'test_PRBCCMO_semantics:NoBoundaryBandTraining', ...
        'Boundary-band samples must not feed MLP training.');
    requireNotContains(coreText,'AppendPairLocalChainRows', ...
        'test_PRBCCMO_semantics:NoPairLocalChainRows', ...
        'Pair-local chain rows must be removed from MLP training.');
    requireNotContains(coreText,'AppendEasyAnchorRows', ...
        'test_PRBCCMO_semantics:NoEasyAnchors', ...
        'Easy anchors must be removed from MLP training.');
    requireNotContains(coreText,'BalanceBoundaryBCEDatasetByPair', ...
        'test_PRBCCMO_semantics:NoPairBalancedOldTraining', ...
        'Old pair-balanced/easy training must be removed.');
    requireNotContains(coreText,'DecisionDistanceNormalized(double(B(2*Active-1).decs)', ...
        'test_PRBCCMO_semantics:NoDecisionDistanceTrainingFilter', ...
        'Training pair selection must not filter B pairs by decision distance.');
    requireNotContains(coreText,'Scarcity=', ...
        'test_PRBCCMO_semantics:NoScarcityUtility', ...
        'I-I utility must not multiply by sector scarcity.');
    requireNotContains(coreText,'Utility=BRank+ProbRank;', ...
        'test_PRBCCMO_semantics:NoAdditiveBRankProbRankUtility', ...
        'I-I utility must not keep B and MLP as parallel additive judges.');
    requireNotContains(coreText,'Prob.*', ...
        'test_PRBCCMO_semantics:NoMultiplicativeRawProbUtility', ...
        'I-I utility must not use raw multiplicative probability.');
    requireNotContains(coreText,'Meta.sectorCover', ...
        'test_PRBCCMO_semantics:NoSectorCoverMeta', ...
        'Boundary meta no longer needs sector-cover scarcity.');
    requireNotContains(coreText,'train_src_boundary_band', ...
        'test_PRBCCMO_semantics:NoBoundaryBandMetric', ...
        'Core metrics must not expose boundary-band training fields.');
    requireNotContains(coreText,'train_easy_feasible', ...
        'test_PRBCCMO_semantics:NoEasyFeasibleMetric', ...
        'Core metrics must not expose easy-feasible training fields.');
    requireNotContains(coreText,'train_easy_infeasible', ...
        'test_PRBCCMO_semantics:NoEasyInfeasibleMetric', ...
        'Core metrics must not expose easy-infeasible training fields.');
    requireNotContains(coreText,'mlp_gap_feasible', ...
        'test_PRBCCMO_semantics:NoOldMLPGapFeasible', ...
        'Old easy/boundary MLP gap metrics must be removed.');
    requireNotContains(coreText,'mlp_gap_infeasible', ...
        'test_PRBCCMO_semantics:NoOldMLPGapInfeasible', ...
        'Old easy/boundary MLP gap metrics must be removed.');

    requireNotContains(coreText,'FrontGap', ...
        'test_PRBCCMO_semantics:NoFrontGapRuntime', ...
        'FrontGap must not participate in runtime code.');
    requireNotContains(coreText,'RunBoundaryMLPTraining', ...
        'test_PRBCCMO_semantics:NoHandCodedTrainer', ...
        'Hand-coded MLP training must be removed.');
    requireNotContains(coreText,'tanh(', ...
        'test_PRBCCMO_semantics:NoTanhManualMLP', ...
        'The MLP must not use the old hand-coded tanh network.');
    requireNoForbiddenCoreFields(coreText);
    requireNoPairwiseRankLoss(coreText);
    requireNoDeprecatedEntrypoints(algorithmDir);
    requireNoDeprecatedDataDirs(algorithmDir);
end

