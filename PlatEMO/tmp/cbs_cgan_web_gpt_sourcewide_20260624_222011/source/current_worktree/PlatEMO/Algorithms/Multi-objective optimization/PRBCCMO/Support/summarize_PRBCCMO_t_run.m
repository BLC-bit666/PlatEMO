function Summary = summarize_PRBCCMO_t_run(runFolder)
% Summarize one PRBCCMO_t run from the minimal core_metrics.csv contract.

    if nargin < 1 || isempty(runFolder)
        error('summarize_PRBCCMO_t_run:MissingRunFolder','runFolder is required.');
    end

    runFolder = char(string(runFolder));
    metaFile = fullfile(runFolder,'run_meta.csv');
    coreFile = fullfile(runFolder,'core_metrics.csv');
    assert(isfolder(runFolder) && isfile(metaFile) && isfile(coreFile), ...
        'summarize_PRBCCMO_t_run:MissingCsv', ...
        'Run folder must contain run_meta.csv and core_metrics.csv: %s', runFolder);

    Meta = readtable(metaFile,'TextType','string');
    Core = PRBCCMOUtils.numericizeTable(readtable(coreFile,'TextType','string'));
    PRBCCMOUtils.requireColumns(Core,coreMetricColumns(),coreFile);

    Summary = emptySummary(Meta,runFolder,metaFile,coreFile);
    if isempty(Core)
        return;
    end

    Last = Core(end,:);
    Summary.generation_count = height(Core);
    Summary.final_generation = PRBCCMOUtils.scalarValue(Last,'generation');
    Summary.final_fe = PRBCCMOUtils.scalarValue(Last,'fe');
    Summary.final_fe_ratio = PRBCCMOUtils.scalarValue(Last,'fe_ratio');

    Summary.final_b_pair_count = PRBCCMOUtils.scalarValue(Last,'b_pair_count');
    Summary.final_b_mean_pair_gap = PRBCCMOUtils.scalarValue(Last,'b_mean_pair_gap');
    Summary.mean_b_mean_pair_gap = PRBCCMOUtils.meanFinite(Core.b_mean_pair_gap);
    Summary.p90_b_mean_pair_gap = PRBCCMOUtils.percentileFinite(Core.b_mean_pair_gap,90);
    Summary.final_b_p90_pair_gap = PRBCCMOUtils.scalarValue(Last,'b_p90_pair_gap');
    Summary.final_b_mean_mid_scalar = PRBCCMOUtils.scalarValue(Last,'b_mean_mid_scalar');
    Summary.mean_b_mean_mid_scalar = PRBCCMOUtils.meanFinite(Core.b_mean_mid_scalar);
    Summary.final_b_mean_infeasible_boundary_dist = PRBCCMOUtils.scalarValue(Last,'b_mean_infeasible_boundary_dist');
    Summary.mean_b_mean_infeasible_boundary_dist = PRBCCMOUtils.meanFinite(Core.b_mean_infeasible_boundary_dist);
    Summary.final_b_p90_infeasible_boundary_dist = PRBCCMOUtils.scalarValue(Last,'b_p90_infeasible_boundary_dist');
    Summary.final_b_max_infeasible_boundary_dist = PRBCCMOUtils.scalarValue(Last,'b_max_infeasible_boundary_dist');
    Summary.final_b_far_infeasible_boundary_ratio = PRBCCMOUtils.scalarValue(Last,'b_far_infeasible_boundary_ratio');
    Summary.mean_b_far_infeasible_boundary_ratio = PRBCCMOUtils.meanFinite(Core.b_far_infeasible_boundary_ratio);
    Summary.final_b_inf_unconstrained_src_ratio = PRBCCMOUtils.scalarValue(Last,'b_inf_unconstrained_src_ratio');
    Summary.mean_b_inf_unconstrained_src_ratio = PRBCCMOUtils.meanFinite(Core.b_inf_unconstrained_src_ratio);
    Summary.final_b_overlap_popc_ratio = PRBCCMOUtils.scalarValue(Last,'b_overlap_popc_ratio');
    Summary.mean_b_overlap_popc_ratio = PRBCCMOUtils.meanFinite(Core.b_overlap_popc_ratio);
    Summary.final_b_overlap_popu_ratio = PRBCCMOUtils.scalarValue(Last,'b_overlap_popu_ratio');
    Summary.mean_b_overlap_popu_ratio = PRBCCMOUtils.meanFinite(Core.b_overlap_popu_ratio);
    Summary.final_b_inf_src_popu = PRBCCMOUtils.scalarValue(Last,'b_inf_src_popu');
    Summary.final_b_inf_src_offu = PRBCCMOUtils.scalarValue(Last,'b_inf_src_offu');
    Summary.final_b_inf_src_refinement = PRBCCMOUtils.scalarValue(Last,'b_inf_src_refinement');
    Summary.final_b_active_sector_ratio = PRBCCMOUtils.scalarValue(Last,'b_active_sector_ratio');
    Summary.mean_b_active_sector_ratio = PRBCCMOUtils.meanFinite(Core.b_active_sector_ratio);
    Summary.mean_b_changed_pair_count = PRBCCMOUtils.meanFinite(Core.b_changed_pair_count);
    Summary.mean_b_changed_pair_ratio = PRBCCMOUtils.meanFinite(Core.b_changed_pair_ratio);
    Summary.mean_b_added_pair_count = PRBCCMOUtils.meanFinite(Core.b_added_pair_count);
    Summary.mean_b_replaced_pair_count = PRBCCMOUtils.meanFinite(Core.b_replaced_pair_count);
    Summary.mean_b_dropped_pair_count = PRBCCMOUtils.meanFinite(Core.b_dropped_pair_count);
    Summary.mean_b_contracted_pair_count = PRBCCMOUtils.meanFinite(Core.b_contracted_pair_count);
    Summary.mean_b_global_change_pair_ratio = PRBCCMOUtils.meanFinite(Core.b_global_change_pair_ratio);
    Summary.mean_b_contraction_pair_ratio = PRBCCMOUtils.meanFinite(Core.b_contraction_pair_ratio);

    Summary.mlp_due_events = sum(double(Core.mlp_due) > 0);
    Summary.mlp_can_train_events = sum(double(Core.mlp_can_train) > 0);
    Summary.mlp_trained_events = sum(double(Core.mlp_trained) > 0);
    Summary.final_train_size = PRBCCMOUtils.scalarValue(Last,'train_size');
    Summary.mean_train_size = PRBCCMOUtils.meanFinite(Core.train_size);
    Summary.final_train_pos = PRBCCMOUtils.scalarValue(Last,'train_pos');
    Summary.final_train_neg = PRBCCMOUtils.scalarValue(Last,'train_neg');
    Summary.final_train_b_core_count = PRBCCMOUtils.scalarValue(Last,'train_b_core_count');
    Summary.final_train_refinement_count = PRBCCMOUtils.scalarValue(Last,'train_refinement_count');
    Summary.final_train_current_pop_count = PRBCCMOUtils.scalarValue(Last,'train_current_pop_count');
    Summary.final_train_refinement_pos_count = PRBCCMOUtils.scalarValue(Last,'train_refinement_pos_count');
    Summary.final_train_refinement_neg_count = PRBCCMOUtils.scalarValue(Last,'train_refinement_neg_count');
    Summary.mean_train_refinement_ratio = PRBCCMOUtils.meanFinite(Core.train_refinement_ratio);
    Summary.mean_mlp_prob_bcore_feasible = PRBCCMOUtils.meanFinite(Core.mlp_prob_bcore_feasible);
    Summary.mean_mlp_prob_bcore_infeasible = PRBCCMOUtils.meanFinite(Core.mlp_prob_bcore_infeasible);
    Summary.mean_mlp_prob_curr_feasible = PRBCCMOUtils.meanFinite(Core.mlp_prob_curr_feasible);
    Summary.mean_mlp_prob_curr_infeasible = PRBCCMOUtils.meanFinite(Core.mlp_prob_curr_infeasible);
    Summary.mean_prob_accepted_refinement = PRBCCMOUtils.meanFinite(Core.prob_accepted_refinement);
    Summary.mean_prob_rejected_refinement = PRBCCMOUtils.meanFinite(Core.prob_rejected_refinement);
    Summary.mean_mlp_prob_bcore_gap = PRBCCMOUtils.meanFinite(Core.mlp_prob_bcore_gap);
    Summary.mean_mlp_prob_current_gap = PRBCCMOUtils.meanFinite(Core.mlp_prob_current_gap);
    Summary.mean_prob_refinement_gap = PRBCCMOUtils.meanFinite(Core.prob_refinement_gap);
    Summary.mlp_two_inf_tournament_total = PRBCCMOUtils.sumFinite(Core.mlp_two_inf_tournament_total);
    Summary.mean_mlp_two_inf_tournament_total = PRBCCMOUtils.meanFinite(Core.mlp_two_inf_tournament_total);
    Summary.mlp_effective_win_total = PRBCCMOUtils.sumFinite(Core.mlp_effective_win_total);
    Summary.mean_mlp_effective_win_total = PRBCCMOUtils.meanFinite(Core.mlp_effective_win_total);
    Summary.mlp_primary_resolution_total = PRBCCMOUtils.sumFinite(Core.mlp_primary_resolution_total);
    Summary.mean_mlp_primary_resolution_total = PRBCCMOUtils.meanFinite(Core.mlp_primary_resolution_total);
    Summary.b_fallback_total = PRBCCMOUtils.sumFinite(Core.b_fallback_total);
    Summary.mean_b_fallback_total = PRBCCMOUtils.meanFinite(Core.b_fallback_total);
    Summary.mean_mlp_two_inf_tournament_rate = PRBCCMOUtils.meanFinite(Core.mlp_two_inf_tournament_rate);
    Summary.mean_mlp_effective_win_rate = PRBCCMOUtils.meanFinite(Core.mlp_effective_win_rate);
    Summary.mean_mlp_primary_resolution_rate = PRBCCMOUtils.meanFinite(Core.mlp_primary_resolution_rate);
    Summary.mean_b_fallback_rate = PRBCCMOUtils.meanFinite(Core.b_fallback_rate);

    MLPInfActive = double(Core.inf_mlp_used) > 0;
    Summary.mlp_inf_selection_generations = sum(MLPInfActive);
    Summary.mlp_inf_selection_rate = Summary.mlp_inf_selection_generations / max(height(Core),1);
    Summary.inf_feasible_deficit_total = PRBCCMOUtils.sumFinite(Core.inf_feasible_deficit);
    Summary.mean_inf_feasible_deficit = PRBCCMOUtils.meanFinite(Core.inf_feasible_deficit);
    Summary.mean_inf_feasible_deficit_when_mlp_active = PRBCCMOUtils.meanFinite(Core.inf_feasible_deficit(MLPInfActive));
    Summary.mean_inf_selected_when_mlp_active = PRBCCMOUtils.meanFinite(Core.inf_selected(MLPInfActive));
    Summary.inf_pool_generations = sum(double(Core.inf_pool_size) > 0);
    Summary.inf_ranked_total = PRBCCMOUtils.sumFinite(Core.inf_ranked_count);
    Summary.mean_inf_ranked_count = PRBCCMOUtils.meanFinite(Core.inf_ranked_count);
    Summary.inf_selection_generations = sum(double(Core.inf_selected) > 0);
    Summary.inf_selected_total = PRBCCMOUtils.sumFinite(Core.inf_selected);
    Summary.mean_inf_pool_mean_utility = PRBCCMOUtils.meanFinite(Core.inf_pool_mean_utility);
    Summary.mean_inf_selected_mean_utility = PRBCCMOUtils.meanFinite(Core.inf_selected_mean_utility);
    Summary.mean_inf_utility_gain = PRBCCMOUtils.meanFinite(Core.inf_utility_gain);
    Summary.pos_rate_inf_utility_gain = PRBCCMOUtils.positiveRate(Core.inf_utility_gain);
    Summary.mean_inf_pool_mean_prob = PRBCCMOUtils.meanFinite(Core.inf_pool_mean_prob);
    Summary.mean_inf_selected_mean_prob = PRBCCMOUtils.meanFinite(Core.inf_selected_mean_prob);
    Summary.mean_inf_selected_prob_gain = PRBCCMOUtils.meanFinite(Core.inf_selected_prob_gain);
end

