function test_CBS_CGAN_sample_info()
%TEST_CBS_CGAN_SAMPLE_INFO Verify query mapping for generated decisions.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    rng(11,'twister');
    testSampleInfoMapsRepeatedQueryConditions();
    testSampleInfoAcceptsFixedLatentSamples();
    fprintf('CBS-CGAN sample info regression passed.\n');
end

function testSampleInfoMapsRepeatedQueryConditions()
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,4,1) + rand(4,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,4,1);
    TrainC = [0.10 0.90;0.30 0.70;0.60 0.40;0.90 0.10];
    QueryC = [0.25 0.75;0.75 0.25];
    Options = struct( ...
        'zDim',2, ...
        'iter',1, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',2e-4, ...
        'dPretrainIter',0, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'sigma',0.05);

    GAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem,Options);
    [RawDec,Info] = BoundaryCGAN_CBS('samplebycondition',GAN, ...
        QueryC,3,Options);

    assert(size(RawDec,1) == 6, ...
        'Expected three generated decisions per query condition.');
    assert(isfield(Info,'query_index'), ...
        'samplebycondition must return query_index for diagnostics.');
    assert(isequal(Info.query_index(:),[1;1;1;2;2;2]), ...
        'query_index must map generated rows back to QueryC rows.');
    assert(isfield(Info,'condition') && isequal(size(Info.condition),[6 2]), ...
        'samplebycondition must return the repeated generation conditions.');

end

function testSampleInfoAcceptsFixedLatentSamples()
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,4,1) + rand(4,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,4,1);
    TrainC = [0.10 0.90;0.30 0.70;0.60 0.40;0.90 0.10];
    QueryC = [0.25 0.75;0.75 0.25];
    Options = struct( ...
        'zDim',2, ...
        'iter',1, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',2e-4, ...
        'dPretrainIter',0, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'sigma',0.05);

    GAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem,Options);
    FixedOptions = Options;
    FixedOptions.sampleZ = [0 0;0.5 -0.5;0 0;0.5 -0.5];

    rng(101,'twister');
    [DecA,InfoA] = BoundaryCGAN_CBS('samplebycondition',GAN, ...
        QueryC,2,FixedOptions);
    rng(202,'twister');
    [DecB,InfoB] = BoundaryCGAN_CBS('samplebycondition',GAN, ...
        QueryC,2,FixedOptions);

    assert(isequal(size(DecA),size(DecB)) && max(abs(DecA(:)-DecB(:))) < 1e-12, ...
        'Fixed latent samples must make samplebycondition deterministic.');
    assert(isfield(InfoA,'z') && isequal(size(InfoA.z),[4 2]), ...
        'samplebycondition must expose the latent rows used for visual diagnostics.');
    assert(max(abs(InfoA.z(:)-InfoB.z(:))) < 1e-12, ...
        'Returned latent samples must match across deterministic runs.');
end
