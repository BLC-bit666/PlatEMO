function test_CBS_region_gan_branches()
%TEST_CBS_REGION_GAN_BRANCHES Verify region BCE/WGAN comparison branches.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    assert(exist('CBS_RegionCGAN','class') == 8, ...
        'Region BCE-CGAN control algorithm must exist.');
    assert(exist('CBS_RegionWGAN_GP','class') == 8, ...
        'Region WGAN-GP comparison algorithm must exist.');

    testRegionWGANMainlineDefaults();
    testBalancedQueryAllocation();
    testBoundaryCGANRecordsTrainingHistory();
    testBoundaryWGANTrainsAndSamples();
    fprintf('CBS region GAN branch regressions passed.\n');
end

function testRegionWGANMainlineDefaults()
    Defaults = CBS_RegionWGAN_GP.mainlineDefaults();
    assert(Defaults.ganKind == "wgan-gp", ...
        'RegionGAN mainline must use the WGAN-GP branch.');
    assert(Defaults.queryMode == "random_all_w", ...
        'RegionGAN mainline must use fully random QueryC over all refs.');
    assert(Defaults.prevBMemMode == "prev1_fair_union", ...
        'RegionGAN mainline must retain previous BMem as fair competitors.');
    assert(Defaults.ganMiniBatch == 32, ...
        'RegionGAN mainline must keep ganMiniBatch=32.');
    assert(Defaults.minGANTrainCount == 32, ...
        'RegionGAN mainline must keep minGANTrainCount=32.');
    assert(Defaults.nGen == 30, ...
        'RegionGAN mainline must generate at most 30 GAN offspring per refresh.');
    assert(Defaults.maxAnchorsPerRef == 5, ...
        'RegionGAN mainline must keep the ref-cap quality gate at five anchors.');
    assert(Defaults.gpLambda == 10 && Defaults.nCritic == 5, ...
        'RegionGAN mainline must retain the validated WGAN-GP critic settings.');
end

function testBalancedQueryAllocation()
    rng(219,'twister');
    QueryC = [(1:20)' zeros(20,1)];
    [SampleC,Counts] = RunRegionGAN_RC('allocatequery',QueryC,2,30);
    assert(size(SampleC,1) == 30, ...
        'Allocated query rows must respect the nGen hard cap.');
    assert(numel(Counts) == size(QueryC,1), ...
        'Allocation counts must map back to every original QueryC row.');
    assert(all(Counts >= 1) && all(Counts <= 2), ...
        'With nGen=30, K=20, qpc=2, every region gets 1 or 2 samples.');
    assert(sum(Counts) == 30, ...
        'Allocation counts must sum to the sampled QueryC row count.');

    [SmallSampleC,SmallCounts] = RunRegionGAN_RC('allocatequery',QueryC(1:2,:),2,30);
    assert(size(SmallSampleC,1) == 4 && all(SmallCounts == 2), ...
        'Small region counts should use qpc as a per-region cap, not fill nGen.');
end

function testBoundaryWGANTrainsAndSamples()
    rng(211,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,8,1) + rand(8,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,8,1);
    TrainC = rand(8,2);
    Options = struct( ...
        'zDim',6, ...
        'iter',1, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',1e-4, ...
        'nCritic',1, ...
        'gpLambda',10, ...
        'generatorHidden',[32 32], ...
        'criticHidden',[32 32], ...
        'sigma',1.0);

    GAN = BoundaryWGAN_RC('train',[],TrainX,TrainC,Problem,Options);
    assert(isfield(GAN,'netG') && isfield(GAN,'netC'), ...
        'BoundaryWGAN_RC must return generator and critic networks.');
    assert(layerOutputSize(GAN.netG,'g_fc1') == 32 && ...
            layerOutputSize(GAN.netG,'g_fc2') == 32, ...
        'WGAN generator must follow the small [32 32] hidden layers.');
    assert(layerOutputSize(GAN.netC,'c_fc1') == 32 && ...
            layerOutputSize(GAN.netC,'c_fc2') == 32, ...
        'WGAN critic must follow the small [32 32] hidden layers.');
    assert(~hasLayer(GAN.netC,'c_sigmoid'), ...
        'WGAN critic output must stay linear, not sigmoid/BCE.');

    QueryC = TrainC(1:2,:);
    [Dec,Info] = BoundaryWGAN_RC('samplebycondition',GAN,QueryC,3,Options);
    assert(isequal(size(Dec),[6 Problem.D]), ...
        'WGAN sampling must return queryPerCondition decisions per query.');
    assert(isequal(size(Info.z),[6 Options.zDim]), ...
        'WGAN sample info must expose the latent z used for each sample.');
end

function testBoundaryCGANRecordsTrainingHistory()
    rng(217,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,8,1) + rand(8,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,8,1);
    TrainC = rand(8,2);
    Options = struct( ...
        'zDim',6, ...
        'iter',2, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',1e-4, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'advWeight',1.0, ...
        'trainMode',"iter", ...
        'realLabel',0.9, ...
        'generatorHidden',[32 32], ...
        'discriminatorHidden',[32 32], ...
        'sigma',1.0);

    GAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem,Options);
    assert(isfield(GAN,'train_history') && numel(GAN.train_history) == 3, ...
        'CGAN training must record initial and per-iter diagnostics.');
    required = {'step','loss_d','loss_g','d_real_acc','d_fake_acc', ...
        'd_bal_acc','g_fool_rate','score_real_mean','score_fake_mean', ...
        'score_random_mean'};
    for i = 1 : numel(required)
        assert(isfield(GAN.train_history,required{i}), ...
            'CGAN training history missing field: %s.',required{i});
    end
    assert(all([GAN.train_history.d_real_acc] >= 0 & ...
            [GAN.train_history.d_real_acc] <= 1), ...
        'D real accuracy must stay in [0,1].');
    assert(all([GAN.train_history.d_fake_acc] >= 0 & ...
            [GAN.train_history.d_fake_acc] <= 1), ...
        'D fake accuracy must stay in [0,1].');
    assert(all([GAN.train_history.g_fool_rate] >= 0 & ...
            [GAN.train_history.g_fool_rate] <= 1), ...
        'G fool rate must stay in [0,1].');
    assert(isfinite(GAN.last_discriminator_loss) && ...
            isfinite(GAN.last_generator_loss), ...
        'CGAN must expose final D/G losses as scalar fields.');
    assert(GAN.last_g_fool_rate == GAN.train_history(end).g_fool_rate, ...
        'Final G fool rate must mirror the last training-history row.');
end

function tf = hasLayer(net,name)
    tf = any(string({net.Layers.Name}) == string(name));
end

function value = layerOutputSize(net,name)
    idx = find(string({net.Layers.Name}) == string(name),1,'first');
    assert(~isempty(idx),'Missing layer: %s.',name);
    value = double(net.Layers(idx).OutputSize);
end
