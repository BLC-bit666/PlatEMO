function test_CBS_region_random_query_boundary_runner()
%TEST_CBS_REGION_RANDOM_QUERY_BOUNDARY_RUNNER Verify random-QueryC boundary plots.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    outDir = fullfile(tempdir,sprintf('cbs_region_random_query_%s', ...
        char(java.util.UUID.randomUUID)));
    Options = struct( ...
        'queryMode',"random_all_w", ...
        'plotRun',1, ...
        'stageTargets',[220 420], ...
        'algorithmParams', ...
            {{1,1,3,4,1,8,1e-4,1e-4,2,2,2,2,1,0,4,4,1,5,2}});

    [Summary,EventSummary] = run_CBS_RegionCGAN_training_diagnostics( ...
        outDir,1,"DASCMOP1_BC",20,[],600,1,Options);

    assert(height(Summary) == 1 && Summary.status == "ok", ...
        'Random-query smoke run must complete.');
    assert(ismember("query_mode",string(EventSummary.Properties.VariableNames)), ...
        'Event summary must export the active QueryC mode.');
    generated = EventSummary.raw_generated_count > 0;
    assert(any(generated), ...
        'Smoke run must produce at least one CGAN generation event.');
    assert(all(string(EventSummary.query_mode(generated)) == "random_all_w"), ...
        'Generated events must use random-all-W query conditions.');
    assert(all(EventSummary.query_sample_count(generated) == 3), ...
        'Random-all-W mode must draw nGen query conditions every event.');
    assert(all(EventSummary.all_w_query_generated_count(generated) == 0), ...
        'conditionDiagGap=0 must pause the all-W 100-sample diagnostic.');
    assert(ismember("gap_ratio50",string(EventSummary.Properties.VariableNames)), ...
        'Event summary must export generated boundary-closeness metrics.');

    manifestFile = fullfile(outDir,'figure_manifest.csv');
    assert(isfile(manifestFile), ...
        'Runner must write a figure manifest for RegionCGAN plots.');
    Figures = readtable(manifestFile,'TextType','string');
    assert(height(Figures) == numel(Options.stageTargets), ...
        'plotRun must render one simplified boundary plot per target FE.');
    assert(all(arrayfun(@(f)isfile(f),string(Figures.figure_file))), ...
        'Every figure listed in the manifest must exist on disk.');

    fprintf('CBS RegionCGAN random-query boundary runner smoke passed: %s\n', ...
        outDir);
end
