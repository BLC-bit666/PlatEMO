function test_CBS_RegionCGAN_training_diagnostics_runner()
%TEST_CBS_REGIONCGAN_TRAINING_DIAGNOSTICS_RUNNER Smoke-test the runner output.

    repoRoot = fileparts(fileparts(fileparts(fileparts(fileparts( ...
        mfilename('fullpath'))))));
    addpath(genpath(repoRoot));

    outDir = fullfile(repoRoot,'Data','CBS_RegionCGAN', ...
        ['test_training_diagnostics_', ...
        char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
    Options = struct('algorithmParams', ...
        {{1,1,2,4,1,4,1e-4,1e-4,2,2,2,2,1,10,8,8,2,5,2}});

    Summary = run_CBS_RegionCGAN_training_diagnostics( ...
        outDir,1,"DASCMOP1_BC",10,[],80,1,Options);

    assert(height(Summary) == 1 && Summary.status == "ok", ...
        'Runner must complete a one-task smoke experiment.');
    assert(isfile(fullfile(outDir,'run_summary.csv')), ...
        'Runner must write the aggregate run summary.');
    assert(isfile(fullfile(outDir,'event_summary_all.csv')), ...
        'Runner must write aggregate event diagnostics.');
    assert(isfile(fullfile(outDir,'train_history_all.csv')), ...
        'Runner must write aggregate inner training diagnostics.');
    assert(Summary.train_row_count > 0, ...
        'Smoke run must record at least one CGAN training-history row.');
    TrainHistory = readtable(fullfile(outDir,'train_history_all.csv'), ...
        'Delimiter',',','ReadVariableNames',true,'TextType','string');
    assert(any(string(TrainHistory.Properties.VariableNames) == ...
            "score_random_mean"), ...
        'Runner must export the random-negative diagnostic score.');
    EventSummary = readtable(fullfile(outDir,'event_summary_all.csv'), ...
        'Delimiter',',','ReadVariableNames',true,'TextType','string');
    assert(any(string(EventSummary.Properties.VariableNames) == ...
            "query_exact_ref_match_rate"), ...
        'Runner must export condition-control diagnostic fields.');

    fprintf('CBS_RegionCGAN training diagnostics runner smoke test passed.\n');
end
