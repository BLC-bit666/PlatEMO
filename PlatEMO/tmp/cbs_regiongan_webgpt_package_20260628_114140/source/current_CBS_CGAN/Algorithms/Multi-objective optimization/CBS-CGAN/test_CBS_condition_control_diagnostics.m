function test_CBS_condition_control_diagnostics()
%TEST_CBS_CONDITION_CONTROL_DIAGNOSTICS Verify region-condition probes.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    rng(313,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,8,1) + rand(8,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,8,1);
    TrainC = [0.10 0.90;0.20 0.80;0.50 0.50;0.80 0.20; ...
        0.90 0.10;0.35 0.65;0.65 0.35;0.45 0.55];
    W = [0.00 1.00;0.25 0.75;0.50 0.50;0.75 0.25;1.00 0.00];
    QueryRefs = [2;4];
    QueryC = W(QueryRefs,:);
    Options = struct( ...
        'zDim',3, ...
        'iter',1, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',1e-4, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'advWeight',1.0, ...
        'trainMode',"iter", ...
        'realLabel',0.9, ...
        'generatorHidden',[16 16], ...
        'discriminatorHidden',[16 16], ...
        'trainZMode',"random", ...
        'sampleZMode',"random", ...
        'sigma',1.0);

    GAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem,Options);
    SampleRefs = QueryRefs;
    [RawDec,~] = BoundaryCGAN_CBS('samplebycondition',GAN,QueryC,1,Options);
    [Yb,~] = EvaluateDecisions_CBS(Problem,TrainX);
    BMem = struct('x_b',TrainX,'y_b',Yb,'ref',QueryRefs([1 2 1 2 1 2 1 2]));
    DiagOptions = struct('maxConditions',2,'zSamples',2, ...
        'neighborRadius',1,'allWZPerRef',2);
    originalFE = Problem.FE;

    Diag = ConditionControlDiagnostics_RC("cgan",GAN,QueryC,QueryRefs, ...
        QueryC,SampleRefs,RawDec,BMem,W,Problem,Options,DiagOptions);

    required = {'condition_diag_condition_count', ...
        'condition_diag_z_count', ...
        'same_z_diff_c_dec_median', ...
        'same_c_diff_z_dec_median', ...
        'condition_effect_ratio_dec', ...
        'query_exact_ref_match_rate', ...
        'query_neighbor_ref_match_rate', ...
        'query_target_ref_rank_median', ...
        'all_w_query_generated_count', ...
        'all_w_pm2_ref_match_rate', ...
        'all_w_seen_pm2_ref_match_rate', ...
        'all_w_unseen_pm2_ref_match_rate', ...
        'all_w_shuffled_pm2_ref_match_rate', ...
        'all_w_target_ref_rank_median', ...
        'all_w_feasible_rate_probe'};
    for i = 1 : numel(required)
        assert(isfield(Diag,required{i}), ...
            'Condition diagnostic missing field: %s.',required{i});
        assert(isfinite(Diag.(required{i})), ...
            'Condition diagnostic field must be finite: %s.',required{i});
    end
    assert(Diag.condition_diag_condition_count == 2, ...
        'Diagnostic must use the requested number of query conditions.');
    assert(Diag.condition_diag_z_count == 2, ...
        'Diagnostic must use the requested number of z samples.');
    assert(Problem.FE == originalFE, ...
        'Condition diagnostics must not consume active FE.');
    assert(Diag.query_generated_count == size(RawDec,1), ...
        'Region-match diagnostics must describe the actual generated rows.');
    assert(Diag.all_w_condition_count == size(W,1), ...
        'All-W diagnostics must probe every reference condition.');
    assert(Diag.all_w_z_per_ref == 2, ...
        'All-W diagnostics must use the requested number of z samples per ref.');
    assert(Diag.all_w_query_generated_count == size(W,1)*2, ...
        'All-W diagnostics must generate refs times z-per-ref rows.');
    assert(Diag.all_w_seen_count > 0 && Diag.all_w_unseen_count > 0, ...
        'All-W diagnostics must split seen and unseen reference rows.');

    fprintf('CBS condition-control diagnostics regression passed.\n');
end
