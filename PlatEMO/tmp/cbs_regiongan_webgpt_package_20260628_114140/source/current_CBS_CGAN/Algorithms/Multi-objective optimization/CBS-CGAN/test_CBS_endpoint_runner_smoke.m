function test_CBS_endpoint_runner_smoke()
%TEST_CBS_ENDPOINT_RUNNER_SMOKE Verify retained endpoint comparison runner.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    runnerFile = fullfile(repoRoot,'Algorithms', ...
        'Multi-objective optimization','CBS-CGAN','Support', ...
        'run_CBS_CGAN_endpoint_epoch50_compare_sheets.m');
    assert(isfile(runnerFile), ...
        'Endpoint compare runner file must exist.');

    txt = fileread(runnerFile);
    compact = regexprep(txt,'\s+','');
    compact = erase(compact,'...');
    assert(contains(compact,'"B_ref_y_adv"') || ...
            contains(compact,'''B_ref_y_adv'''), ...
        'Endpoint runner must include the retained B_ref_y_adv mainline.');
    assert(contains(compact,'"B_ref_y_adv_epoch50_endpoint"') || ...
            contains(compact,'''B_ref_y_adv_epoch50_endpoint'''), ...
        'Endpoint runner must include the retained endpoint variant.');
    assert(contains(compact,'"conditionMode","ref_y"') || ...
            contains(compact,'''conditionMode'',"ref_y"'), ...
        'Endpoint runner must use conditionMode=ref_y.');
    assert(contains(compact,'"boundaryTargetMode","feasible_endpoint"') || ...
            contains(compact,'''boundaryTargetMode'',"feasible_endpoint"'), ...
        'Endpoint runner must use feasible endpoint targets.');
    assert(~contains(compact,'latestCBSDataDir'), ...
        'Endpoint runner must not depend on deleted epoch comparison outputs.');
    assert(contains(compact,'contact_sheets_endpoint_compare'), ...
        'Endpoint runner must write a dedicated comparison sheet folder.');

    fprintf('CBS-CGAN endpoint runner smoke passed.\n');
end
