function test_CBS_region_domain_figure_redraw()
%TEST_CBS_REGION_DOMAIN_FIGURE_REDRAW Verify domain-background redraw helper.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    expDir = fullfile(tempdir,sprintf('cbs_region_domain_redraw_%s', ...
        char(java.util.UUID.randomUUID)));
    runDir = fullfile(expDir,'DASCMOP1_BC_run3');
    mkdir(runDir);

    Snapshot = struct( ...
        'problem',"DASCMOP1_BC", ...
        'run',3, ...
        'target_FE',500, ...
        'actual_FE',520, ...
        'generation',4, ...
        'train_objs',[0.4 1.6;0.7 1.2;1.0 0.9], ...
        'generated_objs',[0.55 1.45;0.85 1.05]);
    Saved = struct( ...
        'metric',struct('region_gan_stage_snapshots',Snapshot), ...
        'problem',"DASCMOP1_BC", ...
        'run',3, ...
        'N',20, ...
        'maxFE',1000);
    save(fullfile(runDir,'metric.mat'),'-struct','Saved');

    outDir = fullfile(expDir,'domain_figures_all');
    Manifest = redraw_CBS_RegionCGAN_domain_figures(expDir,outDir);

    assert(height(Manifest) == 1, ...
        'Redraw helper must write one manifest row per saved snapshot.');
    assert(isfile(Manifest.figure_file(1)), ...
        'Redraw helper must create the domain-background PNG.');
    assert(isfile(fullfile(outDir,'domain_figure_manifest.csv')), ...
        'Redraw helper must write the manifest CSV.');

    fprintf('CBS RegionCGAN domain redraw smoke passed: %s\n',outDir);
end
