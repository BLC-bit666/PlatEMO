function S = GANCMOSettings(overrides)
% Training settings shared by the direct-offspring mainline and experiments.
    S = struct('initialG',1000,'updateG',[20 100],'trainInterval',10, ...
        'changeThreshold',.2,'pairsPerDirection',1,'resetInterval',Inf, ...
        'generatorHidden',[8 8],'criticHidden',[16 16],'learningRate',.001, ...
        'noiseSigma',.1,'criticSteps',5,'batchSize',64,'minimumPairs',8, ...
        'minimumPairsContinue',8,'candidateCount',500,'activePairPriority','quality', ...
        'endpointWeight',0,'conditionEncoding','unit', ...
        'maxTrainingObjectiveGap',Inf,'maxCandidateDistanceF',Inf,'learningRateDecay',1, ...
        'learningRateSchedule','cold_tail','candidateTargetCap',Inf,'fullDirectionBatch',false, ...
        'referenceScaling','adaptive','conditionScale',1,'generatorActivation','leakyrelu', ...
        'generatorFrequency',1);
    if nargin>0 && ~isempty(overrides)
        names = fieldnames(overrides);
        assert(all(ismember(names,fieldnames(S))),'GANCMO:UnknownSetting','Unknown setting.');
        for i = 1:numel(names); S.(names{i}) = overrides.(names{i}); end
    end
    % jsondecode returns numeric vectors as columns; callers may use either.
    S.updateG = reshape(S.updateG,1,[]);
    S.generatorHidden = reshape(S.generatorHidden,1,[]);
    S.criticHidden = reshape(S.criticHidden,1,[]);
    positive = [S.initialG,S.updateG,S.trainInterval,S.pairsPerDirection, ...
        S.generatorHidden,S.criticHidden,S.learningRate,S.noiseSigma, ...
        S.criticSteps,S.batchSize,S.minimumPairs,S.minimumPairsContinue,S.candidateCount];
    assert(all(isfinite(positive)&positive>0) && numel(S.updateG)==2);
    assert(S.resetInterval>0 && S.changeThreshold>=0);
    assert(isscalar(S.pairsPerDirection) && S.pairsPerDirection==1, ...
        'GANCMO:BadPairCount','The GANCMO mainline uses exactly one active pair per direction.');
    assert(isscalar(S.endpointWeight) && isfinite(S.endpointWeight) && S.endpointWeight>=0, ...
        'GANCMO:BadEndpointWeight','Endpoint loss weight must be finite and nonnegative.');
    assert(strcmp(S.conditionEncoding,'unit'), ...
        'GANCMO:BadConditionEncoding','The mainline uses M-dimensional unit directions and one binary side bit.');
    assert(isscalar(S.conditionScale) && S.conditionScale==1, ...
        'GANCMO:BadConditionScale','The mainline keeps unit direction scale fixed at one.');
    assert(any(strcmp(S.generatorActivation,{'leakyrelu','sine'})), ...
        'GANCMO:BadGeneratorActivation','Unknown generator activation.');
    assert(isscalar(S.generatorFrequency) && isfinite(S.generatorFrequency) && S.generatorFrequency>0, ...
        'GANCMO:BadGeneratorFrequency','Generator frequency must be finite and positive.');
    assert(isscalar(S.maxTrainingObjectiveGap) && S.maxTrainingObjectiveGap>0, ...
        'GANCMO:BadTrainingGap','Training objective-pair gap must be positive (Inf disables it).');
    assert(isscalar(S.maxCandidateDistanceF) && S.maxCandidateDistanceF>0, ...
        'GANCMO:BadCandidateDistance','Candidate distance limit must be positive (Inf disables it).');
    assert(isscalar(S.learningRateDecay) && isfinite(S.learningRateDecay) && ...
        S.learningRateDecay>0 && S.learningRateDecay<=1, ...
        'GANCMO:BadRateDecay','Learning-rate decay must be in (0,1].');
    assert(any(strcmp(S.learningRateSchedule,{'cold_tail','event_tail','event_exp'})), ...
        'GANCMO:BadRateSchedule','Unknown learning-rate schedule.');
    assert(any(strcmp(S.activePairPriority,{'quality','gap','objective_gap'})), ...
        'GANCMO:BadPairPriority','Active pair priority must be quality, gap, or objective_gap.');
    assert(isscalar(S.candidateTargetCap) && S.candidateTargetCap>=1 && ...
        (isinf(S.candidateTargetCap) || S.candidateTargetCap==fix(S.candidateTargetCap)), ...
        'GANCMO:BadCandidateCap','Per-target-direction candidate cap must be a positive integer or Inf.');
    assert(isscalar(S.fullDirectionBatch) && ismember(S.fullDirectionBatch,[false true]), ...
        'GANCMO:BadBatchCoverage','Full-direction batch setting must be logical.');
    assert(any(strcmp(S.referenceScaling,{'adaptive','objective'})), ...
        'GANCMO:BadReferenceScaling','Reference scaling must be adaptive or objective.');
end
