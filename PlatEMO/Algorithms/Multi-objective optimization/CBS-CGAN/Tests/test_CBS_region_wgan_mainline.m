end

function testExperimentalMechanismSmoke()
    for arm = 0 : 1
        rng(23,'twister');
        Problem = LIRCMOP5_BC('N',20,'D',5,'maxFE',400);
        Algorithm = CBS_RegionWGAN_GP_Experiment('parameter', ...
            {arm,1,2,500},'save',0,'outputFcn',@(varargin)[]);
        Algorithm.Solve(Problem);
        Snapshot = Algorithm.guideExperimentSnapshot();
        assert(Snapshot.generationEvents > 0 && Snapshot.useEvents > 0 && ...
            Snapshot.guidedSelected > 0);
        if arm == 0
            assert(Snapshot.rawCandidates == ...
                100*Snapshot.generationEvents && ...
                Snapshot.criticKept == Snapshot.rawCandidates);
        else
            assert(Snapshot.rawCandidates == ...
                500*Snapshot.generationEvents && ...
                Snapshot.criticKept == 200*Snapshot.generationEvents);
        end
    end
end

