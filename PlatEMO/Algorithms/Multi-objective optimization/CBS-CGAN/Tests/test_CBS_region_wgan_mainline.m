function testProductionMechanismSmoke()
    rng(17,'twister');
    Problem = LIRCMOP5_BC('N',20,'D',5,'maxFE',400);
    Algorithm = CBS_RegionWGAN_GP('parameter', ...
        {500,2,1,4,1,2,0.1},'save',0,'outputFcn',@(varargin)[]);
    Algorithm.Solve(Problem);
    Snapshot = Algorithm.guideExperimentSnapshot();
    assert(Problem.FE == 400 && Snapshot.arm == -1 && ...
        Snapshot.generationMode == "global_critic" && ...
        Snapshot.useMode == "local_target" && ...
        Snapshot.generationEvents > 0 && ...
        Snapshot.rawCandidates == 500*Snapshot.generationEvents && ...
        Snapshot.criticKept == 200*Snapshot.generationEvents && ...
        Snapshot.guidedSelected > 0 && Snapshot.guidedFallback >= 0 && ...
        Snapshot.mappedValid > 0 && ...
        isfinite(Snapshot.meanCenterStep) && ...
        isfinite(Snapshot.meanActualStep));
end

function testFrozenPathIsolation(repoRoot,algorithmFile)
    frozenDir = fullfile(repoRoot,'Data', ...
        'CBS_bt0_vs_nobt_gate_source_snapshot','Algorithms', ...
        'Multi-objective optimization','CBS-CGAN','Experimental');
    if ~isfolder(frozenDir)
        return;
    end
    addpath(frozenDir,'-begin');
    assert(~isempty(which('CBS_RegionWGAN_GP_BT0F0')), ...
        'Frozen-source isolation fixture is not visible.');
    addCBSPaths(repoRoot);
    assert(isempty(which('CBS_RegionWGAN_GP_BT0F0')) && ...
        isempty(which('CBS_RegionWGAN_GP_NoBT')) && ...
        strcmp(which('CBS_RegionWGAN_GP'),algorithmFile), ...
        'addCBSPaths must expose only the live CBS mainline.');
end

function testDistinctOrdinaryDE()
    rng(73,'twister');
    Problem = DASCMOP1_BC('N',6,'D',5,'maxFE',20);
    Population = Problem.Initialization();
    Fitness = (1:numel(Population))';
    [Offspring,Parents] = OperatorDEDistinct_CBS( ...
        Problem,Population,Fitness,4,{1,0.5,0,20});

    assert(all(Parents(:,1) ~= Parents(:,2)) && ...
        all(Parents(:,1) ~= Parents(:,3)) && ...
        all(Parents(:,2) ~= Parents(:,3)));
    Decs = Population.decs;
    expected = Decs(Parents(:,1),:) + ...
        0.5*(Decs(Parents(:,2),:)-Decs(Parents(:,3),:));
    expected = min(max(expected,Problem.lower),Problem.upper);
    assert(isequal(Offspring.decs,expected));
end
