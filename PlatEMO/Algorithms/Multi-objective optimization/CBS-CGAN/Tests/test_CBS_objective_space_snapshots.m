function test_CBS_objective_space_snapshots
%TEST_CBS_OBJECTIVE_SPACE_SNAPSHOTS Verify behavior-neutral point capture.

    rootPath = fileparts(fileparts(fileparts(fileparts(fileparts( ...
        mfilename('fullpath'))))));
    addpath(fullfile(rootPath,'Algorithms','Multi-objective optimization', ...
        'CBS-CGAN','Support'),'-begin');
    addCBSPaths(rootPath);

    seed = 1;
    parameters = {500,6,1,64,5,32,1};
    schedule = struct('initialEpoch',1,'retrainEpoch',1,'nCritic',1);
    diagnostics = struct('enabled',true,'stopAtCGANEnd',false, ...
        'disableOracleAudit',false);
    rng(seed,'twister');
    PlainProblem = LIRCMOP5_BC('N',100,'D',30,'maxFE',8000);
    Plain = PairGuide('parameter',parameters,'save',1, ...
        'outputFcn',@silentOutput);
    Plain.configurePairGuideTrainingExperiment(schedule);
    Plain.configureCutoffDiagnostics(diagnostics);
    Plain.Solve(PlainProblem);
    plainRNG = rng;

    rng(seed,'twister');
    CaptureProblem = LIRCMOP5_BC('N',100,'D',30,'maxFE',8000);
    Capture = PairGuide('parameter',parameters,'save',1, ...
        'outputFcn',@silentOutput);
    Capture.configurePairGuideTrainingExperiment(schedule);
    Capture.configureCutoffDiagnostics(diagnostics);
    Capture.configureObjectiveSpaceSnapshots(struct( ...
        'enabled',true,'targetFE',5000, ...
        'expectedRawCount',500,'expectedGuidedCount',20));
    Capture.Solve(CaptureProblem);
    captureRNG = rng;

    assert(PlainProblem.FE == CaptureProblem.FE && ...
        PlainProblem.FE == PlainProblem.maxFE, ...
        'Snapshot capture changed the evaluation budget.');
    assert(isequal(double(Plain.result{end,2}.decs), ...
        double(Capture.result{end,2}.decs)) && ...
        isequal(double(Plain.result{end,2}.objs), ...
        double(Capture.result{end,2}.objs)) && ...
        isequal(double(Plain.result{end,2}.cons), ...
        double(Capture.result{end,2}.cons)), ...
        'Snapshot capture changed the deterministic population trajectory.');
    assert(isequal(plainRNG,captureRNG), ...
        'Snapshot capture changed the terminal random-number state.');

    Snapshots = Capture.objectiveSpaceSnapshots();
    assert(isscalar(Snapshots) && Snapshots.targetFE == 5000, ...
        'Configured target FE snapshots are missing.');
    assert(all([Snapshots.rawCount] == 500) && ...
        all([Snapshots.requestedCount] == 20) && ...
        all([Snapshots.guidedCount]+[Snapshots.fallbackCount] == 20), ...
        'Raw or guided point counts are incorrect.');
    assert(all(arrayfun(@(S)size(S.rawObjs,1) == 500 && ...
        size(S.guidedObjs,1) == S.guidedCount && ...
        size(S.rawObjs,2) == 2 && ...
        size(S.guidedObjs,2) == 2,Snapshots)), ...
        'Objective-space snapshot shapes are incorrect.');
    assert(all(isfinite([Snapshots.actualFE])) && ...
        all(isfinite([Snapshots.poolFE])), ...
        'Snapshot event FE metadata are missing.');

    fprintf('PairGuide objective-space snapshot capture passed.\n');
end

