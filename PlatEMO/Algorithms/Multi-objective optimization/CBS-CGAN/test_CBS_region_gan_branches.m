        'FixMD experiment runner must exist for unified validation runs.');
    sourceText = fileread(runnerFile);
    expectedRoot = fileparts(fileparts(fileparts(fileparts( ...
        fileparts(runnerFile)))));
    oldRoot = fileparts(fileparts(fileparts(fileparts(runnerFile))));
    assert(isfile(fullfile(expectedRoot,'platemo.m')) && ...
            ~isfile(fullfile(oldRoot,'platemo.m')), ...
