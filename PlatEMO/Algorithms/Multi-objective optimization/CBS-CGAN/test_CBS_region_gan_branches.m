        'FixMD runner must validate the PlatEMO root instead of stopping at Algorithms/.');
    requiredBranches = [ ...
        "fixmd_diag_baseline", ...
        "fixmd_train_gap1_iter50", ...
        "fixmd_train_gap2_iter50", ...
        "fixmd_train_gap1_iter75", ...
        "fixmd_train_gap2_iter75", ...
        "fixmd_train_gap2_delta20_iter50", ...
        "fixmd_train_gap2_delta20_boost75", ...
        "fixmd_prescreen1_fixed50", ...
        "fixmd_prescreen8_fixed50", ...
        "fixmd_prescreen8_delta20_boost75"];
    for i = 1 : numel(requiredBranches)
        assert(contains(sourceText,requiredBranches(i)), ...
            'FixMD runner missing branch: %s.',requiredBranches(i));
