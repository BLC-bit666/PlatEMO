%TEST_CBS_REGION_GAN_BRANCHES Verify region BCE/WGAN comparison branches.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));

    assert(exist('CBS_RegionCGAN','class') == 8, ...
        'Region BCE-CGAN control algorithm must exist.');
    assert(exist('CBS_RegionWGAN_GP','class') == 8, ...
        'Region WGAN-GP comparison algorithm must exist.');

    testRegionWGANMainlineDefaults();
    testBalancedQueryAllocation();
    testDynamicGANIterSchedule();
    testFixmdTrainingTriggerAndTwoLevelIter();
    testFixmdExperimentRunnerBranchCoverage();
    testOffspringGSurvivalCountsDuplicateDecisionsOnce();
    testBoundaryCGANRecordsTrainingHistory();
    testBoundaryWGANTrainsAndSamples();
    testBoundaryWGANSampleZAndPrescreen();
    fprintf('CBS region GAN branch regressions passed.\n');
end

function testRegionWGANMainlineDefaults()
    Defaults = CBS_RegionWGAN_GP.mainlineDefaults();
    assert(Defaults.ganKind == "wgan-gp", ...
        'RegionGAN mainline must use the WGAN-GP branch.');
    assert(Defaults.queryMode == "random_all_w", ...
        'RegionGAN mainline must use fully random QueryC over all refs.');
    assert(Defaults.prevBMemMode == "prev1_fair_union", ...
        'RegionGAN mainline must retain previous BMem as fair competitors.');
    assert(Defaults.bmemBandMode == "current" && ...
            isempty(Defaults.bandMaxAnchorsPerRef), ...
        'RegionGAN mainline must keep the current mixed BMem cloud by default.');
    assert(Defaults.ganMiniBatch == 32, ...
        'RegionGAN mainline must keep ganMiniBatch=32.');
    assert(Defaults.minGANTrainCount == 32, ...
        'RegionGAN mainline must keep minGANTrainCount=32.');
    assert(Defaults.nGen == 30, ...
        'RegionGAN mainline must generate at most 30 GAN offspring per refresh.');
    assert(Defaults.maxAnchorsPerRef == 5, ...
        'RegionGAN mainline must keep the ref-cap quality gate at five anchors.');
    assert(Defaults.ganIter == 100 && Defaults.nCritic == 2, ...
        'RegionGAN mainline must promote C_iter100_ncritic2 as the default training dose.');
    assert(Defaults.gpLambda == 10, ...
        'RegionGAN mainline must retain the WGAN-GP gradient penalty.');
    assert(isfield(Defaults,'sampleSigma') && Defaults.sampleSigma == 0.3, ...
        'RegionGAN mainline must use sampleSigma=0.3 for sampling Z.');
end

function testBalancedQueryAllocation()
    rng(219,'twister');
    QueryC = [(1:20)' zeros(20,1)];
    [SampleC,Counts] = RunRegionGAN_RC('allocatequery',QueryC,2,30);
    assert(size(SampleC,1) == 30, ...
        'Allocated query rows must respect the nGen hard cap.');
    assert(numel(Counts) == size(QueryC,1), ...
        'Allocation counts must map back to every original QueryC row.');
    assert(all(Counts >= 1) && all(Counts <= 2), ...
        'With nGen=30, K=20, qpc=2, every region gets 1 or 2 samples.');
    assert(sum(Counts) == 30, ...
        'Allocation counts must sum to the sampled QueryC row count.');

    [SmallSampleC,SmallCounts] = RunRegionGAN_RC('allocatequery',QueryC(1:2,:),2,30);
    assert(size(SmallSampleC,1) == 4 && all(SmallCounts == 2), ...
        'Small region counts should use qpc as a per-region cap, not fill nGen.');
end

function testFixmdTrainingTriggerAndTwoLevelIter()
    Options = struct( ...
        'trainTriggerMode',"deltaTrainCount20", ...
        'trainTriggerDelta',0.20, ...
        'iter',50, ...
        'ganIterSchedule',"two_level_data_change", ...
        'ganIterStart',75, ...
        'ganIterEnd',50);
    State = RunRegionGAN_RC('inittraintriggerstate');

    [flag,Info] = RunRegionGAN_RC('traintrigger',Options,State,2, ...
        40,10,false);
    assert(flag && Info.trigger_first_train == 1, ...
        'First ready training set must trigger training even off-cycle.');
    Resolved = RunRegionGAN_RC('resolveganoptions',Options,10000, ...
        100000,Info);
    assert(Resolved.iter == 75 && ...
            Resolved.gan_iter_schedule == "two_level_data_change", ...
        'Two-level ganIter must use the boosted iter on first/data-change training.');

    State = RunRegionGAN_RC('updatetraintriggerstate',State,Info);
    [flag,Info] = RunRegionGAN_RC('traintrigger',Options,State,3, ...
        43,10,false);
    assert(~flag && Info.trigger_data_changed == 0, ...
        'Small train_count changes below threshold must not trigger off-cycle.');
    Resolved = RunRegionGAN_RC('resolveganoptions',Options,30000, ...
        100000,Info);
    assert(Resolved.iter == 50, ...
        'Two-level ganIter must use the base iter when data did not change.');

    [flag,Info] = RunRegionGAN_RC('traintrigger',Options,State,4, ...
        49,10,false);
    assert(flag && Info.trigger_train_count_delta >= 0.20, ...
        'Train count changes at or above threshold must trigger off-cycle.');
    Resolved = RunRegionGAN_RC('resolveganoptions',Options,30000, ...
        100000,Info);
    assert(Resolved.iter == 75, ...
        'Two-level ganIter must use the boosted iter on delta-triggered training.');

    OffOptions = struct('trainTriggerMode',"off");
    [flag,Info] = RunRegionGAN_RC('traintrigger',OffOptions,State,5, ...
        80,12,false);
    assert(~flag && Info.trigger_reason == "waiting_period", ...
        'trainTriggerMode=off must preserve periodic-only training.');
end

function testFixmdExperimentRunnerBranchCoverage()
    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    runnerFile = fullfile(repoRoot,'Algorithms', ...
        'Multi-objective optimization','CBS-CGAN','Support', ...
        'run_CBS_RegionWGAN_GP_fixmd_branches.m');
