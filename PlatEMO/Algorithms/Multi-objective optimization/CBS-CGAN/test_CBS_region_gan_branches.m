function testOffspringGSurvivalCountsDuplicateDecisionsOnce()
    GDec = [0 0;0 0;1 1];
    GCon = [-1;-1;1];
    SelectedDec = [0 0;2 2];
    Metrics = RunRegionGAN_RC('offspringgsurvivaldiagnostics', ...
        GDec,GCon,SelectedDec);
    assert(Metrics.offspringG_count == 3 && ...
            Metrics.offspringG_survive_count == 1, ...
        'Survival diagnostics must consume matched selected rows for duplicate generated decisions.');
    assert(abs(Metrics.offspringG_survival_rate - 1/3) < 1e-12, ...
        'Duplicate generated rows must not all survive when one selected copy exists.');
    assert(Metrics.offspringG_feasible_count == 2 && ...
            Metrics.offspringG_feasible_survive_count == 1 && ...
            abs(Metrics.offspringG_feasible_survival_rate - 0.5) < 1e-12, ...
        'Feasible survival diagnostics must use the same one-to-one matching.');
end

function testBoundaryWGANTrainsAndSamples()
    rng(211,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,8,1) + rand(8,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,8,1);
    TrainC = rand(8,2);
    Options = struct( ...
        'zDim',6, ...
        'iter',1, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',1e-4, ...
        'nCritic',1, ...
        'gpLambda',10, ...
        'generatorHidden',[32 32], ...
        'criticHidden',[32 32], ...
        'sigma',1.0);

    GAN = BoundaryWGAN_RC('train',[],TrainX,TrainC,Problem,Options);
    assert(isfield(GAN,'netG') && isfield(GAN,'netC'), ...
        'BoundaryWGAN_RC must return generator and critic networks.');
    assert(layerOutputSize(GAN.netG,'g_fc1') == 32 && ...
            layerOutputSize(GAN.netG,'g_fc2') == 32, ...
        'WGAN generator must follow the small [32 32] hidden layers.');
    assert(layerOutputSize(GAN.netC,'c_fc1') == 32 && ...
            layerOutputSize(GAN.netC,'c_fc2') == 32, ...
        'WGAN critic must follow the small [32 32] hidden layers.');
    assert(~hasLayer(GAN.netC,'c_sigmoid'), ...
        'WGAN critic output must stay linear, not sigmoid/BCE.');
    assert(GAN.critic_holdout_count > 0 && ...
            GAN.critic_train_diag_count + GAN.critic_holdout_count <= ...
            size(TrainX,1), ...
        'WGAN holdout diagnostics must use a split disjoint from the training diagnostic pool.');

    QueryC = TrainC(1:2,:);
    [Dec,Info] = BoundaryWGAN_RC('samplebycondition',GAN,QueryC,3,Options);
    assert(isequal(size(Dec),[6 Problem.D]), ...
        'WGAN sampling must return queryPerCondition decisions per query.');
    assert(isequal(size(Info.z),[6 Options.zDim]), ...
        'WGAN sample info must expose the latent z used for each sample.');
end

function testDynamicGANIterSchedule()
    Options = struct( ...
        'iter',75, ...
        'ganIterSchedule',"linear_fe", ...
        'ganIterStart',150, ...
        'ganIterEnd',30);

    AtStart = RunRegionGAN_RC('resolveganoptions',Options,0,100000);
    At10k = RunRegionGAN_RC('resolveganoptions',Options,10000,100000);
    At50k = RunRegionGAN_RC('resolveganoptions',Options,50000,100000);
    AtEnd = RunRegionGAN_RC('resolveganoptions',Options,100000,100000);
    PastEnd = RunRegionGAN_RC('resolveganoptions',Options,120000,100000);

    assert(AtStart.iter == 150, ...
        'Linear ganIter schedule must use ganIterStart at FE=0.');
    assert(At10k.iter == 138, ...
        'Linear ganIter schedule must interpolate by current FE/maxFE.');
    assert(At50k.iter == 90, ...
        'Linear ganIter schedule must be midpoint at FE=0.5*maxFE.');
    assert(AtEnd.iter == 30 && PastEnd.iter == 30, ...
        'Linear ganIter schedule must clamp at ganIterEnd.');

    Fixed = RunRegionGAN_RC('resolveganoptions',struct('iter',75), ...
        50000,100000);
    assert(Fixed.iter == 75, ...
        'Absent ganIterSchedule, resolveganoptions must preserve fixed iter.');
end

function testBoundaryWGANSampleZAndPrescreen()
    rng(223,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,8,1) + rand(8,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,8,1);
    TrainC = rand(8,2);
    Options = struct( ...
        'zDim',3, ...
        'iter',1, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',1e-4, ...
        'nCritic',1, ...
        'gpLambda',10, ...
        'generatorHidden',[32 32], ...
        'criticHidden',[32 32], ...
        'sigma',0.25, ...
        'sampleZMode',"zero", ...
        'prescreenMultiplier',3);

    GAN = BoundaryWGAN_RC('train',[],TrainX,TrainC,Problem,Options);
    QueryC = TrainC(1:2,:);
    [Dec,Info] = BoundaryWGAN_RC('samplebycondition',GAN,QueryC,2,Options);

    assert(isequal(size(Dec),[4 Problem.D]), ...
        'Prescreened WGAN sampling must preserve the final sample count.');
    assert(isequal(size(Info.z),[4 Options.zDim]) && ...
            all(Info.z(:) == 0), ...
        'sampleZMode=zero must use zero latent vectors only for sampling.');
    assert(Info.prescreen_multiplier == 3, ...
        'WGAN sample info must record the critic prescreen multiplier.');
    assert(Info.prescreen_candidate_count == 12 && ...
            Info.prescreen_selected_count == 4, ...
        'Prescreen diagnostics must count raw candidates and selected rows.');
    assert(isequal(size(Info.prescreen_selected_score),[4 1]), ...
        'Prescreen diagnostics must expose one selected critic score per row.');
    assert(isfield(Info,'generated_critic_score') && ...
            isequal(size(Info.generated_critic_score),[4 1]), ...
        'WGAN sample info must expose one critic score for each generated row.');
    assert(isfield(Info,'prescreen_raw_score') && ...
            isequal(size(Info.prescreen_raw_score),[12 1]), ...
        'Prescreen diagnostics must retain raw candidate critic scores.');

    Options.sampleZMode = "random";
    Options.trainZMode = "random";
    Options.trainSigma = 1.0;
    Options.sampleSigma = 0.01;
    Options.prescreenMultiplier = 1;
    [~,SmallZInfo] = BoundaryWGAN_RC('samplebycondition',GAN,QueryC,4, ...
        Options);
    assert(any(abs(SmallZInfo.z(:)) > 0) && ...
            max(abs(SmallZInfo.z(:))) < 0.1, ...
        'sampleSigma must control sampling Z scale independently.');
end

function testBoundaryCGANRecordsTrainingHistory()
    rng(217,'twister');
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    TrainX = repmat(Problem.lower,8,1) + rand(8,Problem.D).* ...
        repmat(Problem.upper - Problem.lower,8,1);
    TrainC = rand(8,2);
    Options = struct( ...
        'zDim',6, ...
        'iter',2, ...
        'miniBatch',4, ...
        'lrD',1e-4, ...
        'lrG',1e-4, ...
        'dSteps',1, ...
        'gSteps',1, ...
        'advWeight',1.0, ...
        'trainMode',"iter", ...
        'realLabel',0.9, ...
        'generatorHidden',[32 32], ...
        'discriminatorHidden',[32 32], ...
        'sigma',1.0);

    GAN = BoundaryCGAN_CBS('train',[],TrainX,TrainC,Problem,Options);
    assert(isfield(GAN,'train_history') && numel(GAN.train_history) == 3, ...
        'CGAN training must record initial and per-iter diagnostics.');
    required = {'step','loss_d','loss_g','d_real_acc','d_fake_acc', ...
        'd_bal_acc','g_fool_rate','score_real_mean','score_fake_mean', ...
        'score_random_mean'};
    for i = 1 : numel(required)
        assert(isfield(GAN.train_history,required{i}), ...
            'CGAN training history missing field: %s.',required{i});
    end
    assert(all([GAN.train_history.d_real_acc] >= 0 & ...
            [GAN.train_history.d_real_acc] <= 1), ...
        'D real accuracy must stay in [0,1].');
    assert(all([GAN.train_history.d_fake_acc] >= 0 & ...
            [GAN.train_history.d_fake_acc] <= 1), ...
        'D fake accuracy must stay in [0,1].');
    assert(all([GAN.train_history.g_fool_rate] >= 0 & ...
            [GAN.train_history.g_fool_rate] <= 1), ...
        'G fool rate must stay in [0,1].');
    assert(isfinite(GAN.last_discriminator_loss) && ...
            isfinite(GAN.last_generator_loss), ...
        'CGAN must expose final D/G losses as scalar fields.');
    assert(GAN.last_g_fool_rate == GAN.train_history(end).g_fool_rate, ...
        'Final G fool rate must mirror the last training-history row.');
end

function tf = hasLayer(net,name)
    tf = any(string({net.Layers.Name}) == string(name));
end

function value = layerOutputSize(net,name)
    idx = find(string({net.Layers.Name}) == string(name),1,'first');
    assert(~isempty(idx),'Missing layer: %s.',name);
    value = double(net.Layers(idx).OutputSize);
end
