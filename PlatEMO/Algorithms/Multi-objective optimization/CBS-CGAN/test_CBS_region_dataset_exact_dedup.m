function test_CBS_region_dataset_exact_dedup()
%TEST_CBS_REGION_DATASET_EXACT_DEDUP Verify the isolated training-row gate.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));
    Problem = DASCMOP1_BC('N',8,'D',6,'maxFE',100);
    W = [1 0;0 1];
    xA = zeros(1,Problem.D);
    xB = 0.5*ones(1,Problem.D);
    BMem = struct( ...
        'x_b',[xA;xA;xA;xB], ...
        'y_b',[1 2;1 2;1 2;2 1], ...
        'ref',[1;1;2;1], ...
        'source_f',[0;1;0;0], ...
        'age_f',[0;1;0;0], ...
        'front_rank_f',[1;2;1;1]);
    Samples = struct('objs',zeros(0,Problem.M));

    [X0,C0,Q0,B0,I0] = BuildBoundaryDataset_RC( ...
        BMem,Samples,W,Problem,struct('trainDedupMode',"off"));
    assert(size(X0,1) == 4 && size(C0,1) == 4);
    assert(I0.raw_valid_train_count == 4 && ...
        I0.exact_duplicate_train_count == 1 && ...
        I0.removed_duplicate_train_count == 0 && ...
        I0.train_dedup_enabled == 0);

    [X1,C1,Q1,B1,I1] = BuildBoundaryDataset_RC( ...
        BMem,Samples,W,Problem,struct('trainDedupMode',"exact_ref_x"));
    assert(isequal(X1,[xA;xA;xB]));
    assert(isequal(C1,[W(1,:);W(2,:);W(1,:)]));
    assert(size(X1,1) == 3 && I1.raw_valid_train_count == 4 && ...
        I1.valid_train_count == 3 && ...
        I1.exact_duplicate_train_count == 1 && ...
        I1.removed_duplicate_train_count == 1 && ...
        I1.train_dedup_enabled == 1);
    assert(isequal(Q0,Q1) && isequaln(B0,B1), ...
        'Training dedup must not change query support or BMem.');

    didThrow = false;
    try
        BuildBoundaryDataset_RC(BMem,Samples,W,Problem, ...
            struct('trainDedupMode',"approximate"));
    catch ME
        didThrow = strcmp(ME.identifier,'CBSRegionGAN:BadTrainDedupMode');
    end
    assert(didThrow,'Unsupported dedup modes must be rejected.');
    fprintf('CBS exact (ref,x) training dedup test passed.\n');
end
