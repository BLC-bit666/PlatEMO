function ExperimentSummary = ...
        run_CBS_RegionWGAN_GP_structured_z_experiment( ...
        rootOutDir,workerCount,problemNames,N,D,maxFE,runIds)
%RUN_CBS_REGIONWGAN_GP_STRUCTURED_Z_EXPERIMENT Paired categorical-z test.
%   The only behavioral difference between arms is categorical-z plus its
%   minimal linear MI decoder. BMem, query allocation, WGAN capacity,
%   training updates, nGen, and all evolutionary settings remain fixed.

    rootDir = locateRootDir();
    addpath(genpath(rootDir));
    if nargin < 1 || isempty(rootOutDir)
        rootOutDir = fullfile(rootDir,'Data','CBS_RegionGAN_compare', ...
            ['structured_z_mi_', ...
            char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
    end
    if nargin < 2 || isempty(workerCount); workerCount = 8; end
    if nargin < 3 || isempty(problemNames)
        problemNames = ["LIRCMOP5_BC";"LIRCMOP6_BC";"LIRCMOP7_BC"; ...
            "LIRCMOP8_BC";"LIRCMOP9_BC";"LIRCMOP10_BC"];
    end
    if nargin < 4 || isempty(N); N = 100; end
    if nargin < 5 || isempty(D); D = 30; end
    if nargin < 6 || isempty(maxFE); maxFE = 100000; end
    if nargin < 7 || isempty(runIds); runIds = 1:3; end

    workerCount = max(1,round(double(workerCount)));
    if ~isfolder(rootOutDir); mkdir(rootOutDir); end
    writeLockedExperimentDesign(rootOutDir,workerCount,problemNames, ...
        N,D,maxFE,runIds);
    armNames = ["A_control";"B_categorical_z_mi"];
    modes = ["off";"categorical_mi"];
    Rows = repmat(struct( ...
        'arm',"",'structured_z_mode',"",'output_dir',"", ...
        'run_count',0,'ok_run_count',0,'exact_fe_run_count',0, ...
        'status',"pending"),2,1);

    for arm = 1 : 2
        armOutDir = fullfile(rootOutDir,char(armNames(arm)));
        Options = struct( ...
            'captureRun',0, ...
            'stageTargets',[], ...
            'captureWGANTrainHistory',false, ...
            'wganMappingDiagnostics',true, ...
            'bmemLearnabilityDiagnostics',true, ...
            'mappingDiagMaxConditions',8, ...
            'mappingDiagZSamples',8, ...
            'bmemMode',"legacy", ...
            'structuredZMode',modes(arm), ...
            'structuredZMaxModes',5, ...
            'structuredZLambda',1.0, ...
            'schemaVersion',"cbs_structured_z_mi_v1");
        Summary = run_CBS_RegionWGAN_GP_mainline( ...
            armOutDir,workerCount,problemNames,N,D,maxFE,runIds,Options);
        Rows(arm).arm = armNames(arm);
        Rows(arm).structured_z_mode = modes(arm);
        Rows(arm).output_dir = string(armOutDir);
        Rows(arm).run_count = height(Summary);
        Rows(arm).ok_run_count = sum(Summary.status == "ok");
        Rows(arm).exact_fe_run_count = sum( ...
            Summary.finalFE == Summary.maxFE);
        if Rows(arm).ok_run_count == Rows(arm).run_count && ...
                Rows(arm).exact_fe_run_count == Rows(arm).run_count
            Rows(arm).status = "ok";
        else
            Rows(arm).status = "failed";
        end
        ExperimentSummary = struct2table(Rows(1:arm));
        writetable(ExperimentSummary, ...
            fullfile(rootOutDir,'experiment_summary.csv'));
        if Rows(arm).status ~= "ok"
            error('CBSRegionGAN:StructuredZExperimentArmFailed', ...
                'Structured-z experiment arm %s failed integrity checks.', ...
                armNames(arm));
        end
    end
end

function writeLockedExperimentDesign(rootOutDir,workerCount,problemNames, ...
        N,D,maxFE,runIds)
    Design = table( ...
        "structured_z_mi_v1", ...
        strjoin(string(problemNames(:)),';'), ...
        strjoin(string(runIds(:)'),';'), ...
        double(N),double(D),double(maxFE),double(workerCount), ...
        "legacy BMem; 25 populated + 5 unified one-hop frontier; remote=0", ...
        "z=[onehot(k,5),epsilon]; populated active k=min(anchor count,5); frontier k=1", ...
        "linear Q(x,c); generator loss=-critic+1.0*categorical cross-entropy", ...
        "bdist50_true;bwidth90_10_true", ...
        "bcover_eps_true;populated/frontier geometry;anchor utilization;within-ref diversity;BMem geometry;mode accuracy/entropy;runtime", ...
        "paired problem-run event medians;Wilcoxon signed-rank;Holm for two primary metrics", ...
        "both primary metrics improve and guards are non-inferior", ...
        "positive but inconclusive: add only seeds 4-5", ...
        "otherwise reject categorical-z+MI; do not add clustering or other losses", ...
        "all runs must finish at exactly maxFE", ...
        'VariableNames',{'experiment_id','problems','seeds','N','D', ...
        'maxFE','worker_count','fixed_mainline','structured_change', ...
        'mi_change','primary_metrics','guards','statistics', ...
        'promotion_rule','hold_rule','reject_rule','fe_rule'});
    writetable(Design,fullfile(rootOutDir,'experiment_design.csv'));
end

function rootDir = locateRootDir()
    rootDir = fileparts(which('platemo'));
    if isempty(rootDir); rootDir = pwd; end
end
