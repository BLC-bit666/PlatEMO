        Branch.zDim, ...
        Branch.ganIter, ...
        Defaults.ganMiniBatch, ...
        Defaults.ganLrD, ...
        Defaults.ganLrG, ...
        Defaults.frontDepth, ...
        Defaults.pairNeighborRefRadius, ...
        Defaults.refDivisor, ...
        Defaults.minBoundaryLength, ...
        Defaults.queryPerCondition, ...
        Defaults.gpLambda, ...
        Branch.nCritic, ...
        Defaults.maxAnchorsPerRef, ...
        Defaults.minGANTrainCount};
end

function Row = branchRowFromSpec(Branch,outDir)
    Row = emptyBranchRow();
    Row.branch = Branch.name;
    Row.status = "pending";
    Row.out_dir = string(outDir);
    Row.query_mode = Branch.queryMode;
    Row.gan_iter = double(Branch.ganIter);
    Row.z_dim = double(Branch.zDim);
    Row.n_critic = double(Branch.nCritic);
    Row.sample_z_mode = Branch.sampleZMode;
    Row.train_z_mode = Branch.trainZMode;
    Row.sigma = double(Branch.sigma);
    Row.train_sigma = doubleOrNaN(Branch.trainSigma);
    Row.sample_sigma = doubleOrNaN(Branch.sampleSigma);
    Row.gan_iter_schedule = Branch.ganIterSchedule;
    Row.gan_iter_start = doubleOrNaN(Branch.ganIterStart);
    Row.gan_iter_end = doubleOrNaN(Branch.ganIterEnd);
    Row.prescreen_multiplier = double(Branch.prescreenMultiplier);
    Row.bmem_band_mode = Branch.bmemBandMode;
    if isempty(Branch.bandMaxAnchorsPerRef)
        Row.band_max_anchors_per_ref = NaN;
    else
        Row.band_max_anchors_per_ref = double(Branch.bandMaxAnchorsPerRef);
    end
end

function yes = branchComplete(outDir,problemCount,runCount,stageCount)
    summaryFile = fullfile(outDir,'run_summary.csv');
    stageFile = fullfile(outDir,'stage_snapshots_all.csv');
    yes = isfile(summaryFile) && isfile(stageFile) && ...
        countTableRows(summaryFile) == problemCount*runCount && ...
        countOkRunRows(summaryFile) == problemCount*runCount && ...
        countTableRows(stageFile) == problemCount*stageCount;
end

function Row = fillBranchCounts(Row,outDir)
    Row.run_count = countTableRows(fullfile(outDir,'run_summary.csv'));
    Row.ok_run_count = countOkRunRows(fullfile(outDir,'run_summary.csv'));
    Row.stage_snapshot_count = countTableRows(fullfile(outDir, ...
        'stage_snapshots_all.csv'));
    Row.figure_count = numel(dir(fullfile(outDir,'domain_figures_all', ...
        '*domain_boundary.png')));
end

function n = countTableRows(file)
    n = 0;
    if ~isfile(file)
        return;
    end
    fid = fopen(file,'r');
    cleanup = onCleanup(@()fclose(fid));
    while true
        line = fgetl(fid);
        if ~ischar(line)
            break;
        end
        if strlength(string(strtrim(line))) > 0
            n = n + 1;
        end
    end
    n = max(0,n - 1);
end

function n = countOkRunRows(file)
    n = 0;
    if ~isfile(file)
        return;
    end
    fid = fopen(file,'r');
    cleanup = onCleanup(@()fclose(fid));
    header = fgetl(fid);
    if ~ischar(header)
        return;
    end
    names = split(string(header),",");
    statusIdx = find(strcmpi(names,"status"),1);
    if isempty(statusIdx)
        statusIdx = 11;
    end
    while true
        line = fgetl(fid);
        if ~ischar(line)
            break;
        end
        parts = split(string(line),",");
        if numel(parts) >= statusIdx && parts(statusIdx) == "ok"
            n = n + 1;
        end
    end
end

