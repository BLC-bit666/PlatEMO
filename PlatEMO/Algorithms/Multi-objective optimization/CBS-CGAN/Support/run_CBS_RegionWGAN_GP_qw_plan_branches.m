        'train_z_mode',"", ...
        'sigma',NaN, ...
        'train_sigma',NaN, ...
        'sample_sigma',NaN, ...
        'gan_iter_schedule',"", ...
        'gan_iter_start',NaN, ...
        'gan_iter_end',NaN, ...
        'prescreen_multiplier',NaN, ...
        'bmem_band_mode',"", ...
        'band_max_anchors_per_ref',NaN, ...
        'run_count',0, ...
        'ok_run_count',0, ...
        'stage_snapshot_count',0, ...
        'figure_count',0, ...
        'error_message',"");
end

function value = doubleOrNaN(x)
    if isempty(x)
        value = NaN;
    else
        value = double(x);
        if isempty(value) || ~isfinite(value(1))
            value = NaN;
        else
            value = value(1);
        end
    end
end
