function BranchSummary = run_CBS_RegionWGAN_GP_qw_plan_branches( ...
        rootOutDir,stageName,branchNames,workerCount)
%RUN_CBS_REGIONWGAN_GP_QW_PLAN_BRANCHES Run no-figure Query/WGAN branches.
%   All branches use: LIRCMOP5_BC..LIRCMOP10_BC, runs=1:3, N=100,
%   default D, maxFE=100000, workerCount workers, capture run=3 stage
%   snapshots at [10000 30000 50000 70000 100000], and draw no figures.

    repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    addpath(genpath(repoRoot));
    if nargin < 1 || isempty(rootOutDir)
        rootOutDir = fullfile(repoRoot,'Data','CBS_RegionGAN_compare', ...
            ['qw_plan_noplot_',char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
    end
    if nargin < 2 || isempty(stageName)
        stageName = "stage1";
    end
    if nargin < 3 || isempty(branchNames)
        branchNames = ["baseline_random_iter50", ...
            "query_boundary_iter50", ...
            "random_iter100", ...
            "query_boundary_iter100"];
    end
    if nargin < 4 || isempty(workerCount)
        workerCount = 8;
    end

    stageName = string(stageName);
    branchNames = string(branchNames(:)');
    stageDir = fullfile(rootOutDir,char(stageName));
    if ~isfolder(stageDir)
        mkdir(stageDir);
    end

    problems = ["LIRCMOP5_BC";"LIRCMOP6_BC";"LIRCMOP7_BC"; ...
        "LIRCMOP8_BC";"LIRCMOP9_BC";"LIRCMOP10_BC"];
    stageTargets = [10000 30000 50000 70000 100000];
    runIds = 1 : 3;
    N = 100;
    D = [];
    maxFE = 100000;

    Branches = branchSpecs();
    Rows = repmat(emptyBranchRow(),numel(branchNames),1);
    for i = 1 : numel(branchNames)
        name = branchNames(i);
        if ~isfield(Branches,char(name))
            error('CBSRegionWGAN:UnknownQWBranch', ...
                'Unknown Query/WGAN branch: %s.',name);
        end
        Branch = Branches.(char(name));
        outDir = fullfile(stageDir,char(name));
        Rows(i) = branchRowFromSpec(Branch,outDir);
        if branchComplete(outDir,numel(problems),numel(runIds), ...
                numel(stageTargets))
            Rows(i).status = "skipped_complete";
            Rows(i) = fillBranchCounts(Rows(i),outDir);
            fprintf('[%s %d/%d] %s already complete, skipped.\n', ...
                char(stageName),i,numel(branchNames),char(name));
            continue;
        end
        fprintf('[%s %d/%d] running %s -> %s\n',char(stageName),i, ...
            numel(branchNames),char(name),outDir);
        try
            Options = struct( ...
                'algorithmClass',"CBS_RegionWGAN_GP", ...
                'queryMode',Branch.queryMode, ...
                'prevBMemMode',"prev1_fair_union", ...
                'bmemBandMode',Branch.bmemBandMode, ...
                'bandMaxAnchorsPerRef',Branch.bandMaxAnchorsPerRef, ...
                'captureRun',3, ...
                'plotRun',0, ...
                'drawFigures',false, ...
                'stageTargets',stageTargets, ...
                'algorithmParams',{wganParams(Branch)}, ...
                'sampleZMode',Branch.sampleZMode, ...
                'trainZMode',Branch.trainZMode, ...
                'sigma',Branch.sigma, ...
                'trainSigma',Branch.trainSigma, ...
                'sampleSigma',Branch.sampleSigma, ...
                'ganIterSchedule',Branch.ganIterSchedule, ...
                'ganIterStart',Branch.ganIterStart, ...
                'ganIterEnd',Branch.ganIterEnd, ...
                'prescreenMultiplier',Branch.prescreenMultiplier);
            run_CBS_RegionCGAN_training_diagnostics(outDir,workerCount, ...
                problems,N,D,maxFE,runIds,Options);
            Rows(i).status = "ok";
            Rows(i) = fillBranchCounts(Rows(i),outDir);
        catch err
            Rows(i).status = "failed";
            Rows(i).error_message = string(getReport(err,'extended', ...
                'hyperlinks','off'));
            fprintf('[%s %d/%d] %s failed:\n%s\n',char(stageName),i, ...
                numel(branchNames),char(name),char(Rows(i).error_message));
        end
        BranchSummary = struct2table(Rows);
        writetable(BranchSummary,fullfile(stageDir,'branch_summary.csv'));
    end
    BranchSummary = struct2table(Rows);
    writetable(BranchSummary,fullfile(stageDir,'branch_summary.csv'));
    fprintf('Query/WGAN branches written to: %s\n',stageDir);
end

