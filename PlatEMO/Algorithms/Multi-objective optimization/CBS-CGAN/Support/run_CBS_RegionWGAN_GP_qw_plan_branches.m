function S = withFields(Base,name,queryMode,ganIter,nCritic)
    S = Base;
    S.name = string(name);
    S.queryMode = string(queryMode);
    S.ganIter = double(ganIter);
    S.nCritic = double(nCritic);
end

function S = withBMemFields(Base,name,queryMode,ganIter,nCritic, ...
        bmemBandMode,bandMaxAnchorsPerRef)
    S = withFields(Base,name,queryMode,ganIter,nCritic);
    S.bmemBandMode = string(bmemBandMode);
    S.bandMaxAnchorsPerRef = bandMaxAnchorsPerRef;
end

function S = withLinearIter(Base,name,queryMode)
    S = withFields(Base,name,queryMode,Base.ganIter,Base.nCritic);
    S.ganIterSchedule = "linear_fe";
    S.ganIterStart = 150;
    S.ganIterEnd = 30;
end

function S = withLinearIterZ(Base,name,sampleZMode,sigma,zDim)
    S = withLinearIter(Base,name,"boundary_populated");
    S.sampleZMode = string(sampleZMode);
    S.trainSigma = 1.0;
    S.sampleSigma = double(sigma);
    S.zDim = max(1,round(double(zDim)));
end

function S = withFixedIterZ(Base,name,queryMode,ganIter,sampleZMode, ...
        sampleSigma,zDim)
    S = withFields(Base,name,queryMode,ganIter,Base.nCritic);
    S.trainZMode = "random";
    S.sampleZMode = string(sampleZMode);
    S.trainSigma = 1.0;
    if isempty(sampleSigma)
        S.sampleSigma = [];
    else
        S.sampleSigma = double(sampleSigma);
    end
    S.zDim = max(1,round(double(zDim)));
end

