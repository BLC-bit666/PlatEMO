function T = collectDiagnosticTables(files,emptyRow)
    files = string(files(:));
    Schema = struct2table(repmat(emptyRow,0,1));
    Tables = {};
    for i = 1 : numel(files)
        if strlength(files(i)) > 0 && isfile(files(i))
            Ti = readtable(files(i),'TextType','string', ...
                'Delimiter',',','ReadVariableNames',true, ...
                'VariableNamingRule','preserve');
            Tables{end+1,1} = alignTableToSchema(Ti,Schema,emptyRow); %#ok<AGROW>
        end
    end
    if isempty(Tables)
        T = Schema;
    else
        T = vertcat(Tables{:});
    end
end

function T = collectHomogeneousDiagnosticTables(files)
    files = string(files(:));
    Tables = cell(0,1);
    schema = strings(0,1);
    for i = 1 : numel(files)
        if strlength(files(i)) == 0 || ~isfile(files(i))
            continue;
        end
        Ti = readtable(files(i),'TextType','string', ...
            'Delimiter',',','ReadVariableNames',true, ...
            'VariableNamingRule','preserve');
        current = string(Ti.Properties.VariableNames);
        if isempty(schema)
            schema = current;
        elseif ~isequal(current,schema)
            error('CBSRegionDiagnostics:InconsistentBMemSchema', ...
                'BMem diagnostic CSV schemas differ across runs.');
        end
        Tables{end+1,1} = Ti; %#ok<AGROW>
    end
    if isempty(Tables)
        T = table();
    else
        T = vertcat(Tables{:});
    end
end

function T = alignTableToSchema(T,Schema,emptyRow)
    schemaNames = string(Schema.Properties.VariableNames);
    if height(T) == 0
        T = Schema;
        return;
    end
    currentNames = string(T.Properties.VariableNames);
    for i = 1 : numel(schemaNames)
        name = schemaNames(i);
        if ~ismember(name,currentNames)
            T.(name) = defaultTableColumn(emptyRow.(name),height(T));
        end
    end
    extra = setdiff(string(T.Properties.VariableNames),schemaNames, ...
        'stable');
    if ~isempty(extra)
        T(:,cellstr(extra)) = [];
    end
    T = T(:,cellstr(schemaNames));
end

function col = defaultTableColumn(value,n)
    if isstring(value)
        col = repmat(string(value),n,1);
    elseif ischar(value)
        col = repmat(string(value),n,1);
    elseif islogical(value)
        col = false(n,1);
    else
        col = NaN(n,1);
    end
end

