function [Summary,EventSummaryAll,TrainHistoryAll,outDir, ...
    StageSnapshotsAll] = run_CBS_RegionWGAN_GP_mainline( ...
    outDir,workerCount, ...
    problemNames,N,D,maxFE,runIds,Options)
%RUN_CBS_REGIONWGAN_GP_MAINLINE Run the sole CBS RegionWGAN-GP mainline.
%   The runner is intentionally non-visual. It records reproducibility,
%   training, boundary geometry, query attribution, and final populations.

    rootDir = locateRootDir();
    addpath(genpath(rootDir));
    if nargin < 1 || isempty(outDir)
        outDir = fullfile(rootDir,'Data','CBS_RegionGAN_compare', ...
            ['mainline_', ...
            char(datetime('now','Format','yyyyMMdd_HHmmss'))]);
    end
    if nargin < 2 || isempty(workerCount)
        workerCount = 10;
    end
    if nargin < 3 || isempty(problemNames)
        problemNames = ["LIRCMOP5_BC";"LIRCMOP6_BC";"LIRCMOP7_BC"; ...
            "LIRCMOP8_BC";"LIRCMOP9_BC";"LIRCMOP10_BC"];
    end
    if nargin < 4 || isempty(N)
        N = 100;
    end
    if nargin < 5
        D = [];
    end
    if nargin < 6 || isempty(maxFE)
        maxFE = 100000;
    end
    if nargin < 7 || isempty(runIds)
        runIds = 1 : 3;
    end
    if nargin < 8 || isempty(Options)
        Options = struct();
    end
    Options = normalizeDiagnosticOptions(Options);

    workerCount = max(1,round(double(workerCount)));
    if ischar(problemNames)
        problemNames = string(problemNames);
    else
        problemNames = string(problemNames(:));
    end
    runIds = double(runIds(:)');
    N = max(1,round(double(N)));
    maxFE = max(1,round(double(maxFE)));

    if ~isfolder(outDir)
        mkdir(outDir);
    end
    Provenance = CBS_RegionGAN_Provenance(rootDir,Options,workerCount);
    writetable(provenanceScalarTable(Provenance), ...
        fullfile(outDir,'provenance.csv'));
    writetable(Provenance.source_manifest, ...
        fullfile(outDir,'source_manifest.csv'));
    Tasks = buildDiagnosticTasks(problemNames,runIds);
    taskCount = height(Tasks);
    taskProblems = Tasks.problem;
    taskRuns = Tasks.run;
    Rows = repmat(emptyRunRow(),taskCount,1);

    if workerCount > 1
        ensureDiagnosticParallelPool(workerCount);
        doneCount = 0;
        progressQueue = parallel.pool.DataQueue;
        afterEach(progressQueue,@reportProgress);
        parfor task = 1 : taskCount
            Rows(task) = runOneDiagnosticTask(taskProblems(task), ...
                taskRuns(task),outDir,N,D,maxFE,Options,Provenance);
            send(progressQueue,Rows(task));
        end
    else
        for task = 1 : taskCount
            Rows(task) = runOneDiagnosticTask(taskProblems(task), ...
                taskRuns(task),outDir,N,D,maxFE,Options,Provenance);
            fprintf('[%d/%d] %s run=%d status=%s\n',task,taskCount, ...
                char(Rows(task).problem),Rows(task).run,char(Rows(task).status));
        end
    end

    Summary = struct2table(Rows);
    writetable(Summary,fullfile(outDir,'run_summary.csv'));
    EventSummaryAll = collectDiagnosticTables( ...
        Summary.event_summary_file,emptyEventRow());
    writetable(EventSummaryAll,fullfile(outDir,'event_summary_all.csv'));
    TrainHistoryAll = collectDiagnosticTables( ...
        Summary.train_history_file,emptyTrainRow());
    writetable(TrainHistoryAll,fullfile(outDir,'train_history_all.csv'));
    StageSnapshotsAll = collectDiagnosticTables( ...
        Summary.stage_snapshot_file,emptyStageSnapshotRow());
    writetable(StageSnapshotsAll,fullfile(outDir,'stage_snapshots_all.csv'));
    BMemHistoryAll = collectHomogeneousDiagnosticTables( ...
        Summary.bmem_history_file);
    writetable(BMemHistoryAll,fullfile(outDir,'bmem_history_all.csv'));
    BMemRefHistoryAll = collectHomogeneousDiagnosticTables( ...
        Summary.bmem_ref_history_file);
    writetable(BMemRefHistoryAll, ...
        fullfile(outDir,'bmem_ref_history_all.csv'));
    LatentScaleRefHistoryAll = collectHomogeneousDiagnosticTables( ...
        Summary.latent_scale_ref_history_file);
    writetable(LatentScaleRefHistoryAll, ...
        fullfile(outDir,'latent_scale_ref_history_all.csv'));

    function reportProgress(Row)
        doneCount = doneCount + 1;
        fprintf('[%d/%d] %s run=%d status=%s\n',doneCount,taskCount, ...
            char(Row.problem),Row.run,char(Row.status));
    end
end

function rootDir = locateRootDir()
    rootDir = fileparts(which('platemo'));
    if isempty(rootDir)
        rootDir = pwd;
    end
end

function Options = normalizeDiagnosticOptions(Options)
    Options = defaultOption(Options,'algorithmParams',{});
    Options = defaultOption(Options,'captureRun',0);
    Options = defaultOption(Options,'stageTargets',[]);
    Options = defaultOption(Options,'captureWGANTrainHistory',false);
    Options = defaultOption(Options,'wganMappingDiagnostics',false);
    Options = defaultOption(Options,'bmemLearnabilityDiagnostics',false);
    Options = defaultOption(Options,'bmemMode',"legacy");
    Options = defaultOption(Options,'trainDedupMode',"off");
    Options = defaultOption(Options,'mappingDiagMaxConditions',8);
    Options = defaultOption(Options,'mappingDiagZSamples',8);
    Options = defaultOption(Options,'structuredZMode',"off");
    Options = defaultOption(Options,'structuredZMaxModes',5);
    Options = defaultOption(Options,'structuredZLambda',1.0);
    Options = defaultOption(Options,'schemaVersion', ...
        "cbs_region_wgan_mainline_v1");
    Options.captureRun = unique(round(double(Options.captureRun(:)')), ...
        'stable');
    Options.stageTargets = double(Options.stageTargets(:)');
    Options.captureWGANTrainHistory = logical( ...
        Options.captureWGANTrainHistory);
    Options.wganMappingDiagnostics = logical( ...
        Options.wganMappingDiagnostics);
    Options.bmemLearnabilityDiagnostics = logical( ...
        Options.bmemLearnabilityDiagnostics);
    Options.bmemMode = lower(strip(string(Options.bmemMode)));
    if ~isscalar(Options.bmemMode) || ...
            ~ismember(Options.bmemMode,["legacy","coherent"])
        error('CBSRegionGAN:BadBMemMode', ...
            'Options.bmemMode must be "legacy" or "coherent".');
    end
    Options.trainDedupMode = lower(strip(string(Options.trainDedupMode)));
    if ~isscalar(Options.trainDedupMode) || ...
            ~ismember(Options.trainDedupMode,["off","exact_ref_x"])
        error('CBSRegionGAN:BadTrainDedupMode', ...
            'Options.trainDedupMode must be "off" or "exact_ref_x".');
    end
    Options.mappingDiagMaxConditions = max(1,round(double( ...
        Options.mappingDiagMaxConditions)));
    Options.mappingDiagZSamples = max(2,round(double( ...
        Options.mappingDiagZSamples)));
    Options.structuredZMode = lower(strip(string( ...
        Options.structuredZMode)));
    if ~isscalar(Options.structuredZMode) || ...
            ~ismember(Options.structuredZMode,["off","categorical_mi"])
        error('CBSRegionGAN:BadStructuredZMode', ...
            'Options.structuredZMode must be "off" or "categorical_mi".');
    end
    Options.structuredZMaxModes = max(1,round(double( ...
        Options.structuredZMaxModes)));
    Options.structuredZLambda = double(Options.structuredZLambda);
    if ~isscalar(Options.structuredZLambda) || ...
            ~isfinite(Options.structuredZLambda) || ...
            Options.structuredZLambda < 0
        error('CBSRegionGAN:BadStructuredZLambda', ...
            'Options.structuredZLambda must be finite and nonnegative.');
    end
    Options.schemaVersion = string(Options.schemaVersion);
end

function S = defaultOption(S,name,value)
    if ~isfield(S,name) || isempty(S.(name))
        S.(name) = value;
    end
end

function Tasks = buildDiagnosticTasks(problemNames,runIds)
    Rows = repmat(struct('problem',"",'run',NaN), ...
        numel(problemNames)*numel(runIds),1);
    row = 0;
    for p = 1 : numel(problemNames)
        for r = 1 : numel(runIds)
            row = row + 1;
            Rows(row).problem = problemNames(p);
            Rows(row).run = runIds(r);
        end
    end
    Tasks = struct2table(Rows);
end

function Row = runOneDiagnosticTask(problemName,runId,outDir,N,D,maxFE, ...
        Options,Provenance)
    Row = emptyRunRow();
    Row.problem = string(problemName);
    Row.run = double(runId);
    Row.seed = double(runId);
    Row.N = double(N);
    Row.maxFE = double(maxFE);
    Row.schema_version = string(Provenance.schema_version);
    Row.git_sha = string(Provenance.git_sha);
    Row.git_branch = string(Provenance.git_branch);
    Row.git_dirty = double(Provenance.git_dirty);
    Row.source_tree_sha256 = string(Provenance.source_tree_sha256);
    try
        rootDir = locateRootDir();
        addpath(genpath(rootDir));
        try
            maxNumCompThreads(1);
        catch
        end
        rng(Row.seed,'twister');
        ProblemConstructor = str2func(char(Row.problem));
        if isempty(D)
            Problem = ProblemConstructor('N',N,'maxFE',maxFE);
        else
            Problem = ProblemConstructor('N',N,'D',D,'maxFE',maxFE);
        end
        Row.D = double(Problem.D);
        Row.M = double(Problem.M);
        runFolder = fullfile(outDir,sprintf('%s_run%d', ...
            char(Row.problem),round(Row.run)));
        if ~isfolder(runFolder)
            mkdir(runFolder);
        end
        Row.run_folder = string(runFolder);
        Row.metric_file = string(fullfile(runFolder,'metric.mat'));
        Row.event_summary_file = string(fullfile(runFolder, ...
            'event_summary.csv'));
        Row.train_history_file = string(fullfile(runFolder, ...
            'train_history.csv'));
        Row.bmem_history_file = string(fullfile(runFolder, ...
            'bmem_history.csv'));
        Row.bmem_ref_history_file = string(fullfile(runFolder, ...
            'bmem_ref_history.csv'));
        Row.latent_scale_ref_history_file = string(fullfile(runFolder, ...
            'latent_scale_ref_history.csv'));
        Row.stage_snapshot_file = string(fullfile(runFolder, ...
            'stage_snapshots.csv'));
        Row.final_p1_file = string(fullfile(runFolder,'final_p1.csv'));
        Row.final_p2_file = string(fullfile(runFolder,'final_p2.csv'));
        Row.final_feasible_nd_file = string(fullfile(runFolder, ...
            'final_feasible_nd.csv'));
        Row.query_samples_file = string(fullfile(runFolder, ...
            'query_samples.csv'));
        Row.query_ref_exposure_file = string(fullfile(runFolder, ...
            'query_ref_exposure.csv'));
        Row.query_ref_conversion_file = string(fullfile(runFolder, ...
            'query_ref_conversion.csv'));
        Row.gan_bmem_eligible_samples_file = string(fullfile(runFolder, ...
            'gan_bmem_eligible_samples.csv'));
        Row.direct_gan_bmem_entry_file = string(fullfile(runFolder, ...
            'direct_gan_bmem_entry.csv'));
        Row.provenance_file = string(fullfile(runFolder,'provenance.csv'));
        Row.source_manifest_file = string(fullfile(runFolder, ...
            'source_manifest.csv'));

        Control = struct( ...
            'stageTargets',[], ...
            'captureWGANTrainHistory', ...
                Options.captureWGANTrainHistory, ...
            'wganMappingDiagnostics',Options.wganMappingDiagnostics, ...
            'bmemLearnabilityDiagnostics', ...
                Options.bmemLearnabilityDiagnostics, ...
            'bmemMode',Options.bmemMode, ...
            'trainDedupMode',Options.trainDedupMode, ...
            'mappingDiagMaxConditions', ...
                Options.mappingDiagMaxConditions, ...
            'mappingDiagZSamples',Options.mappingDiagZSamples);
        Control.structuredZMode = Options.structuredZMode;
        Control.structuredZMaxModes = Options.structuredZMaxModes;
        Control.structuredZLambda = Options.structuredZLambda;
        if ismember(Row.run,Options.captureRun)
            Control.stageTargets = Options.stageTargets;
        end
        setappdata(0,'CBS_RegionGAN_ExperimentControl',Control);
        cleanupControl = onCleanup(@()removeRegionGANExperimentControl());
        if isempty(Options.algorithmParams)
            Algorithm = CBS_RegionWGAN_GP('save',0,'run',Row.run, ...
                'outputFcn',@(varargin)[]);
        else
            Algorithm = CBS_RegionWGAN_GP('save',0,'run',Row.run, ...
                'outputFcn',@(varargin)[], ...
                'parameter',Options.algorithmParams);
        end
        Algorithm.Solve(Problem);
        clear cleanupControl

        Row.runtime = double(Algorithm.metric.runtime);
        Row.finalFE = double(Algorithm.result{end,1});
        metric = Algorithm.metric;
        [Final,Tracker,QuerySamples] = regionAttributionExports(metric);
        exportFinalPopulationTables(Final,Row);
        exportTrackerTables(Tracker,QuerySamples,Row,size(Final.p1_dec,2));
        writetable(provenanceScalarTable(Provenance),Row.provenance_file);
        writetable(Provenance.source_manifest,Row.source_manifest_file);
        Row.query_sample_row_count = size(QuerySamples.rows,1);
        Row.ref_exposure_row_count = numel(Tracker.ref_exposure);
        Row.ref_conversion_row_count = numel(Tracker.ref_conversions);
        Row.gan_bmem_eligible_sample_row_count = numel(Tracker.samples);
        Row.direct_bmem_entry_row_count = numel(Tracker.direct_entries);
        problem = Row.problem;
        run = Row.run;
        seed = Row.seed;
        provenance = Provenance;
        source_manifest = Provenance.source_manifest;
        save(Row.metric_file,'metric','problem','run','seed','N','maxFE', ...
            'provenance','source_manifest');

        if isfield(Algorithm.metric,'region_gan_history')
            History = Algorithm.metric.region_gan_history;
        elseif isfield(Algorithm.metric,'region_wgan_gp_history')
            History = Algorithm.metric.region_wgan_gp_history;
        elseif isfield(Algorithm.metric,'region_cgan_history')
            History = Algorithm.metric.region_cgan_history;
        else
            History = struct([]);
        end
        [EventSummary,TrainHistory] = buildDiagnosticTables(History,Row);
        writetable(EventSummary,Row.event_summary_file);
        writetable(TrainHistory,Row.train_history_file);
        Row.event_count = height(EventSummary);
        Row.train_row_count = height(TrainHistory);
        BMemHistory = getMetricCellHistory( ...
            metric,'region_gan_bmem_history');
        BMemHistoryTable = regionBMemHistoryTable(BMemHistory,Row);
        writetable(BMemHistoryTable,Row.bmem_history_file);
        Row.bmem_history_row_count = height(BMemHistoryTable);
        BMemRefHistory = getMetricCellHistory( ...
            metric,'region_gan_bmem_ref_history');
        BMemRefHistoryTable = regionBMemRefHistoryTable( ...
            BMemRefHistory,Row);
        writetable(BMemRefHistoryTable,Row.bmem_ref_history_file);
        Row.bmem_ref_history_row_count = height(BMemRefHistoryTable);
        LatentScaleRefHistory = getMetricCellHistory( ...
            metric,'region_gan_latent_scale_ref_history');
        LatentScaleRefHistoryTable = regionLatentScaleRefHistoryTable( ...
            LatentScaleRefHistory,Row);
        writetable(LatentScaleRefHistoryTable, ...
            Row.latent_scale_ref_history_file);
        Row.latent_scale_ref_history_row_count = ...
            height(LatentScaleRefHistoryTable);
        if isfield(Algorithm.metric,'region_gan_stage_snapshots')
            Snapshots = Algorithm.metric.region_gan_stage_snapshots;
        else
            Snapshots = emptyRegionStageSnapshotStruct();
        end
        StageSnapshots = regionStageSnapshotTable(Snapshots,Row);
        writetable(StageSnapshots,Row.stage_snapshot_file);
        Row.status = "ok";
    catch err
        removeRegionGANExperimentControl();
        Row.status = "failed";
        Row.error_message = string(getReport(err,'extended', ...
            'hyperlinks','off'));
    end
end

function removeRegionGANExperimentControl()
    if isappdata(0,'CBS_RegionGAN_ExperimentControl')
        rmappdata(0,'CBS_RegionGAN_ExperimentControl');
    end
end

function T = provenanceScalarTable(P)
    T = table( ...
        string(P.schema_version),string(P.git_sha), ...
        string(P.git_branch),logical(P.git_dirty), ...
        string(P.matlab_release),string(P.host), ...
        double(P.worker_count),string(P.options_json), ...
        string(P.source_tree_sha256), ...
        'VariableNames',{'schema_version','git_sha','git_branch', ...
            'git_dirty','matlab_release','host','worker_count', ...
            'options_json','source_tree_sha256'});
end

function [Final,Tracker,QuerySamples] = regionAttributionExports(metric)
    if ~isstruct(metric) || ~isfield(metric,'region_gan_final') || ...
            ~isfield(metric,'region_gan_query_tracker') || ...
            ~isfield(metric,'region_gan_query_samples')
        error('CBSRegionDiagnostics:MissingAttributionMetric', ...
            'Algorithm metric is missing final, tracker, or query samples.');
    end
    Final = metric.region_gan_final;
    Tracker = metric.region_gan_query_tracker;
    QuerySamples = metric.region_gan_query_samples;
end

function exportFinalPopulationTables(Final,Row)
    writetable(populationArraysTable( ...
        Final.p1_dec,Final.p1_obj,Final.p1_con),Row.final_p1_file);
    writetable(populationArraysTable( ...
        Final.p2_dec,Final.p2_obj,Final.p2_con),Row.final_p2_file);
    writetable(populationArraysTable(Final.p1_feasible_nd_dec, ...
        Final.p1_feasible_nd_obj,Final.p1_feasible_nd_con), ...
        Row.final_feasible_nd_file);
end

function T = populationArraysTable(Dec,Obj,Con)
    Dec = double(Dec);
    Obj = double(Obj);
    Con = double(Con);
    n = size(Dec,1);
    if size(Obj,1) ~= n || size(Con,1) ~= n
        error('CBSRegionDiagnostics:BadFinalPopulationRows', ...
            'Decision, objective, and constraint arrays must have equal rows.');
    end
    names = [indexedNames("x",size(Dec,2)), ...
        indexedNames("f",size(Obj,2)),indexedNames("c",size(Con,2))];
    T = array2table([Dec,Obj,Con],'VariableNames',cellstr(names));
end

function names = indexedNames(prefix,n)
    names = strings(1,n);
    for i = 1 : n
        names(i) = prefix + string(i);
    end
end

function exportTrackerTables(Tracker,QuerySamples,Row,D)
    required = {'ref_exposure','ref_conversions','samples','direct_entries'};
    if ~isstruct(Tracker) || ~all(isfield(Tracker,required))
        error('CBSRegionDiagnostics:BadTrackerExport', ...
            'Tracker export is missing required row sets.');
    end
    writetable(querySampleTable(QuerySamples),Row.query_samples_file);
    writetable(struct2table(Tracker.ref_exposure), ...
        Row.query_ref_exposure_file);
    writetable(struct2table(Tracker.ref_conversions), ...
        Row.query_ref_conversion_file);
    writetable(trackerSampleTable(Tracker.samples,D), ...
        Row.gan_bmem_eligible_samples_file);
    writetable(trackerSampleTable(Tracker.direct_entries,D), ...
        Row.direct_gan_bmem_entry_file);
end

function T = trackerSampleTable(Rows,D)
    T = struct2table(Rows);
    if ismember('decision',T.Properties.VariableNames)
        T.decision = [];
    end
    if isempty(Rows)
        Dec = zeros(0,D);
    else
        Dec = vertcat(Rows.decision);
    end
    if size(Dec,2) ~= D
        error('CBSRegionDiagnostics:BadTrackerDecisionColumns', ...
            'Tracker decisions must match final population dimension.');
    end
    DecisionTable = array2table(Dec, ...
        'VariableNames',cellstr(indexedNames("x",D)));
    T = [T,DecisionTable];
end

function T = querySampleTable(QuerySamples)
    if ~isstruct(QuerySamples) || ~isfield(QuerySamples,'columns') || ...
            ~isfield(QuerySamples,'rows')
        error('CBSRegionDiagnostics:BadQuerySampleExport', ...
            'Query sample export must contain columns and rows.');
    end
    names = string(QuerySamples.columns(:)');
    rows = double(QuerySamples.rows);
    if size(rows,2) ~= numel(names)
        error('CBSRegionDiagnostics:BadQuerySampleColumns', ...
            'Query sample rows must match exported column names.');
    end
    T = array2table(rows,'VariableNames',cellstr(names));
end

function History = getMetricCellHistory(metric,name)
    History = cell(0,1);
    if isstruct(metric) && isfield(metric,name) && ...
            iscell(metric.(name))
        History = metric.(name);
    end
end

function T = regionBMemHistoryTable(History,RunRow)
    D = max(0,round(double(RunRow.D)));
    M = max(0,round(double(RunRow.M)));
    total = 0;
    for s = 1 : numel(History)
        if isstruct(History{s}) && isfield(History{s},'bmem') && ...
                isstruct(History{s}.bmem) && ...
                isfield(History{s}.bmem,'x_f')
            total = total + size(History{s}.bmem.x_f,1);
        end
    end
    problem = repmat(string(RunRow.problem),total,1);
    run = repmat(double(RunRow.run),total,1);
    seed = repmat(double(RunRow.seed),total,1);
    snapshotIndex = zeros(total,1);
    generation = zeros(total,1);
    fe = zeros(total,1);
    bmemRow = zeros(total,1);
    sampleIdF = strings(total,1);
    sampleIdI = strings(total,1);
    pairId = strings(total,1);
    ref = zeros(total,1);
    gap = nan(total,1);
    sourceF = zeros(total,1);
    sourceLabelF = strings(total,1);
    ageF = zeros(total,1);
    frontRankF = nan(total,1);
    candidateRowF = nan(total,1);
    candidateRowI = nan(total,1);
    Xf = nan(total,D);
    Yf = nan(total,M);
    Xi = nan(total,D);
    Yi = nan(total,M);
    PairNormal = nan(total,M);
    idCache = containers.Map('KeyType','char','ValueType','char');
    row = 0;
    for s = 1 : numel(History)
        Snapshot = History{s};
        if ~isstruct(Snapshot) || ~isfield(Snapshot,'bmem') || ...
                ~isstruct(Snapshot.bmem) || ...
                ~isfield(Snapshot.bmem,'x_f')
            continue;
        end
        BMem = Snapshot.bmem;
        n = size(BMem.x_f,1);
        rows = row + (1:n);
        row = row + n;
        if n == 0
            continue;
        end
        snapshotIndex(rows) = s;
        generation(rows) = snapshotNumeric(Snapshot,'generation');
        fe(rows) = snapshotNumeric(Snapshot,'fe');
        bmemRow(rows) = (1:n)';
        ref(rows) = memoryNumericMatrix(BMem,'ref',n,1,NaN);
        gap(rows) = memoryNumericMatrix(BMem,'gap',n,1,NaN);
        sourceF(rows) = memoryNumericMatrix( ...
            BMem,'source_f',n,1,0);
        ageF(rows) = memoryNumericMatrix(BMem,'age_f',n,1,0);
        frontRankF(rows) = memoryNumericMatrix( ...
            BMem,'front_rank_f',n,1,NaN);
        candidateRowF(rows) = memoryNumericMatrix( ...
            BMem,'candidate_row_f',n,1,NaN);
        candidateRowI(rows) = memoryNumericMatrix( ...
            BMem,'candidate_row_i',n,1,NaN);
        Xf(rows,:) = memoryNumericMatrix(BMem,'x_f',n,D,NaN);
        Yf(rows,:) = memoryNumericMatrix(BMem,'y_f',n,M,NaN);
        Xi(rows,:) = memoryNumericMatrix(BMem,'x_i',n,D,NaN);
        Yi(rows,:) = memoryNumericMatrix(BMem,'y_i',n,M,NaN);
        PairNormal(rows,:) = memoryNumericMatrix( ...
            BMem,'pair_normal',n,M,NaN);
        for i = 1 : n
            outRow = rows(i);
            sampleIdF(outRow) = stableDecisionId(idCache,Xf(outRow,:));
            sampleIdI(outRow) = stableDecisionId(idCache,Xi(outRow,:));
            pairId(outRow) = sampleIdF(outRow) + ":" + ...
                sampleIdI(outRow);
            if sourceF(outRow) == 0
                sourceLabelF(outRow) = "current";
            else
                sourceLabelF(outRow) = "previous";
            end
        end
    end
    Base = table(problem,run,seed,snapshotIndex,generation,fe,bmemRow, ...
        sampleIdF,sampleIdI,pairId,ref,gap,sourceF,sourceLabelF, ...
        ageF,frontRankF,candidateRowF,candidateRowI, ...
        'VariableNames',{'problem','run','seed','snapshot_index', ...
        'generation','fe','bmem_row','sample_id_f','sample_id_i', ...
        'pair_id','ref','gap','source_f','source_label_f', ...
        'age_f','front_rank_f','candidate_row_f', ...
        'candidate_row_i'});
    T = [Base, ...
        array2table(Xf,'VariableNames',cellstr(indexedNames("x_f",D))), ...
        array2table(Yf,'VariableNames',cellstr(indexedNames("y_f",M))), ...
        array2table(Xi,'VariableNames',cellstr(indexedNames("x_i",D))), ...
        array2table(Yi,'VariableNames',cellstr(indexedNames("y_i",M))), ...
        array2table(PairNormal,'VariableNames', ...
            cellstr(indexedNames("pair_normal",M)))];
end

function T = regionBMemRefHistoryTable(History,RunRow)
    total = 0;
    for s = 1 : numel(History)
