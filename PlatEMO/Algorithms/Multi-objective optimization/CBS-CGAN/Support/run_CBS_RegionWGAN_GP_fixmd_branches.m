        'hypothesis',"", ...
        'query_mode',"", ...
        'train_gap',NaN, ...
        'gan_iter',NaN, ...
        'z_dim',NaN, ...
        'sample_sigma',NaN, ...
        'prescreen_multiplier',NaN, ...
        'train_trigger_mode',"", ...
        'train_trigger_delta',NaN, ...
        'gan_iter_schedule',"", ...
        'gan_iter_start',NaN, ...
        'gan_iter_end',NaN, ...
        'run_count',0, ...
        'ok_run_count',0, ...
        'stage_snapshot_count',0, ...
        'event_count',0, ...
        'error_message',"");
end
