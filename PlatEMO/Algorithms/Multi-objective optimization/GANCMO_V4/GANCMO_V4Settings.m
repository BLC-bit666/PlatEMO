function S = GANCMO_V4Settings(referenceCount)
% Fixed mainline settings. Joint-input generator noise is always Problem.D.
% Successful training enables CGAN; archive change controls continuation.
% main() supplies the actual direction count; no argument uses the common 100.
    if nargin<1; referenceCount=100; end
    S = struct('initialEpochs',1000,'updateEpochs',200,'maxContinuationGUpdates',1000, ...
        'generatorHidden',128,'criticHidden',128, ...
        'learningRate',.001,'noiseSigma',1, ...
        'criticSteps',2,'minimumDirections',8, ...
        'pairsPerDirection',5,'candidateCount',50*referenceCount,'endpointWeight',50, ...
        'referenceWeightScale',128);
end
