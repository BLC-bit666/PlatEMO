function Columns = composeMetricColumns(MetricNames)
    Columns = cell(1,2*numel(MetricNames));
    Columns(1:2:end) = strcat('mean_',MetricNames);
    Columns(2:2:end) = strcat('std_',MetricNames);
end

function value = meanFinite(values)
    values = finiteValues(values);
    if isempty(values)
        value = NaN;
    else
        value = mean(values);
    end
end

function value = stdFinite(values)
    values = finiteValues(values);
    if numel(values) < 2
        value = NaN;
    else
        value = std(values,0);
    end
end

function values = finiteValues(values)
    values = double(values);
    values = values(isfinite(values));
end
