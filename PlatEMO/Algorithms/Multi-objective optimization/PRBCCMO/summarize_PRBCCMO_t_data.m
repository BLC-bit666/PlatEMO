function [RunTable,ProblemTable,FamilyTable] = summarize_PRBCCMO_t_data(inputPath,outDir)
% Aggregate PRBCCMO_t runs using only the three core observations.

    if nargin < 1 || isempty(inputPath)
        rootDir = fileparts(which('platemo'));
        inputPath = fullfile(rootDir,'Data','PRBCCMO_t');
    end
    if nargin < 2 || isempty(outDir)
        outDir = inputPath;
    end
    if ~isfolder(outDir)
        mkdir(outDir);
    end

    runFolders = resolveRunFolders(inputPath);
    Summaries = cellfun(@summarize_PRBCCMO_t_run,runFolders,'UniformOutput',false);
    RunTable = struct2table([Summaries{:}]');
    writetable(RunTable,fullfile(outDir,'run_summary.csv'));

    ProblemTable = aggregateRunTable(RunTable,"problem");
    writetable(ProblemTable,fullfile(outDir,'problem_summary.csv'));

    FamilyTable = aggregateRunTable(RunTable,"family");
    writetable(FamilyTable,fullfile(outDir,'family_summary.csv'));
end

function runFolders = resolveRunFolders(inputPath)
    if ischar(inputPath) || (isstring(inputPath) && isscalar(inputPath))
        folder = char(string(inputPath));
        if isfolder(folder) && isfile(fullfile(folder,'core_metrics.csv'))
            runFolders = {folder};
            return;
        end
        assert(isfolder(folder), ...
            'summarize_PRBCCMO_t_data:MissingInputFolder', ...
            'Input path not found: %s', folder);
        dirs = dir(folder);
        dirs = dirs([dirs.isdir]);
        dirs = dirs(~ismember({dirs.name},{'.','..'}));
        candidates = fullfile({dirs.folder},{dirs.name});
        keep = cellfun(@(p)isfile(fullfile(p,'core_metrics.csv')),candidates);
        runFolders = reshape(candidates(keep),[],1);
    else
        folders = cellstr(string(inputPath(:)));
        keep = cellfun(@(p)isfolder(p) && isfile(fullfile(p,'core_metrics.csv')),folders);
        runFolders = folders(keep);
    end

    assert(~isempty(runFolders), ...
        'summarize_PRBCCMO_t_data:NoRunFolders', ...
        'No PRBCCMO_t core_metrics.csv run folders were found.');
end

function SummaryTable = aggregateRunTable(RunTable,groupField)
    Keys = unique(string(RunTable.(groupField)),'stable');
    MetricNames = aggregateMetricNames();
    Names = [cellstr(groupField),{'num_runs'},composeMetricColumns(MetricNames)];
    Types = [{'string'},repmat({'double'},1,numel(Names)-1)];
    SummaryTable = table('Size',[numel(Keys),numel(Names)], ...
        'VariableTypes',Types,'VariableNames',Names);

    for i = 1 : numel(Keys)
        Mask = string(RunTable.(groupField)) == Keys(i);
        SummaryTable.(char(groupField))(i) = Keys(i);
        SummaryTable.num_runs(i) = sum(Mask);
        col = 3;
        for m = 1 : numel(MetricNames)
            Values = RunTable.(MetricNames{m})(Mask);
            SummaryTable{i,col} = meanFinite(Values);
            SummaryTable{i,col+1} = stdFinite(Values);
            col = col + 2;
        end
    end
end

