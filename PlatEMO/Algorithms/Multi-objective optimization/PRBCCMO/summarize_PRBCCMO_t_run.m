function requireColumns(T,Names,filePath)
    Missing = setdiff(string(Names),string(T.Properties.VariableNames));
    assert(isempty(Missing), ...
        'summarize_PRBCCMO_t_run:MissingColumns', ...
        'Missing columns in %s: %s', filePath, strjoin(cellstr(Missing), ', '));
end

function value = scalarValue(T,Name)
    value = double(T.(Name)(1));
end

function value = lastFinite(values)
    values = finiteValues(values);
    if isempty(values)
        value = NaN;
    else
        value = values(end);
    end
end

function value = meanFinite(values)
    values = finiteValues(values);
    if isempty(values)
        value = NaN;
    else
        value = mean(values);
    end
end

function value = percentileFinite(values,p)
    values = sort(finiteValues(values));
    if isempty(values)
        value = NaN;
    else
        idx = max(1,min(numel(values),ceil(p/100*numel(values))));
        value = values(idx);
    end
end

function value = sumFinite(values)
    values = finiteValues(values);
    if isempty(values)
        value = 0;
    else
        value = sum(values);
    end
end

function rate = positiveRate(values)
    values = finiteValues(values);
    if isempty(values)
        rate = NaN;
    else
        rate = mean(values > 0);
    end
end

function values = finiteValues(values)
    values = double(values);
    values = values(isfinite(values));
end

function value = metaString(Meta,Name,Default)
    if hasColumns(Meta,{Name}) && height(Meta) > 0
        value = string(Meta.(Name)(1));
    else
        value = string(Default);
    end
end

function value = metaDouble(Meta,Name,Default)
    value = Default;
    if hasColumns(Meta,{Name}) && height(Meta) > 0
        raw = Meta.(Name);
        parsed = str2double(string(raw(1)));
        if ~isnan(parsed)
            value = parsed;
        elseif isnumeric(raw)
            value = double(raw(1));
        end
    end
end

function Flag = hasColumns(T,Names)
    Flag = all(ismember(string(Names),string(T.Properties.VariableNames)));
end

function T = numericizeTable(T)
    Names = T.Properties.VariableNames;
    for i = 1 : numel(Names)
        Value = T.(Names{i});
        if iscell(Value) || isstring(Value)
            Num = str2double(string(Value));
            if any(~isnan(Num))
                T.(Names{i}) = Num;
            end
        elseif islogical(Value)
            T.(Names{i}) = double(Value);
        end
    end
end
