function Summary = summarize_PRBCCMO_t_run(runFolder)
% Summarize one PRBCCMO_t run from the minimal core_metrics.csv contract.

    if nargin < 1 || isempty(runFolder)
        error('summarize_PRBCCMO_t_run:MissingRunFolder','runFolder is required.');
    end

    runFolder = char(string(runFolder));
    metaFile = fullfile(runFolder,'run_meta.csv');
    coreFile = fullfile(runFolder,'core_metrics.csv');
    assert(isfolder(runFolder) && isfile(metaFile) && isfile(coreFile), ...
        'summarize_PRBCCMO_t_run:MissingCsv', ...
        'Run folder must contain run_meta.csv and core_metrics.csv: %s', runFolder);

    Meta = readtable(metaFile,'TextType','string');
    Core = numericizeTable(readtable(coreFile,'TextType','string'));
    requireColumns(Core,coreMetricColumns(),coreFile);

    Summary = emptySummary(Meta,runFolder,metaFile,coreFile);
    if isempty(Core)
        return;
    end

    Last = Core(end,:);
    Trained = Core(Core.mlp_trained > 0,:);

    Summary.generation_count = height(Core);
    Summary.final_generation = scalarValue(Last,'generation');
    Summary.final_fe = scalarValue(Last,'fe');
    Summary.final_fe_ratio = scalarValue(Last,'fe_ratio');

    Summary.final_b_pair_count = scalarValue(Last,'b_pair_count');
    Summary.final_b_mean_pair_gap = scalarValue(Last,'b_mean_pair_gap');
    Summary.mean_b_mean_pair_gap = meanFinite(Core.b_mean_pair_gap);
    Summary.p90_b_mean_pair_gap = percentileFinite(Core.b_mean_pair_gap,90);
    Summary.final_b_p90_pair_gap = scalarValue(Last,'b_p90_pair_gap');
    Summary.final_b_mean_front_gap = scalarValue(Last,'b_mean_front_gap');
    Summary.mean_b_mean_front_gap = meanFinite(Core.b_mean_front_gap);
    Summary.final_b_mean_infeasible_boundary_dist = scalarValue(Last,'b_mean_infeasible_boundary_dist');
    Summary.mean_b_mean_infeasible_boundary_dist = meanFinite(Core.b_mean_infeasible_boundary_dist);
    Summary.final_b_p90_infeasible_boundary_dist = scalarValue(Last,'b_p90_infeasible_boundary_dist');
    Summary.final_b_max_infeasible_boundary_dist = scalarValue(Last,'b_max_infeasible_boundary_dist');
    Summary.final_b_far_infeasible_boundary_ratio = scalarValue(Last,'b_far_infeasible_boundary_ratio');
    Summary.mean_b_far_infeasible_boundary_ratio = meanFinite(Core.b_far_infeasible_boundary_ratio);
    Summary.final_b_inf_unconstrained_src_ratio = scalarValue(Last,'b_inf_unconstrained_src_ratio');
    Summary.mean_b_inf_unconstrained_src_ratio = meanFinite(Core.b_inf_unconstrained_src_ratio);
    Summary.final_b_overlap_popc_ratio = scalarValue(Last,'b_overlap_popc_ratio');
    Summary.mean_b_overlap_popc_ratio = meanFinite(Core.b_overlap_popc_ratio);
    Summary.final_b_overlap_popu_ratio = scalarValue(Last,'b_overlap_popu_ratio');
    Summary.mean_b_overlap_popu_ratio = meanFinite(Core.b_overlap_popu_ratio);
    Summary.final_b_inf_src_popu = scalarValue(Last,'b_inf_src_popu');
    Summary.final_b_inf_src_offu = scalarValue(Last,'b_inf_src_offu');
    Summary.final_b_inf_src_refinement = scalarValue(Last,'b_inf_src_refinement');
    Summary.final_b_active_sector_ratio = scalarValue(Last,'b_active_sector_ratio');
    Summary.mean_b_active_sector_ratio = meanFinite(Core.b_active_sector_ratio);
    Summary.mean_b_changed_pair_count = meanFinite(Core.b_changed_pair_count);
    Summary.mean_b_changed_pair_ratio = meanFinite(Core.b_changed_pair_ratio);
    Summary.mean_b_added_pair_count = meanFinite(Core.b_added_pair_count);
    Summary.mean_b_replaced_pair_count = meanFinite(Core.b_replaced_pair_count);
    Summary.mean_b_dropped_pair_count = meanFinite(Core.b_dropped_pair_count);
    Summary.mean_b_contracted_pair_count = meanFinite(Core.b_contracted_pair_count);
    Summary.mean_b_global_change_pair_ratio = meanFinite(Core.b_global_change_pair_ratio);
    Summary.mean_b_contraction_pair_ratio = meanFinite(Core.b_contraction_pair_ratio);

    Summary.mlp_due_events = sum(double(Core.mlp_due) > 0);
    Summary.mlp_can_train_events = sum(double(Core.mlp_can_train) > 0);
    Summary.mlp_trained_events = sum(double(Core.mlp_trained) > 0);
    Summary.mlp_degraded_events = sum(double(Core.mlp_degraded) > 0);
    Summary.final_mlp_train_acc = lastFinite(Trained.mlp_train_acc);
    Summary.mean_mlp_train_acc = meanFinite(Trained.mlp_train_acc);
    Summary.final_train_size = scalarValue(Last,'train_size');
    Summary.mean_train_size = meanFinite(Core.train_size);
    Summary.final_train_pos = scalarValue(Last,'train_pos');
    Summary.final_train_neg = scalarValue(Last,'train_neg');
    Summary.final_train_src_b = scalarValue(Last,'train_src_b');
    Summary.final_train_src_refinement = scalarValue(Last,'train_src_refinement');
    Summary.final_train_src_boundary_band = scalarValue(Last,'train_src_boundary_band');

    Summary.inf_pool_generations = sum(double(Core.inf_pool_size) > 0);
    Summary.inf_selection_generations = sum(double(Core.inf_selected) > 0);
    Summary.inf_selected_total = sumFinite(Core.inf_selected);
    Summary.mean_inf_pool_mean_prob = meanFinite(Core.inf_pool_mean_prob);
    Summary.mean_inf_selected_mean_prob = meanFinite(Core.inf_selected_mean_prob);
    Summary.mean_inf_prob_gain = meanFinite(Core.inf_prob_gain);
    Summary.pos_rate_inf_prob_gain = positiveRate(Core.inf_prob_gain);
    Summary.inf_carry_generations = sum(double(Core.inf_carry_selected) > 0);
    Summary.inf_carry_selected_total = sumFinite(Core.inf_carry_selected);
    Summary.mean_inf_carry_pool_mean_prob = meanFinite(Core.inf_carry_pool_mean_prob);
    Summary.mean_inf_carry_selected_mean_prob = meanFinite(Core.inf_carry_selected_mean_prob);
    Summary.mean_inf_carry_prob_gain = meanFinite(Core.inf_carry_prob_gain);
    Summary.pos_rate_inf_carry_prob_gain = positiveRate(Core.inf_carry_prob_gain);
end

