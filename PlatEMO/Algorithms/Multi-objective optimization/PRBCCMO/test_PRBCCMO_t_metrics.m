function test_PRBCCMO_t_metrics()
% Regression test for traced PRBCCMO_t boundary-band metrics and summaries.

    rootDir = fileparts(mfilename('fullpath'));
    repoDir = fileparts(fileparts(fileparts(rootDir)));
    addpath(genpath(repoDir));

    traceText = normalizeCode(fileread(fullfile(rootDir,'PRBCCMO_t.m')));
    requireContains(traceText, ...
        'Dataset.Source=Buffer.Source(Ranked);', ...
        'test_PRBCCMO_t_metrics:DatasetSourceTags', ...
        'PRBCCMO_t must preserve exact source tags in the boundary-band dataset.');
    requireContains(traceText, ...
        'Diag.src_b=sum(Dataset.Source==1);', ...
        'test_PRBCCMO_t_metrics:ExactSrcB', ...
        'src_b must be counted from dataset source tags.');
    requireContains(traceText, ...
        'Diag.src_recent_boundary=sum(Dataset.Source==2);', ...
        'test_PRBCCMO_t_metrics:ExactSrcRecent', ...
        'src_recent_boundary must be counted from dataset source tags.');
    requireContains(traceText, ...
        'Diag.src_boundary_evidence=Diag.src_recent_boundary;', ...
        'test_PRBCCMO_t_metrics:ExactSrcBoundaryEvidence', ...
        'src_boundary_evidence must explicitly mirror source-2 evaluated boundary evidence.');
    requireContains(traceText, ...
        'Diag.src_pop_c=sum(Dataset.Source==3);', ...
        'test_PRBCCMO_t_metrics:ExactSrcPopC', ...
        'src_pop_c must be counted from dataset source tags.');
    requireContains(traceText, ...
        'Diag.src_pop_u=sum(Dataset.Source==4);', ...
        'test_PRBCCMO_t_metrics:ExactSrcPopU', ...
        'src_pop_u must be counted from dataset source tags.');
    requireContains(traceText, ...
        'Diag.mean_opp_dist=MeanOrNaN(Dataset.OppDist);', ...
        'test_PRBCCMO_t_metrics:BoundaryBandDistanceMetric', ...
        'Training distance diagnostics must summarize boundary-band opposite distances.');
    requireContains(traceText, ...
        'Stats.margin_oppdist_corr=SafeCorr(Meta.margin,OppDist);', ...
        'test_PRBCCMO_t_metrics:BoundaryFitCorrelation', ...
        'Traced metrics must record whether MLP margin tracks opposite-side boundary distance.');
    requireContains(traceText, ...
        'RootEvidence=BuildSegmentRootEvidence(', ...
        'test_PRBCCMO_t_metrics:SegmentRootEvidenceBuilder', ...
        'Traced diagnostics must build segment-root evidence from local boundary pairs.');
    requireContains(traceText, ...
        'RootDec=BisectSegmentRoots(Problem,FeasibleDec,InfeasibleDec,6);', ...
        'test_PRBCCMO_t_metrics:SixStepSegmentBisection', ...
        'True-boundary diagnostics must use 6-step segment bisection roots.');
    requireContains(traceText, ...
        'Stats.margin_true_boundary_corr=SafeCorr(Meta.margin,TrueBoundaryDist);', ...
        'test_PRBCCMO_t_metrics:TrueBoundaryFitCorrelation', ...
        'Traced metrics must record whether calibrated margin tracks true-boundary distance.');
    requireContains(traceText, ...
        '[RootDist,RootObj]=NearestSegmentRoot(Population,RootEvidence,M);', ...
        'test_PRBCCMO_t_metrics:ObjectiveTrueBoundaryDistance', ...
        'Objective snapshots must expose distance to the nearest bisection segment root.');
    requireContains(traceText, ...
        'BuildSegmentRootEvidenceRows(', ...
        'test_PRBCCMO_t_metrics:SegmentRootEvidenceRows', ...
        'Objective snapshots must include pair endpoints and segment-root rows for plotting.');
    requireContains(traceText, ...
        'Diag.lowmargin_ratio_gain=Diag.selected_lowmargin_ratio-Diag.pool_lowmargin_ratio;', ...
        'test_PRBCCMO_t_metrics:InfeasibleLowMarginGain', ...
        'Infeasible selection diagnostics must compare selected low-margin ratio against the pool.');
    requireContains(traceText, ...
        'OppDist=SupportDistance(CandidateMeta.oppSupport(idx));', ...
        'test_PRBCCMO_t_metrics:BoundaryEventOppDist', ...
        'Boundary event rows must log opposite-side support distance for generated offspring.');
    requireContains(traceText, ...
        'objective_snapshot.csv', ...
        'test_PRBCCMO_t_metrics:ObjectiveSnapshotCsv', ...
        'PRBCCMO_t must emit objective-space snapshots for visual innovation evidence.');
    requireContains(traceText, ...
        'Algorithm.metric.analysis_objective_csv', ...
        'test_PRBCCMO_t_metrics:ObjectiveMetricPath', ...
        'PRBCCMO_t must expose the objective snapshot CSV path in Algorithm.metric.');
    requireContains(traceText, ...
        'LogObjectiveSnapshot', ...
        'test_PRBCCMO_t_metrics:ObjectiveSnapshotLogger', ...
        'PRBCCMO_t must log objective-space populations, archive members, evaluated boundary evidence, and selected boundary offspring.');
    requireContains(traceText, ...
        'WriteContext=WriteContext||WriteBoundaryOff||WriteBoundaryEvidence;', ...
        'test_PRBCCMO_t_metrics:BoundaryEvidenceContextSnapshot', ...
        'A generation with evaluated boundary evidence must also log same-generation C/U/archive context.');
    requireNotContains(traceText, ...
        'AnchorRows', ...
        'test_PRBCCMO_t_metrics:NoAnchorRows', ...
        'Traced metrics must not depend on the old anchor/pair row dataset.');
    requireNotContains(traceText, ...
        'PairRows', ...
        'test_PRBCCMO_t_metrics:NoPairRows', ...
        'Traced metrics must not depend on the old anchor/pair row dataset.');
    requireNotContains(traceText, ...
        'b_mean_dist_to_feasible_region', ...
        'test_PRBCCMO_t_metrics:NoFeasibleRegionDistance', ...
        'Diagnostics must use true-boundary distance instead of feasible-region distance.');

    Algorithm = PRBCCMO_t('save',0,'run',1);
    Problem   = DASCMOP1_BC('N',40,'maxFE',800);
    Algorithm.Solve(Problem);

    runFolder = Algorithm.metric.analysis_folder;
    assert(isfolder(runFolder), ...
        'test_PRBCCMO_t_metrics:MissingRunFolder', ...
        'PRBCCMO_t must emit a trace run folder under Data/PRBCCMO_t.');

    summaryFile  = fullfile(runFolder,'generation_summary.csv');
    boundaryFile = fullfile(runFolder,'boundary_event.csv');
    archiveFile  = fullfile(runFolder,'archive_members.csv');
    objectiveFile = fullfile(runFolder,'objective_snapshot.csv');
    mlpFile      = fullfile(runFolder,'mlp_events.csv');
    metaFile     = fullfile(runFolder,'run_meta.csv');

    assert(isfile(summaryFile) && isfile(boundaryFile) && isfile(archiveFile) && ...
           isfile(objectiveFile) && isfile(mlpFile) && isfile(metaFile), ...
        'test_PRBCCMO_t_metrics:MissingCsvFiles', ...
        'PRBCCMO_t must emit the traced CSV files.');

    Summary = readtable(summaryFile,'TextType','string');
    requireColumns(Summary, { ...
        'boundary_off_count','boundary_evidence_count','boundary_evidence_feasible_ratio', ...
        'boundary_sector_coverage','boundary_mean_pair_dist','boundary_lowmargin_pair_hit', ...
        'boundary_seg_cross_dist','pair_skip_duplicate','seed_b_mean_pair_dist', ...
        'boundary_margin_oppdist_corr','boundary_lowmargin_mean_opp_dist', ...
        'boundary_highmargin_mean_opp_dist','boundary_lowmargin_oppdist_gain', ...
        'boundary_lowmargin_mean_opp_support','boundary_highmargin_mean_opp_support', ...
        'boundary_survive_c_rate','boundary_survive_u_rate', ...
        'seed_b_lowmargin_pair_hit','b_lowmargin_ratio','b_mean_dist_to_true_boundary', ...
        'b_p90_dist_to_true_boundary','boundary_off_hit_rate_eps','archive_hit_rate_eps', ...
        'b_mean_pair_dist','b_lowmargin_pair_hit', ...
        'b_margin_true_boundary_corr','b_margin_oppdist_corr','b_lowmargin_mean_opp_dist','b_highmargin_mean_opp_dist', ...
        'b_lowmargin_oppdist_gain','b_lowmargin_mean_opp_support','b_highmargin_mean_opp_support', ...
        'train_size','train_pos','train_neg','train_sector_coverage', ...
        'train_feasible_endpoint_count','train_pair_count','train_boundary_evidence_count','train_mean_pair_dist','train_can_train', ...
        'train_brier_after','train_logloss_after', ...
        'inf_pool_mean_margin','inf_selected_mean_margin','inf_margin_gain', ...
        'inf_pool_mean_obj_score','inf_selected_mean_obj_score','inf_obj_score_gain', ...
        'inf_pool_lowmargin_ratio','inf_selected_lowmargin_ratio','inf_lowmargin_ratio_gain'});

    Boundary = readtable(boundaryFile,'TextType','string');
    requireColumns(Boundary, { ...
        'pair_feasible_endpoint_side','pair_infeasible_endpoint_side', ...
        'pair_feasible_endpoint_prob','pair_feasible_endpoint_score', ...
        'pair_infeasible_endpoint_prob','pair_infeasible_endpoint_score', ...
        'pair_pred_cross','pair_dist','seg_cross_dist','opp_dist'});

    Archive = readtable(archiveFile,'TextType','string');
    requireColumns(Archive, {'opp_dist','score'});

    Objective = readtable(objectiveFile,'TextType','string');
    requireColumns(Objective, { ...
        'generation','fe','fe_ratio','role','index','sector','feasible', ...
        'prob','margin','opp_support','opp_dist','true_boundary_dist','obj_score','score', ...
        'survive_c','survive_u','root_obj1','root_obj2','obj1','obj2'});
    assert(any(Objective.role == "pop_c") && any(Objective.role == "pop_u") && ...
           any(Objective.role == "archive_b") && any(Objective.role == "boundary_evidence") && ...
           any(Objective.role == "segment_root") && ...
           any(Objective.role == "pair_feasible_endpoint") && any(Objective.role == "pair_infeasible_endpoint"), ...
        'test_PRBCCMO_t_metrics:MissingObjectiveRoles', ...
        'Objective snapshots must include current populations, archive, evaluated boundary evidence, pair endpoints, and segment roots.');
    assert(all(isfinite(Objective.obj1)) && all(isfinite(Objective.obj2)), ...
        'test_PRBCCMO_t_metrics:InvalidObjectiveValues', ...
        'Objective snapshots must contain finite objective coordinates.');
    RootRows = Objective(Objective.role == "segment_root",:);
    assert(~isempty(RootRows) && all(abs(double(RootRows.true_boundary_dist)) < 1e-12), ...
        'test_PRBCCMO_t_metrics:InvalidSegmentRootDistance', ...
        'Segment-root evidence rows must mark roots as zero true-boundary distance.');
    BoundaryRows = Objective(Objective.role == "boundary_evidence" | Objective.role == "boundary_off" | Objective.role == "archive_b",:);
    assert(~isempty(BoundaryRows) && any(isfinite(double(BoundaryRows.root_obj1))) && ...
           any(isfinite(double(BoundaryRows.true_boundary_dist))), ...
        'test_PRBCCMO_t_metrics:MissingNearestRootEvidence', ...
        'Archive, evaluated boundary evidence, and boundary-off rows must carry nearest segment-root coordinates and distances.');
    BoundaryGenerations = unique(Objective.generation(Objective.role == "boundary_off"));
    for g = reshape(BoundaryGenerations,1,[])
        Stage = Objective(Objective.generation == g,:);
        assert(any(Stage.role == "pop_c") && any(Stage.role == "pop_u") && ...
               any(Stage.role == "archive_b"), ...
            'test_PRBCCMO_t_metrics:BoundaryOffMissingSameGenerationContext', ...
            'Every generation with boundary_off rows must include same-generation pop_c/pop_u/archive_b rows.');
    end
    EvidenceGenerations = unique(Objective.generation(Objective.role == "boundary_evidence"));
    for g = reshape(EvidenceGenerations,1,[])
        Stage = Objective(Objective.generation == g,:);
        assert(any(Stage.role == "pop_c") && any(Stage.role == "pop_u") && ...
               any(Stage.role == "archive_b"), ...
            'test_PRBCCMO_t_metrics:BoundaryEvidenceMissingSameGenerationContext', ...
            'Every generation with boundary_evidence rows must include same-generation pop_c/pop_u/archive_b rows.');
    end

    MLP = readtable(mlpFile,'TextType','string');
    requireColumns(MLP, { ...
        'train_size','pos_count','neg_count','sector_coverage', ...
        'feasible_endpoint_count','src_b','src_recent_boundary','src_boundary_evidence','src_pop_c','src_pop_u'});

    RunSummary = summarize_PRBCCMO_t_run(runFolder);
    requireStructFields(RunSummary, { ...
        'problem','family','analysis_folder','final_b_size', ...
        'analysis_objective_csv', ...
        'final_boundary_off_count','final_boundary_evidence_count', ...
        'final_boundary_evidence_feasible_ratio','final_b_lowmargin_ratio', ...
        'final_b_mean_dist_to_true_boundary','final_b_p90_dist_to_true_boundary', ...
        'final_boundary_off_hit_rate_eps','final_archive_hit_rate_eps', ...
        'final_boundary_lowmargin_pair_hit','final_boundary_seg_cross_dist', ...
        'final_boundary_margin_oppdist_corr','final_boundary_lowmargin_oppdist_gain', ...
        'final_boundary_survive_c_rate','final_boundary_survive_u_rate', ...
        'final_b_margin_true_boundary_corr','final_b_margin_oppdist_corr','final_b_lowmargin_oppdist_gain', ...
        'final_inf_margin_gain','final_inf_obj_score_gain','final_inf_lowmargin_ratio_gain', ...
        'final_train_pair_count','final_train_boundary_evidence_count','first_can_train_generation', ...
        'first_trained_generation','stable3_generation'});

    outDir = fullfile(tempdir,'prbccmo_t_metrics_test');
    if ~isfolder(outDir)
        mkdir(outDir);
    end
    [RunTable,ProblemTable,FamilyTable] = summarize_PRBCCMO_t_data(runFolder,outDir);
    assert(~isempty(RunTable) && ~isempty(ProblemTable) && ~isempty(FamilyTable), ...
        'test_PRBCCMO_t_metrics:EmptySummaryTables', ...
        'The summary script must produce run/problem/family tables.');
    requireColumns(ProblemTable, { ...
        'avg_final_boundary_margin_oppdist_corr','avg_final_boundary_lowmargin_oppdist_gain', ...
        'avg_final_boundary_off_count','avg_final_boundary_evidence_count', ...
        'avg_final_boundary_evidence_feasible_ratio','avg_final_b_lowmargin_ratio', ...
        'avg_final_b_mean_dist_to_true_boundary','avg_final_b_p90_dist_to_true_boundary', ...
        'avg_final_boundary_off_hit_rate_eps','avg_final_archive_hit_rate_eps', ...
        'avg_final_train_boundary_evidence_count', ...
        'avg_final_b_margin_true_boundary_corr', ...
        'avg_final_inf_lowmargin_ratio_gain','avg_final_inf_margin_gain','avg_final_inf_obj_score_gain'});
    assert(isfile(fullfile(outDir,'run_summary.csv')) && ...
           isfile(fullfile(outDir,'problem_summary.csv')) && ...
           isfile(fullfile(outDir,'family_summary.csv')), ...
        'test_PRBCCMO_t_metrics:MissingSummaryCsv', ...
        'The summary script must write run/problem/family CSV files.');

    plotDir = fullfile(outDir,'objective_plots');
    PlotFiles = plot_PRBCCMO_t_objective_evidence(runFolder,plotDir);
    assert(~isempty(PlotFiles) && all(isfile(string(PlotFiles))), ...
        'test_PRBCCMO_t_metrics:ObjectivePlotMissing', ...
        'The objective-space plotting helper must create figure files from objective_snapshot.csv.');
    RegionPlot = plot_PRBCCMO_t_generation_region_evidence(runFolder,plotDir);
    assert(isfile(string(RegionPlot)), ...
        'test_PRBCCMO_t_metrics:GenerationRegionPlotMissing', ...
        'The generation-level region plotting helper must create one-generation feasible-region evidence figures.');
    ArchiveRelationPlot = plot_PRBCCMO_t_archive_boundary_relation(runFolder,plotDir);
    assert(isfile(string(ArchiveRelationPlot)), ...
        'test_PRBCCMO_t_metrics:ArchiveRelationPlotMissing', ...
        'The archive-boundary relation plotting helper must include evaluated boundary evidence and create a figure.');

    benchCsv = fullfile(outDir,'benchmark_smoke.csv');
    Results = benchmark_PRBCCMO_t_suite({'DASCMOP1_BC'},1,benchCsv,40,800);
    assert(istable(Results) && height(Results) == 1 && isfile(benchCsv), ...
        'test_PRBCCMO_t_metrics:BenchmarkSmokeFailed', ...
        'The benchmark helper must emit a one-row CSV for the smoke case.');
    requireColumns(Results, { ...
        'problem','family','run','igd','hv','feasible_rate','runtime', ...
        'analysis_folder','analysis_objective_csv','final_b_size','final_b_lowmargin_ratio', ...
        'final_b_mean_dist_to_true_boundary','final_b_p90_dist_to_true_boundary', ...
        'final_boundary_off_hit_rate_eps','final_archive_hit_rate_eps', ...
        'final_boundary_off_count','final_boundary_evidence_count', ...
        'final_boundary_evidence_feasible_ratio','final_boundary_lowmargin_pair_hit', ...
        'final_boundary_seg_cross_dist','final_boundary_margin_oppdist_corr', ...
        'final_boundary_lowmargin_oppdist_gain','final_boundary_survive_c_rate', ...
        'final_boundary_survive_u_rate','final_train_boundary_evidence_count', ...
        'final_inf_lowmargin_ratio_gain','final_inf_margin_gain','final_inf_obj_score_gain', ...
        'stable3_generation'});
end

function requireColumns(T,Names)
    Missing = setdiff(string(Names),string(T.Properties.VariableNames));
    assert(isempty(Missing), ...
        'test_PRBCCMO_t_metrics:MissingColumns', ...
        'Missing expected columns: %s', strjoin(cellstr(Missing), ', '));
end

function requireStructFields(S,Names)
    Missing = Names(~isfield(S,Names));
    assert(isempty(Missing), ...
        'test_PRBCCMO_t_metrics:MissingStructFields', ...
        'Missing expected fields: %s', strjoin(Missing, ', '));
end

function requireContains(text,pattern,id,msg)
    assert(contains(text,normalizeCode(pattern)),id,msg);
end

function requireNotContains(text,pattern,id,msg)
    assert(~contains(text,normalizeCode(pattern)),id,msg);
end

function text = normalizeCode(text)
    text = regexprep(text,'%[^\n\r]*','');
    text = strrep(text,'...','');
    text = regexprep(text,'\s+','');
end
