function test_PRBCCMO_t_metrics()
% Regression test for traced PRBCCMO metric coverage.

    rootDir = fileparts(which('platemo'));
    if isempty(rootDir)
        error('test_PRBCCMO_t_metrics:NoPlatEMO','Cannot locate platemo.m on the MATLAB path.');
    end

    dataDir = fullfile(rootDir,'Data','PRBCCMO_t');
    before = dir(fullfile(dataDir,'PRBCCMO_t_LIRCMOP2_BC_*'));
    beforeNames = {before.name};

    platemo( ...
        'algorithm', @PRBCCMO_t, ...
        'problem',   @LIRCMOP2_BC, ...
        'N',         20, ...
        'maxFE',     200, ...
        'save',      0);

    after = dir(fullfile(dataDir,'PRBCCMO_t_LIRCMOP2_BC_*'));
    newMask = ~ismember({after.name},beforeNames);
    newRuns = after(newMask);
    assert(~isempty(newRuns), ...
        'test_PRBCCMO_t_metrics:NoRunFolder', ...
        'PRBCCMO_t did not create a new run folder for the metric regression test.');

    [~,idx] = max([newRuns.datenum]);
    runFolder = fullfile(dataDir,newRuns(idx).name);

    summary = readtable(fullfile(runFolder,'generation_summary.csv'));
    archive = readtable(fullfile(runFolder,'archive_members.csv'));
    events  = readtable(fullfile(runFolder,'boundary_event.csv'));
    mlp     = readtable(fullfile(runFolder,'mlp_events.csv'));

    requireColumns(summary.Properties.VariableNames,{ ...
        'helper_real_opp_ratio','helper_skip_no_helper', ...
        'boundary_attempts', ...
        'seed_b_size','seed_b_sector_coverage','seed_b_mixed_sectors', ...
        'b_trusted_count','b_trusted_sector_coverage','b_trusted_lowmargin_count', ...
        'b_bal_acc','b_brier','train_minus_boundary_bal_gap','train_minus_b_bal_gap'}, ...
        'test_PRBCCMO_t_metrics:SummaryColumns');
    requireAbsentColumns(summary.Properties.VariableNames,{ ...
        'helper_pred_opp_ratio','train_mean_bound_weight', ...
        'calib_brier_holdout','calib_bal_acc_holdout','temperature'}, ...
        'test_PRBCCMO_t_metrics:SummaryLegacyColumns');

    requireColumns(archive.Properties.VariableNames,{ ...
        'trusted','pred_label','correct'}, ...
        'test_PRBCCMO_t_metrics:ArchiveColumns');

    requireColumns(events.Properties.VariableNames,{ ...
        'anchor_trusted','chosen_pred_label','chosen_correct'}, ...
        'test_PRBCCMO_t_metrics:BoundaryColumns');

    requireColumns(mlp.Properties.VariableNames,{ ...
        'trained','warm_start', ...
        'acc_after','bal_acc_after','brier_after','logloss_after'}, ...
        'test_PRBCCMO_t_metrics:MLPColumns');
    requireAbsentColumns(mlp.Properties.VariableNames,{ ...
        'mean_bound_weight','temperature','calib_size', ...
        'calib_brier_holdout','calib_bal_acc'}, ...
        'test_PRBCCMO_t_metrics:MLPLegacyColumns');

    suiteDir = tempname();
    mkdir(suiteDir);
    cleanupObj = onCleanup(@() cleanupFolder(suiteDir)); %#ok<NASGU>
    copyfile(runFolder,fullfile(suiteDir,newRuns(idx).name));

    suiteSummaryFile = fullfile(suiteDir,'suite_summary.csv');
    suiteSummary = summarize_PRBCCMO_t_data(suiteDir,suiteSummaryFile);
    assert(exist(suiteSummaryFile,'file') == 2, ...
        'test_PRBCCMO_t_metrics:MissingSuiteSummary', ...
        'summarize_PRBCCMO_t_data did not write suite_summary.csv.');
    assert(height(suiteSummary) == 1, ...
        'test_PRBCCMO_t_metrics:UnexpectedSuiteSummaryRows', ...
        'Expected exactly one summarized run in the isolated suite folder.');
    requireColumns(suiteSummary.Properties.VariableNames,{ ...
        'final_b_brier','final_train_minus_b_bal_gap', ...
        'mean_helper_real_opp_ratio','mean_helper_skip_no_helper', ...
        'mean_boundary_attempts','trained_generations','model_ready_generations'}, ...
        'test_PRBCCMO_t_metrics:SuiteSummaryColumns');
    requireAbsentColumns(suiteSummary.Properties.VariableNames,{ ...
        'final_calib_brier_holdout','final_calib_bal_acc_holdout', ...
        'final_temperature','mean_helper_pred_opp_ratio'}, ...
        'test_PRBCCMO_t_metrics:SuiteSummaryLegacyColumns');

    [familySummary,problemSummary] = analyze_PRBCCMO_t_suite(suiteDir);
    assert(exist(fullfile(suiteDir,'suite_family_summary.csv'),'file') == 2, ...
        'test_PRBCCMO_t_metrics:MissingFamilySummary', ...
        'analyze_PRBCCMO_t_suite did not write suite_family_summary.csv.');
    assert(exist(fullfile(suiteDir,'suite_problem_ranked.csv'),'file') == 2, ...
        'test_PRBCCMO_t_metrics:MissingProblemSummary', ...
        'analyze_PRBCCMO_t_suite did not write suite_problem_ranked.csv.');
    assert(~isempty(familySummary) && ~isempty(problemSummary), ...
        'test_PRBCCMO_t_metrics:EmptyAnalysisOutputs', ...
        'analyze_PRBCCMO_t_suite returned empty outputs for the isolated suite.');
    requireColumns(familySummary.Properties.VariableNames,{ ...
        'family','problem_count','mean_final_b_size', ...
        'mean_final_b_trusted_sector_coverage','mean_final_train_minus_b_bal_gap', ...
        'mean_helper_real_opp_ratio','mean_helper_skip_no_helper','mean_boundary_attempts'}, ...
        'test_PRBCCMO_t_metrics:FamilySummaryColumns');
    requireAbsentColumns(familySummary.Properties.VariableNames,{ ...
        'mean_final_calib_brier_holdout','mean_final_temperature'}, ...
        'test_PRBCCMO_t_metrics:FamilySummaryLegacyColumns');
    requireColumns(problemSummary.Properties.VariableNames,{ ...
        'family','problem','final_b_size','final_b_trusted_count', ...
        'final_train_minus_b_bal_gap','mean_helper_real_opp_ratio', ...
        'mean_helper_skip_no_helper','mean_boundary_attempts'}, ...
        'test_PRBCCMO_t_metrics:ProblemSummaryColumns');
    requireAbsentColumns(problemSummary.Properties.VariableNames,{ ...
        'final_calib_brier_holdout','final_calib_bal_acc_holdout', ...
        'final_temperature'}, ...
        'test_PRBCCMO_t_metrics:ProblemSummaryLegacyColumns');

    emptySuiteDir = tempname();
    mkdir(emptySuiteDir);
    emptyCleanupObj = onCleanup(@() cleanupFolder(emptySuiteDir)); %#ok<NASGU>
    [emptyFamilySummary,emptyProblemSummary] = analyze_PRBCCMO_t_suite(emptySuiteDir);
    assert(height(emptyFamilySummary) == 0, ...
        'test_PRBCCMO_t_metrics:EmptyFamilySummaryHeight', ...
        'Expected empty FamilySummary for an empty suite directory.');
    assert(height(emptyProblemSummary) == 0, ...
        'test_PRBCCMO_t_metrics:EmptyProblemSummaryHeight', ...
        'Expected empty ProblemSummary for an empty suite directory.');
    requireColumns(emptyFamilySummary.Properties.VariableNames,{ ...
        'family','problem_count','mean_final_b_size', ...
        'mean_final_b_brier','mean_helper_skip_no_helper','mean_boundary_attempts'}, ...
        'test_PRBCCMO_t_metrics:EmptyFamilySummarySchema');
    requireColumns(emptyProblemSummary.Properties.VariableNames,{ ...
        'family','problem','final_b_size','final_b_brier', ...
        'mean_helper_skip_no_helper','mean_boundary_attempts'}, ...
        'test_PRBCCMO_t_metrics:EmptyProblemSummarySchema');
end

function requireColumns(names,required,identifier)
    missing = required(~ismember(required,names));
    assert(isempty(missing),identifier, ...
        'Missing expected columns: %s', strjoin(missing,', '));
end

function requireAbsentColumns(names,forbidden,identifier)
    present = forbidden(ismember(forbidden,names));
    assert(isempty(present),identifier, ...
        'Found legacy columns that should be removed: %s', strjoin(present,', '));
end

function cleanupFolder(folder)
    if exist(folder,'dir') == 7
        rmdir(folder,'s');
    end
end
