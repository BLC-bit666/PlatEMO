            case 'F_F'
                Stats.ff = Stats.ff + 1;
            case 'F_I'
                Stats.fi = Stats.fi + 1;
            case 'I_F'
                Stats.if = Stats.if + 1;
            case 'I_I'
                Stats.ii = Stats.ii + 1;
        end
    end
end

