function Diag = BuildBoundaryDiagnostics(Candidates,PopulationC,PopulationU,W,Model,Phase,Generation,FE)
    N    = numel(Candidates);
    Diag = InitEmptyBoundaryDiag(Phase,Generation,FE);
    if N <= 0
        return;
    end

    RefObj   = [Candidates.objs;PopulationC.objs;PopulationU.objs];
    Sector    = AssociateSectorsLocal(Candidates.objs,W,RefObj);
    Scalar    = ComputeSectorScalar(Candidates.objs,W,RefObj,Sector);
    RepC      = BuildSectorRepresentatives(PopulationC,W,RefObj,true);
    RepU      = BuildSectorRepresentatives(PopulationU,W,RefObj,false);
    [Prob,~]  = PredictBoundaryMLP(Model,Candidates.decs);
    Feasible  = all(Candidates.cons<=0,2);

    Diag.count           = N;
    Diag.phase           = repmat({Phase},N,1);
    Diag.generation      = Generation*ones(N,1);
    Diag.fe              = FE*ones(N,1);
    Diag.candidate_index = (1:N)';
    Diag.sector          = Sector(:);
    Diag.feasible        = double(Feasible(:));
    Diag.scalar          = Scalar(:);
    Diag.prob            = Prob(:);
    Diag.abs_p05         = abs(Prob(:)-0.5);
    Diag.rank_in_sector  = nan(N,1);
    Diag.selected        = zeros(N,1);
    Diag.repC_has        = zeros(N,1);
    Diag.repU_has        = zeros(N,1);
    Diag.rep_gate_ok     = zeros(N,1);
    Diag.repC_index      = nan(N,1);
    Diag.repU_index      = nan(N,1);
    Diag.repC_scalar     = nan(N,1);
    Diag.repU_scalar     = nan(N,1);
    Diag.repC_feasible   = nan(N,1);
    Diag.repU_feasible   = nan(N,1);
    Diag.rep_pair_type   = repmat({''},N,1);
    Diag.scalar_lower    = nan(N,1);
    Diag.scalar_upper    = nan(N,1);
    Diag.scalar_mid      = nan(N,1);
    Diag.scalar_span     = nan(N,1);
    Diag.between_ok      = zeros(N,1);
    Diag.dist_to_c       = nan(N,1);
    Diag.dist_to_u       = nan(N,1);
    Diag.lambda_u_to_c   = nan(N,1);
    Diag.closer_to_c     = zeros(N,1);
    Diag.closer_to_u     = zeros(N,1);
    Diag.side_expected   = repmat({''},N,1);
    Diag.side_ok         = zeros(N,1);
    Diag.first_fail      = repmat({''},N,1);
    Diag.mid_dist_norm   = nan(N,1);
    Diag.opposite_side   = repmat({''},N,1);

    for i = 1 : N
        s = Sector(i);
        Diag.side_expected{i} = Ternary(Feasible(i),'C','U');
        if s <= 0 || s > numel(RepC.has)
            Diag.first_fail{i} = 'representative';
            continue;
        end

        Diag.repC_has(i)    = double(RepC.has(s));
        Diag.repU_has(i)    = double(RepU.has(s));
        Diag.rep_gate_ok(i) = double(RepC.has(s) && RepU.has(s));
        if ~Diag.rep_gate_ok(i)
            Diag.first_fail{i} = 'representative';
            continue;
        end

        Diag.repC_index(i)    = RepC.idx(s);
        Diag.repU_index(i)    = RepU.idx(s);
        Diag.repC_scalar(i)   = RepC.scalar(s);
        Diag.repU_scalar(i)   = RepU.scalar(s);
        Diag.repC_feasible(i) = double(RepC.feasible(s));
        Diag.repU_feasible(i) = double(RepU.feasible(s));
        Diag.rep_pair_type{i} = BuildPairType(RepC.feasible(s),RepU.feasible(s));

        Diag.scalar_lower(i)  = min(RepC.scalar(s),RepU.scalar(s));
        Diag.scalar_upper(i)  = max(RepC.scalar(s),RepU.scalar(s));
        Diag.scalar_mid(i)    = 0.5*(RepC.scalar(s)+RepU.scalar(s));
        Diag.scalar_span(i)   = max(abs(RepC.scalar(s)-RepU.scalar(s)),1e-12);
        Diag.mid_dist_norm(i) = abs(Scalar(i)-Diag.scalar_mid(i))/Diag.scalar_span(i);
        Diag.between_ok(i)    = double(IsBetween(Scalar(i),RepC.scalar(s),RepU.scalar(s)));
        if ~Diag.between_ok(i)
            Diag.first_fail{i} = 'scalar';
        end

        Diag.dist_to_c(i)     = abs(Scalar(i)-RepC.scalar(s));
        Diag.dist_to_u(i)     = abs(Scalar(i)-RepU.scalar(s));
        Diag.closer_to_c(i)   = double(Diag.dist_to_c(i) <= Diag.dist_to_u(i)+1e-12);
        Diag.closer_to_u(i)   = double(Diag.dist_to_u(i) <= Diag.dist_to_c(i)+1e-12);
        if abs(RepC.scalar(s)-RepU.scalar(s)) < 1e-12
            Diag.lambda_u_to_c(i) = 0.5;
        else
            Diag.lambda_u_to_c(i) = (Scalar(i)-RepU.scalar(s))/(RepC.scalar(s)-RepU.scalar(s));
        end

        if Feasible(i)
            Diag.side_ok(i) = double(Diag.between_ok(i) && Diag.closer_to_c(i));
        else
            Diag.side_ok(i) = double(Diag.between_ok(i) && Diag.closer_to_u(i));
        end

        if isempty(Diag.first_fail{i})
            if Diag.side_ok(i)
                Diag.first_fail{i} = 'pass';
            else
                Diag.first_fail{i} = 'relative_side';
            end
        end
    end
end

