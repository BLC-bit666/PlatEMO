function Stats = SummarizeRepresentativePairs(PopulationC,PopulationU,W,ExtraRef)
    Stats = struct('shared',0,'ff',0,'fi',0,'if',0,'ii',0);
    if nargin < 4
        ExtraRef = [];
    end
    if isempty(PopulationC) || isempty(PopulationU)
        return;
