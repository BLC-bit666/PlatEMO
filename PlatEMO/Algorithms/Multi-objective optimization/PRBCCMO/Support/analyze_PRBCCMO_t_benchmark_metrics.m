function Summary = buildGroupedSummary(T,GroupFields,MetricNames)
    if isempty(T) || isempty(MetricNames)
        Summary = emptyGroupedSummary(GroupFields,MetricNames);
        return;
    end
    Keys = unique(T(:,GroupFields),'rows','stable');
    Names = [GroupFields,{'num_runs'},composeMetricNames(MetricNames)];
    Types = [repmat({'string'},1,numel(GroupFields)),{'double'}, ...
        repmat({'double'},1,2*numel(MetricNames))];
    Summary = table('Size',[height(Keys),numel(Names)], ...
        'VariableTypes',Types,'VariableNames',Names);
    for i = 1 : height(Keys)
        Mask = true(height(T),1);
        for g = 1 : numel(GroupFields)
            Field = GroupFields{g};
            Summary.(Field)(i) = string(Keys.(Field)(i));
            Mask = Mask & string(T.(Field)) == string(Keys.(Field)(i));
        end
        Summary.num_runs(i) = sum(Mask);
        col = numel(GroupFields) + 2;
        for m = 1 : numel(MetricNames)
            Values = double(T.(MetricNames{m})(Mask));
            Summary{i,col} = PRBCCMOUtils.meanFinite(Values);
            Summary{i,col+1} = PRBCCMOUtils.stdFinite(Values);
            col = col + 2;
        end
    end
end

function Summary = emptyGroupedSummary(GroupFields,MetricNames)
    Names = [GroupFields,{'num_runs'},composeMetricNames(MetricNames)];
    Types = [repmat({'string'},1,numel(GroupFields)),{'double'}, ...
        repmat({'double'},1,2*numel(MetricNames))];
    Summary = table('Size',[0,numel(Names)],'VariableTypes',Types,'VariableNames',Names);
end

function Names = composeMetricNames(MetricNames)
    Names = cell(1,2*numel(MetricNames));
    Names(1:2:end) = strcat('mean_',MetricNames);
    Names(2:2:end) = strcat('std_',MetricNames);
end

function Paired = buildPairedHelpTable(Runs)
    PairMetrics = { ...
        'igd','final_b_mean_pair_gap','final_b_mean_mid_scalar', ...
        'final_b_mean_infeasible_boundary_dist','final_b_far_infeasible_boundary_ratio', ...
        'mlp_trained_events','final_train_size', ...
        'final_train_b_core_count','final_train_refinement_count','final_train_current_pop_count', ...
        'final_train_refinement_pos_count','final_train_refinement_neg_count','mean_train_refinement_ratio', ...
        'mean_mlp_prob_curr_feasible','mean_mlp_prob_curr_infeasible', ...
        'mean_prob_accepted_refinement','mean_prob_rejected_refinement', ...
        'mean_mlp_prob_bcore_gap','mean_mlp_prob_current_gap','mean_prob_refinement_gap', ...
        'mlp_two_inf_tournament_total','mean_mlp_two_inf_tournament_total', ...
        'mlp_effective_win_total','mean_mlp_effective_win_total', ...
        'mlp_primary_resolution_total','mean_mlp_primary_resolution_total', ...
        'b_fallback_total','mean_b_fallback_total', ...
        'mean_mlp_two_inf_tournament_rate','mean_mlp_effective_win_rate', ...
        'mean_mlp_primary_resolution_rate','mean_b_fallback_rate', ...
        'mlp_inf_selection_generations','mlp_inf_selection_rate', ...
        'inf_feasible_deficit_total','mean_inf_feasible_deficit_when_mlp_active', ...
        'mean_inf_selected_when_mlp_active', ...
        'inf_ranked_total','mean_inf_ranked_count', ...
        'inf_selection_generations','inf_selected_total', ...
        'mean_inf_selected_mean_utility','mean_inf_utility_gain','pos_rate_inf_utility_gain', ...
        'mean_inf_selected_prob_gain'};
    PairMetrics = PairMetrics(ismember(PairMetrics,Runs.Properties.VariableNames));
    Keys = unique(Runs(:,{'problem','family','run'}),'rows','stable');
    Names = [{'problem','family','run'},pairMetricNames(PairMetrics)];
    Rows = cell(height(Keys),numel(Names));
    row = 0;
    for i = 1 : height(Keys)
        Mask = string(Runs.problem) == string(Keys.problem(i)) & ...
            string(Runs.family) == string(Keys.family(i)) & ...
            double(Runs.run) == double(Keys.run(i));
        Local = Runs(Mask,:);
        Mlp = find(string(Local.variant) == "PRBCCMO-MLPcmp",1);
        NoMlp = find(string(Local.variant) == "PRBCCMO-noMLPcmp",1);
        if isempty(Mlp) || isempty(NoMlp)
            continue;
        end
        row = row + 1;
        Row = cell(1,numel(Names));
        Row(1:3) = {string(Keys.problem(i)),string(Keys.family(i)),double(Keys.run(i))};
        col = 4;
        for m = 1 : numel(PairMetrics)
            Metric = PairMetrics{m};
            MlpValue = double(Local.(Metric)(Mlp));
            NoMlpValue = double(Local.(Metric)(NoMlp));
            Row{col} = MlpValue;
            Row{col+1} = NoMlpValue;
            if strcmp(Metric,'igd')
                Row{col+2} = NoMlpValue - MlpValue;
            else
                Row{col+2} = MlpValue - NoMlpValue;
            end
            col = col + 3;
        end
        Rows(row,:) = Row;
    end
    Rows = Rows(1:row,:);
    Paired = cell2table(Rows,'VariableNames',Names);
    if ismember('delta_igd_mlp',Paired.Properties.VariableNames)
        Delta = double(Paired.delta_igd_mlp);
        Result = classifyIgdDelta(Delta);
        Paired.mlp_igd_result = Result;
        Paired.mlp_igd_win = double(Result == "win");
        Paired.mlp_igd_loss = double(Result == "loss");
        Paired.mlp_igd_tie = double(Result == "tie");
        Paired.mlp_igd_missing = double(Result == "missing");
    end
end

function Names = pairMetricNames(MetricNames)
    Names = cell(1,3*numel(MetricNames));
    for i = 1 : numel(MetricNames)
        base = MetricNames{i};
        Names{3*i-2} = ['mlp_cmp_',base];
        Names{3*i-1} = ['no_mlp_cmp_',base];
        if strcmp(base,'igd')
            Names{3*i} = 'delta_igd_mlp';
        else
            Names{3*i} = ['delta_',base,'_mlp_cmp_minus_no_mlp_cmp'];
        end
    end
end

function Names = pairedMetricColumns(T)
    if isempty(T)
        Names = {};
        return;
    end
    Names = T.Properties.VariableNames;
    Names = Names(startsWith(Names,'delta_') | startsWith(Names,'mlp_cmp_') | startsWith(Names,'no_mlp_cmp_'));
end

function Summary = buildPairedIgdOutcomeSummary(Paired)
    Names = {'scope','family','num_pairs','mlp_igd_wins','mlp_igd_losses','mlp_igd_ties','mlp_igd_missing', ...
        'mlp_igd_win_rate','mean_delta_igd_mlp','median_delta_igd_mlp'};
    Types = {'string','string','double','double','double','double','double','double','double','double'};
    if isempty(Paired) || ~ismember('delta_igd_mlp',Paired.Properties.VariableNames)
        Summary = table('Size',[0,numel(Names)],'VariableTypes',Types,'VariableNames',Names);
        return;
    end

    Families = ["__overall__";unique(string(Paired.family),'stable')];
    Summary = table('Size',[numel(Families),numel(Names)], ...
        'VariableTypes',Types,'VariableNames',Names);
    for i = 1 : numel(Families)
        if Families(i) == "__overall__"
            Mask = true(height(Paired),1);
            Summary.scope(i) = "overall";
            Summary.family(i) = "";
        else
            Mask = string(Paired.family) == Families(i);
            Summary.scope(i) = "family";
            Summary.family(i) = Families(i);
        end
        Delta = double(Paired.delta_igd_mlp(Mask));
        Result = classifyIgdDelta(Delta);
        Summary.num_pairs(i) = numel(Delta);
        Summary.mlp_igd_wins(i) = sum(Result == "win");
        Summary.mlp_igd_losses(i) = sum(Result == "loss");
        Summary.mlp_igd_ties(i) = sum(Result == "tie");
        Summary.mlp_igd_missing(i) = sum(Result == "missing");
        Summary.mlp_igd_win_rate(i) = Summary.mlp_igd_wins(i) / max(Summary.num_pairs(i),1);
        Summary.mean_delta_igd_mlp(i) = PRBCCMOUtils.meanFinite(Delta);
        Summary.median_delta_igd_mlp(i) = median(Delta(isfinite(Delta)),'omitnan');
    end
end

function Result = classifyIgdDelta(DeltaIGD)
    Tol = 1e-12;
    Result = strings(numel(DeltaIGD),1);
    Result(:) = "tie";
    Result(DeltaIGD > Tol) = "win";
    Result(DeltaIGD < -Tol) = "loss";
    Result(~isfinite(DeltaIGD)) = "missing";
end
