function Outputs = analyze_PRBCCMO_t_benchmark_metrics(benchmarkInput,outDir)
% Analyze PRBCCMO_t boundary, MLP training, and infeasible-selection metrics.

    if nargin < 1 || isempty(benchmarkInput)
        rootDir = fileparts(which('platemo'));
        benchmarkInput = fullfile(rootDir,'Data','PRBCCMO_t','benchmark_runs.csv');
    end
    if nargin < 2 || isempty(outDir)
        outDir = fileparts(char(string(benchmarkInput)));
    end
    if ~isfolder(outDir)
        mkdir(outDir);
    end

    if istable(benchmarkInput)
        Runs = benchmarkInput;
    else
        Runs = readtable(char(string(benchmarkInput)),'TextType','string');
    end
    Runs = normalizeRunTable(Runs);
    PRBCCMOUtils.requireColumns(Runs,{'problem','family','run','variant','igd','analysis_folder'});

    Inventory = metricInventory();
    writetable(Inventory,fullfile(outDir,'metric_inventory.csv'));

    MetricNames = metricColumns(Runs);
    VariantSummary = buildGroupedSummary(Runs,{'variant'},MetricNames);
    FamilyVariantSummary = buildGroupedSummary(Runs,{'family','variant'},MetricNames);
    ProblemVariantSummary = buildGroupedSummary(Runs,{'problem','family','variant'},MetricNames);
    PairedHelp = buildPairedHelpTable(Runs);
    PairedFamilySummary = buildGroupedSummary(PairedHelp,{'family'},pairedMetricColumns(PairedHelp));
    PairedIgdOutcomeSummary = buildPairedIgdOutcomeSummary(PairedHelp);

    writetable(VariantSummary,fullfile(outDir,'metric_variant_summary.csv'));
    writetable(FamilyVariantSummary,fullfile(outDir,'metric_family_variant_summary.csv'));
    writetable(ProblemVariantSummary,fullfile(outDir,'metric_problem_variant_summary.csv'));
    writetable(PairedHelp,fullfile(outDir,'metric_paired_mlp_help.csv'));
    writetable(PairedFamilySummary,fullfile(outDir,'metric_paired_mlp_help_family_summary.csv'));
    writetable(PairedIgdOutcomeSummary,fullfile(outDir,'metric_paired_mlp_igd_outcome_summary.csv'));

    Outputs = struct( ...
        'metric_inventory_csv',string(fullfile(outDir,'metric_inventory.csv')), ...
        'metric_variant_summary_csv',string(fullfile(outDir,'metric_variant_summary.csv')), ...
        'metric_family_variant_summary_csv',string(fullfile(outDir,'metric_family_variant_summary.csv')), ...
        'metric_problem_variant_summary_csv',string(fullfile(outDir,'metric_problem_variant_summary.csv')), ...
        'metric_paired_mlp_help_csv',string(fullfile(outDir,'metric_paired_mlp_help.csv')), ...
        'metric_paired_mlp_help_family_summary_csv',string(fullfile(outDir,'metric_paired_mlp_help_family_summary.csv')), ...
        'metric_paired_mlp_igd_outcome_summary_csv',string(fullfile(outDir,'metric_paired_mlp_igd_outcome_summary.csv')));
end

function T = normalizeRunTable(T)
    Names = T.Properties.VariableNames;
    for i = 1 : numel(Names)
        Value = T.(Names{i});
        if iscell(Value)
            Value = string(Value);
        end
        if isstring(Value)
            Num = str2double(Value);
            if any(isfinite(Num)) && ~ismember(Names{i},{'problem','family','variant','analysis_folder','analysis_core_csv'})
                T.(Names{i}) = Num;
            else
                T.(Names{i}) = Value;
            end
        elseif islogical(Value)
            T.(Names{i}) = double(Value);
        end
    end
end

