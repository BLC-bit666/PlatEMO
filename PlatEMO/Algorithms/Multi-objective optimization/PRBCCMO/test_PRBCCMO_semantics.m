function requireContains(text,pattern,id,msg)
    assert(contains(normalizeText(text),normalizeText(pattern)),id,msg);
end

function requireNotContains(text,pattern,id,msg)
    assert(~contains(normalizeText(text),normalizeText(pattern)),id,msg);
end

function blocks = loadSemanticBlocks(filePath)
    text = fileread(filePath);
    blocks = struct( ...
        'mainBlock',extractBetweenMarkers(text, ...
            '^\s*function\s+main\s*\(\s*Algorithm\s*,\s*Problem\s*\)', ...
            '^%%\s*=+\s*Main-population offspring\s*=+\s*$'), ...
        'trainGate',extractFunctionBlock(text,'CanTrainBoundaryModel'), ...
        'trainArchive',extractFunctionBlock(text,'UpdateTrainArchive'), ...
        'buildMeta',extractFunctionBlock(text,'BuildBoundaryMeta'), ...
        'supportBuilder',extractFunctionBlock(text,'BuildBoundarySupportSet'), ...
        'probeGeneration',extractFunctionBlock(text,'GenerateBoundaryOffspringModelDriven'), ...
        'bridgeMask',extractFunctionBlock(text,'ResolveBridgeBoundaryMask'), ...
        'helperSelect',extractFunctionBlock(text,'SelectBoundaryHelper'), ...
        'referenceMask',extractFunctionBlock(text,'ResolveReferenceMask'), ...
        'mlpTrain',extractFunctionBlock(text,'TrainBoundaryMLP'));
end

function block = extractBetweenMarkers(text,startPattern,endPattern)
    lines = splitSourceLines(text);
    startIdx = findLine(lines,startPattern,1);
    endIdx = findLine(lines,endPattern,startIdx);
    block = strjoin(lines(startIdx:endIdx),newline);
end

function block = extractFunctionBlock(text,name)
    lines = splitSourceLines(text);
    startPattern = ['^function.*' regexptranslate('escape',name) '\s*\('];
    startIdx = findLine(lines,startPattern,1);
    endIdx = numel(lines);
    for i = startIdx + 1 : numel(lines)
        if ~isempty(regexp(lines{i},'^(function\b|%%\s*=+)','once'))
            endIdx = i - 1;
            break;
        end
    end
    block = strjoin(lines(startIdx:endIdx),newline);
end

function idx = findLine(lines,pattern,startIdx)
    idx = [];
    for i = startIdx : numel(lines)
        if ~isempty(regexp(lines{i},pattern,'once'))
            idx = i;
            return;
        end
    end
    assert(~isempty(idx), ...
        'test_PRBCCMO_semantics:MissingBlock', ...
        'Failed to locate source block for pattern: %s', ...
        pattern);
end

function lines = splitSourceLines(text)
    lines = regexp(text,'\r\n|\n|\r','split');
end

function text = normalizeText(text)
    text = stripMatlabComments(text);
    text = strrep(text,'...','');
    text = regexprep(text,'\s+','');
end

function text = stripMatlabComments(text)
    lines = splitSourceLines(text);
    for i = 1 : numel(lines)
        lines{i} = stripLineComment(lines{i});
    end
    text = strjoin(lines,newline);
end

function line = stripLineComment(line)
    inString = false;
    i = 1;
    while i <= length(line)
        if line(i) == ''''
            if inString && i < length(line) && line(i+1) == ''''
                i = i + 2;
                continue;
            end
            inString = ~inString;
            i = i + 1;
            continue;
        end
        if line(i) == '%' && ~inString
            line = line(1:i-1);
            return;
        end
        i = i + 1;
    end
end
