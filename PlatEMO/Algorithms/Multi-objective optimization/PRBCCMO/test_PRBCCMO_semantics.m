function test_PRBCCMO_semantics()
% Regression guard for PRBCCMO boundary-learning semantics.

    rootDir = fileparts(mfilename('fullpath'));
    mainText = fileread(fullfile(rootDir,'PRBCCMO.m'));
    traceText = fileread(fullfile(rootDir,'PRBCCMO_t.m'));

    requireContains(mainText,'[Core,CoreSource]=BuildCoreTrainPopulation(B,RecentBoundaryOff);', ...
        'test_PRBCCMO_semantics:MainCoreTrain', ...
        'PRBCCMO.m must build the training core from B and RecentBoundaryOff.');
    requireContains(traceText,'[Core,CoreSource]=BuildCoreTrainPopulation(B,RecentBoundaryOff);', ...
        'test_PRBCCMO_semantics:TraceCoreTrain', ...
        'PRBCCMO_t.m must build the training core from B and RecentBoundaryOff.');

    requireContains(mainText,'BridgeMask=ResolveBridgeBoundaryMask(Meta,TrainArchive,SectorNeighbors,size(W,1));', ...
        'test_PRBCCMO_semantics:MainBridgeGateMask', ...
        'PRBCCMO.m must gate untrusted sectors through bridge-qualified admission.');
    requireContains(mainText,'B=SelectTopKPerSector(CandidateB,Meta,BridgeMask,kappa);', ...
        'test_PRBCCMO_semantics:MainBridgeGateSelect', ...
        'PRBCCMO.m must pass BridgeMask into sector-wise boundary admission.');
    requireContains(traceText,'BridgeMask=ResolveBridgeBoundaryMask(Meta,TrainArchive,SectorNeighbors,size(W,1));', ...
        'test_PRBCCMO_semantics:TraceBridgeGateMask', ...
        'PRBCCMO_t.m must gate untrusted sectors through bridge-qualified admission.');
    requireContains(traceText,'B=SelectTopKPerSector(CandidateB,Meta,BridgeMask,kappa);', ...
        'test_PRBCCMO_semantics:TraceBridgeGateSelect', ...
        'PRBCCMO_t.m must pass BridgeMask into sector-wise boundary admission.');

    requireContains(mainText,'TrainArchive=TrimTrainArchiveBySectorQuota(TrainArchive,MaxTrain);', ...
        'test_PRBCCMO_semantics:MainSectorQuota', ...
        'PRBCCMO.m must trim the train archive by sector-wise quotas.');
    requireContains(traceText,'TrainArchive=TrimTrainArchiveBySectorQuota(TrainArchive,MaxTrain);', ...
        'test_PRBCCMO_semantics:TraceSectorQuota', ...
        'PRBCCMO_t.m must trim the train archive by sector-wise quotas.');

    requireNotContains(mainText,'CalibArchive=InitCalibrationArchive(Problem.D);', ...
        'test_PRBCCMO_semantics:MainNoInitCalibArchive', ...
        'PRBCCMO.m must not initialize a calibration archive after the plain-BCE cleanup.');
    requireNotContains(traceText,'CalibArchive=InitCalibrationArchive(Problem.D);', ...
        'test_PRBCCMO_semantics:TraceNoInitCalibArchive', ...
        'PRBCCMO_t.m must not initialize a calibration archive after the plain-BCE cleanup.');

    requireNotContains(mainText,'CalibArchive=UpdateCalibrationArchive(CalibArchive,BoundaryOff,Problem.FE,MaxCalib);', ...
        'test_PRBCCMO_semantics:MainNoUpdateCalibArchive', ...
        'PRBCCMO.m must not update a calibration archive after the plain-BCE cleanup.');
    requireNotContains(traceText,'CalibArchive=UpdateCalibrationArchive(CalibArchive,BoundaryOff,Problem.FE,MaxCalib);', ...
        'test_PRBCCMO_semantics:TraceNoUpdateCalibArchive', ...
        'PRBCCMO_t.m must not update a calibration archive after the plain-BCE cleanup.');

    requireNotContains(mainText,'TrainArchive.BoundWeight', ...
        'test_PRBCCMO_semantics:MainNoTrainArchiveBoundWeight', ...
        'PRBCCMO.m must not keep BoundWeight in the train archive after the plain-BCE cleanup.');
    requireNotContains(traceText,'TrainArchive.BoundWeight', ...
        'test_PRBCCMO_semantics:TraceNoTrainArchiveBoundWeight', ...
        'PRBCCMO_t.m must not keep BoundWeight in the train archive after the plain-BCE cleanup.');

    requireNotContains(mainText,'Meta.boundWeight', ...
        'test_PRBCCMO_semantics:MainNoMetaBoundWeight', ...
        'PRBCCMO.m must not propagate boundary weights through meta rows after the plain-BCE cleanup.');
    requireNotContains(traceText,'Meta.boundWeight', ...
        'test_PRBCCMO_semantics:TraceNoMetaBoundWeight', ...
        'PRBCCMO_t.m must not propagate boundary weights through meta rows after the plain-BCE cleanup.');

    requireNotContains(mainText,'[Weight,NormWeight]=BuildSampleWeights(Y,TrainArchive.BoundWeight,TrainArchive.Source);', ...
        'test_PRBCCMO_semantics:MainNoSampleWeights', ...
        'PRBCCMO.m must not build weighted BCE sample weights after the plain-BCE cleanup.');
    requireNotContains(traceText,'[Weight,NormWeight]=BuildSampleWeights(Y,TrainArchive.BoundWeight,TrainArchive.Source);', ...
        'test_PRBCCMO_semantics:TraceNoSampleWeights', ...
        'PRBCCMO_t.m must not build weighted BCE sample weights after the plain-BCE cleanup.');

    requireNotContains(mainText,'BoundWeight=ComputeBoundaryWeights(Candidates.decs,CandLabel,Sector,EvalPool.decs,RefLabel,RefSector,SectorNeighbors);', ...
        'test_PRBCCMO_semantics:MainNoComputeBoundaryWeights', ...
        'PRBCCMO.m must not compute boundary weights after the plain-BCE cleanup.');
    requireNotContains(traceText,'BoundWeight=ComputeBoundaryWeights(Candidates.decs,CandLabel,Sector,EvalPool.decs,RefLabel,RefSector,SectorNeighbors);', ...
        'test_PRBCCMO_semantics:TraceNoComputeBoundaryWeights', ...
        'PRBCCMO_t.m must not compute boundary weights after the plain-BCE cleanup.');

    requireNotContains(mainText,'Model.T=FitTemperatureScaling(Model,CalibArchive);', ...
        'test_PRBCCMO_semantics:MainNoTemperatureScaling', ...
        'PRBCCMO.m must not apply temperature scaling after the plain-BCE cleanup.');
    requireNotContains(traceText,'Model.T=FitTemperatureScaling(Model,CalibArchive);', ...
        'test_PRBCCMO_semantics:TraceNoTemperatureScaling', ...
        'PRBCCMO_t.m must not apply temperature scaling after the plain-BCE cleanup.');
end

function requireContains(text,pattern,identifier,messageText)
    assert(contains(normalizeSourceText(text),normalizeSourceText(pattern)),identifier,'%s',messageText);
end

function requireNotContains(text,pattern,identifier,messageText)
    assert(~contains(normalizeSourceText(text),normalizeSourceText(pattern)),identifier,'%s',messageText);
end

function text = normalizeSourceText(text)
    text = regexprep(text,'%[^\n\r]*','');
    text = strrep(text,'...','');
    text = regexprep(text,'\s+','');
end
