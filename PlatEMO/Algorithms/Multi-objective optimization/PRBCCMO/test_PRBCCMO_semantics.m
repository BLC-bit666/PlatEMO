function test_PRBCCMO_semantics()
% Static guard for the PRBCCMO-v2 objective-boundary contract.

    rootDir = fileparts(mfilename('fullpath'));
    mainText = normalizeCode(fileread(fullfile(rootDir,'PRBCCMO.m')));
    traceText = normalizeCode(fileread(fullfile(rootDir,'PRBCCMO_t.m')));
    coreText = normalizeCode(fileread(fullfile(rootDir,'PRBCCMO_objective_core.m')));

    requireContains(mainText, ...
        '[Params{:}]=Algorithm.ParameterSet(40,80,0.05,4,0.1,20,150);', ...
        'test_PRBCCMO_semantics:MainParameters', ...
        'PRBCCMO must default to the selected IGD-tuned parameter set.');
    requireContains(traceText, ...
        '[Params{:}]=Algorithm.ParameterSet(40,80,0.05,4,0.1,20,150,0);', ...
        'test_PRBCCMO_semantics:TraceParameters', ...
        'PRBCCMO_t must default to the selected IGD-tuned parameter set.');
    requireContains(traceText,'Algorithm.metric.analysis_core_csv=Observer.core_file;', ...
        'test_PRBCCMO_semantics:AnalysisCoreCsv', ...
        'PRBCCMO_t must expose core_metrics.csv.');
    requireContains(coreText,'''core_file'',fullfile(RunFolder,''core_metrics.csv'')', ...
        'test_PRBCCMO_semantics:CoreFile', ...
        'The observer must use core_metrics.csv.');

    Fields = coreMetricColumns();
    for i = 1 : numel(Fields)
        requireContains(coreText,['''',Fields{i},''''], ...
            ['test_PRBCCMO_semantics:CoreField_',Fields{i}], ...
            ['core_metrics.csv is missing required field ',Fields{i},'.']);
    end
    requireContains(coreText,'[BatchDec,RefineInfo]=InjectBoundaryRefinementIntoHelperOffspring', ...
        'test_PRBCCMO_semantics:RefineInfoReturned', ...
        'Helper refinement must return RefineInfo for same-pair contraction.');
    requireContains(coreText,'Kbis=3;', ...
        'test_PRBCCMO_semantics:FixedKbis', ...
        'Boundary refinement must use internal Kbis=3.');
    requireContains(coreText,'ContractBoundaryPairsByRefinedSamples', ...
        'test_PRBCCMO_semantics:SamePairContraction', ...
        'Refined samples must attempt strict bracket same-pair contraction.');
    requireContains(coreText,'IsBracketTighter', ...
        'test_PRBCCMO_semantics:BracketTighterGate', ...
        'Same-pair contraction must accept only tighter brackets.');
    requireContains(coreText,'BuildTrainingBufferT', ...
        'test_PRBCCMO_semantics:TrainingBufferT', ...
        'MLP training must use T = B + recent refinement + small real boundary-band.');
    requireContains(coreText,'BalanceTrainingDataset', ...
        'test_PRBCCMO_semantics:BalancedTraining', ...
        'MLP training must use 1:1 feasible/infeasible balanced batches.');
    requireContains(coreText,'Key=[Meta.frontGap(idx),-Meta.prob(idx),Meta.supportDistObjToB(idx),idx];', ...
        'test_PRBCCMO_semantics:UnifiedInfeasibleKey', ...
        'Infeasible selection must use [FrontGap, -prob, DistToB, index].');
    requireContains(coreText,'Carry=min(max(1,round(0.01*N)),numel(Infeasible));', ...
        'test_PRBCCMO_semantics:CarrySlot', ...
        'Model-ready selection must reserve a one-percent infeasible carry slot.');
    requireNotContains(coreText,'ModelDegraded=IsBoundaryModelDegradedForCarry(MLPDiag);', ...
        'test_PRBCCMO_semantics:NoCarryDegradationCheck', ...
        'Carry gate must not be hard-disabled by training accuracy degradation.');
    requireNotContains(coreText,'NeedGeometry', ...
        'test_PRBCCMO_semantics:NoNeedGeometrySwitch', ...
        'Boundary geometry must be computed for infeasible selection even when the model is ready.');
    requireNotContains(coreText,'BuildDatasetFromBoundaryArchive', ...
        'test_PRBCCMO_semantics:NoBOnlyDatasetBuilder', ...
        'MLP training must no longer be pure B-only.');
    requireNotContains(coreText,'CarryPick=Population([]);', ...
        'test_PRBCCMO_semantics:NoUnusedCarryPickInit', ...
        'Carry selection must not keep an unused CarryPick initialization.');
    requireNotContains(coreText,'ifnumel(Feasible)>=NPopulation=ObjectiveSelectionWithLastSectorTruncation(Feasible,N,W);return;', ...
        'test_PRBCCMO_semantics:NoFeasibleEarlyReturn', ...
        'Feasible>=N must not bypass the model-ready carry slot.');
    requireNoForbiddenCoreFields(coreText);
    requireNoPairwiseRankLoss(coreText);
end

