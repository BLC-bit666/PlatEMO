function test_PRBCCMO_semantics()
% Static regression guard for the boundary-band fix.md semantics.

    rootDir = fileparts(mfilename('fullpath'));
    mainText  = normalizeCode(fileread(fullfile(rootDir,'PRBCCMO.m')));
    traceText = normalizeCode(fileread(fullfile(rootDir,'PRBCCMO_t.m')));

    verifyBoundaryBandSemantics(mainText,'Main');
    verifyBoundaryBandSemantics(traceText,'Trace');
end

function verifyBoundaryBandSemantics(text,prefix)
    requireContains(text, ...
        'ModelState.trainBuffer=InitTrainingBuffer();', ...
        [prefix 'TrainingBufferState'], ...
        'Model state must keep a rolling training buffer.');
    requireContains(text, ...
        '[ModelState.trainBuffer,BufferDiag,ModelState.lastCandidateDec]=UpdateTrainingBuffer(', ...
        [prefix 'UpdateTrainingBuffer'], ...
        'Training evidence must be updated through a rolling boundary-band buffer.');
    requireContains(text, ...
        'Band=CollectSectorBoundaryBand(', ...
        [prefix 'CollectSectorBoundaryBand'], ...
        'Dataset construction must collect sector-local boundary-band samples.');
    requireContains(text, ...
        'BuildBoundaryDatasetFromBuffer(', ...
        [prefix 'DatasetFromBuffer'], ...
        'MLP training data must be built from the buffer, not fixed pairs.');
    requireContains(text, ...
        'Model=TrainBoundaryMLP(Model,Dataset,hidden,epoch,lr,Mode);', ...
        [prefix 'WarmStartSignature'], ...
        'TrainBoundaryMLP must accept the previous model and an explicit cold/finetune mode.');
    requireContains(text, ...
        'CanWarmStartBoundaryMLP(Model,D,Hidden)', ...
        [prefix 'WarmStartGuard'], ...
        'MLP training must reuse compatible weights instead of always random restarting.');
    requireContains(text, ...
        'Summary.new_sample_ratio>=0.20', ...
        [prefix 'BufferChangeTrigger'], ...
        'Retraining must be triggered by meaningful training-buffer change.');
    requireContains(text, ...
        'Summary.mixed_sector_gain>0', ...
        [prefix 'MixedSectorExpansionTrigger'], ...
        'Retraining must react to mixed-sector expansion.');
    requireContains(text, ...
        'Summary.validation_brier>ModelState.lastValidationBrier+0.02', ...
        [prefix 'ValidationDropTrigger'], ...
        'Retraining must react to boundary validation degradation.');
    requireContains(text, ...
        'CandidateMeta.oppSupport>=AnchorOppSupport', ...
        [prefix 'BoundaryOffspringSupportGate'], ...
        'Boundary offspring must not accept lower opposite-side support.');
    requireContains(text, ...
        'CandidateMeta.objScore<=CandidateAnchorObjScore+0.10', ...
        [prefix 'BoundaryOffspringObjectiveGate'], ...
        'Boundary offspring must not accept obvious objective relevance degradation.');
    requireContains(text, ...
        'EvaluatedCandidate=Problem.Evaluation(CandidateDec);', ...
        [prefix 'EvaluatedChildObjectiveMeta'], ...
        'Boundary offspring objective relevance must be checked after child evaluation.');
    requireContains(text, ...
        'CandidateMeta=BuildBoundaryMeta(EvaluatedCandidate,W,Model,PopulationC,PopulationU,SupportBase);', ...
        [prefix 'ChildObjectiveFromEvaluation'], ...
        'Candidate objective score must come from evaluated child objectives, not the parent proxy.');
    requireContains(text, ...
        'NewRows=~ismember(Buffer.Dec,OldDec,''rows'');', ...
        [prefix 'BufferReplacementChange'], ...
        'Buffer-change retraining must count replacement rows even when buffer size is unchanged.');
    requireContains(text, ...
        '[W1,b1,W2,b2]=RebaseBoundaryMLPNormalization(Model,Mu,Sigma);', ...
        [prefix 'WarmStartNormalizationRebase'], ...
        'Warm-start must rebase old weights into the new normalization space.');
    requireContains(text, ...
        'Trusted=FindSupportedBoundaryCandidates(Meta,W);', ...
        [prefix 'SupportedInfeasibleGate'], ...
        'Infeasible selection must hard-gate MLP-guided candidates by real opposite-side support.');
    requireContains(text, ...
        'StablePool=KeepUniquePopulation([PopulationC,PopulationU]);', ...
        [prefix 'StablePoolOnce'], ...
        'Boundary offspring must build the stable parent pool once per generation call.');
    requireContains(text, ...
        'StablePoolBase=BuildOppositeSupportBase(StablePool,W);', ...
        [prefix 'StablePoolBaseOnce'], ...
        'Stable parent support base must be precomputed outside the anchor loop.');
    requireContains(text, ...
        'StablePoolMeta=BuildBoundaryMeta(StablePool,W,[],PopulationC,PopulationU,StablePoolBase);', ...
        [prefix 'StablePoolMetaOnce'], ...
        'Stable parent meta must be precomputed outside the anchor loop.');
    requireContains(text, ...
        'Parent3=SelectStableParentFast(StablePool,StablePoolMeta,ParentMeta.sector(BaseIdx));', ...
        [prefix 'StableParentFast'], ...
        'Stable parent selection must reuse precomputed pool meta.');
    requireContains(text, ...
        'RepC=BuildRepresentativeIndexBySector(PopulationC,W);', ...
        [prefix 'RepresentativePrecomputeC'], ...
        'PopulationC representatives must precompute sector/front/crowding once.');
    requireContains(text, ...
        'RepU=BuildRepresentativeIndexBySector(PopulationU,W);', ...
        [prefix 'RepresentativePrecomputeU'], ...
        'PopulationU representatives must precompute sector/front/crowding once.');
    requireContains(text, ...
        'Z=ComputeIdealPoint(', ...
        [prefix 'IdealPointOnly'], ...
        'Sector association must use ideal points instead of unique reference objective matrices.');
    requireContains(text, ...
        'SupportBase=BuildOppositeSupportBase(Support,W);', ...
        [prefix 'OppositeSupportBase'], ...
        'Opposite-side support must cache support labels, neighbors, and distance scale before meta reuse.');
    requireContains(text, ...
        'SupportCache=ResolveOppositeSupportCache(Support,W,RefObj);', ...
        [prefix 'OppositeSupportResolve'], ...
        'Boundary meta must resolve sectors from a reusable support cache instead of rebuilding all support data.');
    requireContains(text, ...
        'OppSupport=ComputeOppositeSupportFromCache(', ...
        [prefix 'OppositeSupportFromCache'], ...
        'Opposite-side support queries must reuse cached support data.');
    requireContains(text, ...
        'if~HaveDecisionRowsChanged(LastCandidateDec,PreviousCandidateDec)', ...
        [prefix 'TrainingBufferCandidateChangeGate'], ...
        'Training buffer update must skip sector/opposite-distance rebuild when the candidate set is unchanged.');
    requireContains(text, ...
        'Eligible=ResolveTrainingCandidateEligibility(', ...
        [prefix 'TrainingBufferIncrementalEligibility'], ...
        'Training buffer update must restrict opposite-distance work to new/core boundary candidates.');
    requireContains(text, ...
        'OppDist=ComputeOppositeDistanceForCandidates(Population.decs,Label,Sector,W,Eligible);', ...
        [prefix 'TrainingBufferEligibleOppDist'], ...
        'Training buffer opposite-distance computation must accept an eligibility mask.');
    requireContains(text, ...
        '[Population,Source]=MergeTrainingSourcePopulations(B,RecentBoundaryOff,PopulationC,PopulationU);', ...
        [prefix 'TrainingSourceDirectTags'], ...
        'Training candidate source tags must be carried during concatenation instead of recovered by repeated ismember.');
    requireContains(text, ...
        'CandidateDec=zeros(Budget,size(ParentPool.decs,2));', ...
        [prefix 'CandidatePreallocation'], ...
        'Boundary offspring candidates must be preallocated by budget.');
    requireContains(text, ...
        'RecentBoundaryOff=BoundaryOff;B=UpdateBoundaryArchive(B,RecentBoundaryOff,PopulationC,PopulationU,W,Model,kappa);', ...
        [prefix 'EndOfGenerationArchiveUpdate'], ...
        'Boundary archive must be updated once at the end of the generation with the selected populations.');
    requireContains(text, ...
        'B=UpdateBoundaryArchive(B,RecentBoundaryOff,PopulationC,PopulationU,W,Model,kappa);[Model,ModelState', ...
        [prefix 'ArchiveBeforeModelUpdate'], ...
        'Boundary model updates must use the end-of-generation archive and populations.');

    requireNotContains(text, ...
        'CollectLocalBoundaryPairs(', ...
        [prefix 'NoPairCollector'], ...
        'Fixed feasible/infeasible pair collectors must be removed.');
    requireNotContains(text, ...
        'Summary.pair_ready', ...
        [prefix 'NoPairReadyTrigger'], ...
        'Retraining must not use pair-ready gates.');
    requireNotContains(text, ...
        'CurrentFE-ModelState.lastTrainFE>=2*Problem.N', ...
        [prefix 'NoFEOnlyTrigger'], ...
        'Retraining must not be controlled by a fixed FE interval.');
    requireNotContains(text, ...
        'Model=TrainBoundaryMLP(Dataset,hidden,epoch,lr);', ...
        [prefix 'NoColdOnlyTrainCall'], ...
        'MLP training must not use the old cold-start-only signature.');
    requireNotContains(text, ...
        'ProxyObjScore=ParentMeta.objScore(BaseIdx);', ...
        [prefix 'NoParentProxyObjectiveGate'], ...
        'Boundary offspring objective relevance must not reuse the anchor objective score as the child score.');
    requireNotContains(text, ...
        'Added=max(0,NewSize-OldSize);', ...
        [prefix 'NoSizeOnlyBufferChange'], ...
        'Buffer-change retraining must not depend only on buffer size growth.');
    requireNotContains(text, ...
        'W1=Model.W1;', ...
        [prefix 'NoRawWarmStartWeights'], ...
        'Warm-start must not reuse first-layer weights without normalization rebasing.');
    requireNotContains(text, ...
        'BuildReferenceObj(', ...
        [prefix 'NoReferenceObjMatrix'], ...
        'Code must not build unique reference objective matrices when only the ideal point is needed.');
    requireNotContains(text, ...
        'PickRepresentativeInSector(', ...
        [prefix 'NoPerSectorRepresentativeRecompute'], ...
        'Representative selection must not recompute sectors, fronts, and crowding inside each sector.');
    requireNotContains(text, ...
        'PoolMeta=BuildBoundaryMeta(Pool,W,[],PopulationC,PopulationU,Pool);', ...
        [prefix 'NoStableParentMetaInLoop'], ...
        'Stable parent selection must not rebuild pool meta inside the anchor loop.');
    requireNotContains(text, ...
        'Source(ismember(Population.decs', ...
        [prefix 'NoSourceRecoveryIsmember'], ...
        'Training source recovery must not use repeated row-wise ismember calls.');
    requireNotContains(text, ...
        'SupportCache=BuildOppositeSupportCache(Support,W,RefObj);', ...
        [prefix 'NoMetaLocalSupportCacheBuild'], ...
        'BuildBoundaryMeta must not rebuild the full support cache on every call.');
    requireNotContains(text, ...
        'Pick(end+1,:)', ...
        [prefix 'NoRoundRobinDynamicPickGrowth'], ...
        'Sector round-robin selection must preallocate its pick matrix.');
    requireNotContains(text, ...
        'Dist=[Dist;', ...
        [prefix 'NoDistanceScaleDynamicGrowth'], ...
        'Distance-scale estimation must preallocate pairwise distance storage.');
    requireNotContains(text, ...
        'Ranked=[Ranked;', ...
        [prefix 'NoDatasetRankedDynamicGrowth'], ...
        'Boundary dataset construction must preallocate ranked replay indices.');
    requireNotContains(text, ...
        'B=UpdateBoundaryArchive(B,BoundaryOff,PopulationC,PopulationU,W,Model,kappa);', ...
        [prefix 'NoPreSelectionBoundaryArchiveUpdate'], ...
        'Boundary archive must not be rebuilt with boundary offspring before environmental selection.');
end

function requireContains(text,pattern,id,msg)
    assert(contains(text,normalizeCode(pattern)),id,msg);
end

function requireNotContains(text,pattern,id,msg)
    assert(~contains(text,normalizeCode(pattern)),id,msg);
end

function text = normalizeCode(text)
    text = regexprep(text,'%[^\n\r]*','');
    text = strrep(text,'...','');
    text = regexprep(text,'\s+','');
end
