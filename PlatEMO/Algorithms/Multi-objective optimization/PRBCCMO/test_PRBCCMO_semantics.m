function requireContains(text,pattern,id,msg)
    assert(contains(text,normalizeCode(pattern)),id,msg);
end

function requireNotContains(text,pattern,id,msg)
    assert(~contains(text,normalizeCode(pattern)),id,msg);
end

function text = normalizeCode(text)
    text = regexprep(text,'%[^\n\r]*','');
    text = strrep(text,'...','');
    text = regexprep(text,'\s+','');
end
