function test_PRBCCMO_semantics()
% Static regression guard for the boundary-band fix.md semantics.

    rootDir = fileparts(mfilename('fullpath'));
    mainText  = normalizeCode(fileread(fullfile(rootDir,'PRBCCMO.m')));
    traceText = normalizeCode(fileread(fullfile(rootDir,'PRBCCMO_t.m')));

    verifyBoundaryBandSemantics(mainText,'Main');
    verifyBoundaryBandSemantics(traceText,'Trace');
end

