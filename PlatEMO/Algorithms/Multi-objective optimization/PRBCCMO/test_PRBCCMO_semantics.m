function requireNoForbiddenCoreFields(coreText)
    Forbidden = { ...
        'b_size','b_sector_coverage','b_mean_age', ...
        'train_brier_after','train_logloss_after', ...
        'inf_supportdistobj_gain','inf_frontgap_gain','inf_selected_sector_coverage'};
    for i = 1 : numel(Forbidden)
        requireNotContains(coreText,Forbidden{i}, ...
            ['test_PRBCCMO_semantics:NoCore_',Forbidden{i}], ...
            ['core_metrics.csv must not expose non-core field ',Forbidden{i},'.']);
    end
end

function requireNoPairwiseRankLoss(coreText)
    lowerText = lower(coreText);
    Forbidden = {'pairwise','rank_lambda','rankloss','rank_loss','rankingloss','ranking_loss'};
    for i = 1 : numel(Forbidden)
        requireNotContains(lowerText,Forbidden{i}, ...
            ['test_PRBCCMO_semantics:No_',Forbidden{i}], ...
            ['MLP code must not depend on pairwise/rank-loss text: ',Forbidden{i}]);
    end
end

function requireContains(text,pattern,id,message)
    assert(contains(text,normalizeCode(pattern)),id,message);
end

function requireNotContains(text,pattern,id,message)
    assert(~contains(text,normalizeCode(pattern)),id,message);
end

function text = normalizeCode(text)
    text = lower(regexprep(text,'\s+',''));
end
