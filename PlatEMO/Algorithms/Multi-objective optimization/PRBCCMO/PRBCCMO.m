%% ========== Round-robin picker ==========

function Pick = SectorRoundRobinPick(Ranked,MaxPick)
    Pick = zeros(0,2);
    if isempty(Ranked) || MaxPick <= 0
        return;
    end

    Ptr = ones(numel(Ranked),1);
    while size(Pick,1) < MaxPick
        Changed = false;
        for s = 1 : numel(Ranked)
            if Ptr(s) <= numel(Ranked{s})
                Pick(end+1,:) = [s,Ranked{s}(Ptr(s))]; %#ok<AGROW>
                Ptr(s) = Ptr(s) + 1;
                Changed = true;
                if size(Pick,1) >= MaxPick
                    break;
                end
            end
        end
        if ~Changed
            break;
        end
    end
end

%% ========== Objective dominance ==========

function Flag = DominatesObjectiveRow(A,B)
    Tol  = 1e-12;
    Flag = all(A <= B + Tol) && any(A < B - Tol);
end
