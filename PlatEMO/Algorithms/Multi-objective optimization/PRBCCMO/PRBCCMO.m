function BatchIdx = BuildBalancedReplayBatch(PosIdx,NegIdx)
    BatchIdx = zeros(0,1);
    if isempty(PosIdx) || isempty(NegIdx)
        return;
    end

    Target = max(1,numel(PosIdx));
    PosPick = PosIdx(randi(numel(PosIdx),Target,1));
    if numel(NegIdx) >= Target
        NegPick = NegIdx(randperm(numel(NegIdx),Target));
    else
        NegPick = NegIdx(randi(numel(NegIdx),Target,1));
    end
    BatchIdx = [PosPick(:);NegPick(:)];
    BatchIdx = BatchIdx(randperm(numel(BatchIdx)));
end

