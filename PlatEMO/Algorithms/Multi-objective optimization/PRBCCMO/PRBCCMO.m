function [Candidates,Source,Weight] = BuildAnchorPairTrainPopulation( ...
    B,RecentBoundaryOff,PopulationC,PopulationU,W,RefObj,kNeg,MinAnchor)
    [Core,CoreSource] = BuildCoreTrainPopulation(B,RecentBoundaryOff);
    CoreLabel = double(all(Core.cons<=0,2));

    AnchorPop    = Core(CoreLabel == 1);
    AnchorSource = CoreSource(CoreLabel == 1);
    NeedAnchor   = max(0,MinAnchor-numel(AnchorPop));
    if NeedAnchor > 0
        if ~isempty(AnchorPop)
            ExistingDec = AnchorPop.decs;
        elseif ~isempty(PopulationC)
            ExistingDec = zeros(0,size(PopulationC.decs,2));
        elseif ~isempty(Core)
            ExistingDec = zeros(0,size(Core.decs,2));
        elseif ~isempty(PopulationU)
            ExistingDec = zeros(0,size(PopulationU.decs,2));
        else
            ExistingDec = zeros(0,0);
        end
        ExtraAnchor = SelectFeasibleAnchorSupplements( ...
            PopulationC,W,RefObj,ExistingDec,NeedAnchor);
        if ~isempty(ExtraAnchor)
            AnchorPop    = [AnchorPop,PopulationC(ExtraAnchor)];
            AnchorSource = [AnchorSource;3*ones(numel(ExtraAnchor),1)];
        end
    end

    if isempty(AnchorPop)
        Candidates = Core([]);
        Source     = zeros(0,1);
        Weight     = zeros(0,1);
        return;
    end

    CoreNeg       = Core(CoreLabel == 0);
    CoreNegSource = CoreSource(CoreLabel == 0);
    [PairNeg,PairSource,PairWeight] = SelectAnchorOppositeShell( ...
        AnchorPop,CoreNeg,CoreNegSource,PopulationU,kNeg);

    Candidates = [AnchorPop,PairNeg];
    Source     = [AnchorSource;PairSource];
    Weight     = [ones(numel(AnchorPop),1);PairWeight];
    [Candidates,Source,Weight] = CollapseTrainPopulationEntries( ...
        Candidates,Source,Weight);
end

function AnchorIdx = SelectFeasibleAnchorSupplements( ...
    PopulationC,W,RefObj,ExistingDec,Need)
    AnchorIdx = zeros(0,1);
    if Need <= 0 || isempty(PopulationC)
        return;
    end

    FeasibleMask = all(PopulationC.cons<=0,2);
    if ~any(FeasibleMask)
        return;
    end

    Taken = false(numel(PopulationC),1);
    if ~isempty(ExistingDec)
        Taken = ismember(PopulationC.decs,ExistingDec,'rows');
    end

    Sector = AssociateSectorsLocal(PopulationC.objs,W,RefObj);
    Scalar = ComputeSectorScalar(PopulationC.objs,W,RefObj,Sector);
    Rep    = BuildSectorRepresentatives(PopulationC,W,RefObj,FeasibleMask);
    RepIdx = Rep.idx(Rep.has);
    RepIdx = RepIdx(~Taken(RepIdx));
    if ~isempty(RepIdx)
        Key = [Scalar(RepIdx), RepIdx(:)];
        [~,ord] = sortrows(Key,[1 2]);
        Use = RepIdx(ord(1:min(Need,numel(ord))));
        AnchorIdx = [AnchorIdx;Use(:)]; %#ok<AGROW>
        Taken(Use) = true;
    end

    if numel(AnchorIdx) >= Need
        return;
    end

    Rest = find(FeasibleMask & ~Taken);
    if isempty(Rest)
        return;
    end
    Key = [Scalar(Rest), ResolveTrainSourcePriority(3*ones(numel(Rest),1)), Rest(:)];
    [~,ord] = sortrows(Key,[1 2 3]);
    NeedMore = min(Need-numel(AnchorIdx),numel(ord));
    AnchorIdx = [AnchorIdx;Rest(ord(1:NeedMore))]; %#ok<AGROW>
end

function [PairNeg,PairSource,PairWeight] = SelectAnchorOppositeShell( ...
    AnchorPop,CoreNeg,CoreNegSource,PopulationU,kNeg)
    PairNeg    = AnchorPop([]);
    PairSource = zeros(0,1);
    PairWeight = zeros(0,1);
    if isempty(AnchorPop) || kNeg <= 0
        return;
    end

    SupplementNeg = PopulationU(any(PopulationU.cons>0,2));
    NegPool       = [CoreNeg,SupplementNeg];
    NegSource     = [CoreNegSource;4*ones(numel(SupplementNeg),1)];
    if isempty(NegPool)
        return;
    end

    NegDec   = NegPool.decs;
    UseCount = zeros(numel(NegPool),1);
    for i = 1 : numel(AnchorPop)
        Need = kNeg;
        AnchorDec = AnchorPop(i).decs;
        for src = [1 2 4]
            if Need <= 0
                break;
            end
            Local = find(NegSource == src);
            if isempty(Local)
                continue;
            end
            Dist = sqrt(sum((NegDec(Local,:) - AnchorDec).^2,2));
            Key  = [Dist(:), Local(:)];
            [~,ord] = sortrows(Key,[1 2]);
            Use = Local(ord(1:min(Need,numel(ord))));
            UseCount(Use) = UseCount(Use) + 1;
            Need = Need - numel(Use);
        end
    end

    Pick       = find(UseCount > 0);
    PairNeg    = NegPool(Pick);
    PairSource = NegSource(Pick);
    PairWeight = UseCount(Pick);
end

function [Population,Source,Weight] = CollapseTrainPopulationEntries( ...
    Population,Source,Weight)
    if isempty(Population)
        Source = zeros(0,1);
        Weight = zeros(0,1);
        return;
    end

    [~,Keep,Group] = unique(double(Population.decs),'rows','stable');
    Population = Population(Keep);
    Source     = Source(Keep);
    Weight     = accumarray(Group,Weight(:),[numel(Keep),1],@sum,0);

    Label = double(all(Population.cons<=0,2));
    Weight(Label == 1) = 1;
end

function Pick = SelectNearestNegativeRows(TrainArchive,AnchorPick,kNeg,MaxPick)
    Pick = zeros(0,1);
    if isempty(AnchorPick) || kNeg <= 0 || MaxPick <= 0
        return;
    end

    NegIdx = find(TrainArchive.Label == 0);
    if isempty(NegIdx)
        return;
    end

    NegDec = TrainArchive.Dec(NegIdx,:);
    Taken  = false(numel(NegIdx),1);
    for i = 1 : numel(AnchorPick)
        if numel(Pick) >= MaxPick
            return;
        end
        Need = min(kNeg,MaxPick-numel(Pick));
        AnchorDec = TrainArchive.Dec(AnchorPick(i),:);
        for src = [1 2 4]
            if Need <= 0
                break;
            end
            Local = find(TrainArchive.Source(NegIdx) == src & ~Taken);
            if isempty(Local)
                continue;
            end
            Dist = sqrt(sum((NegDec(Local,:) - AnchorDec).^2,2));
            Key = [Dist(:), -TrainArchive.Time(NegIdx(Local)), ...
                   -TrainArchive.Weight(NegIdx(Local)), Local(:)];
            [~,ord] = sortrows(Key,[1 2 3 4]);
            Use = Local(ord(1:min(Need,numel(ord))));
            Pick = [Pick;NegIdx(Use)]; %#ok<AGROW>
            Taken(Use) = true;
            Need = Need - numel(Use);
        end
    end
end

