        'brier',NaN, ...
        'logloss',NaN, ...
        'precision',NaN, ...
        'recall',NaN, ...
        'specificity',NaN);
end

function Value = SafeDivide(A,B)
    if B <= 0
        Value = NaN;
    else
        Value = A/B;
    end
end

