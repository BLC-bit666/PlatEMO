function AppendCsvRows(FilePath,Rows)
    if isempty(Rows)
        return;
    end
    if ~iscell(Rows)
        Rows = num2cell(Rows);
    end
    if isvector(Rows)
        Rows = reshape(Rows,1,[]);
    end
    fid = fopen(FilePath,'a');
    Cleaner = onCleanup(@() fclose(fid)); %#ok<NASGU>
    for i = 1 : size(Rows,1)
        Line = cell(1,size(Rows,2));
        for j = 1 : size(Rows,2)
            Line{j} = ToCsvValue(Rows{i,j});
        end
        fprintf(fid,'%s\n',strjoin(Line,','));
    end
end

function S = ToCsvValue(Value)
    if isstring(Value)
        Value = char(Value);
    end
    if ischar(Value)
        Value = strrep(Value,'"','""');
        S = ['"' Value '"'];
    elseif isempty(Value)
        S = '';
    elseif isnumeric(Value) || islogical(Value)
        if isscalar(Value)
            if isnan(Value)
                S = 'NaN';
            elseif isinf(Value)
                S = Ternary(Value > 0,'Inf','-Inf');
            else
                S = sprintf('%.15g',double(Value));
            end
        else
            Flat = Value(:)';
            Parts = arrayfun(@(x)sprintf('%.15g',double(x)),Flat,'UniformOutput',false);
            S = ['"' strjoin(Parts,';') '"'];
        end
    else
        S = ['"' char(string(Value)) '"'];
    end
end

function Out = Ternary(Cond,A,B)
    if Cond
        Out = A;
    else
        Out = B;
    end
end

