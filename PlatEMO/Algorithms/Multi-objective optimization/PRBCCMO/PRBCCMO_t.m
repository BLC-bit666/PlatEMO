function Pick = SelectArchiveRowsBySectorQuota(TrainArchive,MaxTrain)
    CandidateIdx = (1:size(TrainArchive.Dec,1))';
    if isempty(CandidateIdx) || MaxTrain <= 0
        Pick = zeros(0,1);
        return;
    end

    CandidateIdx = CandidateIdx(:);
    Quota = [2 2 1 1];
    Key = [-TrainArchive.Time(CandidateIdx), CandidateIdx];
    [~,ord] = sortrows(Key,[1 2]);
    Sorted = CandidateIdx(ord);
    Pick = zeros(0,1);
    SectorCount = zeros(max([TrainArchive.Sector(:);0]),numel(Quota));
    for i = 1 : numel(Sorted)
        idx = Sorted(i);
        sec = TrainArchive.Sector(idx);
        src = TrainArchive.Source(idx);
        if sec <= 0 || src < 1 || src > numel(Quota)
            continue;
        end
        if SectorCount(sec,src) < Quota(src)
            Pick(end+1,1) = idx; %#ok<AGROW>
            SectorCount(sec,src) = SectorCount(sec,src) + 1;
            if numel(Pick) >= MaxTrain
                return;
            end
        end
    end
end

