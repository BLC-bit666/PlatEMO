function ObjScore = ComputeBoundaryObjectiveScore(Candidates,PopulationC,W,RefObj,Sector)
    N = numel(Candidates);
    ObjScore = zeros(N,1);
    if isempty(Candidates)
        return;
    end

    Scalar = ComputeSectorScalar(Candidates.objs,W,RefObj,Sector);
    [FrontNo,~] = NDSort(Candidates.objs,numel(Candidates));
    if isempty(FrontNo) || max(FrontNo) <= 1
        FrontScore = zeros(N,1);
    else
        FrontScore = (FrontNo(:)-1)/max(max(FrontNo)-1,1);
    end

    ScalarScore = zeros(N,1);
    for s = unique(Sector(:))'
        idx = find(Sector == s);
        if isempty(idx)
            continue;
        end
        Value = Scalar(idx);
        Denom = max(Value) - min(Value);
        if Denom > 1e-12
            ScalarScore(idx) = (Value-min(Value))/Denom;
        end
    end

    Dominated = false(N,1);
    RepC = BuildSectorRepresentatives(PopulationC,W,RefObj,[]);
    for i = 1 : N
        s = Sector(i);
        if s > 0 && s <= numel(RepC.has) && RepC.has(s)
            Dominated(i) = DominatesObjectiveRow( ...
                PopulationC(RepC.idx(s)).objs,Candidates(i).objs);
        end
    end

    ObjScore = 0.4*FrontScore + 0.4*ScalarScore + 0.2*double(Dominated);
    ObjScore = max(0,min(1,ObjScore));
end

function Support = BuildBoundarySupportSet( ...
    Candidates,PopulationC,PopulationU,TrainArchive,W,RefObj)
    D = size(Candidates.decs,2);
    Support = struct( ...
        'Dec',zeros(0,D), ...
        'Label',zeros(0,1), ...
        'Sector',zeros(0,1));
    if ~isempty(TrainArchive.Dec)
        CoreMask = IsCoreTrainSource(TrainArchive.Source);
        Support.Dec    = TrainArchive.Dec(CoreMask,:);
        Support.Label  = TrainArchive.Label(CoreMask);
        Support.Sector = TrainArchive.Sector(CoreMask);
    end
    Support = AppendSupportPopulation(Support,Candidates,W,RefObj);
    Support = AppendSupportPopulation(Support,PopulationC,W,RefObj);
    Support = AppendSupportPopulation(Support,PopulationU,W,RefObj);
end

function Support = AppendSupportPopulation(Support,Population,W,RefObj)
    if isempty(Population)
        return;
    end

    Support.Dec    = [Support.Dec;Population.decs];
    Support.Label  = [Support.Label;double(all(Population.cons<=0,2))];
    Support.Sector = [Support.Sector;AssociateSectorsLocal(Population.objs,W,RefObj)];
    Keep = KeepLatestDecisionRowsLocal(Support.Dec);
    Support.Dec    = Support.Dec(Keep,:);
    Support.Label  = Support.Label(Keep);
    Support.Sector = Support.Sector(Keep);
end

function OppDist = ComputeOppositeDistanceByLabel( ...
    CandDec,CandLabel,CandSector,RefDec,RefLabel,RefSector,SectorNeighbors)
    OppDist = inf(size(CandDec,1),1);
    if isempty(CandDec) || isempty(RefDec)
        return;
    end

    for i = 1 : size(CandDec,1)
        Allowed = ResolveReferenceMask(CandSector(i),RefSector,SectorNeighbors);
        Opp = find(Allowed & RefLabel(:) ~= CandLabel(i));
        if isempty(Opp)
            continue;
        end
        Dist = sqrt(sum((RefDec(Opp,:) - CandDec(i,:)).^2,2));
        OppDist(i) = min(Dist);
    end
end

function Mask = ResolveReferenceMask(Sector,RefSector,SectorNeighbors)
    if isempty(RefSector)
        Mask = true(0,1);
        return;
    end
    if Sector <= 0 || Sector > numel(SectorNeighbors)
        Mask = true(numel(RefSector),1);
        return;
    end
    Allowed = unique([Sector;SectorNeighbors{Sector}(:)]);
    Mask = ismember(RefSector(:),Allowed);
end

function Scale = ResolveDistanceScale(Dec)
    if isempty(Dec)
        Scale = 1;
        return;
    end
    Range = max(Dec,[],1) - min(Dec,[],1);
    Scale = norm(Range)/sqrt(max(size(Dec,2),1));
    if ~isfinite(Scale) || Scale < 1e-6
        Scale = 1;
    end
end

%% ========== Sector / representative tools ==========

function [Core,Source] = BuildCoreTrainPopulation(B,RecentBoundaryOff)
    Core = B([]);
    Source = zeros(0,1);
    if ~isempty(B)
        Core = [Core,B];
        Source = [Source;ones(numel(B),1)];
    end
    if ~isempty(RecentBoundaryOff)
        Core = [Core,RecentBoundaryOff];
        Source = [Source;2*ones(numel(RecentBoundaryOff),1)];
    end
    if isempty(Core)
        return;
    end
    Keep = KeepLatestDecisionRowsLocal(Core.decs);
    Core = Core(Keep);
    Source = Source(Keep);
end

function AnchorIdx = SelectMissingSideAnchors( ...
    Core,CoreSector,CoreLabel,Population,Rep,SectorNeighbors,NeededLabel)
    AnchorIdx = zeros(0,1);
    if isempty(Core) || isempty(Population) || isempty(Rep.has)
        return;
    end

    for s = 1 : numel(Rep.has)
        Allowed = ResolveLocalSectorSet(s,SectorNeighbors);
        CoreIdx = find(ismember(CoreSector,Allowed));
        if isempty(CoreIdx)
            continue;
        end

        LocalLabel = unique(CoreLabel(CoreIdx));
        if numel(LocalLabel) > 1 || LocalLabel(1) == NeededLabel
            continue;
        end

        RepSector = Allowed(Rep.has(Allowed));
        if isempty(RepSector)
            continue;
        end

        CandidateIdx = Rep.idx(RepSector);
        Dist = ComputeRepresentativeToCoreDistance( ...
            Population(CandidateIdx),Core(CoreIdx));
        [~,ord] = sortrows([Dist(:),RepSector(:)],[1 2]);
        best = ord(1);
        AnchorIdx(end+1,1) = CandidateIdx(best); %#ok<AGROW>
    end

    AnchorIdx = unique(AnchorIdx,'stable');
end

function Dist = ComputeRepresentativeToCoreDistance(Representatives,Core)
    Dist = inf(numel(Representatives),1);
    if isempty(Representatives) || isempty(Core)
        return;
    end

    CoreDec = Core.decs;
    for i = 1 : numel(Representatives)
        Delta = CoreDec - Representatives(i).decs;
        Dist(i) = min(sqrt(sum(Delta.^2,2)));
    end
end

function Trusted = ResolveTrustedSectorsFromTrainArchive(TrainArchive,SectorNeighbors,K)
    if nargin < 3 || isempty(K)
        K = numel(SectorNeighbors);
    end
    CoreMask = IsCoreTrainSource(TrainArchive.Source);
    Trusted = ResolveTrustedSectors( ...
        TrainArchive.Label(CoreMask),TrainArchive.Sector(CoreMask), ...
        SectorNeighbors,K);
end

function Trusted = ResolveTrustedSectors(Label,Sector,SectorNeighbors,K)
    if nargin < 4 || isempty(K)
        K = max(numel(SectorNeighbors),max([0;Sector(:)]));
    end
    Trusted = false(K,1);
    if isempty(Label) || isempty(Sector)
        return;
    end

    for s = 1 : K
        Allowed = ResolveLocalSectorSet(s,SectorNeighbors);
        Local = Label(ismember(Sector(:),Allowed));
        Trusted(s) = any(Local == 0) && any(Local == 1);
    end
end

function Allowed = ResolveLocalSectorSet(Sector,SectorNeighbors)
    if Sector <= 0 || Sector > numel(SectorNeighbors)
        Allowed = Sector;
        return;
    end
    Allowed = unique([Sector;SectorNeighbors{Sector}(:)]);
end

function Mask = IsTrustedSector(Sector,TrustedSector)
    Mask = false(size(Sector));
    Valid = Sector > 0 & Sector <= numel(TrustedSector);
    Mask(Valid) = TrustedSector(Sector(Valid));
end

function Mask = IsCoreTrainSource(Source)
    Mask = Source(:) == 1 | Source(:) == 2;
end

function Rep = BuildSectorRepresentatives(Population,W,RefObj,Mask)
    K   = size(W,1);
    Rep = struct('has',false(K,1), ...
                 'idx',zeros(K,1), ...
                 'scalar',inf(K,1));
    if isempty(Population) || isempty(RefObj)
        return;
    end
    if nargin < 4 || isempty(Mask)
        Mask = true(numel(Population),1);
    end

    Sector = AssociateSectorsLocal(Population.objs,W,RefObj);
    Scalar = ComputeSectorScalar(Population.objs,W,RefObj,Sector);
    for s = 1 : K
        idx = find(Sector == s & Mask(:));
        if isempty(idx)
            continue;
        end
        [Rep.scalar(s),loc] = min(Scalar(idx));
        Rep.idx(s) = idx(loc);
        Rep.has(s) = true;
    end
end

function RefObj = BuildReferenceObj(varargin)
    RefObj = [];
    for i = 1 : nargin
        Population = varargin{i};
        if ~isempty(Population)
            RefObj = [RefObj;Population.objs]; %#ok<AGROW>
        end
    end
end

function [Sector,Count] = AssociateSectorsLocal(PopObj,W,RefObj)
    if nargin < 3 || isempty(RefObj)
        RefObj = PopObj;
    end
    if isempty(PopObj)
        Sector = zeros(0,1);
        Count  = zeros(size(W,1),1);
        return;
    end
    if isempty(W)
        Sector = ones(size(PopObj,1),1);
        Count  = size(PopObj,1);
        return;
    end

    MinObj = min(RefObj,[],1);
    MaxObj = max(RefObj,[],1);
    Range  = MaxObj - MinObj;
    Range(Range < 1e-12) = 1;

    Obj = (PopObj - MinObj)./Range;
    ObjNorm = sqrt(sum(Obj.^2,2));
    ZeroMask = ObjNorm < 1e-12;
    Obj(ZeroMask,:) = 1;
    ObjNorm(ZeroMask) = sqrt(size(Obj,2));
    Obj = Obj./ObjNorm(:,ones(1,size(Obj,2)));

    WNorm = sqrt(sum(W.^2,2));
    WNorm(WNorm < 1e-12) = 1;
    Wn = W./WNorm(:,ones(1,size(W,2)));

    Cosine = Obj*Wn';
    [~,Sector] = max(Cosine,[],2);
    Count = accumarray(Sector,1,[size(W,1),1]);
end

function Value = ComputeSectorScalar(Obj,W,RefObj,Sector)
    if isempty(Obj)
        Value = zeros(0,1);
        return;
    end
    if nargin < 2 || isempty(W)
        W = ones(1,size(Obj,2));
    end
    if nargin < 3 || isempty(RefObj)
        RefObj = Obj;
    end
    if nargin < 4 || isempty(Sector)
        Weight = repmat(W(1,:),size(Obj,1),1);
    else
        Weight = W(Sector,:);
    end

    MinObj  = min(RefObj,[],1);
    MaxObj  = max(RefObj,[],1);
    Range   = MaxObj - MinObj;
    Range(Range < 1e-12) = 1;
    NormObj = (Obj-MinObj)./Range;
    Value   = sum(NormObj.*Weight,2);
end

function Neighbors = BuildSectorNeighbors(W,NeighborCount)
    K = size(W,1);
    Neighbors = cell(K,1);
    if K <= 1 || NeighborCount <= 0
        return;
    end

    WNorm = sqrt(sum(W.^2,2));
    WNorm(WNorm < 1e-12) = 1;
    Wn = W./WNorm(:,ones(1,size(W,2)));
    Cosine = Wn*Wn';
    Cosine(1:K+1:end) = -inf;

    for i = 1 : K
        [~,ord] = sort(Cosine(i,:),'descend');
        Neighbors{i} = ord(1:min(NeighborCount,K-1));
    end
end

%% ========== Environmental selection ==========

function Population = EnvironmentalSelectionC(Population,N,W)
    Population = KeepUniquePopulation(Population);
    if isempty(Population)
        return;
    end

    Feasible = FilterFeasiblePopulation(Population);
    if numel(Feasible) >= N
        Population = ObjectiveSelectionWithLastSectorTruncation(Feasible,N,W);
    else
        Next   = Feasible;
        Need   = N - numel(Next);
        Remain = RemovePopulationByDecision(Population,Next);
        if Need > 0 && ~isempty(Remain)
            Next = [Next,ObjectiveSelectionWithLastSectorTruncation( ...
                Remain,min(Need,numel(Remain)),W)]; %#ok<AGROW>
        end
        Population = PadPopulation(Next,N);
    end
end

function Population = EnvironmentalSelectionU(Population,N,W)
    Population = KeepUniquePopulation(Population);
    Population = ObjectiveSelectionWithLastSectorTruncation( ...
        Population,min(N,numel(Population)),W);
    Population = PadPopulation(Population,N);
end

function Population = ObjectiveSelectionWithLastSectorTruncation(Population,N,W)
    if isempty(Population)
        return;
    end
    if N <= 0
        Population = Population([]);
        return;
    end

    N = min(N,numel(Population));
    if numel(Population) <= N
        return;
    end

    [FrontNo,MaxFNo] = NDSort(Population.objs,N);
    Next = FrontNo < MaxFNo;
    Last = find(FrontNo == MaxFNo);
    Need = N - sum(Next);
    if Need > 0 && ~isempty(Last)
        PickLast = SelectLastFrontBySector(Population(Last),Need,W,Population.objs);
        Next(Last(PickLast)) = true;
    end
    Population = Population(Next);
end

function Pick = SelectLastFrontBySector(LastPopulation,N,W,RefObj)
    Pick = zeros(0,1);
    if isempty(LastPopulation) || N <= 0
        return;
    end

    N = min(N,numel(LastPopulation));
    if isempty(W)
        CrowdDis = CrowdingDistance(LastPopulation.objs,ones(1,numel(LastPopulation)));
        [~,ord]  = sort(CrowdDis,'descend');
        Pick     = ord(1:N);
        return;
    end

    Sector   = AssociateSectorsLocal(LastPopulation.objs,W,RefObj);
    Scalar   = ComputeSectorScalar(LastPopulation.objs,W,RefObj,Sector);
    CrowdDis = CrowdingDistance(LastPopulation.objs,ones(1,numel(LastPopulation)));
    Ranked   = cell(size(W,1),1);
    for s = 1 : size(W,1)
        idx = find(Sector == s);
        if isempty(idx)
            continue;
        end
        Key = [-CrowdDis(idx)', Scalar(idx), idx];
        [~,ord] = sortrows(Key,[1 2 3]);
        Ranked{s} = idx(ord);
    end
    Order = SectorRoundRobinPick(Ranked,N);
    Pick  = Order(:,2);
end

function Population = PadPopulation(Population,N)
    if isempty(Population)
        return;
    end

    if numel(Population) < N
        Population = [Population,Population(mod(0:N-numel(Population)-1,numel(Population))+1)];
    else
        Population = Population(1:N);
    end
end

%% ========== Parent-selection indicators ==========

function [Flag,FrontNo,CrowdDis] = ConstraintSideIndicator(Population)
    [FrontNo,CrowdDis] = ObjectiveSideIndicator(Population);
    Flag = double(~all(Population.cons<=0,2));
end

function [FrontNo,CrowdDis] = ObjectiveSideIndicator(Population)
    [FrontNo,~] = NDSort(Population.objs,numel(Population));
    CrowdDis    = CrowdingDistance(Population.objs,FrontNo);
end

%% ========== Population utilities ==========

function Population = FilterFeasiblePopulation(Population)
    if isempty(Population)
        return;
    end
    Population = Population(all(Population.cons<=0,2));
end

function Population = KeepUniquePopulation(Population)
    if isempty(Population)
        return;
    end
    Keep = KeepLatestDecisionRowsLocal(Population.decs);
    Population = Population(Keep);
end

function Population = RemovePopulationByDecision(Population,Remove)
    if isempty(Population) || isempty(Remove)
        return;
    end
    Keep = ~ismember(Population.decs,Remove.decs,'rows');
    Population = Population(Keep);
end

function Keep = KeepLatestDecisionRowsLocal(Dec)
    if isempty(Dec)
        Keep = zeros(0,1);
        return;
    end
    [~,Keep] = unique(double(Dec),'rows','last');
    Keep = sort(Keep);
end

%% ========== Round-robin picker ==========

function Pick = SectorRoundRobinPick(Ranked,MaxPick)
    Pick = zeros(0,2);
    if isempty(Ranked) || MaxPick <= 0
        return;
    end

    Ptr = ones(numel(Ranked),1);
    while size(Pick,1) < MaxPick
        Changed = false;
        for s = 1 : numel(Ranked)
            if Ptr(s) <= numel(Ranked{s})
                Pick(end+1,:) = [s,Ranked{s}(Ptr(s))]; %#ok<AGROW>
                Ptr(s) = Ptr(s) + 1;
                Changed = true;
                if size(Pick,1) >= MaxPick
                    break;
                end
            end
        end
        if ~Changed
            break;
        end
    end
end

%% ========== Objective dominance ==========

function Flag = DominatesObjectiveRow(A,B)
    Tol  = 1e-12;
    Flag = all(A <= B + Tol) && any(A < B - Tol);
end
