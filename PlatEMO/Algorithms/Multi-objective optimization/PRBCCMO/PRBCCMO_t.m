classdef PRBCCMO_t < ALGORITHM
% <2026> <multi> <real> <constrained>
% PRBCCMO_t
% Traced PRBCCMO with CSV diagnostics for fix.md module validation
%
% type    --- 1    --- 1.GA, 2.DE
% hidden  --- 20   --- Hidden neurons of the boundary MLP
% epoch   --- 20   --- Training epochs per update
% lr      --- 0.01 --- Learning rate
% minPos  --- 5    --- Minimum feasible samples before first training
% minNeg  --- 20   --- Minimum infeasible samples before first training
% kappa   --- 3    --- Maximum boundary-archive size per sector
% rhoPre  --- 0.08 --- Boundary-evaluation ratio before the MLP is ready
% rhoPost --- 0.15 --- Boundary-evaluation ratio after the MLP is ready
% gapMin  --- 3    --- Minimum model update gap
% gapMax  --- 10   --- Maximum model update gap
%
% PRBCCMO_t keeps PRBCCMO logic unchanged and records CSV diagnostics under
% Data/PRBCCMO_t/<run-folder>. No analysis MAT files are generated.
%
% PRBCCMO follows fix.md strictly:
%   1) P_C approaches CPF and P_U approaches UPF with shared offspring;
%   2) B stores top-k boundary-information samples per sector with soft
%      minority reservation;
%   3) the boundary MLP is warm-start updated from a core set made of B and
%      recent boundary offspring, plus sector anchors from P_C or P_U only
%      when the local core misses one side;
%   4) boundary offspring are generated by a single anchor-helper-probe
%      chain with fixed probe betas and helper candidates drawn only from
%      P_C union P_U;
%   5) archive update, model training, and probe ranking share the same
%      uncertainty + opposite-side support + objective relevance score.

%------------------------------- Copyright --------------------------------
% Copyright (c) 2026 BIMK Group. You are free to use the PlatEMO for
% research purposes. All publications which use this platform or any code
% in the platform should acknowledge the use of "PlatEMO" and reference "Ye
% Tian, Ran Cheng, Xingyi Zhang, and Yaochu Jin, PlatEMO: A MATLAB platform
% for evolutionary multi-objective optimization [educational forum], IEEE
% Computational Intelligence Magazine, 2017, 12(4): 73-87".
%--------------------------------------------------------------------------

    methods
        function main(Algorithm,Problem)
            [W,Problem.N] = UniformPoint(Problem.N,Problem.M);
            [type,hidden,epoch,lr,minPos,minNeg,kappa, ...
                rhoPre,rhoPost,gapMin,gapMax] = ...
                Algorithm.ParameterSet(1,20,20,0.01,5,20,3,0.08,0.15,3,10);

            kappa = max(1,round(kappa));
            MaxTrain = max(6*Problem.N,4*size(W,1));
            ProbeBeta = [0.25;0.50;0.75;1.05];

            PopulationC = Problem.Initialization();
            PopulationU = Problem.Initialization();
            B           = PopulationC([]);
            Model       = [];
            RecentBoundaryOff = PopulationC([]);

            SectorNeighbors = BuildSectorNeighbors(W,min(max(3,2*Problem.M),max(size(W,1)-1,0)));
            Generation = 0;
            Observer   = InitObserver( ...
                Algorithm,Problem,[type,hidden,epoch,lr,minPos,minNeg,kappa, ...
                rhoPre,rhoPost,gapMin,gapMax],ProbeBeta,MaxTrain);
            Algorithm.metric.analysis_folder          = Observer.folder;
            Algorithm.metric.analysis_meta_csv        = Observer.meta_file;
            Algorithm.metric.analysis_summary_csv     = Observer.summary_file;
            Algorithm.metric.analysis_boundary_csv    = Observer.boundary_file;
            Algorithm.metric.analysis_archive_csv     = Observer.archive_file;
            Algorithm.metric.analysis_mlp_csv         = Observer.mlp_file;

            TrainArchive = InitTrainArchive(Problem.D);
            [TrainArchive,TrainDiag] = UpdateTrainArchiveWithDiagnostics( ...
                TrainArchive,B,PopulationC,PopulationU,RecentBoundaryOff, ...
                W,SectorNeighbors,MaxTrain,0);
            [Model,MLPDiag] = UpdateBoundaryModelWithDiagnostics( ...
                Model,TrainArchive,minPos,minNeg,hidden,epoch,lr, ...
                ResolveModelUpdateGap(gapMin,gapMax,Problem.FE/max(Problem.maxFE,1)),0);
            Observer = LogMLPEvent(Observer,MLPDiag);

            while Algorithm.NotTerminated(PopulationC)
                Generation = Generation + 1;
                OffspringC = GenerateWithinOffspring(Problem,PopulationC,type,true);
                OffspringU = GenerateWithinOffspring(Problem,PopulationU,type,false);

                FERatio     = Problem.FE/max(Problem.maxFE,1);
                RemainingFE = max(0,Problem.maxFE-Problem.FE);

                SeedPool = KeepUniquePopulation([B,PopulationC,PopulationU,OffspringC,OffspringU]);
                [SeedB,~] = UpdateBoundaryArchive( ...
                    SeedPool,W,Model,PopulationC,PopulationU, ...
                    TrainArchive,SectorNeighbors,kappa);
                SeedMeta = BuildBoundaryMeta( ...
                    SeedB,W,Model,PopulationC,PopulationU,TrainArchive,SectorNeighbors);

                BoundaryBudget = ResolveBoundaryBudget( ...
                    Problem.N,rhoPre,rhoPost,RemainingFE,HasBoundaryModel(Model));
                [BoundaryOff,BoundaryDiag] = GenerateBoundaryOffspringModelDriven( ...
                    Problem,PopulationC,PopulationU,SeedB,W,SectorNeighbors,Model, ...
                    TrainArchive,BoundaryBudget,ProbeBeta,Generation,Problem.FE);
                BoundaryOff = KeepUniquePopulation(BoundaryOff);

                CandidateB = KeepUniquePopulation([SeedPool,BoundaryOff]);
                [B,~] = UpdateBoundaryArchive( ...
                    CandidateB,W,Model,PopulationC,PopulationU, ...
                    TrainArchive,SectorNeighbors,kappa);

                QC = KeepUniquePopulation([PopulationC,OffspringC,OffspringU,BoundaryOff]);
                QU = KeepUniquePopulation([PopulationU,OffspringC,OffspringU,BoundaryOff]);
                PopulationC = EnvironmentalSelectionC(QC,Problem.N,W);
                PopulationU = EnvironmentalSelectionU(QU,Problem.N,W);
                BoundarySurvival = ComputeBoundarySurvival(BoundaryOff,PopulationC,PopulationU);

                RecentBoundaryOff = BoundaryOff;
                [TrainArchive,TrainDiag] = UpdateTrainArchiveWithDiagnostics( ...
                    TrainArchive,B,PopulationC,PopulationU,RecentBoundaryOff, ...
                    W,SectorNeighbors,MaxTrain,Problem.FE);
                [Model,MLPDiag] = UpdateBoundaryModelWithDiagnostics( ...
                    Model,TrainArchive,minPos,minNeg,hidden,epoch,lr, ...
                    ResolveModelUpdateGap(gapMin,gapMax,Problem.FE/max(Problem.maxFE,1)), ...
                    Problem.FE);
                Observer = LogMLPEvent(Observer,MLPDiag);
                ArchiveMeta = BuildBoundaryMeta( ...
                    B,W,Model,PopulationC,PopulationU,TrainArchive,SectorNeighbors);
                Observer = LogGenerationDiagnostics( ...
                    Observer,Generation,Problem,PopulationC,PopulationU, ...
                    OffspringC,OffspringU,BoundaryBudget,SeedB,SeedMeta,BoundaryOff,BoundaryDiag, ...
                    BoundarySurvival,B,ArchiveMeta,TrainArchive,TrainDiag,MLPDiag,Model);
            end
        end
    end
end

%% ========== Main-population offspring ==========

function Offspring = GenerateWithinOffspring(Problem,Population,type,isConstraintSide)
    if isempty(Population)
        Offspring = [];
        return;
    end

    N = numel(Population);
    if isConstraintSide
        [Flag,FrontNo,CrowdDis] = ConstraintSideIndicator(Population);
        MatingPool = TournamentSelection(2,2*N,Flag,FrontNo,-CrowdDis);
    else
        [FrontNo,CrowdDis] = ObjectiveSideIndicator(Population);
        MatingPool = TournamentSelection(2,2*N,FrontNo,-CrowdDis);
    end

    if type == 1
        Offspring = OperatorGAhalf(Problem,Population(MatingPool));
    else
        Offspring = OperatorDE(Problem,Population, ...
            Population(MatingPool(1:N)),Population(MatingPool(N+1:end)));
    end
end

%% ========== Main loop helpers ==========

function Budget = ResolveBoundaryBudget(N,rhoPre,rhoPost,RemainingFE,ModelReady)
    if ModelReady
        Ratio = rhoPost;
    else
        Ratio = rhoPre;
    end
    Ratio  = max(0,min(0.5,double(Ratio)));
    Budget = floor(Ratio*N);
    Budget = min(max(0,Budget),max(0,RemainingFE));
end

function Gap = ResolveModelUpdateGap(gapMin,gapMax,FERatio)
    Gap = floor(double(gapMin) + (double(gapMax)-double(gapMin))*FERatio);
    Gap = max(1,Gap);
end

function [Model,Diag] = UpdateBoundaryModelWithDiagnostics( ...
    Model,TrainArchive,minPos,minNeg,hidden,epoch,lr,Gap,Tick)

    Diag = InitMLPDiag(Model,TrainArchive,Gap,Tick,minPos,minNeg);
    if ~Diag.can_train
        return;
    end

    if isempty(Model) || mod(Tick,Gap) == 0
        Diag.warm_start = double(HasBoundaryModel(Model));
        Model = TrainBoundaryMLP(TrainArchive,hidden,epoch,lr,Model);
        Diag.trained           = 1;
        Diag.model_ready_after = double(HasBoundaryModel(Model));
        Diag.stats_after       = EvaluateBinaryPredictions(Model,TrainArchive.Dec,TrainArchive.Label);
    end
end

function Model = UpdateBoundaryModelIfDue( ...
    Model,TrainArchive,minPos,minNeg,hidden,epoch,lr,Gap,Tick)
    [Model,~] = UpdateBoundaryModelWithDiagnostics( ...
        Model,TrainArchive,minPos,minNeg,hidden,epoch,lr,Gap,Tick);
end

function Flag = HasBoundaryModel(Model)
    Flag = ~isempty(Model) && isfield(Model,'Mu');
end

%% ========== Boundary archive and generation ==========

function [B,Meta] = UpdateBoundaryArchive( ...
    CandidateB,W,Model,PopulationC,PopulationU,TrainArchive,SectorNeighbors,kappa)
    if isempty(CandidateB)
        B    = CandidateB;
        Meta = InitBoundaryMeta(0);
        return;
    end

    CandidateB = KeepUniquePopulation(CandidateB);
    Meta       = BuildBoundaryMeta( ...
        CandidateB,W,Model,PopulationC,PopulationU,TrainArchive,SectorNeighbors);
    BridgeMask = ResolveBridgeBoundaryMask(Meta,TrainArchive,SectorNeighbors,size(W,1));
    B          = SelectTopKPerSector(CandidateB,Meta,BridgeMask,kappa);
end

function Meta = BuildBoundaryMeta( ...
    Candidates,W,Model,PopulationC,PopulationU,TrainArchive,SectorNeighbors)
    N = numel(Candidates);
    Meta = InitBoundaryMeta(N);
    if isempty(Candidates)
        return;
    end

    RefObj = BuildReferenceObj(Candidates,PopulationC,PopulationU);
    [Sector,~] = AssociateSectorsLocal(Candidates.objs,W,RefObj);
    [Prob,~]   = PredictBoundaryMLP(Model,Candidates.decs);
    Margin     = 2*abs(Prob(:)-0.5);
    ObjScore   = ComputeBoundaryObjectiveScore(Candidates,PopulationC,W,RefObj,Sector);
    TrustedSector = ResolveTrustedSectorsFromTrainArchive( ...
        TrainArchive,SectorNeighbors,size(W,1));
    TrustedMask   = IsTrustedSector(Sector,TrustedSector);
    Margin(~TrustedMask) = 1;

    Support = BuildBoundarySupportSet( ...
        Candidates,PopulationC,PopulationU,TrainArchive,W,RefObj);
    Label = double(all(Candidates.cons<=0,2));
    OppDist = ComputeOppositeDistanceByLabel( ...
        Candidates.decs,Label,Sector,Support.Dec,Support.Label, ...
        Support.Sector,SectorNeighbors);
    TauD = ResolveDistanceScale(Support.Dec);
    OppSupport = exp(-OppDist./max(TauD,1e-6));
    OppSupport(~isfinite(OppDist)) = 0;
    OppSupport = max(0,min(1,OppSupport));

    Meta.sector     = Sector(:);
    Meta.prob       = Prob(:);
    Meta.margin     = Margin(:);
    Meta.objScore   = ObjScore(:);
    Meta.oppSupport = OppSupport(:);
    Meta.oppDist    = OppDist(:);
    Meta.feasible   = Label(:);
    Meta.trusted    = TrustedMask(:);
    Meta.score      = 0.50*Margin(:) + 0.30*(1-OppSupport(:)) + 0.20*ObjScore(:);
end

function Meta = InitBoundaryMeta(N)
    Meta = struct( ...
        'sector',zeros(N,1), ...
        'prob',0.5*ones(N,1), ...
        'margin',zeros(N,1), ...
        'objScore',zeros(N,1), ...
        'oppSupport',zeros(N,1), ...
        'oppDist',inf(N,1), ...
        'feasible',zeros(N,1), ...
        'trusted',false(N,1), ...
        'score',zeros(N,1));
end

function BridgeMask = ResolveBridgeBoundaryMask(Meta,TrainArchive,SectorNeighbors,K)
    BridgeMask = Meta.trusted(:);
    CoreMask   = IsCoreTrainSource(TrainArchive.Source);
    CoreLabel  = TrainArchive.Label(CoreMask);
    CoreSector = TrainArchive.Sector(CoreMask);
    for i = 1 : numel(Meta.sector)
        if BridgeMask(i) || Meta.sector(i) <= 0 || Meta.sector(i) > K
            continue;
        end
        Allowed = ResolveLocalSectorSet(Meta.sector(i),SectorNeighbors);
        Local = CoreLabel(ismember(CoreSector,Allowed));
        if any(Local == 1-Meta.feasible(i))
            BridgeMask(i) = true;
            continue;
        end
        BridgeMask(i) = HasRealLocalOppositeSupport(Meta,i);
    end
end

function Flag = HasRealLocalOppositeSupport(Meta,idx)
    Flag = idx > 0 && idx <= numel(Meta.oppDist) && ...
           isfinite(Meta.oppDist(idx));
end

function B = SelectTopKPerSector(Candidates,Meta,BridgeMask,kappa)
    if isempty(Candidates)
        B = Candidates;
        return;
    end

    Pick = zeros(0,1);
    for s = unique(Meta.sector(Meta.sector > 0))'
        idx = find(Meta.sector == s & BridgeMask(:));
        if isempty(idx)
            continue;
        end
        Key = [Meta.score(idx), Meta.margin(idx), Meta.objScore(idx), idx(:)];
        [~,ord] = sortrows(Key,[1 2 3 4]);
        Sel = idx(ord(1:min(kappa,numel(idx))));

        Label = Meta.feasible(idx);
        if any(Label == 1) && any(Label == 0)
            SelLabel = Meta.feasible(Sel);
            if isscalar(unique(SelLabel))
                Majority = SelLabel(1);
                OppIdx = idx(Label ~= Majority);
                if ~isempty(OppIdx)
                    AltKey = [Meta.score(OppIdx), Meta.margin(OppIdx), Meta.objScore(OppIdx), OppIdx(:)];
                    [~,altOrd] = sortrows(AltKey,[1 2 3 4]);
                    Alt = OppIdx(altOrd(1));

                    WorstKey = [Meta.score(Sel), Meta.margin(Sel), Meta.objScore(Sel), Sel(:)];
                    [~,worstOrd] = sortrows(WorstKey,[-1 -2 -3 -4]);
                    if Meta.score(Alt) <= Meta.score(Sel(worstOrd(1))) + 0.08
                        Sel(worstOrd(1)) = Alt;
                    end
                end
            end
        end
        Pick = [Pick;Sel(:)]; %#ok<AGROW>
    end

    if isempty(Pick)
        B = Candidates([]);
    else
        B = Candidates(unique(Pick,'stable'));
    end
end

function [Offspring,Diag] = GenerateBoundaryOffspringModelDriven( ...
    Problem,PopulationC,PopulationU,B,W,SectorNeighbors,Model,TrainArchive, ...
    Budget,ProbeBeta,Generation,FE)

    Diag = InitBoundaryDiag(Generation,FE,Budget);

    if isempty(B)
        Offspring = PopulationC([]);
        return;
    end
    if Budget <= 0
        Offspring = B([]);
        return;
    end

    RefObj      = BuildReferenceObj(B,PopulationC,PopulationU);
    ArchiveMeta = BuildBoundaryMeta( ...
        B,W,Model,PopulationC,PopulationU,TrainArchive,SectorNeighbors);
    Pool        = KeepUniquePopulation([PopulationC,PopulationU]);
    PoolMeta    = BuildBoundaryMeta( ...
        Pool,W,Model,PopulationC,PopulationU,TrainArchive,SectorNeighbors);
    Support     = BuildBoundarySupportSet( ...
        B,PopulationC,PopulationU,TrainArchive,W,RefObj);
    SectorOrder = RankBoundarySectors(ArchiveMeta);
    if isempty(SectorOrder)
        Offspring = B([]);
        return;
    end

    ProbeDecAll = zeros(0,Problem.D);
    MaxAttempt  = max(Budget,1)*max(numel(SectorOrder),1)*3;
    Attempt     = 0;
    PoolDec     = zeros(0,Problem.D);
    if ~isempty(Pool)
        PoolDec = [PoolDec;Pool.decs]; %#ok<AGROW>
    end
    if ~isempty(B)
        PoolDec = [PoolDec;B.decs]; %#ok<AGROW>
    end

    while size(ProbeDecAll,1) < Budget && Attempt < MaxAttempt
        s = SectorOrder(mod(Attempt,numel(SectorOrder))+1);
        Attempt = Attempt + 1;
        Diag.attempts = Attempt;

        [Anchor,AnchorMeta,HasAnchor] = SelectBoundaryAnchor(B,ArchiveMeta,s);
        if ~HasAnchor
            continue;
        end

        [Helper,HelperMeta,HasHelper,HelperInfo] = SelectBoundaryHelper( ...
            Anchor,AnchorMeta,Pool,PoolMeta,s,SectorNeighbors,Model);
        if ~HasHelper
            Diag.skipped_no_helper = Diag.skipped_no_helper + 1;
            continue;
        end

        [ProbeDec,Beta] = BuildBoundaryProbeDecisions( ...
            Problem,Anchor.decs,Helper.decs,ProbeBeta);
        [Prob,Score,ProbeMeta] = RankBoundaryProbeCandidates( ...
            Model,ProbeDec,Beta,Anchor,AnchorMeta,Helper,HelperMeta,Support,SectorNeighbors);
        [~,best]  = min(Score);
        Candidate = ProbeDec(best,:);

        if ~isempty(PoolDec) && ismember(Candidate,PoolDec,'rows')
            Diag.skipped_duplicate = Diag.skipped_duplicate + 1;
            continue;
        end
        if ~isempty(ProbeDecAll) && ismember(Candidate,ProbeDecAll,'rows')
            Diag.skipped_duplicate = Diag.skipped_duplicate + 1;
            continue;
        end
        ProbeDecAll(end+1,:) = Candidate; %#ok<AGROW>
        chosenPred = double(Prob(best) >= 0.5);
        Diag.events = [Diag.events; { ...
            Generation,FE,Attempt,s,HelperInfo.type,HelperInfo.feasible, ...
            AnchorMeta.trusted,AnchorMeta.margin,AnchorMeta.oppSupport,AnchorMeta.objScore, ...
            Beta(best),Prob(best),chosenPred,ProbeMeta.margin(best),ProbeMeta.oppSupport(best), ...
            ProbeMeta.oppDist(best),ProbeMeta.objScore(best),Score(best),NaN,NaN}]; %#ok<AGROW>
        Diag.helper_real_opp = Diag.helper_real_opp + double(strcmp(HelperInfo.type,'real_opposite'));
    end

    if isempty(ProbeDecAll)
        Offspring = B([]);
    else
        Offspring = Problem.Evaluation(ProbeDecAll);
        Feasible = double(all(Offspring.cons<=0,2));
        for i = 1 : min(numel(Feasible),size(Diag.events,1))
            Diag.events{i,end-1} = Feasible(i);
            Diag.events{i,end} = double(Diag.events{i,13} == Feasible(i));
        end
        Diag.selected = numel(Offspring);
        Diag.feasible = sum(Feasible == 1);
        Diag.infeasible = sum(Feasible == 0);
    end
end

function SectorOrder = RankBoundarySectors(Meta)
    SectorOrder = zeros(1,0);
    TrustedMask = Meta.sector > 0 & Meta.trusted(:);
    Sectors = unique(Meta.sector(TrustedMask))';
    if isempty(Sectors)
        return;
    end

    Key = zeros(numel(Sectors),3);
    for i = 1 : numel(Sectors)
        idx      = find(Meta.sector == Sectors(i));
        Key(i,1) = min(Meta.score(idx));
        Key(i,2) = min(Meta.margin(idx));
        Key(i,3) = Sectors(i);
    end
    [~,ord]  = sortrows(Key,[1 2 3]);
    SectorOrder = Sectors(ord);
end

function [Anchor,AnchorMeta,Found] = SelectBoundaryAnchor(B,Meta,sector)
    Empty = B([]);
    idx   = find(Meta.sector == sector);
    if isempty(idx)
        Anchor     = Empty;
        AnchorMeta = InitBoundaryMeta(0);
        Found      = false;
        return;
    end

    Key = [Meta.score(idx), Meta.margin(idx), Meta.objScore(idx), idx(:)];
    [~,ord] = sortrows(Key,[1 2 3 4]);
    Pick    = idx(ord(1));
    Anchor  = B(Pick);
    AnchorMeta = ExtractBoundaryMetaRow(Meta,Pick);
    Found   = true;
end

function [Helper,HelperMeta,Found,Info] = SelectBoundaryHelper( ...
    Anchor,AnchorMeta,Pool,PoolMeta,sector,SectorNeighbors,Model)

    Empty    = Pool([]);
    Info     = struct('type','none','feasible',NaN);
    Neighbor = [sector,SectorNeighbors{sector}(:)'];
    Allowed  = ismember(PoolMeta.sector,unique(Neighbor)) & ...
               ~ismember(Pool.decs,Anchor.decs,'rows');
    idx = find(Allowed);
    if isempty(idx)
        Helper     = Empty;
        HelperMeta = InitBoundaryMeta(0);
        Found      = false;
        return;
    end

    AnchorLabel = double(all(Anchor.cons<=0,2));
    Label       = double(all(Pool.cons<=0,2));
    OppReal     = idx(Label(idx) ~= AnchorLabel);
    if ~isempty(OppReal)
        Pick = PickBestHelper(OppReal,PoolMeta);
        Helper     = Pool(Pick);
        HelperMeta = ExtractBoundaryMetaRow(PoolMeta,Pick);
        Info.type  = 'real_opposite';
        Info.feasible = Label(Pick);
        Found      = true;
        return;
    end
    %#ok<INUSD> Model AnchorMeta

    Helper     = Empty;
    HelperMeta = InitBoundaryMeta(0);
    Found      = false;
end

function Pick = PickBestHelper(idx,Meta)
    Key = [Meta.score(idx), Meta.margin(idx), Meta.objScore(idx), idx(:)];
    [~,ord] = sortrows(Key,[1 2 3 4]);
    Pick    = idx(ord(1));
end

function Row = ExtractBoundaryMetaRow(Meta,idx)
    Row = InitBoundaryMeta(1);
    Row.sector     = Meta.sector(idx);
    Row.prob       = Meta.prob(idx);
    Row.margin     = Meta.margin(idx);
    Row.objScore   = Meta.objScore(idx);
    Row.oppSupport = Meta.oppSupport(idx);
    Row.oppDist    = Meta.oppDist(idx);
    Row.feasible   = Meta.feasible(idx);
    Row.trusted    = Meta.trusted(idx);
    Row.score      = Meta.score(idx);
end

function [ProbeDec,Beta] = BuildBoundaryProbeDecisions( ...
    Problem,AnchorDec,HelperDec,FixedBeta)

    Beta = FixedBeta(:);
    Span     = double(Problem.upper - Problem.lower);
    Span(Span < 1e-12) = 1;
    RealIdx  = find(Problem.encoding <= 2);
    OtherIdx = setdiff(1:Problem.D,RealIdx);

    ProbeDec = zeros(numel(Beta),Problem.D);
    for i = 1 : numel(Beta)
        Base = AnchorDec + Beta(i)*(HelperDec-AnchorDec);
        Dec  = Base;
        if ~isempty(RealIdx)
            Dec(RealIdx) = Base(RealIdx) + 0.05*randn(1,numel(RealIdx)).*Span(RealIdx);
        end
        if ~isempty(OtherIdx)
            if Beta(i) <= 0.5
                Dec(OtherIdx) = AnchorDec(OtherIdx);
            else
                Dec(OtherIdx) = HelperDec(OtherIdx);
            end
        end
        ProbeDec(i,:) = Problem.CalDec(Dec);
    end
end

function [Prob,Score,Meta] = RankBoundaryProbeCandidates( ...
    Model,ProbeDec,Beta,Anchor,AnchorMeta,Helper,HelperMeta,Support,SectorNeighbors)
    if isempty(ProbeDec)
        Prob  = zeros(0,1);
        Score = zeros(0,1);
        Meta = struct('margin',zeros(0,1),'oppSupport',zeros(0,1), ...
            'oppDist',zeros(0,1),'objScore',zeros(0,1));
        return;
    end

    [Prob,~] = PredictBoundaryMLP(Model,ProbeDec);
    Margin = 2*abs(Prob(:)-0.5);
    if AnchorMeta.trusted <= 0
        Margin(:) = 1;
    end
    Sector = AnchorMeta.sector*ones(size(ProbeDec,1),1);
    AnchorLabel = double(all(Anchor.cons<=0,2));
    HelperLabel = double(all(Helper.cons<=0,2));
    ProxyLabel  = BuildProbeProxyLabels(Beta,AnchorLabel,HelperLabel);

    OppDist = ComputeOppositeDistanceByLabel( ...
        ProbeDec,ProxyLabel,Sector,Support.Dec,Support.Label, ...
        Support.Sector,SectorNeighbors);
    TauD = ResolveDistanceScale(Support.Dec);
    OppSupport = exp(-OppDist./max(TauD,1e-6));
    OppSupport(~isfinite(OppDist)) = 0;
    OppSupport = max(0,min(1,OppSupport));

    Mix = min(max(Beta(:),0),1);
    ObjScore = (1-Mix)*AnchorMeta.objScore + Mix*HelperMeta.objScore;
    ObjScore = max(0,min(1,ObjScore));
    Score = 0.50*Margin(:) + 0.30*(1-OppSupport(:)) + 0.20*ObjScore(:);
    Meta = struct('margin',Margin(:),'oppSupport',OppSupport(:), ...
        'oppDist',OppDist(:),'objScore',ObjScore(:));
end

function ProxyLabel = BuildProbeProxyLabels(Beta,AnchorLabel,HelperLabel)
    ProxyLabel = AnchorLabel*ones(numel(Beta),1);
    ProxyLabel(Beta(:) >= 0.5) = HelperLabel;
end

%% ========== Training archive ==========

function TrainArchive = InitTrainArchive(D)
    TrainArchive = struct( ...
        'Dec',zeros(0,D), ...
        'Label',zeros(0,1), ...
        'Source',zeros(0,1), ...
        'Sector',zeros(0,1), ...
        'Time',zeros(0,1));   % 1:B core, 2:recent boundary core, 3:P_C feasible anchor, 4:P_U infeasible anchor
end

function TrainArchive = UpdateTrainArchive( ...
    TrainArchive,B,PopulationC,PopulationU,RecentBoundaryOff,W, ...
    SectorNeighbors,MaxTrain,Stamp)

    RefObj = BuildReferenceObj(B,PopulationC,PopulationU,RecentBoundaryOff);
    if isempty(RefObj)
        RefObj = BuildReferenceObj(PopulationC,PopulationU,B);
    end

    [Core,CoreSource] = BuildCoreTrainPopulation(B,RecentBoundaryOff);
    Candidates = Core;
    Source     = CoreSource;
    if ~isempty(Core)
        CoreSector = AssociateSectorsLocal(Core.objs,W,RefObj);
        CoreLabel  = double(all(Core.cons<=0,2));

        RepC = BuildSectorRepresentatives( ...
            PopulationC,W,RefObj,all(PopulationC.cons<=0,2));
        RepU = BuildSectorRepresentatives( ...
            PopulationU,W,RefObj,any(PopulationU.cons>0,2));

        AnchorC = SelectMissingSideAnchors( ...
            Core,CoreSector,CoreLabel,PopulationC,RepC,SectorNeighbors,1);
        AnchorU = SelectMissingSideAnchors( ...
            Core,CoreSector,CoreLabel,PopulationU,RepU,SectorNeighbors,0);
        if ~isempty(AnchorC)
            Candidates = [Candidates,PopulationC(AnchorC)];
            Source = [Source;3*ones(numel(AnchorC),1)];
        end
        if ~isempty(AnchorU)
            Candidates = [Candidates,PopulationU(AnchorU)];
            Source = [Source;4*ones(numel(AnchorU),1)];
        end
    end

    Meta = BuildTrainMeta(Candidates,Source,W,RefObj,Stamp);
    TrainArchive = AppendTrainArchiveWithMeta(TrainArchive,Candidates,Meta);
    TrainArchive = TrimTrainArchiveBySectorQuota(TrainArchive,MaxTrain);
end

