function [RunManifest,outRoot] = run_CCMO_GAN_BDG_cgan_retained_run3( ...
        outRoot,workerCount,problemNames,N,D,maxFE,runIds,selectedVariants)
% Compatibility wrapper for the retired retained-CGAN experiment runner.
% New runs use the FixMD global nondominated mainline only.

    %#ok<INUSD>
    rootDir = fileparts(which('platemo'));
    addpath(genpath(rootDir));
    if nargin < 1 || isempty(outRoot)
        stamp = char(datetime('now','Format','yyyyMMdd_HHmmss'));
        outRoot = fullfile(rootDir,'Data','CCMO_GAN_BDG', ...
            ['FixMD_global_retained_run3_',stamp]);
    end
    if nargin < 2 || isempty(workerCount)
        workerCount = 7;
    end
    if nargin < 3 || isempty(problemNames)
        problemNames = {'DASCMOP1_BC','DASCMOP2_BC','DASCMOP4_BC', ...
            'DASCMOP5_BC','LIRCMOP5_BC','LIRCMOP6_BC', ...
            'LIRCMOP7_BC','LIRCMOP8_BC','LIRCMOP9_BC', ...
            'LIRCMOP10_BC'};
    end
    if nargin < 4 || isempty(N)
        N = 100;
    end
    if nargin < 5
        D = [];
    end
    if nargin < 6 || isempty(maxFE)
        maxFE = 100000;
    end
    if nargin < 7 || isempty(runIds)
        runIds = 1 : 3;
    end

    plotOptions = struct('enable',false,'targets',[], ...
        'plotRuns',[],'plotVariants',[],'ganN',0);
    params = {1,20,0,5,0.20,50,0,200,0,1,1,1, ...
        "g2sl",64,0.9,1e-4,1e-4,"epoch"};
    [Summary,outRoot] = run_CCMO_GAN_BDG_archive_pareto_filters_fullscope( ...
        outRoot,workerCount,problemNames,N,D,maxFE,runIds, ...
        "current",params,plotOptions);

    Row = struct( ...
        'variant',"FixMD_GNDk60_nearseg_huber_z0", ...
        'purpose',"Current FixMD global nondominated mainline.", ...
        'out_dir',string(outRoot), ...
        'summary_file',string(fullfile(outRoot, ...
            'archive_pareto_filter_run_summary.csv')), ...
        'overall_file',string(fullfile(outRoot, ...
            'archive_pareto_filter_overall.csv')), ...
        'ok_count',sum(Summary.status == "ok"), ...
        'failed_count',sum(Summary.status ~= "ok"), ...
        'zDim',0, ...
        'ganIter',50, ...
        'ganGSteps',1, ...
        'generatorLossMode',"conditional_adversarial_huber");
    RunManifest = struct2table(Row);
    writetable(RunManifest,fullfile(outRoot, ...
        'fixmd_global_retained_manifest.csv'));
end
