function assertBoundaryTargetTriplesUseObjectivePairs()
    Problem = struct('D',2,'M',2);
    AF = struct( ...
        'decs',[0.20 0.30;0.40 0.50], ...
        'objs',[2 4;4 2], ...
        'ref',[1;2], ...
        'score',[0;0]);
    AI = struct( ...
        'decs',[0.10 0.20;0.30 0.40], ...
        'objs',[1 3;3 1], ...
        'ref',[1;2], ...
        'score',[0;0]);

    [X,C,Diag] = BuildBoundaryTargetTriples_BDG(AF,AI,Problem);

    expectedY = [1/3 1;1 1/3];
    expectedD = [-1/3 -1/3;-1/3 -1/3];
    assert(isequal(size(X),[2 2]), ...
        'test_CCMO_GAN_BDG_target_conditioned:BadTripleDecisionSize', ...
        'Boundary target triples must expose one AF decision per archive pair.');
    assert(isequal(size(C),[2 4]), ...
        'test_CCMO_GAN_BDG_target_conditioned:BadConditionSize', ...
        'Boundary target conditionData must be [y_t,d_t] with 2*M columns.');
    assert(max(abs(double(C(:,1:2)) - expectedY),[],'all') < 1e-6, ...
        'test_CCMO_GAN_BDG_target_conditioned:BadObjectiveTarget', ...
        'The first M condition columns must be normalized AF objective targets.');
    assert(max(abs(double(C(:,3:4)) - expectedD),[],'all') < 1e-6, ...
        'test_CCMO_GAN_BDG_target_conditioned:BadDirectionTarget', ...
        'The last M condition columns must be normalized objective directions AI-AF.');
    assert(Diag.target_triple_ready == 1 && Diag.target_triple_count == 2, ...
        'test_CCMO_GAN_BDG_target_conditioned:BadTripleDiag', ...
        'Boundary target triple diagnostics must report ready finite pairs.');
end

