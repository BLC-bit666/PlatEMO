        'test_CCMO_GAN_BDG_target_conditioned:BadTargetUnconditionedSample', ...
        'Target-unconditioned GAN must sample complete decision offspring.');
    assert(isfield(GAN,'targetConditionedDiag') && ...
            GAN.targetConditionedDiag.target_mismatch_count == 0 && ...
            GAN.targetConditionedDiag.target_mismatch_batch_count == 0, ...
        'test_CCMO_GAN_BDG_target_conditioned:UnexpectedUnconditionedMismatchDiag', ...
